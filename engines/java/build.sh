#!/usr/bin/env bash
# Compile the Java engine with javac (JDK 17, standard library only), run every pack vector plus unit checks, and
# write build/goat-transformers-<version>.jar: the engine classes and nothing else, no dependencies.
#
# Usage: ./build.sh [--wires LIST] [--no-test] [--out DIR] [PACKS_DIR]   (PACKS_DIR default ../../packs)
#
#   --wires LIST  build with the codecs of these wires only (spec 0.24), a comma-separated subset of
#                 xml,geojson,json,bits,protobuf,text,tlv; `all`, or no --wires, is all seven. The codec sources
#                 of every other wire (src/wire/<wire>/) are not compiled, so the jar does not carry them. A pack
#                 on a wire the build lacks is unknown-wire at load. A build with fewer than seven wires does not
#                 run the test suite, whose unit checks need every wire: ./reduced-check.sh is its test.
#   --no-test     compile and write the jar without running the test suite.
#   --out DIR     write into DIR instead of build/ (DIR is removed first).
set -euo pipefail
cd "$(dirname "$0")"
version=0.8.0
all_wires=(xml geojson json bits protobuf text tlv)
wires_arg=all
run_tests=1
out=build
packs=../../packs
while [ $# -gt 0 ]; do
  case "$1" in
    --wires) [ $# -ge 2 ] || { echo "build.sh: --wires needs a list" >&2; exit 2; }; wires_arg="$2"; shift 2 ;;
    --wires=*) wires_arg="${1#--wires=}"; shift ;;
    --no-test) run_tests=0; shift ;;
    --out) [ $# -ge 2 ] || { echo "build.sh: --out needs a directory" >&2; exit 2; }; out="$2"; shift 2 ;;
    -*) echo "build.sh: unknown option $1" >&2; exit 2 ;;
    *) packs="$1"; shift ;;
  esac
done
case "$out" in
  ""|/|.|..|./|../) echo "build.sh: refusing --out \"$out\"" >&2; exit 2 ;;
esac

# The set, in the order of the specification; each name once.
wires=()
if [ "$wires_arg" = all ]; then
  wires=("${all_wires[@]}")
else
  IFS=',' read -r -a asked <<< "$wires_arg"
  for a in "${asked[@]}"; do
    known=0
    for w in "${all_wires[@]}"; do [ "$a" = "$w" ] && known=1; done
    if [ "$known" = 0 ]; then
      echo "build.sh: --wires: \"$a\" is not a wire (xml, geojson, json, bits, protobuf, text, tlv)" >&2
      exit 2
    fi
  done
  for w in "${all_wires[@]}"; do
    for a in "${asked[@]}"; do
      if [ "$a" = "$w" ]; then wires+=("$w"); break; fi
    done
  done
  if [ "${#wires[@]}" = 0 ]; then
    echo "build.sh: --wires names no wire" >&2
    exit 2
  fi
fi
has() { local w; for w in "${wires[@]}"; do [ "$w" = "$1" ] && return 0; done; return 1; }
full=0
[ "${#wires[@]}" = "${#all_wires[@]}" ] && full=1

rm -rf "$out"
mkdir -p "$out/main" "$out/test" "$out/gen/goat/transformers"

# The source directories of the build: the core (the pack language, the model, the engine), then each wire's
# codec. The json and geojson wires share src/wire/json-tree (JSON objects through the lines of a scope).
dirs=(src/main/java)
for w in "${wires[@]}"; do dirs+=("src/wire/$w"); done
if has json || has geojson; then dirs+=(src/wire/json-tree); fi

# Wires.java: the build's set, and the codec of each wire in it. It names no class of a wire outside the set.
{
  echo 'package goat.transformers;'
  echo
  echo '/** Generated by build.sh: the wires this build has (spec 0.24, ruling 1). Do not edit. */'
  echo 'final class Wires {'
  echo '    private Wires() {}'
  echo
  echo '    /** The wires of this build, in the order of the specification. */'
  printf '    static final java.util.List<String> NAMES = java.util.List.of('
  sep=''
  for w in "${wires[@]}"; do printf '%s"%s"' "$sep" "$w"; sep=', '; done
  echo ');'
  echo
  echo '    /** True when this build has the wire named {@code wire}. */'
  echo '    static boolean has(String wire) { return NAMES.contains(wire); }'
  echo
  echo '    /** The codec of a parsed pack. Pack.parse refuses a pack on a wire this build lacks (ruling 1c of 0.24). */'
  echo '    static Codec<?> codec(Pack p) {'
  echo '        switch (p.wire) {'
  has xml && echo '            case XML: return new XmlCodec(p);'
  has geojson && echo '            case GEOJSON: return new GeoJsonCodec(p);'
  has json && echo '            case JSON: return new JsonCodec(p);'
  has bits && echo '            case BITS: return p.seq != null ? new SeqCodec(p) : new BitsCodec(p);'
  has protobuf && echo '            case PROTOBUF: return new ProtobufCodec(p);'
  has text && echo '            case TEXT: return new TextCodec(p);'
  has tlv && echo '            case TLV: return new TlvCodec(p);'
  echo '            default:'
  echo '                throw new GtException(GtException.Code.UNKNOWN_WIRE, p.format, null, "wire \"" + p.wire.name().toLowerCase(java.util.Locale.ROOT)'
  echo '                        + "\" is a wire of the specification, but this build does not have it");'
  echo '        }'
  echo '    }'
  echo '}'
} > "$out/gen/goat/transformers/Wires.java"

find "${dirs[@]}" "$out/gen" -name '*.java' | sort > "$out/main-sources.txt"
javac --release 17 -Xlint:all -Werror -d "$out/main" @"$out/main-sources.txt"
echo "wires: ${wires[*]}"
if [ "$run_tests" = 1 ] && [ "$full" = 1 ]; then
  find src/test/java -name '*.java' | sort > "$out/test-sources.txt"
  javac --release 17 -Xlint:all -Werror -cp "$out/main" -d "$out/test" @"$out/test-sources.txt"
  java -cp "$out/main:$out/test" goat.transformers.TestRunner "$packs"
elif [ "$run_tests" = 1 ]; then
  echo "tests: not run for a build with fewer than seven wires (the unit checks need every wire); run ./reduced-check.sh"
fi
# The jar: `java -jar` runs the command-line tool (goat.transformers.Cli); on a class path it is the library.
printf '%s\n' \
  'Implementation-Title: goat-transformers' \
  "Implementation-Version: $version" \
  'Automatic-Module-Name: goat.transformers' \
  'Main-Class: goat.transformers.Cli' > "$out/manifest.txt"
jar --create --file "$out/goat-transformers-$version.jar" --manifest "$out/manifest.txt" -C "$out/main" .
echo "jar: $out/goat-transformers-$version.jar"
