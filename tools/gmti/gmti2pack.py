#!/usr/bin/env python3
"""gmti2pack.py: write the gmti pack (engine-spec 0.8, sequential layout) and its
model module from the layout tables in this directory.

Input (this directory, written in this repository's own words from AEDP-4607):
  segments.tsv.txt   one row per field of the packet header and of each segment
  kinds.tsv.txt      one row per segment kind: type code, existence-mask size, requires
  tables.tsv.txt     value tables (target classification onto shared keys)

Output (repository root):
  model/gmti.def           the raw keys and the derive lines
  packs/gmti/pack.def      the pack
  packs/gmti/pack.md       what is mapped and what is not, with counts

Vectors are written by vectors.py, which packs its messages with struct from
its own statement of the layouts and does not read these tables.

How the packet becomes lines:
  - the packet header is common; its size field is `length 32 whole`
  - each segment kind starts with `when 8 <type>` (the segment type) and holds
    its body in `length 32 plus 5` (the segment size counts the 5-byte segment
    header)
  - a segment with an existence mask reads it as `presence <kind>_mask <n>`;
    each field sits in an `if` on its bit. A mask bit of a part the pack does
    not read (form `skip`) gets an empty `if`, so a message that sets it still
    decodes; encode writes that bit 0.
  - the end of a segment the pack does not read (repeated records after the
    first, free text) is skipped by the length extent.

Usage: python3 -I tools/gmti/gmti2pack.py   (from the repository root)
"""
import collections
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC_STD = ("NATO AEDP-4607 Edition A Version 1 (STANAG 4607), NATO Ground Moving Target Indicator "
           "Format (GMTIF), February 2024; NSG Standards Registry, nsgreg.nga.mil")
SRC_GUIDE = ("NATO AEDP-4607.1 Edition A Version 1, GMTIF implementation guide; "
             "NSG Standards Registry, nsgreg.nga.mil")
SRC_TABLES = "layouts restated in tools/gmti/segments.tsv.txt, kinds.tsv.txt and tables.tsv.txt of this repository"
HEAD = "# Generated by tools/gmti/gmti2pack.py from tools/gmti/*.tsv.txt. Do not edit by hand."



# --check: compare with the files in the tree instead of writing them; exit 1 when one differs.
import io as _io
CHECK_MODE = "--check" in sys.argv[1:]
DIFFERS = []


class _Cmp(_io.StringIO):
    def __init__(self, path):
        super().__init__()
        self.path = path

    def close(self):
        if not self.closed:
            try:
                cur = open(self.path, encoding="utf-8").read()
            except OSError:
                cur = None
            if cur != self.getvalue():
                DIFFERS.append(os.path.relpath(self.path, REPO))
        super().close()


def out_open(path):
    return _Cmp(path) if CHECK_MODE else open(path, "w", encoding="utf-8")


def check_exit(name):
    if CHECK_MODE:
        for d in DIFFERS:
            print("differs: " + d)
        print("%s: %s" % (name, "ok" if not DIFFERS else "%d differ" % len(DIFFERS)))
        sys.exit(1 if DIFFERS else 0)

def rows(name):
    with open(os.path.join(HERE, name), newline="", encoding="utf-8") as f:
        lines = [l for l in f if not l.startswith("#")]
    return list(csv.DictReader(lines, delimiter="\t"))


def transform(form, nbits):
    if form == "A":
        return "ascii", "string"
    if form in ("I", "E", "FL"):
        return "uint", "int"
    if form == "SM":    # sign bit, then the magnitude in fixed point (B16: 7 fraction bits, B32: 16)
        return "smscale:1/%d" % (1 << {16: 7, 32: 16}[nbits]), "float"
    if form == "S":
        return "twos", "int"
    if form == "SA":
        return "sscale:180/%d" % (1 << nbits), "float"
    if form == "BA":
        return "uscale:360/%d" % (1 << nbits), "float"
    if form == "BP":
        return "uscale:1/%d" % (1 << {16: 7, 32: 23}[nbits]), "float"
    raise SystemExit("unknown form %s" % form)


def main():
    seg = rows("segments.tsv.txt")
    kinds = rows("kinds.tsv.txt")
    tables = rows("tables.tsv.txt")
    det = {(r["kind"], r["ref"]): (r["key"], r["transform"]) for r in rows("detection.tsv.txt")}
    keys = collections.OrderedDict()      # raw key -> (type, unit, meaning)
    def build(hdr):
        by_kind = collections.OrderedDict()
        for r in seg:
            by_kind.setdefault(r["kind"], []).append(r)
        stats = collections.OrderedDict()
        st_det = [0]
        out = [HEAD,
               ("# One packet: the packet header and its first segment." if hdr else
                "# One segment: the 5-byte segment header and its body, as a caller splits a packet at the segment sizes."),
               "# Raw keys hold the field values in the units of the format; keys of core and track are bound",
               "# where the field is that key.",
               "format        %s" % ("gmti" if hdr else "gmti-segment"), "version       0.1.0", "distribution  public",
               'source        "%s"' % SRC_STD, 'source        "%s"' % SRC_GUIDE, 'source        "%s"' % SRC_TABLES,
               "uses          gmti", "uses          track", "uses          detection",
               "wire          bits", "layout        sequential", "bit_order     msb"]
        for t in tables:
            lo, _, hi = t["native"].partition("-")
            for n in range(int(lo), int(hi or lo) + 1):
                out.append("map  %s  %d  %s" % (t["table"], n, t["model"]))
        if hdr:
            out.append("default  gmti.version_id  41")

        def field_lines(r, ind):
            n = int(r["bytes"]) * 8
            lines = []
            also_det = None
            if r["bind"]:
                key, tr = r["bind"].split()
            else:
                key = "gmti." + r["key"]
                tr, ty = transform(r["form"], n)
                old = keys.get(r["key"])
                if old and old[0] != ty:
                    raise SystemExit("key %s with two types" % r["key"])
                if not old:
                    keys[r["key"]] = (ty, r["unit"] or "-", r["meaning"])
                d = det.get((r["kind"], r["ref"]))
                if d and d[1] == tr:          # the same reading: one more key on the field
                    also_det = d[0]
                elif d:                        # another unit: the detection key reads the field instead
                    key, tr = d
                    st_det[0] += 1
            lines.append("%sfield  %s  %d  %s" % (ind, key, n, tr))
            if also_det:
                lines.append("%salso  %s" % (ind, also_det))
            for a in filter(None, (x.strip() for x in r["also"].split(";"))):
                lines.append("%salso  %s" % (ind, a))
            return lines

        for r in (by_kind.pop("header") if hdr else by_kind.pop("header") and []):
            if r["form"] == "LENWHOLE":
                out.append("length  %d  whole" % (int(r["bytes"]) * 8))
            else:
                out.extend(field_lines(r, ""))
        for k in kinds:
            name = k["kind"]
            rs = by_kind.pop(name)
            st = stats[name] = collections.Counter()
            out += ["kind  %s" % name, "requires  %s" % k["requires"], "when  8  %s" % k["type"], "length  32  plus  5"]
            mask = int(k["mask"])
            if mask:
                out.append("  presence  %s_mask  %d" % (name, mask))
            ind0 = "  "
            for r in rs:
                if name == "dwell" and r["ref"].startswith("D32.") and ind0 == "  ":
                    # the target reports fill the rest of the dwell: one detection item each
                    out.append("  group  detection.items  rest")
                    ind0 = "    "
                if r["form"] == "rest":
                    st["rest"] += 1
                    continue
                if r["form"] == "skip":
                    out += ["  if  %s_mask.%s" % (name, r["bit"]), "  end"]
                    st["skip"] += 1
                    continue
                st["fields"] += 1
                st["bound"] += bool(r["bind"])
                st["first-record"] += r["meaning"].startswith("first ") or "first target" in r["meaning"]
                if r["bit"]:
                    out.append("%sif  %s_mask.%s" % (ind0, name, r["bit"]))
                    out.extend(field_lines(r, ind0 + "  "))
                    out.append("%send" % ind0)
                else:
                    out.extend(field_lines(r, ind0))
            if ind0 != "  ":
                out.append("  end")
            out.append("end")
        if by_kind:
            raise SystemExit("rows of unknown kinds: %s" % list(by_kind))
        return out, stats

    out, stats = build(True)
    seg_out, seg_stats = build(False)
    rec_out, rec_kinds = records(seg, tables, keys, True, det)
    srec_out, _ = records(seg, tables, keys, False, det)
    derived = [("mission_text", "mission_id"), ("job_text", "job_id"), ("revisit_text", "dwell_revisit_index"),
               ("dwell_text", "dwell_index"), ("mti_text", "mti_report_index")]
    model = [HEAD,
             "# Raw fields of the GMTI format (AEDP-4607), in the format's own units.",
             "module        gmti", "version       0.1.0", "distribution  public",
             'source        "%s"' % SRC_STD, 'source        "%s"' % SRC_TABLES]
    for k, (ty, unit, meaning) in keys.items():
        model.append('key  %s  %s  %s  "%s"' % (k, ty, unit, meaning.replace('"', "'")))
    for name, meaning in LISTS:
        model.append('list  %s  "%s"' % (name, meaning))
    for t, a in derived:
        model.append('key  %s  string  -  "decimal text of %s, a part of the derived uid"' % (t, a))
    for t, a in derived:
        model.append("derive  gmti.%s  text_of  gmti.%s" % (t, a))
    parts = "gmti.platform_id gmti.mission_text gmti.job_text gmti.revisit_text gmti.dwell_text"
    model += ["# a dwell: platform / mission / job / revisit / dwell, and the index of its first target report when sent",
              "derive  uid  join:/  %s  gmti.mti_text" % parts,
              "derive  uid  join:/  %s" % parts,
              "# every other segment reports on the platform the packet header names, or on its job",
              "derive  uid  copy  gmti.platform_id"]

    for fmt, lines in (("gmti", out), ("gmti-segment", seg_out), ("gmti-records", rec_out),
                       ("gmti-segment-records", srec_out)):
        os.makedirs(os.path.join(REPO, "packs", fmt), exist_ok=True)
        with out_open(os.path.join(REPO, "packs", fmt, "pack.def")) as f:
            f.write("\n".join(lines) + "\n")
    write_segment_md(kinds, seg_stats, sum(1 for l in seg_out if l.strip().startswith(("field", "also"))))
    write_records_md(rec_kinds, rec_out, srec_out)
    with out_open(os.path.join(REPO, "model", "gmti.def")) as f:
        f.write("\n".join(model) + "\n")
    write_md(kinds, stats, len(keys), sum(1 for l in out if l.strip().startswith(("field", "also"))),
             collections.Counter(r["form"] for r in seg))
    print("gmti: %d kinds, %d raw keys" % (len(kinds), len(keys)), file=sys.stderr)


LISTS = [("targets", "the target reports of a dwell, in wire order"),
         ("scatterers", "the scatterer records of an HRR segment, in wire order"),
         ("records", "the processing records of a processing history segment, in wire order")]
EXTRA_KEYS = [("packet_size", "int", "bytes", "size of the whole packet as stated in its header"),
              ("segment_size", "int", "bytes", "size of the segment, its 5-byte header included, as stated"),
              ("scatterer_magnitude", "int", "-dB/4", "scatterer power below the peak scatterer"),
              ("scatterer_phase", "int", "-", "scatterer phase in steps of a full turn over 256 or 65536")]


LIST_KEY = {"targets": "detection.items"}     # a dwell's target reports are the detections of the dwell


def list_key(name):
    return LIST_KEY.get(name, "gmti." + name)


def records(seg, tables, keys, hdr, det):
    """Fixed-layout pack (engine-spec 0.5 to 0.7 addressing): one kind per profile of profiles.tsv.txt."""
    profiles = rows("profiles.tsv.txt")
    kinds = rows("kinds.tsv.txt")
    stype = {k["kind"]: k["type"] for k in kinds}
    mask_bits = {k["kind"]: int(k["mask"]) for k in kinds}
    by_ref = {(r["kind"], r["ref"]): r for r in seg}
    fmt = "gmti-records" if hdr else "gmti-segment-records"
    for k, ty, unit, meaning in EXTRA_KEYS:
        keys.setdefault(k, (ty, unit, meaning))
    out = [HEAD,
           "# %s: the repeated records (target reports, HRR scatterers, processing records) as a counted group." %
           ("One packet of one segment" if hdr else "One segment"),
           "# Fixed layout: one kind per existence-mask profile of profiles.tsv.txt, so every field has a fixed place.",
           "format        %s" % fmt, "version       0.1.0", "distribution  public",
           'source        "%s"' % SRC_STD, 'source        "%s"' % SRC_GUIDE, 'source        "%s"' % SRC_TABLES,
           "uses          gmti", "uses          track", "uses          detection", "wire          bits", "word_bytes    1",
           "bit_order     msb"]
    for t in tables:
        lo, _, hi = t["native"].partition("-")
        for n in range(int(lo), int(hi or lo) + 1):
            out.append("map  %s  %d  %s" % (t["table"], n, t["model"]))

    def key_of(r, n):
        if r["bind"]:
            return [r["bind"].split()]
        tr, ty = transform(r["form"], n)
        keys.setdefault(r["key"], (ty, r["unit"] or "-", r["meaning"]))
        lines = [("gmti." + r["key"], tr)]
        for a in filter(None, (x.strip() for x in r["also"].split(";"))):
            key, _, table = a.split()
            lines.append((key, tr + " via " + table))
        d = det.get((r["kind"], r["ref"]))
        if d:                                  # the detection key at the same bits, in its own unit
            lines.append(d)
        return lines

    pos = 0
    if hdr:
        for r in seg:
            if r["kind"] != "header":
                continue
            n = int(r["bytes"]) * 8
            if r["form"] == "LENWHOLE":
                out.append("field  gmti.packet_size  0:%d:%d  uint" % (pos, n))
            else:
                for key, tr in key_of(r, n):
                    out.append("field  %s  0:%d:%d  %s" % (key, pos, n, tr))
            pos += n
    base = pos
    summary = []
    for p in profiles:
        sk = p["segment"]
        out += ["kind  %s" % p["kind"], "requires  %s" % list_key(p["list"]), "when  0:%d:8  %s" % (base, stype[sk])]
        lines = ["field  gmti.segment_size  0:%d:32  uint" % (base + 8)]
        cur = base + 40
        mb = mask_bits[sk]
        refs = p["body"].split(",")
        items = [i.split("/") for i in p["items"].split(",")]
        if mb:
            mask = 0
            for ref in refs + [i[0] for i in items]:
                mask |= 1 << (mb - int(by_ref[(sk, ref)]["bit"]))
            for off in range(0, mb, 32):
                w = min(32, mb - off)
                out.append("when  0:%d:%d  %d" % (cur + off, w, (mask >> (mb - off - w)) & ((1 << w) - 1)))
            cur += mb
        where = {}
        for ref in refs:
            r = by_ref[(sk, ref)]
            n = int(r["bytes"]) * 8
            where[ref] = (cur, n)
            for key, tr in key_of(r, n):
                lines.append("field  %s  0:%d:%d  %s" % (key, cur, n, tr))
            cur += n
        for cond in filter(None, p["when"].split(",")):
            ref, val = cond.split("=")
            out.append("when  0:%d:%d  %s" % (where[ref][0], where[ref][1], val))
        body, ipos = [], 0
        for it in items:
            r = by_ref[(sk, it[0])]
            if len(it) == 2:
                n = int(it[1])
                key = {"H32.1": "scatterer_magnitude", "H32.2": "scatterer_phase"}[it[0]]
                body.append("  field  gmti.%s  0:%d:%d  uint" % (key, ipos, n))
            else:
                n = int(r["bytes"]) * 8
                for key, tr in key_of(r, n):
                    body.append("  field  %s  0:%d:%d  %s" % (key, ipos, n, tr))
            ipos += n
        cpos, clen = where[p["count"]]
        out += lines + ["group  %s  0:%d  item %d  count 0:%d:%d" % (list_key(p["list"]), cur, ipos, cpos, clen)] + body + ["end"]
        summary.append((p, cur // 8, ipos // 8, mask if mb else None))
    return out, summary


