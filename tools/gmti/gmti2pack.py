def write_records_md(summary, rec_out, srec_out):
    for fmt, lines, hdr in (("gmti-records", rec_out, True), ("gmti-segment-records", srec_out, False)):
        t = [HEAD.replace("# ", "<!-- ", 1) + " -->", "", "# " + fmt, "",
             ("One STANAG 4607 packet of one segment" if hdr else "One STANAG 4607 segment (as `gmti-segment` reads it)") +
             " whose repeated records are read as a list: the target",
             "reports of a dwell (`detection.items`, the detections of the dwell), the scatterer records of an HRR segment (`gmti.scatterers`)",
             "and the processing records of a processing history segment (`gmti.records`).",
             "`distribution public`.", "",
         "Layouts from NATO standardization documents published on the NSG Standards Registry; NATO is",
         "acknowledged as their source. They are restated in this project's own words; see PROVENANCE.md.", "",
             "The record count of these segments is not directly before the records, so the sequential layout",
             "of `gmti` cannot read them as a list. This pack uses the fixed layout instead (`word_bytes 1`,",
             "every field at a bit offset), where a group is counted by a field anywhere before it. A fixed",
             "layout needs every field at a fixed place, so each kind is one existence mask: the field sets",
             "of the exploitation classes of the implementation guide (AEDP-4607.1 Annex C). The kind is chosen",
             "by the segment type and the mask (and, for HRR, the sizes of magnitude and phase).", "",
             "| kind | mask | body bytes before the records | record bytes | list | basis |", "|---|---|---|---|---|---|"]
        for p, start, isize, mask in summary:
            m = ("`%x`" % mask) if mask is not None else "none"
            t.append("| `%s` | %s | %d | %d | `%s` | %s |" % (p["kind"], m, start - 37, isize, list_key(p["list"]), p["basis"]))
        t += ["",
              "%d `field` lines. Keys are those of `model/gmti.def` and the detection keys of" %
              sum(1 for l in lines if l.strip().startswith("field")),
              "`tools/gmti/detection.tsv.txt`; the fixed layout reads each field as its raw key and, at the same bits,",
              "as its detection key, so both are present. A target report is one item of `detection.items`, holding",
              "`lat`, `lon`, `hae`, `le`, `track.class`, `track.simulated` and the detection item keys as `gmti` reads",
              "them. The list was `gmti.targets` before the detection module: that list key stays declared in",
              "`model/gmti.def` and is no longer read. What `gmti` leaves unstated (the dwell time as `time_ms`,",
              "`detection.dwell_id`, the dwell area as WKT) is unstated here too: see `gmti/pack.md`.", "",
              "## Mask disagreement in the implementation guide", "",
              "The guide lists the targeting class as 21 dwell fields without the scale factors (62 bytes) and a",
              "19-byte target report with high-resolution positions, and states its mask as `ff c7 1f fa 7f 80 00",
              "00`. That mask sets the scale factors and the reduced-size positions and clears the high-resolution",
              "ones. `dwell-targeting` follows the field table (its mask, computed here, is `ff 07 1f fb 9f 80 00",
              "00`); `dwell-targeting-as-masked` reads a dwell sent with the stated mask. The HRR mask the guide",
              "states for the targeting-with-HRR class (`ff ff f0`) does not match its field table either; the HRR",
              "kinds follow the table.", "",
              "## Not mapped", "",
              "| What | Why |", "|---|---|",
              "| a dwell, HRR segment or processing history with another mask | a fixed layout holds one mask per kind; such a segment is `no-kind` here and is read by `gmti`, first record only |",
              "| the packet size and segment size as lengths | the fixed layout has no length construct: they are raw keys (`gmti.packet_size`, `gmti.segment_size`) written back as decoded, so a list changed in the model needs those keys changed too |",
              "| the record count | written from the number of items (a count locator), and also kept as its raw key |",
              "| an entity from another format | every kind requires its list; a track of another format has no gmti list, so encode is `no-kind` |",
              "| HRR scatterer range and doppler indices | not in the guide's HRR field set (sparse chips are not one of its kinds) |",
              "",
              "## Message convention", "",
              "Hex text, most significant bit first. Vectors are synthetic, packed by `tools/gmti/vectors.py`.", ""]
        with out_open(os.path.join(REPO, "packs", fmt, "pack.md")) as f:
            f.write("\n".join(t))


