#!/usr/bin/env python3
"""catalog-radial: every public format family of packs/ as a radial chart
around the shared model, for the site's first section and for docs/figures.

The shared model is at the centre. The inner ring holds the domains
(tools/catalog-families/_domains.json), one arc each, labelled along the arc;
an arc is at least as wide as its label, so a small domain stays labelled.
Outside it, one bar per family: its length is the logarithm of the family's
pack count, its colour that of its domain. A dashed outer ring with no label
stands for the private overlays, which the same engines read; nothing of any
overlay is named or counted.

It reads the same table and packs/ as tools/catalog-figure.py (its
load_table, pack_names and classify), so it holds every family the figure
holds, with the same counts.

It writes:
  site/index.html     the chart (inline SVG), its legend and a table of every
                      family, between the lines
                        <!-- radial: generated by tools/catalog-radial.py; edit the families, not this -->
                        <!-- /radial -->
  docs/figures/catalog-radial-light.svg, catalog-radial-dark.svg
                      the same chart as a standalone figure, with a key of the
                      domains under it

Usage:
  python3 -I tools/catalog-radial.py            write all three
  python3 -I tools/catalog-radial.py --site     write only the page (site/build.sh
                                                runs it, so a deployed page always
                                                shows the tree it was built from)
  python3 -I tools/catalog-radial.py --check    write nothing; exit 1 when any of
                                                the three differs (the counts pull
                                                request, as catalog-figure --check)

The output depends only on packs/ and the family table: sorted, no timestamp,
fixed decimals, \\n line ends. Standard library only; it reads files and runs
nothing.
"""
import argparse
import importlib.machinery
import importlib.util
import math
import os
import re
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)


def _figure_module():
    loader = importlib.machinery.SourceFileLoader("catalog_figure", os.path.join(HERE, "catalog-figure.py"))
    spec = importlib.util.spec_from_loader("catalog_figure", loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


fig = _figure_module()

START = "<!-- radial: generated by tools/catalog-radial.py; edit the families, not this -->"
END = "<!-- /radial -->"
SITE = os.path.join("site", "index.html")
OUT_NAMES = ("catalog-radial-light.svg", "catalog-radial-dark.svg")

# The domains' colours, in the order of _domains.json. Checked with the
# dataviz palette validator on the ring order (each domain beside the next,
# the last beside the first): every neighbouring pair is at least 9 apart
# (OKLab x100) under protan and deutan simulation and 19 under normal vision,
# light against #f3f5f6 and dark against #0b131a. Colour is never the only
# key: every arc is labelled and the legend names each domain.
COLOURS = {
    "air": ("#2a78d6", "#3987e5"),
    "land": ("#eb6834", "#d95926"),
    "sea": ("#1baf7a", "#199e70"),
    "space": ("#6250d6", "#9085e9"),
    "uncrewed": ("#e34948", "#e66767"),
    "c2": ("#184f95", "#6d8ff0"),
    "sensors": ("#008300", "#0ca30c"),
    "transport": ("#e87ba4", "#d55181"),
    "iot": ("#eda100", "#c98500"),
    "networks": ("#009a8a", "#1fa08f"),
    "maps": ("#a14a1a", "#c77a3a"),
}
# The label on a domain's arc: the first word of its name, unless set here.
SHORT = {"land": "Land", "uncrewed": "Uncrewed", "c2": "C2", "maps": "Maps"}

# The site's own colours (site/assets/site.css), for the standalone figures.
THEMES = {
    "light": {"bg": "#f3f5f6", "ink": "#0f1c26", "quiet": "#47575f", "rule": "#c3ccd2", "core": "#d9e6f6"},
    "dark": {"bg": "#0b131a", "ink": "#e2e9ee", "quiet": "#9fb0bb", "rule": "#2b3a46", "core": "#14304f"},
}

# Geometry, in units of a 680-wide view box centred on (C, C).
VIEW = 680
C = VIEW // 2
R_CORE = 100           # the shared model
R_DOM_IN, R_DOM_OUT = 108, 142
R_LABEL = 122          # baseline of a label on the upper half (inside the arc)
R_BAR0 = 148           # where the bars start
R_BAR_MAX = 300        # the longest family
MIN_BAR = 8            # a family of one pack
R_PRIVATE = 318        # the dashed ring
DOM_GAP = 2.0          # degrees between domains
SCALE_GAP = 7.0        # degrees left open at the top, where the scale is labelled
SCALE_SIZE = 12        # the scale's labels
EX_SIZE = 13           # the worked example's two lines
MARK_R = 10            # a numbered marker (the page only)
MARK_PRIVATE = 225     # where marker 4 sits on the dashed ring, in degrees
BAR_GAP = 0.18         # degrees each side of a bar
LABEL_SIZE = 12
LABEL_PAD = 6          # units of arc beside a label


class RadialError(Exception):
    pass


def short_name(dom):
    return SHORT.get(dom["id"], re.split(r"[ ,]", dom["name"])[0])


def survey(packs_dir, families_dir):
    """-> [{id, name, short, families: [{name, packs}], packs}] in table order."""
    table = fig.load_table(families_dir)
    domains, _ = fig.classify(table, fig.pack_names(packs_dir))
    by_name = {d["name"]: d for d in table["domains"]}
    out = []
    for d in domains:
        meta = by_name[d["name"]]
        if meta["id"] not in COLOURS:
            raise RadialError("the domain %r has no colour in tools/catalog-radial.py" % meta["id"])
        out.append({"id": meta["id"], "name": d["name"], "short": short_name(meta),
                    "families": [{"name": f["name"], "packs": f["packs"]} for f in d["families"]],
                    "packs": sum(f["packs"] for f in d["families"])})
    return out


def allocate(domains):
    """Each domain's arc in degrees: its share of the families, but never
    narrower than its label. -> [(start, end)] clockwise from the top, which
    leaves SCALE_GAP open at the top for the scale's labels."""
    return allocate_full(domains)[0]


def allocate_full(domains):
    """-> ([(start, end)], [True for each domain widened to fit its label])"""
    total_fams = sum(len(d["families"]) for d in domains)
    room = 360.0 - DOM_GAP * (len(domains) - 1) - SCALE_GAP
    mins = []
    for d in domains:
        w = fig.text_width(d["short"], LABEL_SIZE, True) + 2 * LABEL_PAD
        mins.append(math.degrees(w / R_LABEL))
    if sum(mins) > room:
        raise RadialError("the domain labels need %.0f degrees, more than the ring holds" % sum(mins))
    # widen the narrow ones to their minimum and share what is left among the rest
    fixed = [False] * len(domains)
    while True:
        free = room - sum(m for m, f in zip(mins, fixed) if f)
        fams = sum(len(d["families"]) for d, f in zip(domains, fixed) if not f)
        angles = [mins[i] if fixed[i] else free * len(d["families"]) / fams for i, d in enumerate(domains)]
        newly = [i for i, a in enumerate(angles) if not fixed[i] and a < mins[i]]
        if not newly:
            break
        for i in newly:
            fixed[i] = True
    spans, at = [], SCALE_GAP / 2
    for a in angles:
        spans.append((at, at + a))
        at += a + DOM_GAP
    assert abs(at - DOM_GAP + SCALE_GAP / 2 - 360.0) < 1e-6 and total_fams
    return spans, fixed


def pt(r, deg):
    t = math.radians(deg)
    return C + r * math.sin(t), C - r * math.cos(t)


def f2(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


def sector(r0, r1, a0, a1):
    x0, y0 = pt(r1, a0)
    x1, y1 = pt(r1, a1)
    x2, y2 = pt(r0, a1)
    x3, y3 = pt(r0, a0)
    large = 1 if a1 - a0 > 180 else 0
    return "M%s %sA%d %d 0 %d 1 %s %sL%s %sA%d %d 0 %d 0 %s %sZ" % (
        f2(x0), f2(y0), r1, r1, large, f2(x1), f2(y1), f2(x2), f2(y2), r0, r0, large, f2(x3), f2(y3))


def label_arc(a0, a1):
    """A path for a label between a0 and a1: clockwise on the upper half,
    counter-clockwise (so the text stands upright) on the lower half."""
    mid = (a0 + a1) / 2 % 360
    if 90 < mid < 270:
        r = R_LABEL + LABEL_SIZE - 2
        x0, y0 = pt(r, a1)
        x1, y1 = pt(r, a0)
        return "M%s %sA%d %d 0 0 0 %s %s" % (f2(x0), f2(y0), r, r, f2(x1), f2(y1))
    x0, y0 = pt(R_LABEL, a0)
    x1, y1 = pt(R_LABEL, a1)
    return "M%s %sA%d %d 0 0 1 %s %s" % (f2(x0), f2(y0), R_LABEL, R_LABEL, f2(x1), f2(y1))


def bar_length(n, top):
    if top <= 1:
        return R_BAR_MAX - R_BAR0
    return MIN_BAR + (R_BAR_MAX - R_BAR0 - MIN_BAR) * math.log(n) / math.log(top)


def bar_radius(n, top):
    return R_BAR0 + bar_length(n, top)


def scale_values(top):
    """The packs at which a faint ring is drawn: 1, 10, 100, ... up to the
    longest family."""
    out, v = [], 1
    while v <= top:
        out.append(v)
        v *= 10
    return out


def longest(domains):
    """-> (domain index, family index, family) of the family with the most
    packs; the first of them in ring order on a tie."""
    best = None
    for i, d in enumerate(domains):
        for k, f in enumerate(d["families"]):
            if best is None or f["packs"] > best[2]["packs"]:
                best = (i, k, f)
    return best


def example(domains, spans, top):
    """Where the worked example goes: the longest bar, a leader from its tip
    straight up (on the right half) or down (on the left half), so it runs
    beside the smallest families of the domain before it, and two lines of
    text at the edge of the view box. -> dict of the geometry and the text."""
    i, k, f = longest(domains)
    a0, a1 = spans[i]
    step = (a1 - a0) / len(domains[i]["families"])
    theta = a0 + (k + 0.5) * step
    x0, y0 = pt(bar_radius(f["packs"], top) + 4, theta)
    up = theta % 360 < 180
    y_end = 46 if up else VIEW - 46
    lines = (f["name"], "%s pack%s, the longest bar" % (fig.grouped(f["packs"]), "" if f["packs"] == 1 else "s"))
    ys = (16, 38) if up else (VIEW - 30, VIEW - 8)
    right = x0 >= C
    x_text = min(x0 + 20, VIEW - 2) if right else max(x0 - 20, 2)
    width = max(fig.text_width(lines[0], EX_SIZE, True), fig.text_width(lines[1], EX_SIZE))
    if (right and x_text - width < 0) or (not right and x_text + width > VIEW):
        raise RadialError("the worked example %r does not fit beside its leader" % lines[0])
    # marker 3 at the far end of the leader, beside the two lines
    my = y_end + MARK_R + 2 if up else y_end - MARK_R - 2
    return {"domain": domains[i], "family": f, "theta": theta, "x0": x0, "y0": y0, "y_end": y_end,
            "lines": lines, "ys": ys, "x_text": x_text, "anchor": "end" if right else "start",
            "mark": (x0, my)}


def marker(n, x, y):
    return ('<g class="rd-mark" aria-hidden="true"><circle cx="%s" cy="%s" r="%d"/>'
            '<text x="%s" y="%s" class="rd-mark-t" text-anchor="middle" dy="0.35em">%d</text></g>'
            % (f2(x), f2(y), MARK_R, f2(x), f2(y), n))


def domain_marker_at(domains, spans):
    """Marker 2 sits on the inner ring of the domain with the most free arc
    beside its label, between the end of the label and the end of the arc.
    -> (domain index, angle)."""
    best = None
    for i, (d, (a0, a1)) in enumerate(zip(domains, spans)):
        half = math.degrees((fig.text_width(d["short"], LABEL_SIZE, True) + 2 * LABEL_PAD) / 2 / R_LABEL)
        free = (a1 - a0) / 2 - half
        if best is None or free > best[0]:
            best = (free, i, (a0 + a1) / 2 + half + free / 2)
    r_mid = (R_DOM_IN + R_DOM_OUT) / 2
    if math.radians(best[0]) * r_mid < 2 * MARK_R:
        raise RadialError("no domain's arc has room beside its label for the marker")
    return best[1], best[2]


def tip(fam, dom):
    return "%s: %s pack%s (%s)" % (fam["name"], fig.grouped(fam["packs"]), "" if fam["packs"] == 1 else "s", dom["name"])


def totals(domains):
    fams = sum(len(d["families"]) for d in domains)
    packs = sum(d["packs"] for d in domains)
    return fams, packs


def chart(domains, ids, interactive):
    """The SVG elements of the chart (no <svg> element). `ids` prefixes the
    ids of the label paths, so two copies can share a page."""
    spans = allocate(domains)
    top = max(f["packs"] for d in domains for f in d["families"])
    fams, packs = totals(domains)
    scale = scale_values(top)
    ex = example(domains, spans, top)
    out = ['<circle cx="%d" cy="%d" r="%d" class="rd-private"/>' % (C, C, R_PRIVATE)]
    # the log scale: a faint ring at 1, 10, 100 ... packs, under the bars
    out += ['<circle cx="%d" cy="%d" r="%s" class="rd-scale"/>' % (C, C, f2(bar_radius(v, top))) for v in scale]
    out += ['<circle cx="%d" cy="%d" r="%d" class="rd-core"/>' % (C, C, R_CORE),
           '<text x="%d" y="%d" class="rd-t rd-core-t" text-anchor="middle">shared</text>' % (C, C - 4),
           '<text x="%d" y="%d" class="rd-t rd-core-t" text-anchor="middle">model</text>' % (C, C + 16)]
    first = True
    for i, (d, (a0, a1)) in enumerate(zip(domains, spans)):
        out.append('<path d="%s" class="rd-dom rd-%s"/>' % (sector(R_DOM_IN, R_DOM_OUT, a0, a1), d["id"]))
        pid = "%s-l%d" % (ids, i)
        out.append('<path id="%s" d="%s" fill="none"/>' % (pid, label_arc(a0, a1)))
        out.append('<text class="rd-t rd-dom-t"><textPath href="#%s" startOffset="50%%" text-anchor="middle">%s</textPath></text>'
                   % (pid, escape(d["short"])))
        step = (a1 - a0) / len(d["families"])
        for k, f in enumerate(d["families"]):
            b0, b1 = a0 + k * step + BAR_GAP, a0 + (k + 1) * step - BAR_GAP
            r1 = R_BAR0 + bar_length(f["packs"], top)
            text = tip(f, d)
            if interactive:
                out.append('<path d="%s" class="rd-bar rd-%s" tabindex="%d" role="img" aria-label="%s" data-tip="%s"><title>%s</title></path>'
                           % (sector(R_BAR0, r1, b0, b1), d["id"], 0 if first else -1,
                              escape(text, {'"': "&quot;"}), escape(text, {'"': "&quot;"}), escape(text)))
                first = False
            else:
                out.append('<path d="%s" class="rd-bar rd-%s"><title>%s</title></path>' % (sector(R_BAR0, r1, b0, b1), d["id"], escape(text)))
    # the scale's labels, up the open spoke at the top, over everything
    for v in scale:
        out.append('<text x="%d" y="%s" class="rd-t rd-scale-t" text-anchor="middle" dy="0.35em">%s</text>'
                   % (C, f2(C - bar_radius(v, top)), fig.grouped(v) + (" packs" if v == scale[-1] and v > 1 else "")))
    # the worked example: the longest bar, named, with its pack count
    lead_end = ex["mark"][1] + (MARK_R if ex["y_end"] < C else -MARK_R) if interactive else ex["y_end"]
    out.append('<path d="M%s %sV%s" class="rd-lead"/>' % (f2(ex["x0"]), f2(ex["y0"]), f2(lead_end)))
    out.append('<text class="rd-t rd-ex-t" text-anchor="%s"><tspan x="%s" y="%d" class="rd-ex-name">%s</tspan><tspan x="%s" y="%d">%s</tspan></text>'
               % (ex["anchor"], f2(ex["x_text"]), ex["ys"][0], escape(ex["lines"][0]), f2(ex["x_text"]), ex["ys"][1], escape(ex["lines"][1])))
    if interactive:
        _, ang = domain_marker_at(domains, spans)
        out.append(marker(1, C, C - 44))
        out.append(marker(2, *pt((R_DOM_IN + R_DOM_OUT) / 2, ang)))
        out.append(marker(3, *ex["mark"]))
        out.append(marker(4, *pt(R_PRIVATE, MARK_PRIVATE)))
    return out, fams, packs


def colour_css(theme_index):
    return " ".join(".rd-%s{--rd:%s}" % (k, v[theme_index]) for k, v in COLOURS.items())


def and_list(items):
    items = list(items)
    if len(items) < 2:
        return "".join(items)
    return "%s and %s" % (", ".join(items[:-1]), items[-1])


def key_items(domains):
    """The four entries of "How to read it", numbered as the markers on the
    chart. Each states what the code draws, with the tree's numbers."""
    fams, _ = totals(domains)
    top = max(f["packs"] for d in domains for f in d["families"])
    _, _, best = longest(domains)
    fixed = allocate_full(domains)[1]
    free = [escape(d["short"]) for d, f in zip(domains, fixed) if not f]
    if not any(fixed):
        arc = "Arc width: its share of the %d families." % fams
    elif free:
        arc = ("Arc width is mostly not a count: each arc fits its label, and only %s %s wider, by number of "
               "families." % (and_list(free), "is" if len(free) == 1 else "are"))
    else:
        arc = "Arc width is not a count: each arc fits its label."
    rings = and_list(fig.grouped(v) for v in scale_values(top))
    return [
        "<b>Center: the shared model.</b> Every format converts through it.",
        "<b>Inner ring: a domain,</b> the color of its bars and its legend square. "
        + arc,
        "<b>A bar: one family,</b> largest first, clockwise. Length: its packs on a log scale, read against the "
        "faint rings at %s. The longest: %s, %s pack%s." % (rings, escape(best["name"]), fig.grouped(best["packs"]),
                                                             "" if best["packs"] == 1 else "s"),
        "<b>Dashed ring: private overlays</b> plug in here; the same engines read them. None is drawn or counted.",
    ]


def site_block(domains):
    els, fams, packs = chart(domains, "rd", True)
    nd = len(domains)
    top = max(f["packs"] for d in domains for f in d["families"])
    _, _, best = longest(domains)
    desc = ("%s public formats in %d families and %d domains, drawn around the shared model: one bar per family, "
            "its length the logarithm of its pack count, read against faint rings at %s packs, coloured by domain. "
            "The longest bar is %s, %s packs. A dashed outer ring stands for private overlays."
            % (fig.grouped(packs), fams, nd, and_list(fig.grouped(v) for v in scale_values(top)),
               best["name"], fig.grouped(best["packs"])))
    lines = [START,
             '<section id="catalog" class="catalog" aria-labelledby="h-catalog">',
             '  <div class="wrap">',
             '    <p class="tag">The catalog</p>',
             '    <h2 id="h-catalog">%s formats in %d families, one shared model</h2>' % (fig.grouped(packs), fams),
             '    <div class="radial">',
             '      <figure class="radial-fig">',
             '        <div class="radial-key">',
             '          <p class="radial-key-h" id="rd-key-h">How to read it</p>',
             '          <ol class="radial-key-list" aria-labelledby="rd-key-h">']
    for n, text in enumerate(key_items(domains), 1):
        lines.append('            <li><span class="rk-n" aria-hidden="true">%d</span><span>%s</span></li>' % (n, text))
    lines += ['          </ol>',
             '        </div>',
             '        <div class="radial-chart">',
             '          <svg viewBox="0 0 %d %d" role="group" aria-labelledby="rd-title" aria-describedby="rd-desc" id="rd-svg">' % (VIEW, VIEW),
             '            <title id="rd-title">Every public format family, by domain</title>',
             '            <desc id="rd-desc">%s</desc>' % escape(desc),
             '            <style>%s @media (prefers-color-scheme: dark){%s}</style>' % (colour_css(0), colour_css(1))]
    lines += ["            " + e for e in els]
    lines += ['          </svg>',
              '          <div class="radial-tip" id="rd-tip" role="status" aria-live="polite" hidden></div>',
              '        </div>',
              '        <figcaption>Hover over a bar, or focus the chart and use the arrow keys, for its family and '
              'number of packs. The table under the chart lists every family.</figcaption>',
              '      </figure>',
              '      <ul class="radial-legend">']
    for d in domains:
        top3 = ", ".join("%s %s" % (escape(f["name"]), fig.grouped(f["packs"])) for f in d["families"][:3])
        lines.append('        <li class="rd-%s"><span class="rl-sw" aria-hidden="true"></span><span class="rl-text"><b>%s</b> <span class="rl-count">%d famil%s, %s pack%s</span><span class="rl-top">%s</span></span></li>'
                     % (d["id"], escape(d["name"]), len(d["families"]), "y" if len(d["families"]) == 1 else "ies",
                        fig.grouped(d["packs"]), "" if d["packs"] == 1 else "s", top3))
    lines += ['      </ul>',
              '    </div>',
              '    <details class="radial-table">',
              '      <summary>Every family as a table</summary>',
              '      <div class="table-scroll"><table>',
              '        <thead><tr><th scope="col">Domain</th><th scope="col">Family</th><th scope="col" class="n">Packs</th></tr></thead>',
              '        <tbody>']
    for d in domains:
        for f in d["families"]:
            lines.append('          <tr><td>%s</td><td>%s</td><td class="n">%s</td></tr>'
                         % (escape(d["name"]), escape(f["name"]), fig.grouped(f["packs"])))
    lines += ['        </tbody>',
              '      </table></div>',
              '    </details>',
              '  </div>',
              '</section>',
              END]
    return "\n".join(lines)


def standalone(domains, theme):
    c = THEMES[theme]
    ti = 0 if theme == "light" else 1
    els, fams, packs = chart(domains, "rd-" + theme, False)
    head = 64
    key_top = head + VIEW + 4
    cols, row_h = 2, 22
    rows = -(-len(domains) // cols)
    caption_y = key_top + rows * row_h + 18
    height = caption_y + 24
    title = "Every public format, by family: %d families, %s formats" % (fams, fig.grouped(packs))
    desc = ("One bar per family around the shared model, its length the logarithm of its pack count, coloured by "
            "domain. A dashed outer ring stands for private overlays, which the same engines read.")
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="100%%" role="img" aria-labelledby="t d">' % (VIEW, height),
           '<title id="t">%s</title>' % escape(title),
           '<desc id="d">%s</desc>' % escape(desc),
           "<style>",
           "  .rd-bg{fill:%s} .rd-t{font-family:%s;fill:%s}" % (c["bg"], fig.FONT, c["ink"]),
           "  .rd-q{fill:%s}" % c["quiet"],
           "  .rd-core{fill:%s} .rd-core-t{font-size:15px;font-weight:600}" % c["core"],
           "  .rd-dom{fill:var(--rd);fill-opacity:.22} .rd-dom-t{font-size:%dpx;font-weight:700}" % LABEL_SIZE,
           "  .rd-bar{fill:var(--rd)}",
           "  .rd-private{fill:none;stroke:%s;stroke-width:1.5;stroke-dasharray:6 6}" % c["quiet"],
           "  .rd-sw{fill:var(--rd)}",
           "  .rd-scale{fill:none;stroke:%s;stroke-width:1}" % c["rule"],
           "  .rd-scale-t{font-size:%dpx;fill:%s;paint-order:stroke;stroke:%s;stroke-width:4px;stroke-linejoin:round}" % (SCALE_SIZE, c["quiet"], c["bg"]),
           "  .rd-lead{fill:none;stroke:%s;stroke-width:1}" % c["ink"],
           "  .rd-ex-t{font-size:%dpx} .rd-ex-name{font-weight:700}" % EX_SIZE,
           "  %s" % colour_css(ti),
           "</style>",
           '<rect x="0" y="0" width="%d" height="%d" class="rd-bg"/>' % (VIEW, height),
           '<text x="20" y="30" class="rd-t" font-size="18" font-weight="700">%s</text>' % escape(title),
           '<text x="20" y="50" class="rd-t rd-q" font-size="13">Bar length: the pack count on a log scale, read against the faint rings; colour: the domain.</text>',
           '<g transform="translate(0 %d)">' % head]
    out += els
    out.append("</g>")
    colw = (VIEW - 40) // cols
    for i, d in enumerate(domains):
        x = 20 + (i % cols) * colw
        y = key_top + (i // cols) * row_h
        out.append('<rect x="%d" y="%d" width="12" height="12" rx="2" class="rd-sw rd-%s"/>' % (x, y + 2, d["id"]))
        label = "%s %s" % (d["name"], fig.grouped(d["packs"]))
        if fig.text_width(label, 13) > colw - 22:
            raise RadialError("the key line %r is wider than its column" % label)
        out.append('<text x="%d" y="%d" class="rd-t" font-size="13">%s <tspan class="rd-q">%s</tspan></text>'
                   % (x + 18, y + 12, escape(d["name"]), fig.grouped(d["packs"])))
    out.append('<text x="20" y="%d" class="rd-t rd-q" font-size="13">The dashed outer ring: private overlays plug in here: the same engines read them.</text>' % caption_y)
    out.append("</svg>")
    return "\n".join(out) + "\n"


def splice(page, block):
    if page.count(START) != 1 or page.count(END) != 1:
        raise RadialError("%s must hold the line %s once and the line %s once" % (SITE, START, END))
    a = page.index(START)
    b = page.index(END) + len(END)
    return page[:a] + block + page[b:]


def outputs(root, packs_dir, families_dir):
    domains = survey(packs_dir, families_dir)
    with open(os.path.join(root, SITE), encoding="utf-8") as fh:
        page = fh.read()
    files = {SITE: splice(page, site_block(domains))}
    for name, theme in zip(OUT_NAMES, ("light", "dark")):
        files[os.path.join("docs", "figures", name)] = standalone(domains, theme)
    return domains, files


def main(argv=None, root=REPO):
    ap = argparse.ArgumentParser(prog="catalog-radial", description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="write nothing; exit 1 when an output differs")
    mode.add_argument("--site", action="store_true", help="write only site/index.html")
    ap.add_argument("--packs", default=None, help=argparse.SUPPRESS)
    ap.add_argument("--families", default=None, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    packs_dir = args.packs or os.path.join(root, "packs")
    families_dir = args.families or os.path.join(root, "tools", "catalog-families")
    try:
        domains, files = outputs(root, packs_dir, families_dir)
    except (fig.CatalogError, RadialError, OSError) as e:
        print("catalog-radial: %s" % e, file=sys.stderr)
        return 1
    if args.site:
        files = {SITE: files[SITE]}
    if args.check:
        stale = []
        for rel, text in files.items():
            try:
                with open(os.path.join(root, rel), "rb") as fh:
                    same = fh.read() == text.encode("utf-8")
            except OSError:
                same = False
            if not same:
                stale.append(rel)
        if stale:
            print("catalog-radial: %s differ%s from what it would write; run python3 -I tools/catalog-radial.py"
                  % (", ".join(stale), "s" if len(stale) == 1 else ""), file=sys.stderr)
            return 1
        print("catalog-radial: the chart is up to date")
        return 0
    for rel, text in files.items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    fams, packs = totals(domains)
    print("catalog-radial: wrote %s (%d families, %s formats)" % (", ".join(sorted(files)), fams, fig.grouped(packs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
