def build(sink):
    written, counters = {}, {}
    here = os.path.dirname(os.path.dirname(HERE))
    model = gtcheck.Model()
    for name in ("core", "probe"):
        with open(os.path.join(here, "model", name + ".def"), encoding="utf-8") as fh:
            model.add(fh.read(), name)
    for name, text in PACKS.items():
        gtcheck.load_pack(text, model, name)
        sink.write("packs/%s/pack.def" % name, text)
        written[name] = 1

    def vec(frm, to, name, inp, expect=None, error=None, model=None, ref=""):
        got = failed = None
        ent = {}
        try:
            ent, run = convert(frm, to, inp)
            got = run()
        except Fail as e:
            failed = e.kind
        assert (got, failed) == (expect, error), (frm, to, name, expect, error, got, failed)
        for k, v in (model or {}).items():
            if k == "@absent":
                assert not set(v) & set(ent), (name, v)
            elif k == "@inner_kind":
                assert ent[k][1] == v, name
            elif k.endswith(".#"):
                assert str(len(ent[k[:-2]])) == v, (name, k)
            else:
                assert str(ent[k]) == v, (name, k, v, ent.get(k))
        d = {"name": name, "from": frm, "to": to, "input": inp}
        d.update({"expect_error": error} if error else {"expect": expect})
        if model:
            d["model"] = model
        d["source"] = "constructed"
        d["reference"] = ref
        counters[frm] = counters.get(frm, 0) + 1
        sink.write("packs/%s/vectors/%02d-%s.json" % (frm, counters[frm], name),
                   json.dumps(d, indent=2, ensure_ascii=False) + "\n")
        written[frm] += 1

    def rt(p, name, inp, expect=None, **kw):
        vec(p, p, name, inp, expect, **kw)

    def enc(p, name, inp, expect=None, **kw):
        vec(A + "json", p, p[len("conformance-"):] + "-" + name, inp, expect, **kw)
    MW, TE, NK = "malformed-wire", "transform-encode", "no-kind"

    # ==== `as ... optional` on either side, on two keys
    K = "spec 0.52 Choosing the kind, for the outer and for the inner pack; "
    c = A + "opt"
    enc(c, "both-keys-absent", '{"y":7}', "020107", ref=K + "both terms hold; each writes its own first value")
    rt(c, "decode-and-round-trip", "050107", "050107", model={"@kind": "only", "@inner_kind": "p", "probe.w": "5", "probe.x": "1", "probe.y": "7"},
       ref="spec 0.34 Decode: each label sets its own key")
    enc(c, "both-keys-held", '{"w":5,"x":2,"y":7}', "050207", ref=K + "5 and 2 match")
    enc(c, "outer-key-not-matching", '{"w":9,"x":2,"y":7}', error=NK, ref=K + "w = 9 fails the outer term")
    enc(c, "inner-key-not-matching", '{"w":5,"x":9,"y":7}', error=NK, ref=K + "x = 9 fails the inner term")
    vec(A + "in-opt", c, "inner-to-outer", "0207", "020207", ref="spec 0.34 Conversion: Entity.kind p is kept; w is absent: 2")
    vec(c, A + "in-opt", "outer-to-inner", "050107", "0107", ref="spec 0.34 Conversion: Entity.inner_kind p is kept")
    c = A + "opt-outer-req"
    enc(c, "outer-key-absent", '{"x":2,"y":7}', error=NK, ref="spec 0.30: the outer kind, not optional, needs w")
    enc(c, "outer-key-held", '{"w":2,"y":7}', "020107", ref=K + "w = 2 matches; x is absent: 1")
    c = A + "opt-inner-req"
    enc(c, "inner-key-absent", '{"w":2,"y":7}', error=NK, ref="spec 0.30: the inner kind, not optional, needs x")
    enc(c, "inner-key-held", '{"x":2,"y":7}', "020207", ref=K + "w is absent: 2; x = 2 matches")
    rt(c, "recorded-inner-kind", "050107", "050107", model={"@inner_kind": "p"}, ref="spec 0.34 ruling 10: a kind recorded")

    # ==== a kind with `inner` chosen by `as … optional`
    c = A + "choose"
    C = "spec 0.52 Choosing the kind: "
    enc(c, "key-absent-first-kind", '{"y":5}', "0105", ref=C + "a: x is absent, y held; the inner pack in-y")
    enc(c, "key-absent-second-kind", '{"z":6}', "0206", ref=C + "a requires y; b: the inner pack in-z")
    enc(c, "key-held", '{"x":2,"y":5,"z":6}', "0206", ref=C + "x = 2 fails a; b")
    enc(c, "key-held-requires-fails", '{"x":2,"y":5}', error=NK, ref=C + "x = 2 fails a; b requires z")
    rt(c, "decode-and-round-trip", "0206", "0206", model={"@kind": "b", "probe.x": "2", "probe.z": "6", "@absent": ["@inner_kind", "probe.y"]},
       ref="spec 0.34 Decode: b's inner pack; it has no kinds, so no inner kind is recorded")

    # ==== a switch after a window, before an `inner` line
    c = A + "switch-n"
    W = "spec 0.52 ruling 9 and 0.33 Encode: the window settles before the switch; then the `inner` line; "
    enc(c, "key-absent-standing-bits", '{"w":2,"z":6,"n":9}', "020609", ref=W + "w's 02 stands: case 2, z")
    enc(c, "key-absent-first-value", '{"y":5,"z":6,"n":9}', "010509", ref=W + "w is absent: 1, case 1, y")
    enc(c, "key-held", '{"x":2,"z":6,"n":9}', "020609", ref=W + "x = 2 is written: case 2, z")
    rt(c, "decode-and-round-trip", "020609", "020609", model={"@kind": "a", "probe.x": "2", "probe.w": "2", "probe.z": "6", "probe.n": "9"},
       ref="spec 0.33 and 0.34 Decode: the bytes after the switch are the inner input")
    # ==== rulings 18 and 19 for a fixed inner pack
    P = "spec 0.52 ruling 18 and 0.34 ruling 14: the empty group of the inner pack counts up to its start, byte 4; "
    L = "spec 0.34 Decode step 3: bytes after the inner message's end; "
    Q = "spec 0.34 ruling 18: `partial` ignores them, and they do not come back; "
    NO = {"probe.items.#": "0", "probe.n": "5"}
    for tail in ("", "-partial"):
        c = E + "base" + tail
        rt(c, "inner-input-ends-before-the-start", "070500", error=MW, ref=P + "ruling 15 of 0.34: whether it is an error is the inner pack's rule: malformed-wire")
        rt(c, "inner-input-one-byte-short", "07050000", error=MW, ref=P + "3 bytes of 4")
        rt(c, "empty-list", "0705000000", "0705000000", model=NO, ref=P + "nothing is left over")
        rt(c, "bytes-no-line-writes", "0705001122", "0705000000", model=NO, ref=P + "they lie before the end and are not left over; encode writes zero bits")
        if tail:
            rt(c, "byte-after-the-start", "0705000000aa", "0705000000", model=NO, ref=P + Q)
        else:
            rt(c, "byte-after-the-start", "0705000000aa", error=MW, ref=P + L)
        rt(c, "one-item", "0705010000aa", "0705010000aa", model={"probe.items.#": "1"}, ref="spec 0.34 ruling 14: the items count")
        enc(c, "absent-list", '{"x":7,"n":5}', "0705000000", ref=P + "encode writes up to the start")
    Z = "spec 0.52 ruling 19 and 0.34 ruling 14: no counted bit, the end is 0; "
    X = {"probe.x": "7", "@absent": ["probe.y"]}
    Y = {"probe.x": "7", "probe.y": "7"}
    for tail in ("", "-partial"):
        def left(c, name, inp, expect, model, ref):
            if tail:
                rt(c, name, inp, expect, model=model, ref=ref + Q)
            else:
                rt(c, name, inp, error=MW, ref=ref + L)
        c = E + "gate" + tail
        rt(c, "empty-inner-input", "07", "07", model=X, ref=Z + "nothing is left over (ruling 16 of 0.34); encode writes none")
        left(c, "unheld-gate-bits-are-left-over", "0700", "07", X, Z + "the gate bits of a block that does not hold do not count; ")
        left(c, "unheld-gate-longer-input", "070207", "07", X, Z)
        rt(c, "held-gate", "070107", "070107", model=Y, ref="spec 0.34 ruling 14: a held block's lines and gate locator count: 2 bytes")
        rt(c, "held-gate-inner-input-short", "0701", error=MW, ref="spec 0.17 Decode: y of the held block is missing")
        left(c, "held-gate-byte-after-the-end", "070107aa", "070107", Y, "spec 0.34 ruling 14: the end is 2; ")
        enc(c, "without-the-key", '{"x":7}', "07", ref=Z + "encode writes none")
        enc(c, "with-the-key", '{"x":7,"y":7}', "070107", ref="spec 0.17 Encode: the block is open")
        c = E + "gate-words" + tail
        rt(c, "empty-inner-input", "07", "07", model=X, ref=Z + "no smallest length of one word")
        left(c, "unheld-gate-one-word", "0700000000", "07", X, Z + "the whole word is left over; ")
