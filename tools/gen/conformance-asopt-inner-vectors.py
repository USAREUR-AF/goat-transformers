Fail = ASOPT.Fail


def seq_pack(name):
    """The parsed pack, and {kind name or None: (inner format, partial)}."""
    kept, inner, kind = [], {}, None
    for raw in PACKS[name].splitlines():
        t = raw.split("#")[0].split()
        if t[:1] == ["kind"]:
            kind = t[1]
        if t[:1] == ["inner"]:
            inner[kind] = (t[1], t[2:] == ["partial"])
        else:
            kept.append(raw)
    return ASOPT.parse_pack("\n".join(kept)), inner


def of_inner(name):
    """(codec, its pack name) of a fixed inner pack, or None for a pack here."""
    if name.startswith(NOWORD.PREFIX):
        return NOWORD, name[len(NOWORD.PREFIX):]
    if name.startswith(EMPTY.PREFIX):
        return EMPTY, name[len(EMPTY.PREFIX):]
    return None


def inner_end(module, pack, data, hexed):
    """0.34 ruling 14: the fixed inner message's end in bytes."""
    if module is EMPTY:
        return -(-EMPTY.dec_scope(pack, EMPTY.to_bits(pack, hexed), 0, pack["lines"], {}) // 8)
    end = 0
    held = pack["gate"] is not None and NOWORD.read(data, *pack["gate"][0]) == pack["gate"][1]
    if held:
        end = sum(pack["gate"][0])
    for _, span, _, gated in pack["fields"]:
        if held or not gated:
            end = max(end, sum(span))
    return NOWORD.words(pack, end)


def decode_inner(name, hexed, partial):
    data, kind = bytes.fromhex(hexed), None
    fixed = of_inner(name)
    if fixed:
        module, short = fixed
        pack = module.parse(module.PACKS[short])
        try:
            ent = module.decode(pack, hexed)
        except module.Fail as e:
            raise Fail(str(e))
        end = inner_end(module, pack, data, hexed)
    else:
        pack, _ = seq_pack(name)
        bits, ent = "".join(format(b, "08b") for b in data), {}
        end = -(-ASOPT.dec_body(bits, 0, pack, ent) // 8)
        kind = ent.pop("@kind", None)
    if len(data) > end and not partial:
        raise Fail("malformed-wire")
    return ent, kind


def after_pack(name):
    """The parts of a pack `after` wrote, or None."""
    rows = [r.split("#")[0].split() for r in PACKS[name].splitlines()]
    rows = [r for r in rows if r]
    if ["length", "8"] not in rows:
        return None
    p = {"when": None, "arms": []}
    for t in rows:
        if t[0] == "inner":
            p["inner"] = t[1]
        elif t[0] == "kind":
            p["kind"] = t[1]
        elif t[0] == "when":
            p["when"] = {"ranges": [(int(v), int(v)) for v in t[2].split(",")], "optional": t[-1] == "optional"}
        elif t[0] == "switch":
            p["key"] = t[1]
        elif t[0] in ("case", "else"):
            p["arms"].append([t[1] if t[0] == "case" else None, None])
        elif t[0] == "field" and p["arms"]:
            p["arms"][-1][1] = t[1]
    return p


def arm_of(p, value):
    arm = next((k for v, k in p["arms"] if v is None or v == str(value)), None)
    if arm is None:
        raise Fail("no-kind")
    return arm


def after_decode(p, text):
    data = bytes.fromhex(text)
    if len(data) < 1 or len(data) < data[0] + 3:
        raise Fail("malformed-wire")
    end = 1 + data[0]
    ent, kind = decode_inner(p["inner"], data[1:end].hex(), False)
    if kind:
        ent["@inner_kind"] = (p["inner"], kind)
    if p["when"]:
        if not ASOPT.matches(data[end], p["when"]):
            raise Fail("no-kind")
        ent["@kind"] = p["kind"]
    ent.setdefault(p["key"], data[end])
    ent.setdefault(arm_of(p, ent[p["key"]]), data[end + 1])
    return ent


def after_encode(p, ent, same, inner_kind):
    key, w = p["key"], p["when"]
    if w and not (same and "@kind" in ent):
        if not (ASOPT.matches(ent[key], w) if key in ent else w["optional"]):
            raise Fail("no-kind")
    sub = {k: v for k, v in ent.items() if k != "@kind"}
    if inner_kind and inner_kind[0] == p["inner"]:
        sub["@kind"] = inner_kind[1]
    text = encode(p["inner"], sub, "@kind" in sub, None)
    value = ent.get(key, w["ranges"][0][0] if w else 0)
    if w and not ASOPT.matches(value, w):
        raise Fail("transform-encode")
    arm = arm_of(p, value)
    return "%02x%s%02x%02x" % (len(text) // 2, text, value, ent.get(arm, 0))


def decode(name, text):
    p = after_pack(name)
    if p:
        return after_decode(p, text)
    pack, inner = seq_pack(name)
    if pack["json"]:
        return ASOPT.decode(pack, text)
    bits = "".join(format(b, "08b") for b in bytes.fromhex(text))
    ent, at = {}, 0
    for w in [n for n in pack["common"] if n["d"] == "when"]:   # a common `when`, here always first
        if at + w["n"] > len(bits) or not ASOPT.matches(int(bits[at:at + w["n"]], 2), w):
            raise Fail("no-kind")
        ent[w["as"]] = int(bits[at:at + w["n"]], 2)
        at += w["n"]
    pack["common"] = [n for n in pack["common"] if n["d"] != "when"]
    pos = ASOPT.dec_body(bits, at, pack, ent)
    line = inner.get(ent.get("@kind"))
    if line:
        assert pos % 8 == 0
        sub, kind = decode_inner(line[0], text[pos // 4:], line[1])
        assert not set(sub) & set(ent)  # 0.52 ruling 20
        ent.update(sub)
        if kind:
            ent["@inner_kind"] = (line[0], kind)
    return ent


def encode(name, ent, same, inner_kind):
    p = after_pack(name)
    if p:
        return after_encode(p, ent, same, inner_kind)
    pack, inner = seq_pack(name)
    if pack["json"]:
        return ASOPT.encode(pack, ent, False)
    out = ASOPT.Out()
    chosen = None
    if pack["kinds"]:
        recorded = ent.get("@kind") if same else None
        chosen = next((k["name"] for k in pack["kinds"] if (k["name"] == recorded if recorded else ASOPT.qualifies(k, ent))), None)
    ASOPT.enc_body(out, pack, ent, same)
    assert len(out.bits) % 8 == 0
    text = "".join("%02x" % int("".join(out.bits[i:i + 8]), 2) for i in range(0, len(out.bits), 8))
    line = inner.get(chosen)
    if not line:
        return text
    fixed = of_inner(line[0])
    if fixed:
        module, short = fixed
        try:
            args = (False,) if module is EMPTY else ()
            return text + module.encode(module.parse(module.PACKS[short]), ent, *args)
        except module.Fail as e:
            raise Fail(str(e))
    sub = {k: v for k, v in ent.items() if k != "@kind"}
    if inner_kind and inner_kind[0] == line[0]:
        sub["@kind"] = inner_kind[1]
    return text + encode(line[0], sub, "@kind" in sub, None)


def convert(frm, to, text):
    ent = decode(frm, text)
    kind = ent.get("@inner_kind")
    if not kind and "@kind" in ent and frm != to:
        kind = (frm, ent["@kind"])      # Conversion: kept when `to` holds this format
    return ent, lambda: encode(to, ent, frm == to, kind)


