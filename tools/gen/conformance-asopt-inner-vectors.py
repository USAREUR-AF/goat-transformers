#!/usr/bin/env python3
"""Write the vectors of spec 0.52 with inner packs (0.34): the packs
`conformance-asopt-inner-*` (`as ... optional` on either side of an `inner`
line, on two keys; a kind with an `inner` line; a switch before and after one;
the error order of a window and an `inner` line) and
`conformance-emptygroup-inner-*` (rulings 18 and 19 of an inner pack of a fixed
layout). No pair shares a key: 0.52 ruling 20 refuses that, and
conformance-inner-refused-vectors.py pins it.

Every expected value is worked out by hand from the spec text (0.34 Decode,
Encode and rulings 1 to 23; 0.52 rulings 1 to 19; the sections they cite). The
working is each vector's `reference`; the value is written out literally. The
second computation takes one pack's codec from conformance-asopt-vectors.py
(sequential packs), conformance-emptygroup-vectors.py and
conformance-noword-vectors.py (fixed inner packs) and adds the layer here:
decode, the leftover check, the joining of keys, and encode. It covers only the
lines these packs use. Each pack is loaded with tools/gen/gtcheck.py. Nothing
here imports or calls an engine.

Inner packs of `conformance-emptygroup-inner-*` are the packs
`conformance-emptygroup-base` and `conformance-noword-*`.

Inputs: model/core.def and model/probe.def, and the three generators named
above. With --check nothing is written and the exit status is 1 when a committed
file differs from what this writes.

Usage: python3 -I tools/gen/conformance-asopt-inner-vectors.py [--out DIR] [--check]
"""
