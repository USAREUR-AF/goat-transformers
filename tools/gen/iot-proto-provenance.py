def module_of(pack):
    return pack.replace("-", "")


def render(pack, fam):
    names = "tools/gen/names/%s.json" % pack
    out = [
        "SPDX licence: %s" % fam["spdx"],
        "",
    ]
    if fam.get("restated"):
        out += [
            "This repository's restatement is Apache-2.0; the source files are under the %s, "
            "whose notice is in `NOTICE`. No code is copied." % fam["restated"],
            "",
        ]
    out += [
        "# Provenance of the schema sources",
        "",
        "Pack `%s` and module `%s` are generated by `tools/gen/proto2pack.py` (run script "
        "`%s`) from the files below. The files are not kept in this repository."
        % (pack, module_of(pack), fam["run"]),
        "",
        "## %s" % fam["title"],
        "",
        "| | |",
        "|---|---|",
        "| Repository | %s |" % fam["repo"],
        "| Version | %s |" % fam["version"],
        "| Files read by the generator | %s |" % fam["files"],
        "| Fetched from | %s |" % fam["fetched"],
        "| Date read | %s |" % DATE_READ,
        "",
        "## License statements at that commit",
        "",
    ]
    out += fam["license"]
    out += [
        "",
        "## What this repository holds from those files",
        "",
        "The generator is run with `--no-comments`. The pack, the module `%s`, the names file "
        "`%s` and the generated vectors record field numbers, message and field names, enum "
        "value names and numbers, and field types, and nothing else from those files: no "
        "comment and no line of a file. The notes in pack.md (`%s`) are this repository's own "
        "words. The values in the vectors are made by the generator, which checks each one "
        "with its own protobuf codec." % (module_of(pack), names, fam["notes"]),
    ]
    if fam["extra"]:
        out += ["", fam["extra"]]
    out += ["", "## SHA-256", "", "```"]
    out += ["%s  %s" % s for s in fam["sums"]]
    out += ["```", ""]
    return "\n".join(out)


def main(argv):
    check = False
    if argv and argv[0] == "--check":
        check, argv = True, argv[1:]
    if len(argv) != 1:
        sys.stderr.write("usage: iot-proto-provenance.py [--check] <checkout>\n")
        return 2
    packs = os.path.join(argv[0], "packs")
    differs = 0
    count = 0
    for pack in sorted(os.listdir(packs)):
        fam = next((f for p, f in FAMILIES.items() if pack.startswith(p)), None)
        if fam is None or not os.path.isfile(os.path.join(packs, pack, "pack.def")):
            continue
        count += 1
        path = os.path.join(packs, pack, "PROVENANCE.md")
        text = render(pack, fam)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                old = fh.read()
        if old == text:
            continue
        if check:
            sys.stderr.write("differs: %s\n" % path)
            differs = 1
        else:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)
    sys.stderr.write("iot-proto-provenance: %d packs%s\n" % (count, " differ" if differs else ""))
    return differs


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
