#!/bin/bash
# Regenerate the SBF packs: one `bits` pack per block group of the Septentrio
# Binary Format definitions of pysbf2 (github.com/semuconsulting/pysbf2), one
# kind per block of fixed length, one module per group (model/sbf<group>.def)
# and the block-header module model/sbf.def.
#
# Usage: tools/gen/sbf-run.sh <checkout> <sources> [--fetch] [--check]
#
# <checkout> is a goat-transformers checkout; it is written: model/sbf*.def and
# packs/sbf-*/ (pack.def, pack.md, PROVENANCE.md, vectors/). The generator reads
# the definition files as Python syntax trees and never runs them; it checks
# the SHA-256 of every input against tools/gen/sources/sbf-PROVENANCE.md and
# stops when one differs. With --check it writes nothing and reports any file
# that differs from what it would write.
#
# <sources> is a directory for the pysbf2 tree. It is not kept in the
# repository. With --fetch the script downloads tag v1.0.7,
#   https://codeload.github.com/semuconsulting/pysbf2/tar.gz/38eb890ddfae29f55a8cdfe4029033e2077767fc
#   sha256 1d458f0e9bc30442ca6020f36647e6c3c1cee161efbe2c0dda706c54b17c9e1c
# and unpacks it to <sources>/pysbf2-<commit>/. License: BSD 3-Clause, Copyright
# (c) 2020 semuadmin (Steve Smith) (LICENSE at the root of the commit, verbatim
# in tools/gen/sources/sbf-PROVENANCE.md).
set -euo pipefail
ROOT="$(cd "$1" && pwd)"
mkdir -p "$2"
SRC="$(cd "$2" && pwd)"
GEN="$(cd "$(dirname "$0")" && pwd)"
COMMIT=38eb890ddfae29f55a8cdfe4029033e2077767fc
TAR_SHA=1d458f0e9bc30442ca6020f36647e6c3c1cee161efbe2c0dda706c54b17c9e1c
shift 2
if [ "${1:-}" = "--fetch" ]; then
  shift
  curl -sS -f -L -o "$SRC/pysbf2-$COMMIT.tar.gz" "https://codeload.github.com/semuconsulting/pysbf2/tar.gz/$COMMIT"
  echo "$TAR_SHA  $SRC/pysbf2-$COMMIT.tar.gz" | sha256sum -c -
  tar -xzf "$SRC/pysbf2-$COMMIT.tar.gz" -C "$SRC"
fi
if [ "${1:-}" != "--check" ]; then
  # remove what an earlier run wrote (files whose header names this generator)
  for f in "$ROOT"/model/sbf*.def "$ROOT"/packs/sbf-*/pack.def; do
    [ -e "$f" ] || continue
    if head -3 "$f" | grep -q "Generated by tools/gen/sbf2pack.py"; then
      case "$f" in
        */pack.def) rm -rf "$(dirname "$f")" ;;
        *) rm -f "$f" ;;
      esac
    fi
  done
fi
python3 -I "$GEN/sbf2pack.py" --src "$SRC/pysbf2-$COMMIT" --out "$ROOT" --core-def "$ROOT/model/core.def" "$@"
