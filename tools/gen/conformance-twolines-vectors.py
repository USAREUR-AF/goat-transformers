#!/usr/bin/env python3
"""Write the vectors of one key on two lines, one of them with a value table:
0.7 ruling 10 with 0.6 rulings 4 and 5, on `json` and `xml`, in the packs
`conformance-twolines-*`.

Every expected value is worked out by hand from those rulings and the rules of
0.6 they join ("Value tables", "One key at several locators"), and written
literally. The sentence each rests on is in its `reference`:

  - a line whose transform succeeds and whose table has no entry for a value of
    a different type fails the decode, wherever it stands (0.7 ruling 10);
  - a line whose transform fails is forgiven when another line succeeds;
  - where the types agree a value with no entry passes through, so the line
    succeeds and the earliest line's value is used.

A second computation, the small codec below, reads the pack text with its own
parser and applies the rules. Nothing here imports or calls an engine.

Inputs: none. Writes, under --out, the packs named above. The same run always
gives the same bytes. With --check nothing is written and the exit status is 1
when a committed file differs from what this script writes.

Usage: python3 -I tools/gen/conformance-twolines-vectors.py [--out DIR] [--check]
"""
import json
import os
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402

P = "conformance-twolines-"
GENERATED = "# Generated by tools/gen/conformance-twolines-vectors.py. Do not edit by hand.\n"
SOURCE = '"goat-transformers spec/engine-spec.md (synthetic probe format, no external standard)"'
TYPES = {"probe.x": int, "probe.y": int, "probe.label": str}
DEC = "transform-decode"


def convert(text, inp):
    """(entity, output) of a same-format conversion, or (None, error kind)."""
    rows, tables, wire = [], {}, None
    for t in (raw.split() for raw in text.splitlines() if not raw.startswith("#")):
        if t[0] == "wire":
            wire = t[1]
        elif t[0] == "map":
            tables.setdefault(t[1], []).append((t[2], t[3]))
        elif t[0] == "field":
            rows.append((t[1], t[2].lstrip("@"), t[3], t[5] if len(t) > 4 else None))
    place = json.loads(inp) if wire == "json" else ET.fromstring(inp).attrib
    ent, failed = {}, set()
    for key, loc, tr, via in rows:
        if loc not in place:
            continue
        raw = place[loc]
        try:
            if wire == "json" and not isinstance(raw, int if tr == "int" else str):
                raise ValueError(raw)
            v = int(raw) if tr == "int" else raw
        except ValueError:
            failed.add(key)                     # a failed transform: forgiven below
            continue
        if via:
            hit = [m for n, m in tables[via] if n == str(v)]
            if not hit and type(v) is not TYPES[key]:
                return None, DEC                # 0.7 ruling 10: not forgiven
            v = TYPES[key](hit[0]) if hit else v
        ent.setdefault(key, v)
    if failed - set(ent):
        return None, DEC
    out = []
    for key, loc, tr, via in rows:
        if key not in ent:
            continue
        v = ent[key]
        if via:
            hit = [n for n, m in tables[via] if m == str(v)]
            v = (int(hit[0]) if tr == "int" else hit[0]) if hit else v
            assert type(v) is (int if tr == "int" else str)
        out.append((loc, v))
    if wire == "json":
        return ent, json.dumps(dict(out), separators=(",", ":"))
    return ent, "<e%s/>" % "".join(' %s="%s"' % o for o in out)


def build(sink):
    written = {}

    def put(rel, text):
        sink.write(rel, text)
        written[rel.split("/")[1]] = written.get(rel.split("/")[1], 0) + 1

    tables = "map t h 6\nmap t f 3\nmap s p alpha\nmap n 1 10\n"
    plain = (("probe.x", "a", "int", ""), ("probe.label", "c", "string", ""), ("probe.y", "e", "int", ""))
    tabled = (("probe.x", "b", "string", " via t"), ("probe.label", "d", "string", " via s"),
              ("probe.y", "f", "int", " via n"))
    L10 = "0.7 ruling 10: the transform succeeds and the table has no entry, so the line fails the decode; "
    SAME = "0.6 Value tables: with no entry the value passes through when the two types are the same; "
    EARLY = "0.6 One key at several locators: the earliest line that succeeds; encode writes both"
    # (name, members, what comes back or the error, model, reference), members in the order a to f
    cases = {
        "later": [
            ("entry-in-the-later-line", {"a": 3, "b": "h"}, {"a": 3, "b": "f"}, {"probe.x": "3"}, EARLY),
            ("no-entry-in-the-later-line", {"a": 3, "b": "zz"}, None, None,
             L10 + "that the earlier line succeeds does not matter"),
            ("no-entry-and-the-earlier-line-absent", {"b": "zz"}, None, None, L10 + "0.6 ruling 4"),
            ("no-entry-and-the-earlier-transform-fails", {"a": "q", "b": "zz"}, None, None, L10 + "no line succeeds"),
            ("earlier-transform-fails-and-is-forgiven", {"a": "q", "b": "h"}, {"a": 6, "b": "h"}, {"probe.x": "6"},
             "0.6 ruling 5 and 0.7 ruling 10: a failed transform is forgiven when another line succeeds"),
            ("same-type-text-passes", {"c": "q", "d": "zz"}, {"c": "q", "d": "q"}, {"probe.label": "q"},
             SAME + EARLY),
            ("same-type-text-entry", {"c": "alpha", "d": "p"}, {"c": "alpha", "d": "p"}, {"probe.label": "alpha"}, EARLY),
            ("same-type-integer-passes", {"e": 5, "f": 7}, {"e": 5, "f": 5}, {"probe.y": "5"}, SAME + EARLY),
        ],
        "earlier": [
            ("entry-in-the-earlier-line", {"b": "h", "a": 3}, {"b": "h", "a": 6}, {"probe.x": "6"}, EARLY),
            ("no-entry-in-the-earlier-line", {"b": "zz", "a": 3}, None, None,
             L10 + "0.6 ruling 4: later lines of the key are not tried"),
            ("no-entry-and-the-later-line-absent", {"b": "zz"}, None, None, L10 + "0.6 ruling 4"),
            ("same-type-text-passes", {"d": "zz", "c": "q"}, {"d": "zz", "c": "zz"}, {"probe.label": "zz"},
             SAME + "the earlier line succeeds with it"),
            ("same-type-integer-passes", {"f": 7, "e": 5}, {"f": 7, "e": 7}, {"probe.y": "7"},
             SAME + "the earlier line succeeds with it"),
        ],
    }
    for order in ("later", "earlier"):
        for wire in ("json", "xml"):
            name = P + order + "-" + wire
            at = "@" if wire == "xml" else ""
            pairs = [(x, y) if order == "later" else (y, x) for x, y in zip(plain, tabled)]
            text = (GENERATED + "# Conformance probe pack: one key on two lines, the %s of them with a value\n"
                    "# table (0.7 ruling 10; 0.6 rulings 4 and 5). Public. No kinds. The table types\n"
                    "# differ for probe.x and agree for probe.label and probe.y.\n" % order)
            text += "format  %s\nversion 0.64.0\ndistribution public\nsource  %s\nuses    probe\nwire    %s\n" % (
                name, SOURCE, wire) + ("root    e\n" if wire == "xml" else "") + tables
            for pair in pairs:
                for key, loc, tr, opt in pair:
                    text += "field   %s  %s%s  %s%s\n" % (key, at, loc, tr, opt)
            for old in sink.listdir("packs/%s/vectors" % name):
                sink.remove("packs/%s/vectors/%s" % (name, old))
            put("packs/%s/pack.def" % name, text)
            rows = list(cases[order])
            if wire == "json":
                forgiven = ({"a": 3, "b": 5}, {"a": 3, "b": "f"}) if order == "later" else (
                    {"b": 5, "a": 3}, {"b": "f", "a": 3})
                rows.append(("transform-of-the-table-line-fails-and-is-forgiven",) + forgiven + (
                    {"probe.x": "3"}, "0.6 ruling 5 and 0.7 ruling 10: the transform fails, so the table is not reached"))

            def form(d):
                if wire == "json":
                    return json.dumps(d, separators=(",", ":"))
                return "<e%s/>" % "".join(' %s="%s"' % kv for kv in d.items())

            for i, (vname, inp, out, model, ref) in enumerate(rows, 1):
                d = {"name": vname, "from": name, "to": name, "input": form(inp)}
                ent, got = convert(text, form(inp))
                if out is None:
                    d["expect_error"] = DEC
                    assert ent is None and got == DEC, (name, vname, got)
                else:
                    d["expect"] = form(out)
                    assert got == form(out), (name, vname, "hand", form(out), "computed", got)
                    assert all(str(ent[k]) == v for k, v in model.items()), (name, vname)
                    d["model"] = model
                d["source"], d["reference"] = "constructed", "spec " + ref
                put("packs/%s/vectors/%02d-%s.json" % (name, i, vname), json.dumps(d, indent=2) + "\n")
    return written


def main(argv=None):
    return genio.vector_main("conformance-twolines-vectors.py", __doc__, build, argv)


if __name__ == "__main__":
    sys.exit(main())
