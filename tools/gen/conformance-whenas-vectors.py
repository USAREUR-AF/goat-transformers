def build(sink):
    written, counters = {}, {}
    derive_targets = set()
    for raw in sink.read("model/probe.def").splitlines():
        t = tokens_of(raw)
        if t and t[0] == "derive":
            derive_targets.add(t[1])
    for name, text in PACKS.items():
        # no derive target of probe is a key these packs map or require
        assert not any(t in text.replace("=", " ").split() for t in derive_targets), name
        sink.write("packs/%s%s/pack.def" % (PREFIX, name), text)
        written[PREFIX + name] = 1
        # each pack loads by the load rules (second computation)
        assert check_load([sink.read("model/core.def"), sink.read("model/probe.def")], text) is None, name

    def emit(owner, d):
        counters[owner] = counters.get(owner, 0) + 1
        sink.write("packs/%s/vectors/%02d-%s.json" % (owner, counters[owner], d["name"]),
                   json.dumps(d, indent=2, ensure_ascii=False) + "\n")
        written[owner] = written.get(owner, 0) + 1

    def vec(owner, name, frm, to, inp, expect=None, error=None, model=None, ref=""):
        """Pack names without the prefix. The second computation must agree."""
        got = ent = None
        try:
            ent, got = convert(frm, to, inp)
        except Fail as e:
            assert error == e.kind, (name, error, e.kind, e.why)
            if model:       # the decode alone must still succeed for a model check
                pf = parse_pack(PACKS[frm])
                ent = seq_decode(pf, inp) if pf["wire"] == "bits" else json_decode(pf, inp)
        else:
            assert error is None and got == expect, (name, expect, got)
        if model:
            have = model_of(ent)
            for k, v in model.items():
                if k == "@complete":
                    # step 3 of vector-format: the completed entity is the
                    # decoded one plus derived keys; no listed key is a derive
                    # target, and @kind names the decoded kind (ruling 34)
                    assert v is True and not any(m.split(".#")[0] in derive_targets for m in model), name
                elif k == "@absent":
                    for gone in v:
                        assert gone not in have and gone + ".#" not in have, (name, gone)
                else:
                    assert have.get(k) == v, (name, k, v, have.get(k))
        d = {"name": name, "from": PREFIX + frm, "to": PREFIX + to, "input": inp}
        if error:
            d["expect_error"] = error
        else:
            d["expect"] = expect
        if model:
            d["model"] = model
        d["source"] = SOURCE
        d["reference"] = ref
        emit(PREFIX + owner, d)

    # ==========================================================================
    # conformance-whenas-kinds: n : 8; label : 8 held by x; one 1 [y : 8],
    # span 2..4,9 [z : 16], big 200..255 [nothing].
    # ==========================================================================
    D = "spec 0.30 Decode: when the kind is selected, the key holds the bits read as an unsigned integer; "
    E = "spec 0.30 Encode, Choosing the kind: a kind with `when ... as <k>` qualifies only when the entity holds <k> and its value matches the `when`; "
    W = "spec 0.30 Encode, The bits written: the line writes the value of <k> when the entity holds it and it matches; "
