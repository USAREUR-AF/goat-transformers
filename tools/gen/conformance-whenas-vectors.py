class Fail(Exception):
    """A conversion or a load that fails with an error kind of the spec."""

    def __init__(self, kind, why=""):
        super().__init__(kind, why)
        self.kind, self.why = kind, why


def tokens_of(raw):
    out, i = [], 0
    while i < len(raw):
        c = raw[i]
        if c in " \t":
            i += 1
        elif c == "#":
            break
        elif c == '"':
            j = raw.index('"', i + 1)
            out.append(raw[i + 1:j])
            i = j + 1
        else:
            j = i
            while j < len(raw) and raw[j] not in " \t":
                j += 1
            out.append(raw[i:j])
            i = j
    return out


