def model_keys(pack):
    """6a and 6b of 0.11 with ruling 5 of 0.30 (second computation)."""
    out = []

    def add(k):
        if k not in out:
            out.append(k)

    def lines(ls, prefix):
        for n in ls:
            if n["d"] == "field":
                add(prefix + n["key"])
            elif n["d"] == "when" and n["as"]:
                add(prefix + n["as"])
            elif n["d"] == "group":
                inner = prefix + n["key"] + "[]"
                add(inner)
                scope(n["common"], n["kinds"], inner + ".")
            elif n["d"] == "switch":
                for _, body in n["arms"]:
                    lines(body, prefix)

    def scope(common, kinds, prefix):
        lines(common, prefix)
        for k in kinds:
            lines(k["lines"], prefix)

    scope(pack["common"], pack["kinds"], "")
    return out


