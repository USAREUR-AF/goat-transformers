#!/usr/bin/env python3
"""Write the packs and vectors of spec 0.30, a sequential discriminator that
is also a key (`when <len> <values> as <key>`): the packs
`conformance-whenas-*` with their vectors and the load vectors from 3000.

Every expected value here is worked out by hand from the spec text (Version
0.30, its rules, load errors and rulings 1 to 18, and the sections they refer
to: 0.5 kinds, decode and encode, ruling 2 of 0.5 for 64-bit `uint`; 0.6
defaults; 0.7 and 0.8 groups, sequential lines, items by kind and rulings 10,
13, 26 and 27 of 0.8; 0.11 rulings 2c, 5b and 6; 0.20 lists and ranges,
`requires =`, `switch` and rulings 4, 11, 19 and 23; 0.21 rulings 11 and 32)
and the pack layouts. The hand working is the comment above each group of
vectors and the `reference` member of each vector; the value is written out
literally. It is checked against a second computation: the small codecs
below read the pack texts with their own parser and apply the rules to the
input, and a small load checker applies the load rules in the order of 5b of
0.11, 19 of 0.20 and 16 and 17 of 0.30 to each load vector. They cover only
the lines these files use. Nothing here imports or calls an engine, and
gtcheck.py is not used: it predates 0.30 and refuses `as`.

Readings of the text these vectors rest on (quoted in the report that came
with them):
  - A `switch` on an `as` key (ruling 2) selects on encode by the value the
    `when` line wrote: "the key's line" of 0.20 Encode is the `when … as`
    line, so a common `when … as` whose key is absent writes its first value
    and the switch selects by that value.
  - A common `when` may stand after other common lines (ruling 2 of 0.30
    speaks of a `switch` before a common `as` line; ruling 10 of 0.8 limits
    the place of a `when` only within a kind).
  - A key bound by `as` in a group body is an item key, and a `field` of the
    same name at message level is in another scope: the two load.
  - Ruling 17, "`module-not-used`, then `undeclared-key`, over every line",
    is read as two passes: every line for `module-not-used`, then every line
    for `undeclared-key` (the order of 0.4).
  - `as` is matched as written: `AS` is another token (ruling 15).

Inputs: model/core.def and model/probe.def (key types). Writes, under --out:
packs/conformance-whenas-*/pack.def and vectors/*.json,
and packs/conformance/load-vectors/3000-* and up. The capability vector of
ruling 5 is computed and checked but not written (WRITE_CAP, and the comment
where it is built). With --check nothing is
written and the exit status is 1 when a committed file differs from what this
script writes.

Usage: python3 -I tools/gen/conformance-whenas-vectors.py [--out DIR] [--check]
"""
