PACK_DIRECTIVES = {"format", "version", "distribution", "source", "uses", "wire", "root", "field", "when",
                   "const", "kind", "requires", "default", "map", "typemap", "group", "end", "word_bytes",
                   "bit_order", "layout", "also", "pad", "align", "presence", "if", "opt", "chain", "fx",
                   "length", "delimiter", "start", "checksum", "switch", "case", "else", "count"}
ONE_ARG = {"format", "version", "distribution", "source", "uses", "wire", "root", "kind", "word_bytes",
           "bit_order", "layout", "pad", "align", "switch", "case"}
NEEDS_WIRE = {"root", "field", "when", "const", "group", "end", "word_bytes", "bit_order", "layout", "also",
              "pad", "align", "presence", "if", "opt", "chain", "fx", "length"}
YIELDS = {"uint": "int", "ascii": "string", "int": "int", "string": "string", "pvarint": "int"}
WIRE_LINES = {"field", "when", "const", "group", "opt", "pad", "align", "length", "count", "presence"}


def module_types(text):
    name, types = None, {}
    for raw in text.splitlines():
        t = tokens_of(raw)
        if t and t[0] == "module":
            name = t[1]
        elif t and t[0] in ("key", "list"):
            types[t[1]] = t[2] if t[0] == "key" else "list"
    return name, types


def check_load(models, text):
    """The kind of the first failure of a load, or None."""
    try:
        _check_load(models, text)
    except Fail as e:
        return e.kind
    return None


def _check_load(models, text):
    types = {}
    for m in models:
        name, keys = module_types(m)
        for k, ty in keys.items():
            types[k if name == "core" else name + "." + k] = ty
    hdr, wire, seq, rows = {}, None, False, []
    # 5b of 0.11, steps 1 to 10: the line checks, as the file is read
    for no, raw in enumerate(text.split("\n"), 1):
        t = tokens_of(raw)
        if not t:
            continue
        d, a = t[0], t[1:]
        if d not in PACK_DIRECTIVES:
            raise Fail("unknown-directive", d)
        if d in ONE_ARG and len(a) != 1 or d == "else" and a:
            raise Fail("bad-directive", "argument count")
        if d in NEEDS_WIRE and wire is None:
            raise Fail("missing-wire", d)
        if d in ("format", "version", "wire", "distribution"):
            if d in hdr:
                raise Fail("bad-directive", "repeated header")
            hdr[d] = a[0]
        if d == "source":
            hdr["source"] = a[0]
        if d == "wire":
            wire = a[0]
        if d == "layout":
            seq = a[0] == "sequential"
        if d == "field" and a[2].split(":")[0] not in YIELDS:
            raise Fail("unknown-transform", a[2])
        if d in ("field", "when") and wire == "bits":
            loc = a[0] if d == "when" else a[1]
            if seq and (not loc.isdigit() or int(loc) == 0):
                raise Fail("bad-locator", loc)
        rows.append((no, d, a))
    # after the file: missing-format, missing-version, missing-wire
    for need in ("format", "version", "wire"):
        if need not in hdr:
            raise Fail("missing-" + need)
    tree = build_tree(rows, wire, seq)
    whole_file_checks(tree, rows, wire, seq)
    # then the order of 0.4
    if "distribution" not in hdr:
        raise Fail("missing-distribution")
    if "source" not in hdr:
        raise Fail("missing-source")
    model_checks(rows, types, ["core"] + [a[0] for _, d, a in rows if d == "uses"])


def build_tree(rows, wire, seq):
    """Kinds and blocks; a node is a list [no, d, args, body, kinds]."""
    top = {"common": [], "kinds": []}
    stack, prev = [], None
    for no, d, a in rows:
        if d in ("format", "version", "distribution", "source", "uses", "wire", "layout", "bit_order",
                 "word_bytes", "root", "map", "typemap"):
            continue
        holder = stack[-1] if stack else top
        if d == "end":
            if not stack:
                raise Fail("bad-directive", "stray end")
            stack.pop()
            prev = None
            continue
        if d == "kind":
            holder["kinds"].append({"name": a[0], "requires": [], "lines": [], "no": no})
            prev = None
            continue
        if d == "requires":
            if not holder["kinds"]:
                raise Fail("bad-directive", "requires with no kind")
            holder["kinds"][-1]["requires"] += [(no, term) for term in a]
            prev = None
            continue
        if d in ("case", "else"):
            holder["arms"].append({"values": a[0].split(",") if a else None, "lines": [], "no": no})
            prev = None
            continue
        node = {"no": no, "d": d, "a": a, "common": [], "kinds": [], "arms": [], "prev": prev}
        if holder.get("arms") is not None and "d" in holder and holder["d"] == "switch":
            holder["arms"][-1]["lines"].append(node)
        elif holder["kinds"]:
            holder["kinds"][-1]["lines"].append(node)
        else:
            holder["common"].append(node)
        if d in ("group", "opt", "if", "chain", "switch") or (d == "length" and "whole" not in a):
            stack.append(node)
        prev = node if d in ("field", "also") else None
    if stack:
        raise Fail("bad-directive", "block with no end")
    return top


def walk(lines):
    for n in lines:
        yield n
        yield from walk(n["common"])
        for arm in n["arms"]:
            yield from walk(arm["lines"])
        for k in n["kinds"]:
            yield from walk(k["lines"])


def whole_file_checks(top, rows, wire, seq):
    every = list(walk(top["common"])) + [n for k in top["kinds"] for n in walk(k["lines"])]
    for n in every:
        if n["d"] == "when":
            a = n["a"]
            if len(a) < 2:
                raise Fail("bad-directive", "when with no value")
            if len(a) > 2:
                # 0.30 ruling 15: `as <key>` after the values, on a sequential
                # pack only; anything else is a third token (ruling 23 of 0.20)
                if not (wire == "bits" and seq and len(a) == 4 and a[2] == "as" and a[3] != "as"):
                    raise Fail("bad-directive", "a token after the values of a when")
            if wire == "bits":
                width = int(a[0].split(":")[-1])
                for v in a[1].split(","):
                    lo, dots, hi = v.partition("..")
                    if not lo.isdigit() or (dots and not hi.isdigit()):
                        raise Fail("bad-directive", "when value")
                    if int(hi or lo) >> width or int(lo) > int(hi or lo):
                        raise Fail("bad-directive", "when value does not fit")
        if n["d"] == "also" and (n["prev"] is None):
            raise Fail("bad-directive", "also not after a field")
    if wire == "bits" and seq:
        body_checks(top["common"], top["kinds"], message=True)
    elif any(n["d"] == "when" for n in top["common"]) and not top["kinds"]:
        raise Fail("bad-directive", "when with no kind")


def as_of(node):
    return node["a"][3] if node["d"] == "when" and len(node["a"]) == 4 else None


def mapped_in(lines, into_groups=False):
    """Keys of `field` and `also` lines of a reading path, every case included,
    not inside group bodies."""
    out = []
    for n in lines:
        if n["d"] in ("field", "also"):
            out.append(n["a"][0])
        for arm in n["arms"]:
            out += mapped_in(arm["lines"])
        if n["d"] != "group":
            out += mapped_in(n["common"])
    return out


def body_checks(common, kinds, message):
    """One body of a sequential pack: the message, or a group body."""
    if not kinds and any(n["d"] == "when" for n in common):
        raise Fail("bad-directive", "when in a body with no kind")
    for n in common:
        if n["d"] != "when":
            for inner in walk(n["common"]) if n["d"] != "group" else ():
                if inner["d"] == "when":
                    raise Fail("bad-directive", "when inside a block")
            for arm in n["arms"]:
                if any(i["d"] == "when" for i in walk(arm["lines"])):
                    raise Fail("bad-directive", "when inside a case")
    for kind in kinds:
        seen_other = False
        for n in kind["lines"]:
            if n["d"] == "when":
                if seen_other:      # ruling 10 of 0.8, ruling 18 of 0.30
                    raise Fail("bad-directive", "when after another line of its kind")
            elif n["d"] != "default":
                seen_other = True
            if n["d"] != "group":
                if any(i["d"] == "when" for i in walk(n["common"])) or \
                        any(i["d"] == "when" for arm in n["arms"] for i in walk(arm["lines"])):
                    raise Fail("bad-directive", "when inside a block")
    paths = [common + k["lines"] for k in kinds] or [common]
    for path in paths:
        # 0.30 load errors and ruling 9: one `as` per key in a path, and no
        # `field` or `also` mapping an `as` key in the path
        bound = [as_of(n) for n in path if as_of(n)]
        if len(bound) != len(set(bound)):
            raise Fail("bad-directive", "two `as` lines name one key")
        if set(bound) & set(mapped_in(path)):
            raise Fail("bad-directive", "an `as` key also mapped by a field or also line")
        # 0.20: a switch key mapped earlier in reading order; 0.30 ruling 2:
        # a kind's `as` key from the start of its kind, a common one from its line
        switch_checks(path, common, set())
        # 0.21 rulings 11 and 32: a `rest` group is the last wire line
        for i, n in enumerate(path):
            if n["d"] == "group" and len(n["a"]) > 1 and n["a"][1] == "rest":
                if any(m["d"] in WIRE_LINES for m in path[i + 1:]):
                    raise Fail("bad-directive", "a wire line after a rest group")
    for n in common + [m for k in kinds for m in k["lines"]]:
        for g in walk([n]):
            if g["d"] == "group" and (g["common"] or g["kinds"]):
                body_checks(g["common"], g["kinds"], message=False)


def switch_checks(path, common, mapped):
    kind_bound = {as_of(n) for n in path[len(common):] if as_of(n)}
    started_kind = False
    mapped = set(mapped)
    for i, n in enumerate(path):
        if i == len(common) and not started_kind:
            mapped |= kind_bound
            started_kind = True
        if as_of(n):
            mapped.add(as_of(n))
        if n["d"] in ("field", "also"):
            mapped.add(n["a"][0])
        if n["d"] == "switch":
            if n["a"][0] not in mapped:
                raise Fail("bad-directive", "switch on a key not mapped earlier")
            for arm in n["arms"]:
                mapped |= set(mapped_in(arm["lines"]))


def model_checks(rows, types, uses):
    keyed = []          # (key, what) in line order
    for no, d, a in rows:
        if d == "field":
            keyed.append((a[0], ("field", a[2])))
        elif d == "also":
            keyed.append((a[0], ("also", None)))
        elif d == "default":
            keyed.append((a[0], ("default", a[1])))
        elif d == "group":
            keyed.append((a[0], ("group", None)))
        elif d == "when" and len(a) == 4:
            keyed.append((a[3], ("as", None)))
        elif d == "requires":
            for term in a:
                key, eq, values = term.partition("=")
                keyed.append((key, ("requires=", values) if eq else ("requires", None)))
    module = lambda k: k.partition(".")[0] if "." in k else "core"   # noqa: E731
    for key, _ in keyed:                    # first pass: module-not-used, every line
        if module(key) not in uses:
            raise Fail("module-not-used", key)
    for key, _ in keyed:                    # then undeclared-key, every line
        if key not in types:
            raise Fail("undeclared-key", key)
    for key, (what, _) in keyed:            # second pass: a list key with `=`
        if what == "requires=" and types[key] == "list":
            raise Fail("bad-directive", "list key with =")
    for key, (what, arg) in keyed:          # third pass: types, in line order
        ty = types[key]
        if what == "field" and (ty == "list" or YIELDS[arg.split(":")[0]] != ty):
            raise Fail("key-type-mismatch", key)
        if what == "group" and ty != "list":
            raise Fail("key-type-mismatch", key)
        if what == "default" and not (ty == "int" and arg.lstrip("-").isdigit() or ty in ("string", "float")):
            raise Fail("key-type-mismatch", key)
        if what == "as" and ty != "int":    # 0.30: a list key, or a type that is not int
            raise Fail("key-type-mismatch", key)
    switch_values(rows, keyed, types)


def switch_values(rows, keyed, types):
    """Fourth pass (ruling 19 of 0.20): `requires =` and `case` values in line
    order, each line's types before its duplicates."""
    def int_ok(v):
        return v.lstrip("-").isdigit() and v.count("-") <= 1 and not v.startswith("+")
    stack = []
    for no, d, a in rows:
        if d == "requires":
            for term in a:
                key, eq, values = term.partition("=")
                if eq and types[key] == "int" and not all(int_ok(v) for v in values.split(",")):
                    raise Fail("key-type-mismatch", term)
        elif d == "switch":
            stack.append((a[0], set()))
        elif d == "case":
            key, seen = stack[-1]
            vals = a[0].split(",")
            if types.get(key) == "int" and not all(int_ok(v) for v in vals):
                raise Fail("key-type-mismatch", a[0])
            canon = [str(int(v)) for v in vals]
            if len(set(canon)) != len(canon) or seen & set(canon):
                raise Fail("bad-directive", "a case value twice")
            seen |= set(canon)
        elif d == "end" and stack:
            # an `end` closes the innermost block; only a switch is tracked here
            pass
    return None


