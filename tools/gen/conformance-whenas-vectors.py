def ranges_of(text):
    out = []
    for v in text.split(","):
        lo, _, hi = v.partition("..")
        out.append((int(lo), int(hi or lo)))
    return out


def parse_pack(text):
    """{"wire", "common", "kinds"}; a node is a dict with `d`."""
    pack = {"wire": None, "common": [], "kinds": []}
    stack = []

    def kinds_here():
        return stack[-1]["kinds"] if stack else pack["kinds"]

    def into():
        if stack:
            top = stack[-1]
            if top["d"] == "switch":
                return top["arms"][-1][1]
            if top["kinds"]:
                return top["kinds"][-1]["lines"]
            return top["common"]
        return pack["kinds"][-1]["lines"] if pack["kinds"] else pack["common"]

    for raw in text.splitlines():
        t = tokens_of(raw)
        if not t or t[0] in ("format", "version", "distribution", "source", "uses", "layout", "bit_order"):
            continue
        d, a = t[0], t[1:]
        if d == "wire":
            pack["wire"] = a[0]
        elif d == "end":
            stack.pop()
        elif d == "kind":
            kinds_here().append({"name": a[0], "requires": [], "lines": []})
        elif d == "requires":
            kinds_here()[-1]["requires"] += a
        elif d in ("case", "else"):
            stack[-1]["arms"].append((a[0].split(",") if a else None, []))
        elif d == "field":
            into().append({"d": d, "key": a[0], "loc": a[1], "tr": a[2]})
        elif d == "when":
            assert len(a) == 2 or (len(a) == 4 and a[2] == "as"), raw
            into().append({"d": d, "n": int(a[0]), "ranges": ranges_of(a[1]), "as": a[3] if len(a) == 4 else None})
        elif d == "default":
            into().append({"d": d, "key": a[0], "value": int(a[1])})
        elif d == "group":
            node = {"d": d, "key": a[0], "loc": a[1], "count": int(a[2]) if len(a) > 2 else None,
                    "common": [], "kinds": []}
            into().append(node)
            stack.append(node)
        elif d == "switch":
            node = {"d": d, "key": a[0], "arms": [], "kinds": None}
            into().append(node)
            stack.append(node)
        else:
            raise AssertionError("line not covered: " + raw)
    return pack


def matches(pattern, ranges):
    return any(lo <= pattern <= hi for lo, hi in ranges)


def as_int(bits_value, n):
    """0.5 ruling 2 / 0.30 ruling 7: 64 bits with the top bit set are negative."""
    return bits_value - (1 << 64) if n == 64 and bits_value >> 63 else bits_value


class Reader:
    def __init__(self, hextext):
        self.bits = "".join(format(b, "08b") for b in bytes.fromhex(hextext))
        self.pos = 0

    def read(self, n):
        if self.pos + n > len(self.bits):
            raise Fail("malformed-wire", "past the end")
        v = int(self.bits[self.pos:self.pos + n], 2)
        self.pos += n
        return v


def seq_decode(pack, hexin):
    ent = {}
    rd = Reader(hexin)
    dec_scope(rd, pack["common"], pack["kinds"], ent)
    return ent


def dec_scope(rd, common, kinds, ent):
    dec_lines(rd, common, ent)
    if not kinds:
        return
    start = rd.pos
    for kind in kinds:
        rd.pos, got, ok, i = start, {}, True, 0
        lines = kind["lines"]
        while i < len(lines) and lines[i]["d"] == "when":
            w = lines[i]
            v = rd.read(w["n"])
            if not matches(v, w["ranges"]):
                ok = False
                break
            if w["as"]:
                got[w["as"]] = as_int(v, w["n"])
            i += 1
        if ok:              # ruling 12: the key is set only when the kind is selected
            ent.update(got)
            ent["@kind"] = kind["name"]
            dec_lines(rd, lines[i:], ent)
            return
    raise Fail("no-kind", "no kind holds")


def dec_lines(rd, lines, ent):
    for node in lines:
        d = node["d"]
        if d == "field":
            assert node["tr"] == "uint"
            n = int(node["loc"])
            ent[node["key"]] = as_int(rd.read(n), n)
        elif d == "when":                       # a common `when`
            v = rd.read(node["n"])
            if not matches(v, node["ranges"]):
                raise Fail("no-kind", "a common `when` fails")
            if node["as"]:
                ent[node["as"]] = as_int(v, node["n"])
        elif d == "group":
            items = []
            for _ in range(rd.read(node["count"])):
                item = {}
                dec_scope(rd, node["common"], node["kinds"], item)
                items.append(item)
            ent[node["key"]] = items
        elif d == "switch":
            arm = select_arm(node, ent.get(node["key"]))
            dec_lines(rd, arm, ent)


def select_arm(node, value):
    text = None if value is None else str(value)
    for values, body in node["arms"]:
        if values is None or (text is not None and text in [str(int(v)) for v in values]):
            return body
    raise Fail("no-kind", "no case holds")


def qualifies(kind, ent):
    """0.5 step 2, 0.20 `requires =`, and the implicit term of 0.30."""
    for term in kind["requires"]:
        key, eq, values = term.partition("=")
        if key not in ent:
            return False
        if eq and str(ent[key]) not in [str(int(v)) for v in values.split(",")]:
            return False
    for node in kind["lines"]:
        if node["d"] == "when" and node["as"]:
            if node["as"] not in ent or not matches(ent[node["as"]] & M64, node["ranges"]):
                return False
    return True


def seq_encode(pack, ent, same):
    out = []
    enc_scope(out, pack["common"], pack["kinds"], ent, same)
    bits = "".join(out)
    bits += "0" * (-len(bits) % 8)
    return "".join("%02x" % int(bits[i:i + 8], 2) for i in range(0, len(bits), 8))


def enc_scope(out, common, kinds, ent, same):
    lines = list(common)
    if kinds:
        # ruling 10: the kind is chosen before any line is written
        recorded = ent.get("@kind") if same else None
        chosen = next((k for k in kinds if k["name"] == recorded), None) if recorded else None
        if chosen is None:
            chosen = next((k for k in kinds if qualifies(k, ent)), None)
        if chosen is None:
            raise Fail("no-kind", "no kind qualifies")
        lines += chosen["lines"]
    defaults = {n["key"]: n["value"] for n in lines if n["d"] == "default"}
    enc_lines(out, lines, ent, defaults, {}, same)


def put(out, value, n):
    assert 0 <= value < (1 << n), (value, n)
    out.append(format(value, "0%db" % n))


def enc_lines(out, lines, ent, defaults, back, same):
    for node in lines:
        d = node["d"]
        if d == "field":
            n = int(node["loc"])
            v = ent.get(node["key"], defaults.get(node["key"]))
            pattern = 0 if v is None else v & ((1 << n) - 1)
            put(out, pattern, n)
            back[node["key"]] = as_int(pattern, n)
        elif d == "when":
            k = node["as"]
            if k and k in ent:              # "holds": the entity, never a default (ruling 6)
                pattern = ent[k] & M64
                if not matches(pattern, node["ranges"]):
                    raise Fail("transform-encode", "the held value does not match the `when`")
            else:
                pattern = node["ranges"][0][0]
            put(out, pattern, node["n"])
            if k:
                back[k] = as_int(pattern, node["n"])
        elif d == "group":
            items = ent.get(node["key"]) or []
            put(out, len(items), node["count"])
            for item in items:
                enc_scope(out, node["common"], node["kinds"], item, same)
        elif d == "switch":
            arm = select_arm(node, back.get(node["key"]))
            enc_lines(out, arm, ent, defaults, back, same)


def json_decode(pack, text):
    obj = json.loads(text)
    ent = {}

    def fields(lines, src, dst):
        for node in lines:
            if node["d"] == "field" and src.get(node["loc"]) is not None:
                v = src[node["loc"]]
                assert isinstance(v, int) and not isinstance(v, bool)
                dst[node["key"]] = v
            elif node["d"] == "group" and node["loc"] in src:
                dst[node["key"]] = []
                for item_src in src[node["loc"]]:
                    item = {}
                    fields(node["common"], item_src, item)
                    dst[node["key"]].append(item)
    fields(pack["common"], obj, ent)
    return ent


def json_encode(pack, ent):
    def build(lines, src):
        out = {}
        for node in lines:
            if node["d"] == "field" and node["key"] in src:
                out[node["loc"]] = src[node["key"]]
            elif node["d"] == "group" and node["key"] in src:
                out[node["loc"]] = [build(node["common"], item) for item in src[node["key"]]]
        return out
    return json.dumps(build(pack["common"], ent), separators=(",", ":"))


def convert(frm, to, inp):
    pf, pt = parse_pack(PACKS[frm]), parse_pack(PACKS[to])
    ent = seq_decode(pf, inp) if pf["wire"] == "bits" else json_decode(pf, inp)
    same = frm == to
    # 0.5: convert clears Entity.kind unless from == to; an item's kind names
    # its format and is not used by another (ruling 26 of 0.8). No derive line
    # of probe has a target these packs map or require (checked in build).
    enc = ent if same else strip_kinds(ent)
    got = seq_encode(pt, enc, same) if pt["wire"] == "bits" else json_encode(pt, enc)
    return ent, got


def strip_kinds(ent):
    out = {}
    for k, v in ent.items():
        if k == "@kind":
            continue
        out[k] = [strip_kinds(i) for i in v] if isinstance(v, list) else v
    return out


def model_of(ent, prefix=""):
    have = {}
    for k, v in ent.items():
        if isinstance(v, list):
            have[prefix + k + ".#"] = str(len(v))
            for i, item in enumerate(v):
                have.update(model_of(item, "%s%s[%d]." % (prefix, k, i)))
        else:
            have[prefix + k] = str(v)
    return have


