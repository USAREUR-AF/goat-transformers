    vec("json", "kinds-encode-chooses-the-kind-by-a-range", "json", "kinds", '{"n":7,"x":4,"z":258}', "07040102",
        ref=E + "x = 4 lies in span's 2..4; The bits written: the held value 4 is written, not the first value 2")
