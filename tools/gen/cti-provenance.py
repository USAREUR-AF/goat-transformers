def text(pack, src, commit, files, lic):
    rows = "\n".join("| `%s` | `%s` |" % f for f in files)
    return ("# Provenance: %s pack\n\nSPDX licence: Apache-2.0\n\n"
            "Generated by `tools/gen/cti-run.sh` with `tools/gen/jsonschema2pack.py`. No source file is copied "
            "into this repository. Read on 2026-11-21.\n\n"
            "| | |\n|---|---|\n| Source | %s, commit `%s` |\n\n| File | SHA-256 |\n|---|---|\n%s\n\n%s\n\n"
            "The vectors are written by jsonschema2pack from values it chooses; no published record is used.\n"
            % (pack, src, commit, rows, lic))


def main():
    gt = sys.argv[1]
    check = "--check" in sys.argv[2:]
    bad = 0
    for pack, (src, commit, files, lic) in P.items():
        t = text(pack, src, commit, files, lic)
        path = os.path.join(gt, "packs", pack, "PROVENANCE.md")
        if check:
            cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if cur != t:
                print("differs: packs/%s/PROVENANCE.md" % pack)
                bad += 1
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(t)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
