#!/usr/bin/env python3
"""Write the packs and vectors that pin rulings 1 to 5 of spec version 0.11
(spec/engine-spec.md, "Rulings for 0.11"): XML text, the grammar of numbers in
text, `iso8601_ms`, the scaled and integer transforms of the `bits` wire, and
the load and call failures that had no kind.

Every expected value is worked out here from the rule the specification
states: the XML escapes by a function of this file, the float text from the
shortest digits that read back as the same double, epoch milliseconds from
the proleptic Gregorian calendar, bit fields by a packer of this file. Nothing
calls an engine.

The script writes, and owns:
  packs/conformance-xml-text*/        packs/conformance-numbers*/
  packs/conformance-time*/            packs/conformance-scale*/
  packs/conformance/load-vectors/     files numbered 339 to 499
  packs/conformance/vectors/          files named unknown-*-format*.json

Inputs: none; every value is stated in this file. Writes, under --out, the
files named above. The same run always gives the same bytes. With --check
nothing is written and the exit status is 1 when a committed file differs from
what this script writes.

Usage: python3 -I tools/gen/conformance-rulings011-vectors.py [--out DIR] [--check]
"""
import datetime
import json
import os
import struct
import sys
from decimal import Decimal

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402

SOURCE = 'source  "goat-transformers spec/engine-spec.md, Rulings for 0.11 (synthetic probe format, no external standard)"'
GENERATED = "# Generated by tools/gen/conformance-rulings011-vectors.py. Do not edit by hand.\n"
LOAD_FIRST = 339   # the first load vector this script writes
LOAD_LAST = 499    # the last number it owns


def build(sink):
    """Write every file through the Output `sink`; {pack: number of files}."""
    written = {}
    counts = {}
    started = set()


    def put(rel, text):
        """Write one file through the sink and count it under its pack."""
        sink.write(rel, text)
        owner = rel.split("/")[1]
        written[owner] = written.get(owner, 0) + 1


    def write_json(rel, d):
        put(rel, json.dumps(d, indent=2, ensure_ascii=False) + "\n")


    def clear(rel_dir, keep=lambda name: False):
        """Remove the .json files of an earlier run from `rel_dir`."""
        for old in sink.listdir(rel_dir):
            if old.endswith(".json") and not keep(old):
                sink.remove(rel_dir + "/" + old)


    def pack(name, comment, body):
        """Write packs/<name>/pack.def and empty its vectors directory."""
        clear("packs/%s/vectors" % name)
        text = GENERATED
        for line in comment.strip().split("\n"):
            text += "# " + line.strip() + "\n"
        text += "format  %s\nversion 0.11.0\ndistribution public\n%s\nuses    probe\n" % (name, SOURCE)
        text += body.strip("\n") + "\n"
        put("packs/%s/pack.def" % name, text)
        started.add(name)


    def vec(frm, to, name, inp, expect=None, error=None, model=None, context=None):
        """One conversion vector of pack `frm`, numbered in call order."""
        assert frm in started, frm
        assert (expect is None) != (error is None), name
        num = counts.get(frm, 0) + 1
        counts[frm] = num
        d = {"name": name, "from": frm, "to": to, "input": inp}
        if error is None:
            d["expect"] = expect
        else:
            d["expect_error"] = error
        if model is not None:
            d["model"] = model
        if context is not None:
            d["context"] = context
        write_json("packs/%s/vectors/%03d-%s.json" % (frm, num, name), d)


    # --- helpers that state the rules --------------------------------------------
    def xml_attr(s):
        """Ruling 1: an attribute value as written."""
        out = ""
        for ch in s:
            out += {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "\t": "&#9;", "\n": "&#10;", "\r": "&#13;"}.get(ch, ch)
        return out


    def xml_text(s):
        """Ruling 1: text content as written."""
        out = ""
        for ch in s:
            out += {"&": "&amp;", "<": "&lt;", ">": "&gt;", "\r": "&#13;"}.get(ch, ch)
        return out


    def json_str(s):
        """Canonical JSON string (Version 0.5, Canonical output)."""
        out = '"'
        for ch in s:
            if ch == '"':
                out += '\\"'
            elif ch == "\\":
                out += "\\\\"
            elif ch in "\n\r\t\b\f":
                out += {"\n": "\\n", "\r": "\\r", "\t": "\\t", "\b": "\\b", "\f": "\\f"}[ch]
            elif ord(ch) < 0x20:
                out += "\\u%04x" % ord(ch)
            else:
                out += ch
        return out + '"'


    def float_text(x):
        """Ruling 3 of 0.1.1 and ruling 2 of 0.11: the shortest digits that read
    back as the same double (`repr`), laid out with no exponent."""
        if x == 0:
            return "0"
        s = format(Decimal(repr(x)), "f")
        if "." in s:
            s = s.rstrip("0").rstrip(".")
        return s


    def bits_hex(fields, order, word_bytes):
        """A fixed-layout `bits` message: `fields` is (bit position, length,
    unsigned value). Bits no field covers are zero."""
        nbits = max(p + n for p, n, _ in fields)
        word = word_bytes * 8
        nbytes = ((nbits + word - 1) // word) * word_bytes
        buf = bytearray(nbytes)
        for pos, n, v in fields:
            assert 0 <= v < (1 << n), (pos, n, v)
            for k in range(n):
                i = pos + k
                if order == "lsb":
                    bit = (v >> k) & 1
                    buf[i // 8] |= bit << (i % 8)
                else:
                    bit = (v >> (n - 1 - k)) & 1
                    buf[i // 8] |= bit << (7 - i % 8)
        return buf.hex()


    def unsigned(v, n):
        return v & ((1 << n) - 1)


    def round_half_away(q):
        """Ruling 4: the integer nearest to the double `q`; a tie goes away from
    zero. Exact: a double is a ratio of integers."""
        num, den = q.as_integer_ratio()
        sign = -1 if num < 0 else 1
        num = abs(num)
        whole, rest = divmod(num, den)
        if 2 * rest >= den:
            whole += 1
        return sign * whole


    def epoch_ms(y, mo, d, h=0, mi=0, s=0, ms=0, offset_min=0):
        days = datetime.date(y, mo, d).toordinal() - datetime.date(1970, 1, 1).toordinal()
        return ((days * 24 + h) * 60 + mi - offset_min) * 60000 + s * 1000 + ms


    def iso_text(ms):
        days, rest = divmod(ms, 86400000)
        date = datetime.date.fromordinal(datetime.date(1970, 1, 1).toordinal() + days)
        h, rest = divmod(rest, 3600000)
        mi, rest = divmod(rest, 60000)
        s, f = divmod(rest, 1000)
        return "%04d-%02d-%02dT%02d:%02d:%02d.%03dZ" % (date.year, date.month, date.day, h, mi, s, f)


    # =============================================================================
    # Ruling 1: XML text
    # =============================================================================
    X = "conformance-xml-text"
    XJ = "conformance-xml-text-json"
    pack(
        X,
        """Conformance probe pack for XML text (ruling 1 of 0.11). Public. No kinds.
    One mapped attribute, one mapped element text and one mapped attribute of
    a child element; any other attribute of the root is residue.""",
        """
wire    xml
root    e
field   uid       @id         string
field   callsign  name/#text  string
field   probe.s1  note/@v     string
""",
    )
    pack(
        XJ,
        """The same three keys on the `json` wire. A vector converts to this pack to
    show the exact string a decode gives, and from it to hand the XML encoder
    a string that XML input cannot hold.""",
        """
wire    json
field   uid       id    string
field   callsign  name  string
field   probe.s1  note  string
""",
    )


    def xdoc(uid=None, name=None, note=None, residue=()):
        """The canonical document of `conformance-xml-text`."""
        out = "<e"
        if uid is not None:
            out += ' id="%s"' % xml_attr(uid)
        for k, v in residue:
            out += ' %s="%s"' % (k, xml_attr(v))
        kids = ""
        if name is not None:
            kids += "<name>%s</name>" % xml_text(name) if name != "" else "<name/>"
        if note is not None:
            kids += '<note v="%s"/>' % xml_attr(note)
        return out + (">" + kids + "</e>" if kids else "/>")


    def jdoc(uid=None, name=None, note=None):
        m = []
        for k, v in (("id", uid), ("name", name), ("note", note)):
            if v is not None:
                m.append('"%s":%s' % (k, json_str(v)))
        return "{" + ",".join(m) + "}"


    def enc(name, uid=None, text=None, note=None, error=None):
        """json -> xml: what the encoder writes for these strings."""
        if error:
            vec(XJ, X, name, jdoc(uid, text, note), error=error)
        else:
            vec(XJ, X, name, jdoc(uid, text, note), xdoc(uid, text, note))


    def dec(name, inp, uid=None, text=None, note=None, residue=()):
        """xml -> json and xml -> xml: what a decode gives, and its canonical form."""
        vec(X, XJ, name + "-decoded", inp, jdoc(uid, text, note))
        vec(X, X, name + "-rewritten", inp, xdoc(uid, text, note, residue))


    def bad(name, inp):
        vec(X, X, name, inp, error="malformed-wire")


    # output
    enc("attribute-escapes-amp-lt-gt-quot-and-not-the-apostrophe", uid="a&b<c>d\"e'f")
    enc("text-escapes-amp-lt-gt-and-not-the-quotes", text="a&b<c>d\"e'f")
    enc("attribute-writes-tab-lf-cr-as-references", uid="a\tb\nc\rd")
    enc("child-attribute-writes-tab-lf-cr-as-references", note="a\tb\nc\rd")
    enc("text-writes-cr-as-a-reference-and-tab-lf-as-themselves", text="a\tb\nc\rd")
    enc("characters-beyond-ascii-are-written-as-utf-8", uid="\u00e9\u20ac\U0001F600", text="\u00e9\u20ac\U0001F600")
    enc("c1-control-and-del-are-written-as-utf-8", uid="a\u007fb\u0085c")
    enc("empty-string-attribute-is-written-empty", uid="")
    enc("empty-string-text-writes-an-empty-element", uid="1", text="")
    enc("attribute-control-character-cannot-be-written", uid="a\u0001b", error="transform-encode")
    enc("text-control-character-cannot-be-written", text="a\u0008b", error="transform-encode")
    enc("text-u-fffe-cannot-be-written", text="a\ufffeb", error="transform-encode")
    enc("attribute-u-ffff-cannot-be-written", uid="a\uffffb", error="transform-encode")

    # input: references
    dec(
        "the-five-predefined-entities",
        '<e id="&amp;&lt;&gt;&quot;&apos;"><name>&amp;&lt;&gt;&quot;&apos;</name></e>',
        uid="&<>\"'",
        text="&<>\"'",
    )
    dec("numeric-references", '<e id="&#65;&#x42;&#X63;&#x20AC;"><name>&#9;&#10;&#13;&#x1F600;</name></e>'.replace("&#X63;", "&#x63;"), uid="ABc\u20ac", text="\t\n\r\U0001F600")
    dec("references-in-an-attribute-are-not-normalised", '<e id="a&#9;b&#10;c&#13;d"/>', uid="a\tb\nc\rd")
    dec("a-reference-to-an-ampersand-is-not-read-again", '<e id="&#38;lt;"><name>&amp;amp;</name></e>', uid="&lt;", text="&amp;")
    bad("unknown-named-entity-in-an-attribute", '<e id="&nbsp;"/>')
    bad("unknown-named-entity-in-text", "<e><name>&copy;</name></e>")
    bad("unknown-named-entity-in-content-no-line-maps", '<e id="1"><other>&bogus;</other></e>')
    bad("predefined-entity-name-in-capitals", '<e id="&AMP;"/>')
    bad("bare-ampersand-in-an-attribute", '<e id="a & b"/>')
    bad("bare-ampersand-in-text", "<e><name>a & b</name></e>")
    bad("ampersand-at-the-end-of-an-attribute", '<e id="a&"/>')
    bad("entity-with-no-semicolon", '<e id="a&amp b"/>')
    bad("entity-with-no-name", '<e id="a&;b"/>')
    bad("less-than-in-an-attribute-value", '<e id="a<b"/>')
    dec("greater-than-in-text-is-read-and-written-escaped", "<e><name>a>b</name></e>", text="a>b")

    # input: CDATA, comments, processing instructions
    dec("cdata-is-text-and-its-markup-is-not-read", "<e><name><![CDATA[a<b&amp;c]]></name></e>", text="a<b&amp;c")
    dec("cdata-joins-the-text-around-it", "<e><name>x<![CDATA[y]]>z<![CDATA[w]]></name></e>", text="xyzw")
    dec("empty-cdata-is-no-character-data", '<e id="1"><name><![CDATA[]]></name></e>', uid="1")
    bad("cdata-with-no-end", "<e><name><![CDATA[a</name></e>")
    bad("cdata-outside-the-root", '<![CDATA[a]]><e id="1"/>')
    dec("comment-inside-the-root-is-skipped", '<e id="1"><!-- c --><name>a<!--x-->b</name><!----></e>', uid="1", text="ab")
    dec("comment-holds-markup-that-is-not-read", '<e id="1"><!-- <name>z</name> &bogus; --></e>', uid="1")
    dec("processing-instruction-inside-the-root-is-skipped", '<e id="1"><?pi x?><name>a<?pi y?>b</name></e>', uid="1", text="ab")
    bad("comment-with-no-end", '<e id="1"><!-- c </e>')
    bad("processing-instruction-with-no-end", '<e id="1"><?pi x </e>')

    # input: text
    dec("text-whitespace-is-kept", "<e><name>  a  b\t\n </name></e>", text="  a  b\t\n ")
    dec("whitespace-only-text-is-text", "<e><name> </name></e>", text=" ")
    dec("text-is-the-character-data-directly-in-the-element", "<e><name>a<b>zz</b>c<b/>d</name></e>", text="acd")
    dec("element-with-no-character-data-has-no-text", '<e id="1"><name></name></e>', uid="1")
    dec("self-closing-element-has-no-text", '<e id="1"><name/></e>', uid="1")
    dec("empty-attribute-is-the-empty-string", '<e id=""/>', uid="")
    dec("line-ends-in-text-are-read-as-lf", "<e><name>a\r\nb\rc\nd</name></e>", text="a\nb\nc\nd")
    dec("tab-and-line-ends-in-an-attribute-are-read-as-spaces", '<e id="a\tb\nc\r\nd\re"/>', uid="a b c d e")
    dec("attribute-in-single-quotes", "<e id='a\"b'/>", uid='a"b')
    dec("apostrophe-in-a-double-quoted-attribute", '<e id="a\'b"/>', uid="a'b")

    # input: byte order mark, duplicate attributes, residue
    dec("leading-byte-order-mark-is-accepted-and-not-written", '\ufeff<e id="a"/>', uid="a")
    dec("byte-order-mark-before-the-xml-declaration", '\ufeff<?xml version="1.0" encoding="UTF-8"?><e id="a"/>', uid="a")
    bad("byte-order-mark-after-the-root", '<e id="a"/>\ufeff')
    bad("two-byte-order-marks", '\ufeff\ufeff<e id="a"/>')
    bad("duplicate-attribute-on-the-root", '<e id="a" id="b"/>')
    bad("duplicate-attribute-no-line-maps", '<e id="a" z="1" z="1"/>')
    bad("duplicate-attribute-on-a-child-no-line-maps", '<e id="a"><other k="1" k="2"/></e>')
    vec(
        X,
        X,
        "residue-attribute-is-decoded-and-written-with-the-same-escapes",
        '<e z="a&#38;b&#9;c&lt;&apos;" id="1"/>',
        xdoc(uid="1", residue=[("z", "a&b\tc<'")]),
    )

    # ruling 1m: an element with no character data has no text, so a valued
    # `when` on it does not hold, the empty text included; a `const` of the
    # empty text writes the element with no content (1e)
    XE = "conformance-xml-empty"
    pack(
        XE,
        """Conformance probe pack for the text of an element with no character
        data (ruling 1m of 0.11). Public. Kinds. The kind `blank` holds only when
        the root's text equals the empty text, which no document gives; the kind
        `marked` writes the empty text as a constant.""",
        """
wire    xml
root    e
kind    blank
when    "#text"  ""
field   uid  @id  string
kind    marked
when    @k  m
field   uid  @id  string
const   "#text"  ""
""",
    )
    vec(XE, XE, "when-of-the-empty-text-does-not-hold-on-an-empty-element", '<e id="a"/>', error="no-kind")
    vec(XE, XE, "when-of-the-empty-text-does-not-hold-on-an-element-with-children", '<e id="a"><x/></e>', error="no-kind")
    vec(XE, XE, "const-of-the-empty-text-writes-an-empty-element", '<e k="m" id="a"/>', '<e k="m" id="a"/>', model={"@kind": "marked", "uid": "a"})

    # =============================================================================
    # Ruling 2: numbers in text
    # =============================================================================
    N = "conformance-numbers"
    NJ = "conformance-numbers-json"
    NG = "conformance-numbers-geojson"
    NF = "conformance-numbers-f64"
    pack(
        N,
        """Conformance probe pack for numbers in text (ruling 2 of 0.11) on the `xml`
    wire. Public. No kinds. An integer and a float in attributes, and one of
    each in element text.""",
        """
wire    xml
root    e
field   probe.n      @n       int
field   probe.a      @a       float
field   probe.val    v/#text  int
field   probe.ratio  r/#text  float
""",
    )
    pack(
        NJ,
        """The integer and the float of `conformance-numbers` as JSON numbers.""",
        """
wire    json
field   probe.n  n  int
field   probe.a  a  float
""",
    )
    pack(
        NG,
        """The integer and the float of `conformance-numbers` as `properties` members
    of a GeoJSON Feature: a member that is a JSON string is read by the text
    grammar, a member that is a JSON number by the JSON rules.""",
        """
wire    geojson
field   probe.n  properties.n  int
field   probe.a  properties.a  float
""",
    )
    pack(
        NF,
        """One IEEE-754 double, most significant byte first. A vector converts from
    this pack to state a float by its bits, so that the text written for it
    does not depend on how an engine reads decimal text.""",
        """
wire       bits
word_bytes 8
bit_order  msb
field   probe.a  0:0:64  f64
""",
    )

    I64_MAX = 2**63 - 1
    I64_MIN = -(2**63)

    for text, name in [
        ("0", "zero"),
        ("7", "one-digit"),
        ("-7", "negative"),
        ("007", "leading-zeros"),
        ("-007", "negative-with-leading-zeros"),
        ("-0", "negative-zero"),
        (str(I64_MAX), "largest"),
        (str(I64_MIN), "smallest"),
        ("0000000000000000000000009223372036854775807", "largest-with-leading-zeros"),
    ]:
        v = int(text)
        vec(N, N, "int-" + name, '<e n="%s"/>' % text, '<e n="%d"/>' % v, model={"probe.n": str(v)})

    for text, name in [
        ("+7", "plus-sign"),
        (" 7", "leading-space"),
        ("7 ", "trailing-space"),
        ("&#9;7", "leading-tab"),
        ("7&#10;", "trailing-line-feed"),
        ("", "empty"),
        ("-", "sign-only"),
        ("--7", "two-signs"),
        ("7-", "sign-after-the-digits"),
        ("7.0", "fraction"),
        ("7.", "trailing-dot"),
        ("7e0", "exponent"),
        ("0x7", "hexadecimal"),
        ("7_0", "underscore"),
        ("1,000", "group-separator"),
        ("\u0667", "arabic-indic-digit"),
        ("\uff17", "fullwidth-digit"),
        ("\u2212" + "7", "unicode-minus-sign"),
        (str(I64_MAX + 1), "one-above-the-largest"),
        (str(I64_MIN - 1), "one-below-the-smallest"),
        ("99999999999999999999999999", "far-above-the-largest"),
    ]:
        vec(N, N, "int-" + name + "-is-refused", '<e n="%s"/>' % text, error="transform-decode")

    vec(N, N, "int-in-element-text", "<e><v>-42</v></e>", "<e><v>-42</v></e>", model={"probe.val": "-42"})
    vec(N, N, "int-in-element-text-with-spaces-is-refused", "<e><v> 42 </v></e>", error="transform-decode")
    vec(N, N, "int-in-element-text-with-line-ends-is-refused", "<e><v>\n42\n</v></e>", error="transform-decode")

    for text, name in [
        ("0", "zero"),
        ("-0", "negative-zero"),
        ("-0.0", "negative-zero-with-a-fraction"),
        ("1.5", "fraction"),
        ("-1.5", "negative"),
        ("007.50", "leading-and-trailing-zeros"),
        ("1e3", "exponent"),
        ("1E3", "capital-exponent"),
        ("1e+3", "exponent-with-a-plus-sign"),
        ("1.5e-3", "negative-exponent"),
        ("12.5e0003", "exponent-with-leading-zeros"),
        ("1e-400", "below-the-smallest-subnormal-reads-as-zero"),
        ("-1e-400", "negative-below-the-smallest-subnormal-reads-as-zero"),
        ("9007199254740993", "halfway-between-two-doubles-goes-to-the-even-one"),
        ("0.1000000000000000055511151231257827021181583404541015625", "fifty-five-fraction-digits"),
        ("1.7976931348623157e308", "largest-double"),
        ("4.9e-324", "smallest-subnormal"),
        ("2.2250738585072011e-308", "just-below-the-smallest-normal"),
        ("0.000001", "small-plain"),
        ("123456789012345678901234567890", "thirty-digit-integer"),
    ]:
        v = float(text)
        assert v == v and abs(v) != float("inf")
        vec(N, N, "float-" + name, '<e a="%s"/>' % text, '<e a="%s"/>' % float_text(v))

    for text, name in [
        ("+1.5", "plus-sign"),
        (" 1.5", "leading-space"),
        ("1.5 ", "trailing-space"),
        ("", "empty"),
        ("-", "sign-only"),
        (".5", "leading-dot"),
        ("-.5", "leading-dot-after-the-sign"),
        ("5.", "trailing-dot"),
        ("5.e3", "dot-with-no-digits-before-the-exponent"),
        (".", "dot-only"),
        ("1e", "exponent-with-no-digits"),
        ("1e+", "exponent-sign-with-no-digits"),
        ("e5", "exponent-only"),
        ("1.5.2", "two-dots"),
        ("1 e3", "space-inside"),
        ("0x10", "hexadecimal"),
        ("0x1p3", "hexadecimal-float"),
        ("Infinity", "infinity"),
        ("-Infinity", "negative-infinity"),
        ("inf", "inf"),
        ("NaN", "nan"),
        ("nan", "nan-in-lower-case"),
        ("1,5", "decimal-comma"),
        ("1_0.5", "underscore"),
        ("1d3", "d-exponent"),
        ("1.5f", "type-suffix"),
        ("\u0661.\u0665", "arabic-indic-digits"),
        ("1e400", "overflow"),
        ("-1e400", "negative-overflow"),
        ("1e309", "just-above-the-largest-double"),
        ("1.7976931348623159e308", "rounds-to-infinity"),
    ]:
        if name in ("overflow", "negative-overflow", "just-above-the-largest-double", "rounds-to-infinity"):
            assert abs(float(text)) == float("inf")
        vec(N, N, "float-" + name + "-is-refused", '<e a="%s"/>' % text, error="transform-decode")

    vec(N, N, "float-in-element-text", "<e><r>-2.5</r></e>", "<e><r>-2.5</r></e>", model={"probe.ratio": "-2.5"})
    vec(N, N, "float-in-element-text-with-spaces-is-refused", "<e><r> 2.5</r></e>", error="transform-decode")

    # canonical float text, from the bits of the double
