    def scaled(kname, name, text):
        """Encode by the rule: quotient in doubles, round half away from zero,
    refuse what does not fit."""
        _, _, _, n, tr, _ = KIND[kname]
        x = float(text)
        if tr == "sscale:1" or tr == "uscale:1":
            q = (x - 0.0) / 1.0
        elif tr == "sscale:1/4:10":
            q = (x - 10.0) * 4.0 / 1.0
        elif tr == "sscale:1e-10":
            q = (x - 0.0) / 1e-10
            if q != q or abs(q) == float("inf"):
                s_enc(kname, name, text, None)
                return None
        else:
            q = x / 180.0 * 32768.0
        r = round_half_away(q)
        s_enc(kname, name, text, r if fits(r, n, not tr.startswith("uscale")) else None)
        return r


