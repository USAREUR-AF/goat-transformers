def runs(lines):
    return [n for n in lines if n["d"] == "inner" and n["a"][1:] == ["run"]] + [m for n in lines for m in runs(n["body"])]


def inners(lines):
    return [n for n in lines if n["d"] == "inner"] + [m for n in lines for m in inners(n["body"])]


def all_lines(pack):
    return pack["body"] + [n for k in pack["kinds"] for n in k["body"]]


def is_carrier(name):
    return bool(runs(all_lines(pack_of(name))))


def withs(lines):
    return {n["a"][n["a"].index("with") + 1] for n in lines if n["d"] == "field" and "with" in n["a"]} | {k for n in lines for k in withs(n["body"])}


def line_checks(name, kind, node):
    """The four checks of 0.34 (the second with 0.92), the fifth of 0.52 and
    ruling 9 of 0.92, at an `inner` line of the pack `name`."""
    fmt = node["a"][0]
    if fmt not in PACKS:
        raise Fail("unknown-format")
    if node["a"][1:] == ["run"] and not {"layout     sequential", "framing    self"} <= set(PACKS[fmt].splitlines()):
        raise Fail("bad-directive")
    inner = pack_of(fmt)
    if inners(all_lines(inner)) or fmt == name:
        raise Fail("bad-directive")
    pack = pack_of(name)
    REF.check(pack, kind, node)
    if node["a"][1:] == ["run"]:
        reach = all_lines(pack) if REF.has(pack["body"], node) else pack["body"] + kind["body"]
        if withs(reach) & REF.entries(all_lines(inner)):
            raise Fail("bad-directive")


def items_in(ent):
    return sum(1 + items_in(i) for v in ent.values() if isinstance(v, list) for i in v)


class Dec:
    """One message of one pack. `run` is the mode of a `run` line: False for
    decode and convert, True for run operations."""

    def __init__(self, name, bits, limit, used=0, run=False):
        self.name, self.pack, self.bits, self.run_mode = name, pack_of(name), bits, run
        self.pos, self.end, self.whole = 0, len(bits), None
        self.input = len(bits)      # 0.83 rulings 5 and 16: a whole length cuts it for all that follows
        self.limit, self.used, self.depth = limit, used, 0
        self.ent, self.failed, self.kind = {}, set(), None
        self.names, self.messages, self.inner = {}, None, None
        self.in_bits = False

    def take(self, n):
        if self.pos + n > min(self.end, self.input):
            raise Fail("malformed-wire")
        self.pos += n
        return int(self.bits[self.pos - n:self.pos], 2)

    def unforgiven(self):
        return bool(self.failed - set(self.ent))

    def lines(self, lines, ent, extent=False):
        for n in lines:
            d, a = n["d"], n["a"]
            if extent and self.pos >= self.end and d == "field":
                continue
            if d == "field":
                raw = self.take(int(a[1]))
                v = raw if a[2] == "uint" else "" if raw == 0 else chr(raw) if 0x20 <= raw <= 0x7e else None
                if v is None:
                    self.failed.add(a[0])
                else:
                    ent.setdefault(a[0], v)
            elif d == "when":
                v = self.take(int(a[0]))
                if not REF.matches(v, n):
                    raise Fail("no-kind")
                ent[REF.as_key(n)] = v
            elif d == "pad":
                self.take(int(a[0]))
            elif d == "align":
                self.pos = min(-(-self.pos // int(a[0])) * int(a[0]), self.end)
            elif d == "presence":
                self.names[a[0]] = self.take(int(a[1]))
            elif d == "if":
                p, i = a[0].split(".")
                if self.names[p] >> (8 - int(i)) & 1:
                    self.lines(n["body"], ent, extent)
            elif d == "count":
                self.names[a[0]] = self.take(int(a[1]))
            elif d == "length" and a[1:] == ["whole"]:
                self.whole = 8 * self.take(int(a[0]))
                if not self.pos <= self.whole <= self.input:
                    raise Fail("malformed-wire")
                self.input = self.whole
                if not extent:
                    self.end = self.whole
            elif d == "length":
                outer = self.end
                if a[0][0] == "@":
                    self.end = self.pos + self.names[a[0][1:]] * int(a[2])
                else:
                    self.end = self.pos + 8 * self.take(int(a[0])) + int(a[0])
                if self.end > min(outer, self.input):       # 0.83 rulings 4, 5 and 17: at the line
                    raise Fail("malformed-wire")
                self.lines(n["body"], ent, True)
                self.pos, self.end = self.end, outer
            elif d == "group":
                got = []
                if a[1] == "count":
                    count = self.take(int(a[2]))
                    if self.used + items_in(self.ent) + count > self.limit:
                        raise Fail("malformed-wire")
                    for _ in range(count):
                        got.append({})
                        self.lines(n["body"], got[-1])
                else:
                    while self.end - self.pos >= 8:
                        if self.used + items_in(self.ent) + len(got) + 1 > self.limit:
                            raise Fail("malformed-wire")
                        got.append({})
                        self.lines(n["body"], got[-1])
                ent[a[0]] = got
            elif d == "switch":
                if a[0] in self.failed:
                    raise Fail("transform-decode")      # 0.92 ruling 3, 0.20 ruling 35
                case = next((c for c in n["body"] if c["values"] is None or str(ent.get(a[0])) in c["values"]), None)
                if case is None:
                    raise Fail("no-kind")
                self.lines(case["body"], ent, extent)
            elif d == "inner":
                self.inner_line(n)
            else:
                raise AssertionError(d)

    def one(self, fmt, start):
        m = Dec(fmt, self.bits[start:self.end], self.limit, self.used + items_in(self.ent))
        m.run()
        end = m.whole if m.whole is not None else -(-m.pos // 8) * 8
        if m.whole is None and end > len(m.bits) or end == 0 and self.run_line:
            raise Fail("malformed-wire")
        return m, start + end

    def inner_line(self, n):
        fmt, word = n["a"][0], n["a"][1:]
        line_checks(self.name, self.kind, n)
        if self.pos % 8 or self.end > self.input:
            raise Fail("malformed-wire")
        self.run_line = word == ["run"]
        self.inner = fmt
        if not self.run_line:
            m, end = self.one(fmt, self.pos)
            if end < self.end and word != ["partial"]:
                raise Fail("malformed-wire")
            self.messages = [m]
        elif not self.run_mode:
            if self.pos == self.end:
                raise Fail("message-count")
            m, end = self.one(fmt, self.pos)
            if end < self.end:
                raise Fail("message-count")
            self.messages = [m]
            self.used += items_in(m.ent)    # 0.34: one decode; not in run operations (ruling 5)
        else:
            self.messages = []
            while self.pos < self.end:
                if len(self.messages) == self.limit:
                    raise Fail("malformed-wire")
                try:
                    m, self.pos = self.one(fmt, self.pos)
                except Fail as e:
                    self.messages.append(e)
                    break
                self.messages.append(m)
        self.pos = self.end

    def run(self):
        self.lines(self.pack["body"], self.ent)
        start = self.pos
        for k in self.pack["kinds"]:
            pos, got = start, {}
            for w in (n for n in k["body"] if n["d"] == "when"):
                at = start + int(w["a"][w["a"].index("at") + 1]) if "at" in w["a"] else pos
                size = int(w["a"][0])
                if at + size > self.end or not REF.matches(int(self.bits[at:at + size], 2), w):
                    break
                if REF.as_key(w):
                    got[REF.as_key(w)] = int(self.bits[at:at + size], 2)
                pos += 0 if "at" in w["a"] else size
            else:
                self.kind, self.pos = k, pos
                self.ent.update(got)
                self.lines([n for n in k["body"] if n["d"] != "when"], self.ent)
                return
        if self.pack["kinds"]:
            raise Fail("no-kind")


def complete(ent, context):
    out = dict(ent)
    for k, v in (context or {}).items():
        out.setdefault(k, int(v))
    if "probe.n" in out:
        out.setdefault("probe.n_copy", out["probe.n"])
    return out


TYPES = {"probe.%s" % k: "int" for k in ("n", "w", "x", "y", "z", "n_copy")}


def context_check(context):
    for k, v in (context or {}).items():
        if k not in TYPES:
            raise Fail("undeclared-key")
        if not v.lstrip("-").isdigit():
            raise Fail("key-type-mismatch")


class Enc:
    """Encodes one pack. `run` is None for one message of `ent`, or a function
    of the inner format that gives the bits of each message and whether it is
    the last."""

    def __init__(self, name, ent, kind=None, inner_kind=None, chosen=None, messages=None):
        self.name, self.pack, self.ent, self.inner_kind, self.messages = name, pack_of(name), ent, inner_kind, messages
        self.out, self.kind = "", chosen
        self.rest_open = False
        if self.pack["kinds"] and chosen is None:
            self.kind = choose(name, ent, kind)

    def put(self, v, n):
        if not 0 <= v < 1 << n:
            raise Fail("transform-encode")
        self.out += format(v, "0%db" % n)

    def lines(self, lines, ent, at=0, top=True, whole=False):
        for i, n in enumerate(lines):
            d, a = n["d"], n["a"]
            if d == "field":
                v = ent.get(a[0])
                if "with" in a and a[a.index("with") + 1] not in ent:
                    v = None
                self.put(0 if v is None or v == "" else ord(v) if a[2] == "ascii" else v, int(a[1]))
            elif d == "when":
                if "at" in a:
                    continue
                key, v = REF.as_key(n), REF.ranges(n)[0][0]
                if key in ent:
                    v = ent[key]
                    if not REF.matches(v, n):
                        raise Fail("transform-encode")
                self.put(v, int(a[0]))
            elif d == "pad":
                self.put(0, int(a[0]))
            elif d == "align":
                self.out += "0" * (-(at + len(self.out)) % int(a[0]))
            elif d == "presence":
                bits = 0
                for m in lines:
                    if m["d"] == "if" and m["a"][0].split(".")[0] == a[0] and self.selected(m["body"], ent):
                        bits |= 1 << (8 - int(m["a"][0].split(".")[1]))
                self.put(bits, 8)
            elif d == "if":
                if self.selected(n["body"], ent):
                    self.lines(n["body"], ent, at, False)
            elif d == "count":
                self.names = getattr(self, "names", {})
                self.names[a[0]] = len(self.out)
                self.put(0, int(a[1]))
                self.width = int(a[1])
            elif d == "length" and a[1:] == ["whole"]:
                self.whole_at = len(self.out)
                whole = True
                self.put(0, int(a[0]))
            elif d == "length":
                head = self.out
                unit = int(a[2]) if a[0][0] == "@" else 8
                size = 0 if a[0][0] == "@" else int(a[0])
                self.out = ""
                self.lines(n["body"], ent, at + len(head) + size, False)
                block = self.out
                block += "0" * (-len(block) % 8)
                if len(block) % unit:
                    raise Fail("transform-encode")
                self.out = head
                if size:
                    self.put(len(block) // 8, size)
                else:
                    p = self.names[a[0][1:]]
                    if len(block) // unit >> self.width:
                        raise Fail("transform-encode")
                    self.out = self.out[:p] + format(len(block) // unit, "0%db" % self.width) + self.out[p + self.width:]
                self.out += block
            elif d == "group":
                items = ent.get(a[0], [])
                if a[1] == "count":
                    self.put(len(items), int(a[2]))
                elif top and not whole:
                    self.rest_open = True
                for item in items:
                    self.lines(n["body"], item, 0, False)
            elif d == "switch":
                v = ent.get(a[0], "" if a[0] == "probe.label" else 0)
                case = next((c for c in n["body"] if c["values"] is None or str(v) in c["values"]), None)
                if case is None:
                    raise Fail("no-kind")
                self.lines(case["body"], ent, at, False)
            elif d == "inner":
                line_checks(self.name, self.kind, n)
                if (at + len(self.out)) % 8:
                    raise Fail("transform-encode")
                run = n["a"][1:] == ["run"]
                if self.messages is not None and run:
                    got = self.messages(a[0])
                else:
                    kind = self.inner_kind[1] if self.inner_kind and self.inner_kind[0] == a[0] else None
                    e = Enc(a[0], self.ent, kind)
                    got = iter([(e.run(), e.rest_open, True)])
                for bits, rest_open, last in got:
                    if run and (not bits or rest_open and not last):
                        raise Fail("transform-encode")
                    self.out += bits
            else:
                raise AssertionError(d)

    def selected(self, body, ent):
        """Content of an `if` that holds one switch on label."""
        (sw,) = body
        v = ent.get(sw["a"][0], "")
        case = next(c for c in sw["body"] if c["values"] is None or v in c["values"])
        return any(m["a"][0] in ent for m in case["body"])

    def run(self):
        self.lines(self.pack["body"], self.ent)
        if self.kind:
            self.lines(self.kind["body"], self.ent)
        self.out += "0" * (-len(self.out) % 8)
        if hasattr(self, "whole_at"):
            self.out = self.out[:self.whole_at] + format(len(self.out) // 8, "08b") + self.out[self.whole_at + 8:]
        return self.out


def choose(name, ent, recorded):
    for k in pack_of(name)["kinds"]:
        if recorded:
            if k["name"] == recorded:
                return k
            continue
        ok = all(r in ent for r in k["requires"])
        for n in k["body"]:
            key = REF.as_key(n)
            if key and not (key in ent and REF.matches(ent[key], n)):
                ok = False
        if ok:
            return k
    raise Fail("no-kind")


def tohex(bits):
    return "".join("%02x" % int(bits[i:i + 8], 2) for i in range(0, len(bits), 8))


def tobits(text):
    return "".join(format(b, "08b") for b in bytes.fromhex(text))


def encode(name, ent, kind, inner_kind):
    if pack_of(name)["json"]:
        return json.dumps({n["a"][1]: ent[n["a"][0]] for n in pack_of(name)["body"] if n["a"][0] in ent}, separators=(",", ":"))
    return tohex(Enc(name, ent, kind, inner_kind).run())


def join(outer, message):
    assert not set(outer) & set(message)
    return dict(outer, **message)


def kept(frm, to, kind, inner_kind):
    """0.34 Conversion: (Entity.kind, Entity.inner_kind) at the encode into `to`."""
    if frm == to:
        return kind, inner_kind
    formats = {n["a"][0] for n in inners(all_lines(pack_of(to)))}
    if inner_kind and inner_kind[0] == to:
        return inner_kind[1], None
    if inner_kind and inner_kind[0] in formats:
        return None, inner_kind
    return (None, (frm, kind)) if kind and frm in formats else (None, None)


def read(name, text, limit, run):
    """A Dec that has run, or for json one whose entity is the object's."""
    pack = pack_of(name)
    if pack["json"]:
        d = Dec(name, "", limit)
        obj = json.loads(text)
        d.ent = {n["a"][0]: obj[n["a"][1]] for n in pack["body"] if n["a"][1] in obj}
        return d, None
    d = Dec(name, tobits(text), limit, run=run)
    try:
        d.run()
    except Fail as e:
        return d, e
    return d, None


def joined(d, m):
    return join(d.ent, m.ent), (d.inner, m.kind["name"]) if m.kind else None


def kind_keys(lines):
    """0.94: the keys of a kind over these lines: mapped fields, list entries
    (not item keys) and the model keys of an `inner` line's pack."""
    out = set()
    for n in lines:
        if n["d"] == "field":
            out.add(n["a"][0])
        elif n["d"] == "group":
            out.add(n["a"][0])
        elif n["d"] == "inner":
            if n["a"][0] in PACKS:
                out |= kind_keys(all_lines(pack_of(n["a"][0])))
        else:
            out |= kind_keys(n["body"])
    return out


def held_check(name, ent, kept_kind, kept_inner):
    """0.94: a conversion into a chosen kind holds one of its keys, else no-kind."""
    pack = pack_of(name)
    if pack["kinds"] and not kept_kind and not kept_inner and not held_by(name, choose(name, ent, None), ent):
        raise Fail("no-kind")


def held_by(name, kind, ent):
    lines = pack_of(name)["body"] + kind["body"]
    if any(REF.as_key(n) and "optional" not in n["a"] for n in lines):
        return True
    keys = kind_keys(lines) | {r.split("=")[0] for r in kind["requires"]}
    return any(k in ent and ent[k] != [] for k in keys)


def convert(frm, to, text, context, limit, d=None):
    if frm not in PACKS or to not in PACKS:
        raise Fail("unknown-format")
    if d is None:
        d, stop = read(frm, text, limit, False)
        if stop:
            raise stop
    ent, inner = (d.ent, None) if not d.messages else joined(d, d.messages[0])
    if d.unforgiven() or d.messages and d.messages[0].unforgiven():
        raise Fail("transform-decode")
    context_check(context)
    if frm != to or context is not None:
        ent = complete(ent, context)
    kind, inner = kept(frm, to, d.kind and d.kind["name"], inner)
    if frm != to:
        held_check(to, ent, kind, inner)
    return encode(to, ent, kind, inner)


def convert_run(frm, to, text, context, limit):
    """The list of results, each ("ok", text) or ("error", kind); Fail for the call."""
    if frm not in PACKS or to not in PACKS:
        raise Fail("unknown-format")
    d, stop = read(frm, text, limit, True)
    carrier = is_carrier(frm)
    to_carrier = is_carrier(to)
    if d.messages is None or not carrier or d.inner and not d.run_line:
        known = d.kind and not runs(d.pack["body"] + d.kind["body"])
        if stop and carrier and not known:
            raise stop                      # stopped before it was known
        if stop:
            if to_carrier:
                raise stop
            return [("error", stop.kind)]
        bad = d.unforgiven() or d.messages and d.messages[0].unforgiven()
        if not bad:
            context_check(context)
        try:
            return [("ok", convert(frm, to, text, context, limit, d))]
        except Fail as e:
            if to_carrier:
                raise
            return [("error", e.kind)]
    good = [m for m in d.messages if isinstance(m, Dec)]
    dead = [m for m in d.messages if isinstance(m, Fail)]
    if to_carrier:
        if dead:
            raise dead[0]
        if stop:
            raise stop
        if d.unforgiven() or any(m.unforgiven() for m in good):
            raise Fail("transform-decode")
        summed(d, good, limit)
        context_check(context)
        return [("ok", tohex(to_run(frm, to, d, good, context)))]
    if stop:
        raise stop
    if d.unforgiven():
        raise Fail("transform-decode")
    summed(d, good, limit)
    context_check(context)
    out = []
    for m in d.messages:
        try:
            if isinstance(m, Fail):
                raise m
            if m.unforgiven():
                raise Fail("transform-decode")
            ent, inner = joined(d, m)
            kind, inner = kept(frm, to, d.kind and d.kind["name"], inner)
            ent = complete(ent, context)
            if frm != to:
                held_check(to, ent, kind, inner)
            out.append(("ok", encode(to, ent, kind, inner)))
        except Fail as e:
            out.append(("error", e.kind))
    return out


def summed(d, good, limit):
    """Ruling 5: the outer items once per message that came to its end, and each one's own."""
    if sum(items_in(d.ent) + items_in(m.ent) for m in good) > limit:
        raise Fail("malformed-wire")


def to_run(frm, to, d, messages, context):
    """Ruling 6."""
    outer = complete(d.ent, context) if frm != to or context is not None else d.ent
    pack = pack_of(to)
    kind = choose(to, outer, d.kind["name"] if d.kind and frm == to else None) if pack["kinds"] else None
    if not runs(pack["body"] + (kind["body"] if kind else [])):
        if len(messages) != 1:
            raise Fail("message-count")
        ent, inner = joined(d, messages[0])
        ent, kept_inner = complete(ent, context), kept(frm, to, None, inner)[1]
        if frm != to and kind and not kept_inner and not held_by(to, kind, ent):
            raise Fail("no-kind")                    # 0.94 ruling 7: checked on the joined entity
        return Enc(to, ent, inner_kind=kept_inner, chosen=kind).run()
    if frm != to and kind:                           # 0.94 ruling 7: the outer entity joined with the first message
        first = complete(joined(d, messages[0])[0], context) if messages else outer
        if not held_by(to, kind, first):
            raise Fail("no-kind")

    def each(fmt):
        for i, m in enumerate(messages):
            ent, inner = joined(d, m)
            if fmt != d.inner or context is not None:
                ent = complete(ent, context)
            e = Enc(fmt, ent, inner[1] if inner and inner[0] == fmt else None)
            yield e.run(), e.rest_open, i == len(messages) - 1
    return Enc(to, outer, chosen=kind, messages=each).run()


