#!/usr/bin/env python3
"""Write the vectors of spec 0.52, a discriminator key the entity need not hold
(`when <len> <values> [at <offset>] as <key> optional`): the packs
`conformance-asopt-*` and the load vectors from 5200.

Every expected value is worked out by hand from the spec text (Version 0.52
and its rulings 1 to 9, the parts of 0.30 and 0.33 it amends, and the sections
they cite: 0.5 kinds, 0.6 context, defaults and the order of `convert`, 0.8
sequential lines and items by kind, 0.20 `requires =` and `switch`, 0.11
ruling 5b). The hand working is the `reference` member of each vector, and the
value is written out literally.

It is checked against a second computation: the small codec below parses the
pack texts with its own parser and applies the rules to the input. It covers
only the lines these packs use. Load vectors are checked against
tools/gen/gtcheck.py; `gtcheck_kind` names what it gives where it does not
make the order of 0.11 ruling 5b. Nothing here imports or calls an engine.

Ruling 10 has no vector here: Version 0.34 is not on this base.

Inputs: model/probe.def. Writes the pack.def files of the `conformance-asopt-*`
packs, their vectors, and the load vectors 5200 onward. With --check nothing is
written and the exit status is 1 when a committed file differs from what this
script writes.

Usage: python3 -I tools/gen/conformance-asopt-vectors.py [--out DIR] [--check]
"""
