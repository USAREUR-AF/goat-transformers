M64 = (1 << 64) - 1
PACKS = {}


def define(name, comment, body, wire="bits"):
    text = "# Generated by tools/gen/conformance-asopt-vectors.py. Do not edit by hand.\n"
    for line in comment.strip("\n").split("\n"):
        text += ("# " + line).rstrip() + "\n"
    text += "format     %s%s\nversion    0.52.0\ndistribution public\n" % (PREFIX, name)
    text += 'source  "goat-transformers spec/engine-spec.md (synthetic probe format, no external standard)"\n'
    text += "uses       probe\nwire       %s\n" % wire
    if wire == "bits":
        text += "layout     sequential\nbit_order  msb\n"
    PACKS[name] = text + body.lstrip("\n")


