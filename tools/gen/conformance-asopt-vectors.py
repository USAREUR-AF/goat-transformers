    BAD, UNK, UND = "bad-directive", "unknown-directive", "undeclared-key"
    MISS = "missing-distribution"

    def load(name, text, error=BAD, head=full_head, core=BARE, gtcheck_kind=None):
        num[0] += 1
        full = "%d-asopt-%s" % (num[0], name)
        got = None
        try:
            m = gtcheck.Model()
            for t in (core, PROBE):
                m.add(t)
            gtcheck.load_pack(head + text, m)
        except gtcheck.CheckError as e:
            got = e.kind
        assert got == (gtcheck_kind or error), (full, error, got)
        d = {"name": full, "models": [core, PROBE], "pack": head + text}
        if error:
            d["expect_error"] = error
        sink.write("packs/conformance/load-vectors/%s.json" % full, json.dumps(d, indent=2) + "\n")
