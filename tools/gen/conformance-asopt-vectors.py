class Fail(Exception):
    def __init__(self, kind, why=""):
        super().__init__(kind, why)
        self.kind = kind


def parse_pack(text):
    pack = {"json": False, "common": [], "kinds": []}
    stack = [pack]
    for raw in text.splitlines():
        t = raw.split("#")[0].split()
        if not t or t[0] in ("format", "version", "distribution", "source", "uses", "layout", "bit_order"):
            continue
        d, a, top = t[0], t[1:], stack[-1]
        if d == "wire":
            pack["json"] = a[0] == "json"
        elif d == "end":
            stack.pop()
        elif d == "kind":
            top["kinds"].append({"name": a[0], "requires": [], "lines": []})
        elif d == "requires":
            top["kinds"][-1]["requires"] += a
        elif d in ("case", "else"):
            top["arms"].append((a[0].split(",") if a else None, []))
        else:
            node = {"d": d, "a": a}
            if d == "when":
                node["n"] = int(a[0])
                node["ranges"] = [(int(v.split("..")[0]), int(v.split("..")[-1])) for v in a[1].split(",")]
                rest = a[2:]
                node["at"] = int(rest[1]) if rest[:1] == ["at"] else None
                rest = rest[2:] if rest[:1] == ["at"] else rest
                node["as"] = rest[1] if rest[:1] == ["as"] else None
                node["optional"] = rest[2:] == ["optional"]
            elif d in ("group", "switch"):
                node.update({"common": [], "kinds": [], "arms": []})
            if top.get("arms"):
                top["arms"][-1][1].append(node)
            elif top["kinds"]:
                top["kinds"][-1]["lines"].append(node)
            else:
                top["common"].append(node)
            if d in ("group", "switch"):
                stack.append(node)
    return pack


def matches(pattern, node):
    return any(lo <= pattern <= hi for lo, hi in node["ranges"])


def signed(v, n):
    return v - (1 << 64) if n == 64 and v >> 63 else v


def dec_body(bits, pos, body, ent):
    pos = dec_lines(bits, pos, body["common"], ent)
    if not body["kinds"]:
        return pos
    for kind in body["kinds"]:
        cur, got = pos, {}
        for w in (n for n in kind["lines"] if n["d"] == "when"):
            start = cur if w["at"] is None else pos + w["at"]
            if start + w["n"] > len(bits):
                break
            v = int(bits[start:start + w["n"]], 2)
            if not matches(v, w):
                break
            if w["as"]:
                got[w["as"]] = signed(v, w["n"])
            if w["at"] is None:
                cur += w["n"]
        else:
            ent.update(got)
            ent["@kind"] = kind["name"]
            return dec_lines(bits, cur, [n for n in kind["lines"] if n["d"] != "when"], ent)
    raise Fail("no-kind")


def dec_lines(bits, pos, lines, ent):
    def take(n):
        nonlocal pos
        if pos + n > len(bits):
            raise Fail("malformed-wire")
        pos += n
        return int(bits[pos - n:pos], 2)
    for node in lines:
        d, a = node["d"], node["a"]
        if d == "field":
            v = take(int(a[1]))
            ent.setdefault(a[0], v)     # 0.6: the earliest line of a key
        elif d == "pad":
            take(int(a[0]))
        elif d == "group":
            items = ent[a[0]] = []
            for _ in range(take(int(a[2]))):
                items.append({})
                pos = dec_body(bits, pos, node, items[-1])
        elif d == "switch":
            for values, body in node["arms"]:
                if values is None or str(ent[a[0]]) in values:
                    pos = dec_lines(bits, pos, body, ent)
                    break
            else:
                raise Fail("no-kind")
    return pos


def qualifies(kind, ent):
    for term in kind["requires"]:
        key, eq, values = term.partition("=")
        if key not in ent or (eq and str(ent[key]) not in values.split(",")):
            return False
    for w in kind["lines"]:
        if w["d"] == "when" and w["as"]:
            if w["as"] not in ent:
                if not w["optional"]:
                    return False
            elif not matches(ent[w["as"]] & M64, w):
                return False
    return True


class Out:
    """The bits written, and for each whether a held key wrote it."""

    def __init__(self):
        self.bits, self.held = [], []

    def put(self, v, n, held=False):
        self.bits += list(format(v, "0%db" % n))
        self.held += [held] * n


def enc_body(out, body, ent, same):
    kind = None
    if body["kinds"]:
        recorded = ent.get("@kind") if same else None
        kind = next((k for k in body["kinds"] if (k["name"] == recorded if recorded else qualifies(k, ent))), None)
        if kind is None:
            raise Fail("no-kind")
    back = {}           # key -> (start, length) of its earliest line; read when a switch needs it
    enc_lines(out, body["common"], ent, same, back, lambda: None)
    if kind is None:
        return
    start, todo = len(out.bits), [n for n in kind["lines"] if n["d"] == "when" and n["at"] is not None]

    def settle():
        while todo:
            w = todo.pop(0)
            s, e = start + w["at"], start + w["at"] + w["n"]
            now, key = int("".join(out.bits[s:e]), 2), w["as"]
            want = now
            if not matches(now, w) or (key in ent and ent[key] & M64 != now):
                want = ent[key] & M64 if key in ent else w["ranges"][0][0]
                new = format(want, "0%db" % w["n"])
                if not matches(want, w) or any(out.held[s + i] and out.bits[s + i] != b for i, b in enumerate(new)):
                    raise Fail("transform-encode")
                out.bits[s:e] = list(new)
                # 0.52 ruling 16: a window takes no bit away from a held key;
                # the held bits here are unchanged and stay held
            if key in ent:
                out.held[s:e] = [True] * w["n"]
            if key:
                back.setdefault(key, (s, w["n"]))
    enc_lines(out, kind["lines"], ent, same, back, settle)
    settle()


def enc_lines(out, lines, ent, same, back, settle):
    for node in lines:
        d, a = node["d"], node["a"]
        if d == "field":
            assert 0 <= ent.get(a[0], 0) < 1 << int(a[1])
            back.setdefault(a[0], (len(out.bits), int(a[1])))
            out.put(ent.get(a[0], 0), int(a[1]), a[0] in ent)
        elif d == "pad":
            out.put(0, int(a[0]))
        elif d == "when" and node["at"] is None:
            v = node["ranges"][0][0]
            if node["as"] in ent:
                v = ent[node["as"]] & M64
                if not matches(v, node):
                    raise Fail("transform-encode")
            if node["as"]:
                back.setdefault(node["as"], (len(out.bits), node["n"]))
            out.put(v, node["n"], node["as"] in ent)    # 0.52 ruling 16
        elif d == "group":
            items = ent.get(a[0], [])
            out.put(len(items), int(a[2]))
            for item in items:
                enc_body(out, node, item, same)
        elif d == "switch":
            settle()
            at, n = back[a[0]]
            value = str(signed(int("".join(out.bits[at:at + n]), 2), n))
            arm = next((b for values, b in node["arms"] if values is None or value in values), None)
            if arm is None:
                raise Fail("no-kind")
            enc_lines(out, arm, ent, same, back, settle)


def decode(pack, text):
    ent = {}
    if not pack["json"]:
        bits = "".join(format(b, "08b") for b in bytes.fromhex(text))
        dec_body(bits, 0, pack, ent)
        return ent

    def members(lines, src, dst):
        for n in lines:
            if n["a"][1] in src:
                v = src[n["a"][1]]
                if n["d"] == "group":
                    dst[n["a"][0]] = [members(n["common"], i, {}) for i in v]
                else:
                    dst[n["a"][0]] = v
        return dst
    return members(pack["common"], json.loads(text), ent)


def encode(pack, ent, same):
    if pack["json"]:
        def obj(lines, src):
            return {n["a"][1]: [obj(n["common"], i) for i in src[n["a"][0]]] if n["d"] == "group" else src[n["a"][0]]
                    for n in lines if n["a"][0] in src}
        return json.dumps(obj(pack["common"], ent), separators=(",", ":"))
    out = Out()
    enc_body(out, pack, ent, same)
    bits = "".join(out.bits)
    bits += "0" * (-len(bits) % 8)
    return "".join("%02x" % int(bits[i:i + 8], 2) for i in range(0, len(bits), 8))


def convert(frm, to, text, context):
    """0.6: decode, the absent keys from the context, the derivations, encode.
    The one `derive` line of probe whose target these packs map is
    `derive probe.n_copy copy probe.n` (asserted in build)."""
    ent = decode(parse_pack(PACKS[frm]), text)
    full = dict(ent)
    for k, v in (context or {}).items():
        full.setdefault(k, int(v))
    if "probe.n" in full and (frm != to or context is not None):
        full.setdefault("probe.n_copy", full["probe.n"])
    return ent, lambda: encode(parse_pack(PACKS[to]), full, frm == to)


def model_of(ent, prefix=""):
    have = {}
    for k, v in ent.items():
        if isinstance(v, list):
            have[prefix + k + ".#"] = str(len(v))
            for i, item in enumerate(v):
                have.update(model_of(item, "%s%s[%d]." % (prefix, k, i)))
        else:
            have[prefix + k] = str(v)
    return have


