#!/usr/bin/env python3
"""Write the packs and vectors that pin `iso8601_s` (spec/engine-spec.md,
"Version 0.26: whole-second time"): a time read as `iso8601_ms` reads it and
written to the whole second.

Every expected value is worked out here from the rule the specification
states: epoch milliseconds from the proleptic Gregorian calendar, and the
written text from the second that holds the instant. Nothing calls an engine.

The script writes, and owns:
  packs/conformance-seconds/          packs/conformance-seconds-json/
  packs/conformance-seconds-jsonstr/  packs/conformance-seconds-text/
  packs/conformance/load-vectors/     files named seconds-*.json

Inputs: none; every value is stated in this file. Writes, under --out, the
files named above. The same run always gives the same bytes. With --check
nothing is written and the exit status is 1 when a committed file differs from
what this script writes.

Usage: python3 -I tools/gen/conformance-seconds-vectors.py [--out DIR] [--check]
"""
import datetime
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402

SOURCE = 'source  "goat-transformers spec/engine-spec.md, Version 0.26 (synthetic probe format, no external standard)"'
GENERATED = "# Generated by tools/gen/conformance-seconds-vectors.py. Do not edit by hand.\n"
LOAD_DIR = "packs/conformance/load-vectors"


def build(sink):
    """Write every file through the Output `sink`; {pack: number of files}."""
    counts = {}
    started = set()
    written = {}

    def put(rel, text):
        sink.write(rel, text)
        owner = rel.split("/")[1]
        written[owner] = written.get(owner, 0) + 1

    def write_json(rel, d):
        put(rel, json.dumps(d, indent=2, ensure_ascii=False) + "\n")

    def clear(rel_dir, keep=lambda name: False):
        for old in sink.listdir(rel_dir):
            if old.endswith(".json") and not keep(old):
                sink.remove(rel_dir + "/" + old)

    def pack(name, comment, body):
        clear("packs/%s/vectors" % name)
        text = GENERATED
        for line in comment.strip().split("\n"):
            text += "# " + line.strip() + "\n"
        text += "format  %s\nversion 0.26.0\ndistribution public\n%s\nuses    probe\n" % (name, SOURCE)
        text += body.strip("\n") + "\n"
        put("packs/%s/pack.def" % name, text)
        started.add(name)

    def vec(frm, to, name, inp, expect=None, error=None, model=None):
        assert frm in started, frm
        assert (expect is None) != (error is None), name
        num = counts.get(frm, 0) + 1
        counts[frm] = num
        d = {"name": name, "from": frm, "to": to, "input": inp}
        if error is None:
            d["expect"] = expect
        else:
            d["expect_error"] = error
        if model is not None:
            d["model"] = model
        write_json("packs/%s/vectors/%03d-%s.json" % (frm, num, name), d)

    def epoch_ms(y, mo, d, h=0, mi=0, s=0, ms=0, offset_min=0):
        days = datetime.date(y, mo, d).toordinal() - datetime.date(1970, 1, 1).toordinal()
        return ((days * 24 + h) * 60 + mi - offset_min) * 60000 + s * 1000 + ms

    def seconds_text(ms):
        """The rule of 0.26: the second that holds the instant, never rounded up."""
        days, rest = divmod(ms, 86400000)
        date = datetime.date.fromordinal(datetime.date(1970, 1, 1).toordinal() + days)
        h, rest = divmod(rest, 3600000)
        mi, rest = divmod(rest, 60000)
        s = rest // 1000
        return "%04d-%02d-%02dT%02d:%02d:%02dZ" % (date.year, date.month, date.day, h, mi, s)

    S = "conformance-seconds"
    SJ = "conformance-seconds-json"
    SS = "conformance-seconds-jsonstr"
    ST = "conformance-seconds-text"
    pack(S, """Conformance probe pack for `iso8601_s` (Version 0.26). Public. No kinds.
    One instant in an attribute.""", """
wire    xml
root    e
field   time_ms  @t  iso8601_s
""")
    pack(SJ, """The instant of `conformance-seconds` as a JSON number of epoch
    milliseconds: a vector converts to this pack to state the decoded value, and
    from it to hand the encoder a value.""", """
wire    json
field   time_ms  t  int
""")
    pack(SS, """`iso8601_s` on the `json` wire (Version 0.26). Public. No kinds.""", """
wire    json
field   time_ms  t  iso8601_s
""")
    pack(ST, """`iso8601_s` on the `text` wire (Version 0.26). Public. No kinds. One
    record of one field.""", """
wire    text
field   time_ms  0  iso8601_s
""")

    MIN_MS = epoch_ms(1, 1, 1)
    MAX_MS = epoch_ms(9999, 12, 31, 23, 59, 59, 999)
    assert MIN_MS == -62135596800000 and MAX_MS == 253402300799999

    def s_ok(name, text, ms):
        vec(S, SJ, name, '<e t="%s"/>' % text, '{"t":%d}' % ms, model={"time_ms": str(ms)})
        vec(S, S, name + "-rewritten", '<e t="%s"/>' % text, '<e t="%s"/>' % seconds_text(ms))

    # Decode reads as `iso8601_ms` reads: the fraction is kept to the millisecond.
    s_ok("epoch", "1970-01-01T00:00:00Z", 0)
    s_ok("milliseconds-are-read", "2024-02-29T12:34:56.789Z", epoch_ms(2024, 2, 29, 12, 34, 56, 789))
    s_ok("nine-fraction-digits", "2024-02-29T12:34:56.999999999Z", epoch_ms(2024, 2, 29, 12, 34, 56, 999))
    s_ok("offset", "2024-01-01T00:00:00.250-05:30", epoch_ms(2024, 1, 1, 5, 30, ms=250))
    s_ok("before-1970-whole-second", "1969-12-31T23:59:59Z", -1000)
    s_ok("before-1970-half-second", "1969-12-31T23:59:59.5Z", -500)
    s_ok("one-millisecond-before-1970", "1969-12-31T23:59:59.999Z", -1)
    s_ok("first-instant-of-year-0001", "0001-01-01T00:00:00Z", MIN_MS)
    s_ok("last-millisecond-of-year-9999", "9999-12-31T23:59:59.999Z", MAX_MS)
    vec(S, S, "no-designator-is-refused", '<e t="2024-01-01T00:00:00"/>', error="transform-decode")
    vec(S, S, "leap-second-is-refused", '<e t="2016-12-31T23:59:60Z"/>', error="transform-decode")

    def s_enc(name, ms):
        vec(SJ, S, "encode-" + name, '{"t":%d}' % ms, '<e t="%s"/>' % seconds_text(ms))

    s_enc("epoch", 0)
    s_enc("last-millisecond-of-a-second", 999)
    s_enc("one-millisecond-before-1970", -1)
    s_enc("one-second-before-1970", -1000)
    s_enc("one-second-and-one-millisecond-before-1970", -1001)
    s_enc("first-instant-of-year-0001", MIN_MS)
    s_enc("last-millisecond-of-year-9999", MAX_MS)
    vec(SJ, S, "encode-one-millisecond-before-year-0001-is-refused", '{"t":%d}' % (MIN_MS - 1), error="transform-encode")
    vec(SJ, S, "encode-first-instant-of-year-10000-is-refused", '{"t":%d}' % (MAX_MS + 1), error="transform-encode")

    ms = epoch_ms(2024, 2, 29, 12, 34, 56, 789)
    vec(SS, SS, "json-string-rewritten", '{"t":"2024-02-29T12:34:56.789Z"}', '{"t":"%s"}' % seconds_text(ms),
        model={"time_ms": str(ms)})
    vec(SS, SS, "json-number-is-refused", '{"t":0}', error="transform-decode")
    vec(ST, ST, "text-rewritten", "2024-02-29T12:34:56.789Z", seconds_text(ms), model={"time_ms": str(ms)})
    vec(ST, ST, "text-before-1970", "1969-12-31T23:59:59.5Z", seconds_text(-500), model={"time_ms": "-500"})

    # Load: valid where `iso8601_ms` is, refused elsewhere.
    clear(LOAD_DIR, keep=lambda name: not name.startswith("seconds-"))
    CORE = 'module core\nversion 0.1.0\ndistribution public\nsource "probe"\nkey uid string -\nkey lat float deg\nkey time_ms int ms\n'
    HEAD = 'format probe\nversion 0.26.0\ndistribution public\nsource "probe"\n'
    num = [0]

    def load(name, pack_text, error=None):
        num[0] += 1
        d = {"name": "seconds-%02d-%s" % (num[0], name), "models": [CORE], "pack": pack_text}
        if error:
            d["expect_error"] = error
        write_json("%s/seconds-%02d-%s.json" % (LOAD_DIR, num[0], name), d)

    load("iso8601-s-on-xml-loads", HEAD + "wire xml\nroot e\nfield time_ms @t iso8601_s\n")
    load("iso8601-s-on-json-loads", HEAD + "wire json\nfield time_ms t iso8601_s\n")
    load("iso8601-s-on-text-loads", HEAD + "wire text\nfield time_ms 0 iso8601_s\n")
    load("iso8601-s-on-bits", HEAD + "wire bits\nword_bytes 1\nfield time_ms 0:0:8 iso8601_s\n", "bad-directive")
    load("iso8601-s-with-a-parameter", HEAD + "wire xml\nroot e\nfield time_ms @t iso8601_s:3\n", "bad-directive")
    load("iso8601-s-on-a-string-key", HEAD + "wire xml\nroot e\nfield uid @t iso8601_s\n", "key-type-mismatch")
    return written


def main(argv=None):
    return genio.vector_main("conformance-seconds-vectors.py", __doc__, build, argv)


if __name__ == "__main__":
    sys.exit(main())
