#!/bin/bash
# Regenerate the Cyphal (UAVCAN v1) packs: one pack per data type of
# github.com/OpenCyphal/public_regulated_data_types (a service gives a -request
# and a -response pack), and one module per namespace (model/cy<namespace>.def).
#
# Usage: tools/gen/dsdl2pack-cyphal-run.sh <checkout> <sources> [--fetch] [--check]
#
# <checkout> is a goat-transformers checkout; it is written: model/cy*.def,
# packs/cyphal-*/ (pack.def, pack.md, PROVENANCE.md, vectors/). The generator
# checks the SHA-256 of every input against tools/gen/sources/cyphal-PROVENANCE.md
# and stops when one differs. With --check it writes nothing and reports any
# file that differs from what it would write.
#
# <sources> is a directory for the DSDL tree. It is not kept in the
# repository. With --fetch the script downloads
#   https://codeload.github.com/OpenCyphal/public_regulated_data_types/tar.gz/86e2f332419ff015f4cc9f1bb7843b02d5f7a5ed
#   sha256 dd16d4168fe11aa918e333afddee7a0851be1965cd007bc0840d57e99cfd8926
# and unpacks it to <sources>/public_regulated_data_types-<commit>/. License:
# MIT (LICENSE at the root of the commit, verbatim in
# tools/gen/sources/cyphal-PROVENANCE.md).
#
# Root namespaces: uavcan and reg. The repository has no other.
set -euo pipefail
ROOT="$(cd "$1" && pwd)"
SRC="$(cd "$2" && pwd)"
GEN="$(cd "$(dirname "$0")" && pwd)"
COMMIT=86e2f332419ff015f4cc9f1bb7843b02d5f7a5ed
TAR_SHA=dd16d4168fe11aa918e333afddee7a0851be1965cd007bc0840d57e99cfd8926
shift 2
if [ "${1:-}" = "--fetch" ]; then
  shift
  curl -sS -f -L -o "$SRC/prdt-$COMMIT.tar.gz" \
    "https://codeload.github.com/OpenCyphal/public_regulated_data_types/tar.gz/$COMMIT"
  echo "$TAR_SHA  $SRC/prdt-$COMMIT.tar.gz" | sha256sum -c -
  tar -xzf "$SRC/prdt-$COMMIT.tar.gz" -C "$SRC"
fi
if [ "${1:-}" != "--check" ]; then
  # remove what an earlier run wrote (files whose header names this generator)
  for f in "$ROOT"/model/cy*.def "$ROOT"/packs/cyphal-*/pack.def; do
    [ -e "$f" ] || continue
    if head -3 "$f" | grep -q "Generated by tools/gen/dsdl2pack.py --cyphal"; then
      case "$f" in
        */pack.def) rm -rf "$(dirname "$f")" ;;
        *) rm -f "$f" ;;
      esac
    fi
  done
fi
python3 -I "$GEN/dsdl2pack.py" --cyphal --dsdl "$SRC/public_regulated_data_types-$COMMIT" --out "$ROOT" \
  --core-def "$ROOT/model/core.def" "$@"
