#!/bin/bash
# Regenerate the DBC packs: one pack per DBC file of github.com/commaai/opendbc
# (the files in opendbc/dbc/, and the files opendbc assembles from parts in
# opendbc/dbc/generator/<brand>/), one module per file (model/dbc<file>.def).
#
# Usage: tools/gen/dbc2pack-run.sh <checkout> <sources> [--fetch] [--check]
#
# <checkout> is a goat-transformers checkout; it is written: model/dbc*.def,
# packs/dbc-*/ (pack.def, pack.md, PROVENANCE.md, vectors/). The generator
# checks the SHA-256 of every input against tools/gen/sources/dbc-PROVENANCE.md
# and stops when one differs. With --check it writes nothing and reports any
# file that differs from what it would write.
#
# <sources> is a directory for the opendbc tree. It is not kept in the
# repository. With --fetch the script downloads
#   https://codeload.github.com/commaai/opendbc/tar.gz/79ddcc7bb72d557fc5b20d038c0fad9c9d423446
#   sha256 0f969d44b18b4da6418bd6e7450854e8213acf3cb5327e66844ed1509aeb5dcb
# and unpacks it to <sources>/opendbc-<commit>/. License: MIT, Copyright (c)
# 2020 Comma.ai, Inc. (LICENSE at the root of the commit, verbatim in
# tools/gen/sources/dbc-PROVENANCE.md).
set -euo pipefail
ROOT="$(cd "$1" && pwd)"
SRC="$(cd "$2" && pwd)"
GEN="$(cd "$(dirname "$0")" && pwd)"
COMMIT=79ddcc7bb72d557fc5b20d038c0fad9c9d423446
TAR_SHA=0f969d44b18b4da6418bd6e7450854e8213acf3cb5327e66844ed1509aeb5dcb
shift 2
if [ "${1:-}" = "--fetch" ]; then
  shift
  curl -sS -f -L -o "$SRC/opendbc-$COMMIT.tar.gz" "https://codeload.github.com/commaai/opendbc/tar.gz/$COMMIT"
  echo "$TAR_SHA  $SRC/opendbc-$COMMIT.tar.gz" | sha256sum -c -
  tar -xzf "$SRC/opendbc-$COMMIT.tar.gz" -C "$SRC"
fi
if [ "${1:-}" != "--check" ]; then
  # remove what an earlier run wrote (files whose header names this generator)
  for f in "$ROOT"/model/dbc*.def "$ROOT"/packs/dbc-*/pack.def; do
    [ -e "$f" ] || continue
    if head -3 "$f" | grep -q "Generated by tools/gen/dbc2pack.py"; then
      case "$f" in
        */pack.def) rm -rf "$(dirname "$f")" ;;
        *) rm -f "$f" ;;
      esac
    fi
  done
fi
# Value tables whose label text the repository's boundary gate does not admit:
# the signals keep their numbers, and each pack.md says so.
NO_TABLE=(
  --no-table psa_aee2010_r3:HS2_DYN1_MDD_ETAT_2B6.MDD_DECEL_CONTROL_REQ
  --no-table psa_aee2010_r3:HS2_DYN_MDD_ETAT_2F6.MDD_DECEL_CONTROL_REQ
  --no-table ford_lincoln_base_pt:Cluster_HEV_Data7_FD1.PreCondStat_D_Dsply
)
python3 -I "$GEN/dbc2pack.py" --src "$SRC/opendbc-$COMMIT" --out "$ROOT" --core-def "$ROOT/model/core.def" \
  "${NO_TABLE[@]}" "$@"
