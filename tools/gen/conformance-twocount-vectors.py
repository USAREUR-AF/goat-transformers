# second computation, part 3: a load checker for the lines the load vectors use
# ------------------------------------------------------------------------------
PACK_DIRECTIVES = {"format", "version", "distribution", "source", "uses", "wire", "layout", "word_bytes",
                   "bit_order", "field", "count", "presence", "pad", "if", "opt", "length", "group", "end",
                   "kind", "when", "switch", "case", "else", "requires", "default"}


def check_load(text):
    """None when the pack loads, else the error kind (0.11 ruling 5b order)."""
    lines = [tokens_of(r) for r in text.splitlines()]
    lines = [t for t in lines if t]
    wire = layout = None
    for t in lines:                                   # the line checks, in file order
        if t[0] not in PACK_DIRECTIVES:
            return "unknown-directive"
        if t[0] == "wire":
            wire = t[1]
        if t[0] == "layout":
            layout = t[1]
        if t[0] == "group" and wire == "protobuf" and not t[2].isdigit():
            return "bad-locator"                      # 0.11 5a; 0.21 ruling 44
    # after the file
    seq = wire == "bits" and layout == "sequential"
    for t in lines:
        if t[0] == "group" and len(t) > 3 and t[2] == "count" and not seq:
            return "bad-directive"                    # 0.21 forms; 0.31 load errors
    if not seq:
        return None
    # names: scopes, references, and reading paths
    decls = []          # [name, path-tags]
    refs = []           # (decl index, path-tags)
    root = {"names": {}, "parent": None}
    scope = root
    common_scope = root
    stack = []          # (kind of block, scope to restore, path tag pushed)
    path = []           # tags of the reading path the line is on: ("kind", k) or ("case", switch id, case id)
    switch_ids = [0]
    kind_scope = None
    kinds, cases = [], {}

    def lookup(name, sc):
        while sc is not None:
            if name in sc["names"]:
                return sc["names"][name]
            sc = sc["parent"]
        return None

    for t in lines:
        d = t[0]
        if d == "kind":
            kinds.append(t[1])
            kind_scope = {"names": {}, "parent": common_scope}
            scope = kind_scope
            path = [("kind", t[1])]
        elif d == "count":
            if t[1] in scope["names"] or lookup(t[1], scope) is not None and scope is kind_scope \
                    and t[1] in common_scope["names"]:
                return "bad-directive"
            scope["names"][t[1]] = ("count", len(decls))
            decls.append((t[1], tuple(path)))
        elif d == "presence":
            if t[1] in scope["names"]:
                return "bad-directive"
            scope["names"][t[1]] = ("presence", None)
        elif d in ("if", "opt", "length"):
            stack.append((d, scope, len(path)))
            scope = {"names": {}, "parent": scope}
        elif d == "switch":
            switch_ids[0] += 1
            stack.append(("switch", scope, len(path), switch_ids[0]))
        elif d in ("case", "else"):
            top = stack[-1]
            del path[top[2]:]
            path.append(("case", top[3], " ".join(t)))
            cases.setdefault(top[3], set()).add(" ".join(t))
            scope = {"names": {}, "parent": top[1]}
        elif d == "group":
            stack.append(("group", scope, len(path)))
            rest = t[3:]
            if len(t) < 3 or t[2] != "count" or (len(rest) == 1 and rest[0].isdigit()):
                pass                                  # `count <len>`; no other mode is used here
            else:
                if not 1 <= len(rest) <= 2:
                    return "bad-directive"            # more than two tokens
                names = []
                for tok in rest:
                    if not tok.startswith("@") or len(tok) == 1:
                        return "bad-directive"        # not `@<name>`
                    names.append(tok[1:])
                if len(set(names)) != len(names):
                    return "bad-directive"            # the same name twice
                for name in names:
                    found = lookup(name, scope)
                    if found is None or found[0] != "count":
                        return "bad-directive"        # not visible, or not a count
                    refs.append((found[1], tuple(path)))
            scope = {"names": {}, "parent": None}     # 0.21 ruling 9: a group body sees only its own
        elif d == "end":
            top = stack.pop()
            scope = top[1]
            del path[top[2]:]
    # every reading path: one kind (or none), one case of each switch
    switch_list = sorted(cases)
    for k in kinds or [None]:
        for choice in itertools.product(*[sorted(cases[s]) for s in switch_list]) or [()]:
            picked = dict(zip(switch_list, choice))

            def on(ps):
                for p in ps:
                    if p[0] == "kind" and p[1] != k:
                        return False
                    if p[0] == "case" and picked.get(p[1]) != p[2]:
                        return False
                return True

            for i, (name, ps) in enumerate(decls):
                if on(ps) and sum(1 for j, rps in refs if j == i and on(rps)) != 1:
                    return "bad-directive"
    return None


