import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402

SOURCE = 'source  "goat-transformers spec/engine-spec.md (synthetic probe format, no external standard)"'
GENERATED = "# Generated by tools/gen/conformance-twocount-vectors.py. Do not edit by hand.\n"
LOAD_DIR = "packs/conformance/load-vectors"
LOAD_FIRST = 3100
OWN_LOAD = re.compile(r"\A31\d\d-twocount-.*\.json\Z")


class Fail(Exception):
    """A conversion or a load that fails with an error kind of the spec."""

    def __init__(self, kind, why=""):
        super().__init__(kind, why)
        self.kind, self.why = kind, why


# ------------------------------------------------------------------------------
# second computation, part 1: a parser of the pack lines these packs use
# ------------------------------------------------------------------------------
def tokens_of(raw):
    out, i = [], 0
    while i < len(raw):
        c = raw[i]
        if c in " \t":
            i += 1
        elif c == "#":
            break
        elif c == '"':
            j = raw.index('"', i + 1)
            out.append(raw[i + 1:j])
            i = j + 1
        else:
            j = i
            while j < len(raw) and raw[j] not in " \t":
                j += 1
            out.append(raw[i:j])
            i = j
    return out


class L:
    """One line of a pack, with its body for a block."""

    def __init__(self, d, a):
        self.d, self.a, self.body = d, a, []


def parse_pack(text):
    """{wire, common, kinds: [(name, when, lines)]} for the subset used here."""
    pack = {"wire": None, "common": [], "kinds": []}
    stack = []

    def into():
        if stack:
            return stack[-1].body
        return pack["kinds"][-1][2] if pack["kinds"] else pack["common"]

    for raw in text.splitlines():
        t = tokens_of(raw)
        if not t or t[0] in ("format", "version", "distribution", "source", "uses", "layout", "bit_order"):
            continue
        d, a = t[0], t[1:]
        if d == "wire":
            pack["wire"] = a[0]
        elif d == "end":
            stack.pop()
        elif d == "kind":
            pack["kinds"].append([a[0], [], []])
        elif d == "when" and not stack:
            pack["kinds"][-1][1].append((int(a[0]), int(a[1])))
        else:
            x = L(d, a)
            into().append(x)
            if d in ("group", "opt", "if", "length"):
                stack.append(x)
    return pack


# ------------------------------------------------------------------------------
# second computation, part 2: the sequential codec (decode and encode)
# ------------------------------------------------------------------------------
def to_bits(hx):
    out = []
    for i in range(0, len(hx), 2):
        b = int(hx[i:i + 2], 16)
        out += [(b >> (7 - k)) & 1 for k in range(8)]
    return out


def to_hex(bits):
    bits = bits + [0] * (-len(bits) % 8)
    return "".join("%02x" % int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8))


def vbits(v, n):
    return [(v >> (n - 1 - k)) & 1 for k in range(n)]


def ascii8_decode(code):
    if code == 0:
        return ""
    if 32 <= code <= 126:
        return chr(code)
    raise Fail("transform-decode", "ascii8 code %d" % code)


class Dec:
    def __init__(self, bits):
        self.bits, self.cur, self.end = bits, 0, [len(bits)]
        self.failed = []

    def at_end(self):
        return len(self.end) > 1 and self.cur >= self.end[-1]

    def take(self, n):
        if self.cur + n > self.end[-1]:
            raise Fail("malformed-wire", "read past the end at bit %d" % self.cur)
        v = 0
        for b in self.bits[self.cur:self.cur + n]:
            v = v * 2 + b
        self.cur += n
        return v

    def lines(self, lines, ent, counts, pres):
        for x in lines:
            d, a = x.d, x.a
            if d == "count":
                plus = int(a[3]) if len(a) > 2 else 0
                if self.at_end():
                    counts[a[0]] = None          # not read: no below-plus check
                    continue
                v = self.take(int(a[1]))
                if v < plus:
                    raise Fail("malformed-wire", "count %s = %d below plus %d" % (a[0], v, plus))
                counts[a[0]] = v - plus          # exact integers (0.21 ruling 7)
            elif d == "field":
                if self.at_end():
                    continue
                v = self.take(int(a[1]))
                if a[2] == "uint":
                    ent[a[0]] = v
                elif a[2] == "chars:ascii8":
                    try:
                        ent[a[0]] = ascii8_decode(v)
                    except Fail:
                        self.failed.append(a[0])
                else:
                    raise AssertionError(a[2])
            elif d == "pad":
                self.take(int(a[0]))
            elif d == "presence":
                pres[a[0]] = 0 if self.at_end() else self.take(int(a[1]))
            elif d == "if":
                name, i = a[0].split(".")
                size = 1
                if (pres.get(name, 0) >> (size - int(i))) & 1:
                    self.lines(x.body, ent, counts, pres)
            elif d == "opt":
                if not self.at_end() and self.take(1):
                    self.lines(x.body, ent, counts, pres)
            elif d == "length":
                assert len(a) == 1
                if self.at_end():
                    continue
                n = self.take(int(a[0])) * 8
                stop = self.cur + n
                if stop > self.end[-1]:
                    raise Fail("malformed-wire", "length past the input")
                self.end.append(stop)
                self.lines(x.body, ent, counts, pres)
                self.end.pop()
                self.cur = stop
            elif d == "group":
                assert a[1] == "count" and all(t.startswith("@") for t in a[2:])
                if self.at_end():
                    continue                     # not reached: absent, not compared
                got = [counts[t[1:]] for t in a[2:]]
                if len(set(got)) != 1:
                    raise Fail("malformed-wire", "counts disagree: %s" % got)
                n = got[0]
                if n > self.end[-1] - self.cur:
                    raise Fail("malformed-wire", "%d items, %d bits left" % (n, self.end[-1] - self.cur))
                items = []
                for _ in range(n):
                    it = {}
                    self.lines(x.body, it, {}, {})
                    items.append(it)
                ent[a[0]] = items
            else:
                raise AssertionError(d)


def seq_decode(pack, hx):
    dec = Dec(to_bits(hx))
    ent = {}
    common_counts, pres = {}, {}
    dec.lines(pack["common"], ent, common_counts, pres)
    if pack["kinds"]:
        start = dec.cur
        for name, whens, lines in pack["kinds"]:
            dec.cur = start
            if all(dec.take(n) == v for n, v in whens):
                ent["@kind"] = name
                dec.lines(lines, ent, dict(common_counts), pres)
                break
        else:
            raise Fail("no-kind")
    if dec.failed:
        raise Fail("transform-decode", ",".join(dec.failed))
    return ent


def content(lines, ent):
    for x in lines:
        if x.d == "field" and x.a[0] in ent:
            return True
        if x.d == "group" and ent.get(x.a[0]):
            return True
        if x.d in ("if", "opt", "length") and content(x.body, ent):
            return True
    return False


class Enc:
    def __init__(self):
        self.fills = []       # (count name, len, plus, buffer, offset): set after the group

    def lines(self, lines, ent, out, counts):
        for x in lines:
            d, a = x.d, x.a
            if d == "count":
                plus = int(a[3]) if len(a) > 2 else 0
                slot = {"len": int(a[1]), "plus": plus, "items": None, "buf": out, "at": len(out)}
                out += [0] * int(a[1])
                counts[a[0]] = slot
                self.fills.append(slot)
            elif d == "field":
                n = int(a[1])
                v = ent.get(a[0])
                if v is None:
                    out += [0] * n
                elif a[2] == "uint":
                    if not 0 <= v < (1 << n):
                        raise Fail("transform-encode")
                    out += vbits(v, n)
                elif a[2] == "chars:ascii8":
                    assert len(v) == 1 and 32 <= ord(v) <= 126
                    out += vbits(ord(v), n)
            elif d == "pad":
                out += [0] * int(a[0])
            elif d == "presence":
                assert a[1] == "1"
                bit = any(y.d == "if" and y.a[0] == a[0] + ".1" and content(y.body, ent) for y in lines)
                out.append(1 if bit else 0)
                counts["?" + a[0]] = bit
            elif d == "if":
                if counts["?" + a[0].split(".")[0]]:
                    self.lines(x.body, ent, out, counts)
            elif d == "opt":
                bit = content(x.body, ent)
                out.append(1 if bit else 0)
                if bit:
                    self.lines(x.body, ent, out, counts)
            elif d == "length":
                block = []
                self.lines(x.body, ent, block, dict(counts))
                block += [0] * (-len(block) % 8)
                n = len(block) // 8
                if n >= (1 << int(a[0])):
                    raise Fail("transform-encode")
                out += vbits(n, int(a[0]))
                base = len(out)
                for slot in self.fills:
                    if slot["buf"] is block:
                        slot["buf"], slot["at"] = out, slot["at"] + base
                out += block
            elif d == "group":
                items = ent.get(a[0])
                for t in a[2:]:
                    counts[t[1:]]["items"] = None if items is None else len(items)
                for it in items or []:
                    self.lines(x.body, it, out, {})
            else:
                raise AssertionError(d)

    def finish(self):
        # 0.21 ruling 30: the range check runs when the message is finished
        for slot in self.fills:
            v = (slot["items"] or 0) + slot["plus"]
            if not 0 <= v < (1 << slot["len"]):
                raise Fail("transform-encode", "count %d out of range" % v)
            slot["buf"][slot["at"]:slot["at"] + slot["len"]] = vbits(v, slot["len"])


def seq_encode(pack, ent):
    enc = Enc()
    out, counts = [], {}
    enc.lines(pack["common"], ent, out, counts)
    if pack["kinds"]:
        name, whens, lines = pack["kinds"][0]
        assert len(pack["kinds"]) == 1
        for n, v in whens:
            out += vbits(v, n)
        enc.lines(lines, ent, out, counts)
    enc.finish()
    return to_hex(out)


def json_decode(pack, text):
    obj = json.loads(text)
    ent = {}
    for x in pack["common"]:
        if x.a[1] in obj:
            if x.d == "field":
                ent[x.a[0]] = obj[x.a[1]]
            else:
                ent[x.a[0]] = [{x.body[0].a[0]: v} for v in obj[x.a[1]]]
    return ent


def json_encode(pack, ent):
    parts = []
    for x in pack["common"]:
        if x.a[0] not in ent:
            continue
        v = ent[x.a[0]]
        if x.d == "group":
            v = [it[x.body[0].a[0]] for it in v]
        parts.append(json.dumps(x.a[1]) + ":" + json.dumps(v, separators=(",", ":")))
    return "{" + ",".join(parts) + "}"


def convert(packs, frm, to, inp):
    src, dst = packs[frm], packs[to]
    ent = json_decode(src, inp) if src["wire"] == "json" else seq_decode(src, inp)
    ent.pop("@kind", None) if dst["kinds"] == [] else None
    return json_encode(dst, ent) if dst["wire"] == "json" else seq_encode(dst, ent), ent


def model_of(ent):
    out = {}
    for k, v in ent.items():
        if k == "@kind":
            out[k] = v
        elif isinstance(v, list):
            out[k + ".#"] = str(len(v))
            for i, it in enumerate(v):
                for ik, iv in it.items():
                    out["%s[%d].%s" % (k, i, ik)] = str(iv)
        else:
            out[k] = str(v)
    return out


