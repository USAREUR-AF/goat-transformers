#!/usr/bin/env python3
"""Write the vectors of spec 0.31, one list counted from two places
(`group <list> count @<a> @<b>`): the packs `conformance-twocount-*` and the
load vectors from 3100.

Every expected value here is worked out by hand from the spec text (Version
0.31 and its rulings 1 to 8, and the sections they refer to: 0.8 sequential
lines, `opt`, presence, `length` and rulings 5, 7, 14 and 25; 0.21 counts
and its rulings 2, 6, 7, 9, 12, 20, 22, 23, 30 and 44; 0.22 ruling 5; 0.11
rulings 5a and 5b; 0.1.1 ruling 9). The hand working is the comment above
each vector, bytes written as hex, and the value is written out literally.

It is checked against a second computation: the small codec below parses the
pack.def text this script writes with its own parser and applies the rules to
the input; the small load checker below applies the 0.31 load rules and the
0.11 order of checks to each load vector. Both cover only the lines these
packs and load vectors use. Nothing here imports or calls an engine.

Readings of the text these vectors rest on (reported with them):
  - "each count that was read passes its own below-`plus` check": a count
    line at the end of a `length` extent is not read and has no check
    (conformance-twocount-length, `count-b-at-the-extent-end-is-not-read`).
  - "A value outside 0 ... 2^len - 1 for either count is `transform-encode`":
    an empty, present list is in range or not as any other number of items
    (0.21: "absent and empty lists included").
  - The three decode checks of ruling 4 give one error kind, so their order is
    not visible in a vector; the vectors show each check failing alone, and two
    failing together.

Inputs: none; every value is stated in this file. Writes, under --out, the
files named above. The same run always gives the same bytes. With --check
nothing is written and the exit status is 1 when a committed file differs from
what this script writes.

Usage: python3 -I tools/gen/conformance-twocount-vectors.py [--out DIR] [--check]
"""
