#!/usr/bin/env python3
"""ipfix2def: the IANA IPFIX Information Elements as the model module `ipfix`.

Usage: python3 -I tools/gen/ipfix2def.py --csv <ipfix-information-elements.csv> --out <checkout> [--check]

Reads the registry of IPFIX Information Elements that IANA publishes as CSV
(https://www.iana.org/assignments/ipfix/ipfix-information-elements.csv) and writes
model/ipfix.def: one key per element whose abstract data type a fixed-width field of the
`bits` wire can hold, named from the element's name in snake case
(sourceIPv4Address -> source_ipv4_address), and the list `records` that the flow packs
(IPFIX, NetFlow version 9, NetFlow version 5) read their flow records into.

  unsigned8 .. unsigned64, signed32, boolean, dateTimeSeconds .. dateTimeNanoseconds,
  ipv4Address, macAddress                      int (the field as an integer)
  float64                                      float
  string                                       string
  ipv6Address                                  eight int keys <name>_g0 .. <name>_g7, the
                                               address in 16-bit groups, first group first
  octetArray, unsigned256, basicList, subTemplateList, subTemplateMultiList
                                               no key (no fixed-width integer holds them)

The meaning of a key is the element's number, name, abstract type, semantics and units as
the registry lists them; no description text is taken. Rows that are ranges or reserved
are skipped. Python 3 standard library only; every file goes through tools/gen/genio.py.
"""
import argparse
import csv
import hashlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402

NAME = "ipfix2def"
INT_TYPES = {"unsigned8", "unsigned16", "unsigned32", "unsigned64", "signed8", "signed16", "signed32",
             "signed64", "boolean", "dateTimeSeconds", "dateTimeMilliseconds", "dateTimeMicroseconds",
             "dateTimeNanoseconds", "ipv4Address", "macAddress"}
NO_KEY = {"octetArray", "unsigned256", "basicList", "subTemplateList", "subTemplateMultiList"}
NOTES = {
    "ipv4Address": "the address as a 32-bit integer",
    "macAddress": "the 48-bit address as an integer",
    "boolean": "1 true, 2 false on the wire (RFC 7011 6.1.5)",
    "dateTimeSeconds": "seconds since 1970-01-01 UTC",
    "dateTimeMilliseconds": "milliseconds since 1970-01-01 UTC",
    "dateTimeMicroseconds": "NTP timestamp format (RFC 7011 6.1.9), as one 64-bit integer",
    "dateTimeNanoseconds": "NTP timestamp format (RFC 7011 6.1.10), as one 64-bit integer",
}


class DefError(Exception):
    pass


def snake(name):
    s = name.replace("IPv4", "Ipv4").replace("IPv6", "Ipv6")
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return s.lower()


def rows(path):
    with open(path, encoding="utf-8", newline="") as fh:
        data = list(csv.DictReader(fh))
    need = {"ElementID", "Name", "Abstract Data Type", "Data Type Semantics", "Status", "Units"}
    if not data or not need <= set(data[0]):
        raise DefError("%s: not the IANA IPFIX Information Elements CSV (columns %s)" % (path, sorted(need)))
    out = []
    for r in data:
        eid, name, adt = r["ElementID"].strip(), r["Name"].strip(), r["Abstract Data Type"].strip()
        if not re.fullmatch(r"\d+", eid) or not adt or name in ("", "Reserved") or name.startswith("Assigned"):
            continue
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name):
            raise DefError("element %s: name %r is not an identifier" % (eid, name))
        out.append((int(eid), name, adt, r["Data Type Semantics"].strip(), r["Status"].strip(),
                    r["Units"].strip()))
    return out


def module_text(elems, csv_sha, csv_date):
    w = ["# The ipfix module: the IPFIX Information Elements of the IANA registry, one key per",
         "# element a fixed-width field can hold, and the list of flow records. Generated by",
         "# tools/gen/ipfix2def.py from the registry CSV; edit the generator, not this file.",
         "module        ipfix",
         "version       0.1.0",
         "distribution  public",
         'source        "IANA, IP Flow Information Export (IPFIX) Entities, registry IPFIX Information '
         'Elements, https://www.iana.org/assignments/ipfix/ipfix-information-elements.csv, registry updated '
         '%s, sha256 %s; element numbers, names, abstract types, semantics and units only"' % (csv_date, csv_sha),
         ('source        "IANA and IETF joint statement on the Protocol Registries (CC0 1.0), '
          'https://www.iana.org/help/licensing-terms"'),
         "",
         ('list  records  "the flow records of one message: one item per Data Record (IPFIX), flow '
          'record (NetFlow version 9) or flow (NetFlow version 5)"'),
         ""]
    seen, skipped = set(), []
    for eid, name, adt, sem, status, units in elems:
        if adt in NO_KEY:
            skipped.append((eid, name, adt))
            continue
        if adt not in INT_TYPES and adt not in ("float64", "float32", "string", "ipv6Address"):
            raise DefError("element %d %s: abstract type %s is not known to the generator" % (eid, name, adt))
        base = snake(name)
        bits = [adt] + ([sem] if sem else []) + (["units %s" % units] if units else []) + \
               (["deprecated"] if status == "deprecated" else [])
        what = "IE %d %s: %s" % (eid, name, ", ".join(bits))
        if adt == "ipv6Address":
            for g in range(8):
                key = "%s_g%d" % (base, g)
                if key in seen:
                    raise DefError("key %s twice" % key)
                seen.add(key)
                w.append('key  %-56s int     -  "%s; 16-bit group %d of 8 of the address"' % (key, what, g + 1))
            continue
        if base in seen:
            raise DefError("key %s twice" % base)
        seen.add(base)
        typ = "int" if adt in INT_TYPES else ("float" if adt.startswith("float") else "string")
        note = NOTES.get(adt)
        w.append('key  %-56s %-7s -  "%s%s"' % (base, typ, what, "; " + note if note else ""))
    w.append("")
    w.append("# Elements with no key (octetArray, unsigned256 and the structured types): %s" %
             ", ".join("%d" % e for e, _, _ in skipped))
    w.append("")
    return "\n".join(w), len(seen), skipped


def main(argv=None):
    ap = argparse.ArgumentParser(prog=NAME, description=__doc__.split("\n\n")[0])
    ap.add_argument("--csv", required=True)
    ap.add_argument("--registry-date", required=True, help="the date the registry states it was updated")
    genio.add_arguments(ap)
    a = ap.parse_args(argv)
    try:
        with open(a.csv, "rb") as fh:
            sha = hashlib.sha256(fh.read()).hexdigest()
        text, n, skipped = module_text(rows(a.csv), sha, a.registry_date)
    except (DefError, OSError) as e:
        print("%s: %s" % (NAME, e), file=sys.stderr)
        return 1
    out = genio.Output(a.out, check=a.check)
    out.write("model/ipfix.def", text)
    st = out.report(NAME)
    if not a.check:
        print("model/ipfix.def: %d keys, %d elements without a key" % (n, len(skipped)))
    return st


if __name__ == "__main__":
    sys.exit(main())
