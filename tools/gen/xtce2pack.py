def sample(leaf, i):
    """A raw value for a vector: within the field and different per field."""
    if leaf.enum:
        vals = sorted(leaf.enum.values())
        return vals[i % len(vals)]
    if leaf.transform in ("f32", "f64"):
        return None
    if leaf.ktype == "string":
        return None
    top = (1 << (leaf.bits - (1 if leaf.transform.startswith(("twos", "sscale")) else 0))) - 1
    return (i * 37 + 5) % (top + 1) if top else 0


ITEMS = 2   # the items a vector writes for each repeat of variable count


def vector(fmt, module, k, db_label):
    """A round trip of the kind, its bits written here from the kind's lines:
    a `when` pad holds its criterion value and any other pad zero bits, a count
    the number of items (ITEMS), integers and enumerations sample values,
    floats and texts zero bits (0.0 and the empty text)."""
    bits, model = [], {"@kind": k.name}
    whens = {off: (n, v, key) for n, v, off, key in k.whens}

    def emit(n, v):
        bits.extend((v >> (n - 1 - i)) & 1 for i in range(n))

    def walk(lines, top, salt):
        for i, item in enumerate(lines):
            if item[0] == "stop":
                return False
            if item[0] == "pad":
                at = len(bits)
                if top and at in whens:
                    n, v, key = whens[at]
                    model[module + "." + key] = str(v)
                    emit(n, v)
                else:
                    emit(item[1], 0)
            elif item[0] == "count":
                emit(item[2], ITEMS)
            elif item[0] == "group":
                model["%s.%s.#" % (module, item[1])] = str(ITEMS)
                for j in range(ITEMS):
                    walk(item[3], False, salt + 7 * (j + 1))
            else:
                leaf = item[1]
                raw = sample(leaf, i + salt)
                emit(leaf.bits, raw or 0)
                if top and raw is not None and leaf.ktype == "int":
                    # a two's complement value with its top bit set reads negative
                    v = raw - (1 << leaf.bits) if leaf.transform == "twos" and raw >> (leaf.bits - 1) else raw
                    model[module + "." + leaf.key] = str(v)
        return True

    walk(k.lines, True, 0)
    bits += [0] * (-len(bits) % 8)
    msg = bytes(int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)).hex()
    return {"name": "rt-" + k.name, "from": fmt, "to": fmt, "input": msg, "expect": msg, "model": model,
            "source": "written by tools/gen/xtce2pack.py from the container's entries in %s" % db_label,
            "reference": "CCSDS 660.0-B-2: a sequence container's entries in order, most significant bit first"}


def render(lines, module, ind):
    out = []
    for item in lines:
        if item[0] == "pad":
            out.append("%spad   %d" % (ind, item[1]))
        elif item[0] == "stop":
            out.append("%s# not mapped from here on: %s" % (ind, item[1]))
        elif item[0] == "count":
            out.append("%scount  %s  %d" % (ind, item[1], item[2]))
        elif item[0] == "group":
            out.append("%sgroup  %s.%s  count @%s" % (ind, module, item[1], item[2]))
            out += render(item[3], module, ind + "  ")
            out.append("%send" % ind)
        else:
            leaf = item[1]
            out.append("%sfield  %s.%s  %d  %s" % (ind, module, leaf.key, leaf.bits, leaf.transform))
    return out


def pack_text(fmt, module, db_label, sources, kinds):
    L = [GENERATED.format(db=db_label),
         "# One kind per concrete container; each comparison of its restriction criteria",
         "# is a `when ... at ... as` on the bits it compares (engine-spec 0.30, 0.33).",
         "format     %s" % fmt, "version    0.1.0", "distribution public"]
    L += ['source     "%s"' % s for s in sources]
    L += ["uses       %s" % module, "wire       bits", "layout     sequential", "bit_order  msb"]
    for k in kinds:
        L += ["", "kind  %s" % k.name]
        for n, v, off, key in k.whens:
            L.append("when  %d  %d  at %d  as %s.%s" % (n, v, off, module, key))
        L += render(k.lines, module, "")
    return "\n".join(L) + "\n"


def module_text(module, db_label, sources, leaves, lists=None):
    L = ["# The %s module: the parameters of the XTCE database %s, as its containers" % (module, db_label),
         "# lay them out. Written by tools/gen/xtce2pack.py; do not edit by hand.",
         "module        %s" % module, "version       0.1.0", "distribution  public"]
    L += ['source        "%s"' % s for s in sources[:1]]
    width = max(len(k) for k in leaves)
    for key in sorted(leaves):
        leaf = leaves[key]
        desc = (leaf.desc or key.replace("_", " ")).replace('"', "'")
        L.append('key   %-*s  %-6s -  "%s"' % (width, key, leaf.ktype, desc))
    for name in sorted(lists or {}):
        L.append('list  %-*s  "%s"' % (width, name, (lists[name]).replace('"', "'")))
    return "\n".join(L) + "\n"


def pack_md(fmt, db_label, family, kinds, left_out):
    L = ["# %s" % fmt, "",
         "The containers of the XTCE database %s that extend `%s`, as one" % (db_label, family),
         "`layout sequential` `bits` pack written by `tools/gen/xtce2pack.py`. Each concrete",
         "container is a message kind. Its restriction criteria, and those of its bases,",
         "are `when ... at <offset> as <key>` lines on the bits they compare, so the kind is",
         "selected by them on decode and chosen by those keys on encode; the compared",
         "bits are a `pad` in the kind, since the `as` key holds them.", "",
         "| Kind | Fields | Selected by | Not mapped from |", "|---|---:|---|---|"]
    for k in kinds:
        sel = ", ".join("`%s` = %d" % (key, v) for _, v, _, key in k.whens) or "none"
        L.append("| `%s` | %d | %s | %s |" % (k.name, len(k.leaves), sel, k.stop or ""))
    notes = [n for k in kinds for n in k.notes]
    if notes:
        L += ["", "Read again:", ""] + ["- %s" % n for n in notes]
    if left_out:
        L += ["", "Containers left out, with the reason:", ""]
        L += ["- `%s`: %s" % (n, why) for n, why in left_out]
    L += ["", "Floats and texts are written as zero bits in the round-trip vectors, which",
          "check the bytes and the integer, boolean and enumerated keys.", "",
          "Do not edit `pack.def`, `PROVENANCE.md`, the module or the `rt-*` vectors by hand:",
          "change the generator or its inputs and run it again. The `derived-*` vectors",
          "were derived by hand from the database and the specification, with no engine",
          "and not by the generator, which keeps them."]
    return "\n".join(L) + "\n"


def provenance_md(fmt, db, table):
    return "\n".join([
        "# PROVENANCE: %s" % fmt, "",
        "| Item | Value |", "|---|---|",
        "| Source | XTCE database `%s`, from %s |" % (db["file"], table["repository"]),
        "| Commit | `%s` |" % table["commit"],
        "| SHA-256 | `%s` |" % db["sha256"],
        "| Licence | %s, stated in the file's own header and in the repository's LICENSE |" % db["licence"],
        "| Standard | XTCE, CCSDS 660.0-B-2 (OMG XTCE 1.2). Its notice grants a licence to write software based on the standard; no part of it is copied here |",
        "| Distribution | public |", "",
        "The pack was written by `tools/gen/xtce2pack.py` from this file alone.", ""])


def read_provenance(text):
    """The repository, commit and the files of tools/gen/sources/xtce-PROVENANCE.md."""
    table = {"files": []}
    for line in text.splitlines():
        m = re.match(r"\| (repository|commit) \| `?([^`|]+?)`? \|$", line)
        if m:
            table[m.group(1)] = m.group(2)
        m = re.match(r"\| `([^`]+\.xml)` \| `([0-9a-f]{64})` \| ([^|]+) \| ([a-z0-9-]+) \|$", line)
        if m:
            table["files"].append({"file": m.group(1), "sha256": m.group(2), "licence": m.group(3).strip(),
                                   "name": m.group(4)})
    if not table["files"] or "commit" not in table or "repository" not in table:
        raise GenError("%s names no repository, commit or file" % PROV)
    return table


def run(src, out, provenance=None):
    here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    table = read_provenance(open(provenance or os.path.join(here, PROV), encoding="utf-8").read())
    core = open(os.path.join(here, "model", "core.def"), encoding="utf-8").read()
    report = []
    for db in table["files"]:
        path = os.path.join(src, db["file"])
        if sha256(path) != db["sha256"]:
            raise GenError("%s does not match the SHA-256 in %s" % (db["file"], PROV))
        root = System(ET.parse(path).getroot(), None)
        module = "xtce" + re.sub(r"[^a-z0-9]", "", db["name"])
        label = "%s (%s @%s)" % (db["file"], table["repository"], table["commit"][:9])
        sources = ["XTCE database %s, %s at commit %s (sha256 %s); %s" % (
            db["file"], table["repository"], table["commit"], db["sha256"], db["licence"]),
            "XTCE, CCSDS 660.0-B-2 (OMG XTCE 1.2): the meaning of the database's containers and encodings"]

        def keyname(psys, pel):
            rel = psys.path[len(root.path):].strip("/")
            return snake((rel + "/" if rel else "") + pel.get("name"))

        leaves, lists, packs = {}, {}, []
        for fam, concrete in families(root):
            kinds, left_out = [], []
            for c in concrete:
                try:
                    k = build_kind(c, keyname)
                except (GenError, Stop) as e:
                    left_out.append((c.name, str(e)))
                    continue
                if not k.whens:
                    left_out.append((c.name, "no criterion selects it"))
                    continue
                kinds.append(k)
            if not kinds:
                report.append("%s: family %s: no kind (%d left out)" % (db["file"], fam.name, len(left_out)))
                continue
            # more criteria first, so a container is tried before the bases it narrows
            kinds.sort(key=lambda k: -len(k.whens))
            names = [k.name for k in kinds]
            if len(set(names)) != len(names):
                raise GenError("two containers of family %s have one name" % fam.name)
            for k in kinds:
                for lf in k.leaves + k.item_leaves:
                    leaves[lf.key] = lf
                lists.update(k.lists)
                for _, _, _, key in k.whens:
                    leaves.setdefault(key, Leaf(key, 0, "uint", "int", desc="the bits that select a container"))
            packs.append((fam, kinds, left_out))
        out.write("model/%s.def" % module, module_text(module, label, sources, leaves, lists))
        for fam, kinds, left_out in packs:
            fmt = "xtce-%s-%s" % (db["name"], snake(fam.name).replace("_", "-"))
            pdir = "packs/" + fmt
            text = pack_text(fmt, module, label, sources, kinds)
            out.write(pdir + "/pack.def", text)
            vecs = {"rt-%s.json" % k.name: vector(fmt, module, k, label) for k in kinds}
            # only the round trips are the generator's; vectors derived by hand
            # beside them (derived-*.json) are kept
            for old in out.listdir(pdir + "/vectors"):
                if old.startswith("rt-") and old.endswith(".json") and old not in vecs:
                    out.remove("%s/vectors/%s" % (pdir, old))
            for n, v in vecs.items():
                out.write("%s/vectors/%s" % (pdir, n), json.dumps(v, indent=2) + "\n")
            model = gtcheck.Model()
            model.add(core, "model/core.def")
            model.add(out.read("model/%s.def" % module), "model/%s.def" % module)
            gtcheck.load_pack(out.read(pdir + "/pack.def"), model, pdir + "/pack.def")
            out.write(pdir + "/pack.md", pack_md(fmt, label, fam.name, kinds, left_out))
            out.write(pdir + "/PROVENANCE.md", provenance_md(fmt, db, table))
            report.append("%s: %d kinds, %d left out" % (fmt, len(kinds), len(left_out)))
    return report


def main(argv=None):
    here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap = argparse.ArgumentParser(prog="xtce2pack", description=__doc__.split("\n\n")[0])
    genio.add_arguments(ap, default_out=here)
    ap.add_argument("--src", required=True, help="the directory that holds the database files")
    ap.add_argument("--provenance", help="the table of databases (default %s)" % PROV)
    args = ap.parse_args(argv)
    out = genio.Output(args.out, check=args.check)
    try:
        lines = run(args.src, out, args.provenance)
    except (GenError, gtcheck.CheckError) as e:
        print("xtce2pack: %s" % e, file=sys.stderr)
        return 1
    print("\n".join(lines))
    return out.report("xtce2pack.py")


if __name__ == "__main__":
    sys.exit(main())
