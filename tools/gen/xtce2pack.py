class GenError(Exception):
    pass


class Stop(Exception):
    """An entry or type this phase does not state: the kind's mapping ends here."""


def tag(el):
    return el.tag[len(NS):] if el.tag.startswith(NS) else el.tag


def snake(text):
    s = re.sub(r"[^0-9A-Za-z]+", "_", text).strip("_")
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower()
    return re.sub(r"_+", "_", s) or "x"


def sha256(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


# --------------------------------------------------------------- database ---

class System:
    """One SpaceSystem: its types, parameters and containers by name."""

    def __init__(self, el, parent):
        self.el, self.parent = el, parent
        self.name = el.get("name")
        self.path = (parent.path if parent else "") + "/" + self.name
        self.children = {}
        self.types, self.params, self.containers = {}, {}, {}
        tm = el.find(NS + "TelemetryMetaData")
        if tm is not None:
            for section, store in (("ParameterTypeSet", self.types), ("ParameterSet", self.params),
                                   ("ContainerSet", self.containers)):
                s = tm.find(NS + section)
                for item in (s if s is not None else []):
                    if item.get("name"):
                        store[item.get("name")] = item
        for sub in el.findall(NS + "SpaceSystem"):
            self.children[sub.get("name")] = System(sub, self)

    def root(self):
        return self.parent.root() if self.parent else self

    def every(self):
        yield self
        for c in self.children.values():
            yield from c.every()


def lookup(system, ref, kind):
    """(system, element, member path) for a reference to a parameter, type or
    container, by the path rules of XTCE: `/a/b/x` from the root, `../x` and
    `./x` relative, and a bare relative name looked up in the system and then in
    each enclosing one. For a parameter, steps after it name aggregate members."""
    store = {"param": "params", "type": "types", "container": "containers"}[kind]
    steps = ref.split("/")
    starts = [system.root()] if ref.startswith("/") else []
    if not starts:
        s = system
        while s is not None:
            starts.append(s)
            s = s.parent
    for start in starts:
        found = _walk(start, [x for x in steps if x != ""] if ref.startswith("/") else steps, store, kind,
                      absolute=ref.startswith("/"))
        if found:
            return found
        if ref.startswith(("./", "../")):
            break
    raise GenError("%s %s: no such %s from %s" % (kind, ref, kind, system.path))


def _walk(start, steps, store, kind, absolute):
    s = start
    if absolute:
        if not steps or steps[0] != s.name:
            return None
        steps = steps[1:]
    for i, step in enumerate(steps):
        if step == ".":
            continue
        if step == "..":
            if s.parent is None:
                return None
            s = s.parent
            continue
        last = i == len(steps) - 1
        table = getattr(s, store)
        if step in table and (last or kind == "param"):
            return s, table[step], [x for x in steps[i + 1:] if x not in (".",)]
        if step in s.children:
            s = s.children[step]
            continue
        return None
    return None


# ------------------------------------------------------------------ types ---

class Leaf:
    """One field of the wire: its key, its bits, its transform and key type."""

    def __init__(self, key, bits, transform, ktype, enum=None, desc=""):
        self.key, self.bits, self.transform, self.ktype = key, bits, transform, ktype
        self.enum, self.desc = enum or {}, desc

    def fixed(self):
        return self.bits is not None


def integer_encoding(enc):
    if enc is None:
        return 8, False
    if enc.get("byteOrder", "mostSignificantByteFirst") != "mostSignificantByteFirst":
        raise Stop("byte order %s" % enc.get("byteOrder"))
    coding = enc.get("encoding", "unsigned")
    if coding not in ("unsigned", "twosComplement"):
        raise Stop("integer encoding %s" % coding)
    return int(enc.get("sizeInBits", "8")), coding == "twosComplement"


def polynomial(enc):
    """(c0, c1) texts of a polynomial calibrator of degree 0 or 1, or None."""
    cal = enc.find(NS + "DefaultCalibrator") if enc is not None else None
    if cal is None:
        return None
    if cal.find(NS + "PolynomialCalibrator") is None:
        raise Stop("calibrator %s" % tag(list(cal)[0]) if len(cal) else "empty calibrator")
    terms = {int(t.get("exponent")): t.get("coefficient") for t in cal.find(NS + "PolynomialCalibrator")}
    if any(e > 1 for e in terms) or not terms:
        raise Stop("polynomial calibrator of degree above 1")
    return terms.get(0, "0"), terms.get(1, "0")


def number_text(t):
    """A coefficient as gtcheck's number text: decimal, no exponent."""
    if not re.fullmatch(r"-?\d+(\.\d+)?", t):
        raise Stop("calibrator coefficient %s" % t)
    return t


def factor_text(t):
    """A scale factor: an exact ratio is written as the fraction (`0.1` as
    `1/10`), as ruling 1 of engine-spec 0.5 asks, because the division gives the
    nearest double to the exact value and the product does not."""
    from fractions import Fraction
    f = Fraction(number_text(t))
    return str(f.numerator) if f.denominator == 1 else "%d/%d" % (f.numerator, f.denominator)


def leaves_of(system, ptype, key, desc):
    """The fields a parameter of `ptype` takes on the wire."""
    kind = tag(ptype)
    if kind == "AggregateParameterType":
        out = []
        for m in ptype.find(NS + "MemberList"):
            ms, mt, _ = lookup(system, m.get("typeRef"), "type")
            out += leaves_of(ms, mt, key + "_" + snake(m.get("name")), m.get("shortDescription") or desc)
        return out
    if kind in ("IntegerParameterType", "EnumeratedParameterType", "BooleanParameterType"):
        enc = ptype.find(NS + "IntegerDataEncoding")
        if enc is None and ptype.find(NS + "BinaryDataEncoding") is not None:
            raise Stop("binary encoding of %s" % kind)
        bits, signed = integer_encoding(enc)
        enum = {}
        if kind == "EnumeratedParameterType":
            for e in ptype.iter(NS + "Enumeration"):
                enum[e.get("label")] = int(e.get("value"))
        if kind == "BooleanParameterType":
            enum = {ptype.get("zeroStringValue", "False"): 0, ptype.get("oneStringValue", "True"): 1}
        cal = polynomial(enc)
        if cal and kind == "IntegerParameterType":
            c0, c1 = number_text(cal[0]), factor_text(cal[1])
            if (c0, c1) not in (("0", "1"), ("0.0", "1")):
                return [Leaf(key, bits, "%s:%s:%s" % ("sscale" if signed else "uscale", c1, c0), "float", desc=desc)]
        if cal and kind != "IntegerParameterType":
            raise Stop("calibrator on %s" % kind)
        return [Leaf(key, bits, "twos" if signed else "uint", "int", enum, desc)]
    if kind == "FloatParameterType":
        fenc = ptype.find(NS + "FloatDataEncoding")
        if fenc is not None:
            if fenc.get("encoding", "IEEE754_1985") != "IEEE754_1985":
                raise Stop("float encoding %s" % fenc.get("encoding"))
            if fenc.get("byteOrder", "mostSignificantByteFirst") != "mostSignificantByteFirst":
                raise Stop("byte order %s" % fenc.get("byteOrder"))
            size = int(fenc.get("sizeInBits", "32"))
            if size not in (32, 64) or fenc.find(NS + "DefaultCalibrator") is not None:
                raise Stop("float of %d bits or calibrated" % size)
            return [Leaf(key, size, "f%d" % size, "float", desc=desc)]
        enc = ptype.find(NS + "IntegerDataEncoding")
        bits, signed = integer_encoding(enc)
        cal = polynomial(enc) or ("0", "1")
        c0, c1 = number_text(cal[0]), factor_text(cal[1])
        return [Leaf(key, bits, "%s:%s:%s" % ("sscale" if signed else "uscale", c1, c0), "float", desc=desc)]
    if kind == "StringParameterType":
        senc = ptype.find(NS + "StringDataEncoding")
        size = senc.find(NS + "SizeInBits") if senc is not None else None
        fixed = size.find(NS + "Fixed") if size is not None else None
        value = fixed.find(NS + "FixedValue") if fixed is not None else None
        if value is None:
            raise Stop("a string whose size is not fixed")
        bits = int(value.text)
        if bits % 8 or not 8 <= bits <= 2040:
            raise Stop("a string of %d bits" % bits)
        return [Leaf(key, bits, "utf8", "string", desc=desc)]
    raise Stop(kind)


# ------------------------------------------------------------- containers ---

class Container:
    def __init__(self, system, el):
        self.system, self.el = system, el
        self.name = el.get("name")
        self.abstract = el.get("abstract") == "true"
        base = el.find(NS + "BaseContainer")
        self.base_ref = base.get("containerRef") if base is not None else None
        self.criteria_el = base.find(NS + "RestrictionCriteria") if base is not None else None
        self.base = None
        self.children = []


def comparisons(c):
    """The (system, parameter reference, value) comparisons of a container's
    own criteria; GenError when they cannot be stated by this phase."""
    rc = c.criteria_el
    if rc is None:
        return []
    out = []
    for item in rc:
        t = tag(item)
        if t == "Comparison":
            cmps = [item]
        elif t == "ComparisonList":
            cmps = list(item.iter(NS + "Comparison"))
        else:
            raise GenError("criteria %s" % t)
        for cmp in cmps:
            if cmp.get("comparisonOperator", "==") != "==":
                raise GenError("comparison %s" % cmp.get("comparisonOperator"))
            if cmp.get("instance", "0") != "0":
                raise GenError("comparison of instance %s" % cmp.get("instance"))
            out.append((c.system, cmp.get("parameterRef"), cmp.get("value"), cmp.get("useCalibratedValue", "true")))
    return out


class Kind:
    def __init__(self, name):
        self.name = name
        self.lines = []          # ("field", Leaf) | ("pad", bits) | ("stop", why)
        self.whens = []          # (bits, value, offset, key)
        self.leaves = []         # the Leafs of the field lines, in order
        self.item_leaves = []    # the Leafs of the lines of group bodies
        self.lists = {}          # list name -> description
        self.item_bits = {}      # list name -> bits of one item
        self.notes = []
        self.stop = None


def entries_of(c):
    chain = []
    x = c
    while x is not None:
        chain.append(x)
        x = x.base
    out = []
    for x in reversed(chain):
        el = x.el.find(NS + "EntryList")
        out += [(x.system, e) for e in (el if el is not None else [])]
    return out


class Layout:
    """Lays out a container's entries as lines, with the bit offset of each.

    The offset counts from the message's first bit. Each container's bit 0 is
    the start of the whole container, inherited entries included, and an
    included container's locations count from where it is included (the XTCE
    schema's description of LocationInContainerInBits)."""

    def __init__(self, kind, want, keyname):
        self.k, self.want, self.keyname = kind, want, keyname
        self.offset = 0
        self.placed = {}      # parameter key -> (lines, index, offset, bits) of its field line
        self.variable = False # True after a group whose size the count sets
        self.overlaid = {}    # key read again on the bits of an earlier field -> that field's key

    def move_to(self, target, lines):
        if target > self.offset:
            lines.append(("pad", target - self.offset))
            self.offset = target
        elif target < self.offset:
            raise Stop("an entry before the end of the entry ahead of it")

    def location(self, e, start):
        """The bit an entry starts at, or None for the next one."""
        loc = e.find(NS + "LocationInContainerInBits")
        if loc is None:
            return None
        fv = loc.find(NS + "FixedValue")
        if fv is None:
            raise Stop("an entry at a location that is not fixed")
        v = int(fv.text.strip())
        where = loc.get("referenceLocation", "previousEntry")
        if where == "previousEntry":
            return self.offset + v
        if where == "containerStart":
            if self.variable:
                raise Stop("an entry located from the container's start after a repeat of variable count")
            return start + v
        raise Stop("an entry located from %s" % where)

    def leaves(self, system, ref):
        psys, pel, members = lookup(system, ref, "param")
        if members:
            raise Stop("an entry of an aggregate's member")
        tsys, tel, _ = lookup(psys, pel.get("parameterTypeRef"), "type")
        return leaves_of(tsys, tel, self.keyname(psys, pel), pel.get("shortDescription") or ""), pel

    def entries(self, entries, start, lines, in_group=False):
        for system, e in entries:
            self.entry(system, e, start, lines, in_group)

    def entry(self, system, e, start, lines, in_group):
        t = tag(e)
        if e.find(NS + "IncludeCondition") is not None:
            raise Stop("an entry with an include condition")
        if t not in ("ParameterRefEntry", "ContainerRefEntry"):
            raise Stop(t)
        target = self.location(e, start)
        repeat = e.find(NS + "RepeatEntry")
        if repeat is not None:
            self.repeated(system, e, target, start, repeat, lines, in_group)
            return
        if target is not None and target < self.offset and t == "ParameterRefEntry" and not in_group:
            self.overlay(system, e, target)
            return
        if target is not None:
            self.move_to(target, lines)
        self.one(system, e, lines, in_group, suffix="")

    def overlay(self, system, e, target):
        """An entry located on the bits of a field already laid out, of the same
        size: the same bits read again under a second name. It is kept only as
        the count of a later repeat (`repeated`), which turns that field's line
        into the count."""
        leaves, _ = self.leaves(system, e.get("parameterRef"))
        hit = [(key, at) for key, at in self.placed.items() if at[2] == target]
        if len(leaves) != 1 or not hit or hit[0][1][3] != leaves[0].bits:
            raise Stop("an entry before the end of the entry ahead of it")
        first_key, at = hit[0]
        self.placed[leaves[0].key] = at
        self.overlaid[leaves[0].key] = first_key

    def one(self, system, e, lines, in_group, suffix):
        if tag(e) == "ContainerRefEntry":
            cs, cel, _ = lookup(system, e.get("containerRef"), "container")
            here = self.offset
            sub = Container(cs, cel)
            chain = []
            x = sub
            while x is not None:
                chain.append(x)
                x = None
                if chain[-1].base_ref:
                    bs, bel, _ = lookup(chain[-1].system, chain[-1].base_ref, "container")
                    x = Container(bs, bel)
            for c in reversed(chain):
                el = c.el.find(NS + "EntryList")
                for item in (el if el is not None else []):
                    if suffix:
                        self.suffixed(c.system, item, here, lines, in_group, suffix)
                    else:
                        self.entry(c.system, item, here, lines, in_group)
            return
        leaves, _ = self.leaves(system, e.get("parameterRef"))
        for leaf in leaves:
            if suffix:
                leaf = Leaf(leaf.key + suffix, leaf.bits, leaf.transform, leaf.ktype, leaf.enum, leaf.desc)
            if not in_group and leaf.key in self.want:
                self.k.whens.append((leaf.bits, self.want.pop(leaf.key), self.offset, leaf.key))
                lines.append(("pad", leaf.bits))
            elif any(leaf.key == w[3] for w in self.k.whens):
                # its `when ... as` binds the key already (0.30 forbids a second line)
                raise Stop("a second instance of %s, which selects the kind" % leaf.key)
            else:
                if not in_group:
                    self.placed[leaf.key] = (lines, len(lines), self.offset, leaf.bits)
                lines.append(("field", leaf))
                if not in_group:
                    self.k.leaves.append(leaf)
                else:
                    self.k.item_leaves.append(leaf)
            self.offset += leaf.bits

    def suffixed(self, system, item, start, lines, in_group, suffix):
        if item.find(NS + "RepeatEntry") is not None:
            raise Stop("a repeat inside a repeat")
        if item.find(NS + "IncludeCondition") is not None:
            raise Stop("an entry with an include condition")
        target = self.location(item, start)
        if target is not None:
            self.move_to(target, lines)
        self.one(system, item, lines, in_group, suffix)

    def repeated(self, system, e, target, start, repeat, lines, in_group):
        count = repeat.find(NS + "Count")
        if count is None or len(count) != 1:
            raise Stop("a repeat whose count is not one value")
        if repeat.find(NS + "Offset") is not None and repeat.find(NS + "Offset").find(NS + "FixedValue").text.strip() != "0":
            raise Stop("a repeat with an offset between its items")
        how = count[0]
        if tag(how) == "FixedValue":
            n = int(how.text.strip())
            if not 1 <= n <= 32:
                raise Stop("a repeat of %d" % n)
            if target is not None:
                self.move_to(target, lines)
            for i in range(1, n + 1):
                self.one(system, e, lines, in_group, suffix="_%d" % i)
            return
        if tag(how) != "DynamicValue" or in_group:
            raise Stop("a repeat counted by %s" % tag(how))
        ref = how.find(NS + "ParameterInstanceRef")
        if ref is None or how.find(NS + "LinearAdjustment") is not None or ref.get("instance", "0") != "0":
            raise Stop("a repeat counted by an adjusted value")
        leaves, _ = self.leaves(system, ref.get("parameterRef"))
        if len(leaves) != 1 or leaves[0].transform != "uint":
            raise Stop("a repeat counted by a value that is not an unsigned integer")
        ckey = leaves[0].key
        if ckey not in self.placed:
            raise Stop("a repeat counted by a value laid out after it")
        clines, ci, _, cbits = self.placed.pop(ckey)
        if clines[ci][0] != "field":
            raise Stop("a repeat counted by a value already used")
        clines[ci] = ("count", "n_" + ckey, cbits)
        gone = self.overlaid.get(ckey, ckey)
        self.k.leaves = [lf for lf in self.k.leaves if lf.key != gone]
        if gone != ckey:
            self.k.notes.append("`%s` is read again as `%s`, the count of the repeat: the field is the count line"
                                % (gone, ckey))
        if target is not None:
            self.move_to(target, lines)
        name = snake(e.get("containerRef") or e.get("parameterRef")) + "_items"
        body = []
        before = self.offset
        self.one(system, e, body, True, suffix="")
        if any(x[0] in ("stop", "group", "count") for x in body):
            raise Stop("a repeated entry that is not fixed")
        self.k.item_bits[name] = self.offset - before
        self.offset = before          # the items' size is not known here
        lines.append(("group", name, "n_" + ckey, body))
        self.k.lists[name] = "items of %s, as many as %s states" % (e.get("containerRef") or e.get("parameterRef"), ckey)
        self.variable = True          # offsets after this group depend on the count


def build_kind(c, keyname):
    """The kind of a concrete container, or GenError when its criteria cannot be stated."""
    k = Kind(snake(c.name))
    # every comparison along the chain: (leaf key, raw value)
    wanted = []
    x = c
    while x is not None:
        for system, ref, value, calibrated in comparisons(x):
            psys, pel, members = lookup(system, ref, "param")
            tsys, tel, _ = lookup(psys, pel.get("parameterTypeRef"), "type")
            try:
                leaves = leaves_of(tsys, tel, keyname(psys, pel), "")
            except Stop as e:
                raise GenError("criterion on %s: %s" % (ref, e))
            key = keyname(psys, pel) + "".join("_" + snake(m) for m in members)
            leaf = next((lf for lf in leaves if lf.key == key), None)
            if leaf is None or leaf.ktype != "int":
                raise GenError("criterion on %s, which is not an integer, boolean or enumerated field" % ref)
            if leaf.enum and value in leaf.enum:
                raw = leaf.enum[value]
            elif re.fullmatch(r"\d+", value or ""):
                raw = int(value)
            else:
                raise GenError("criterion value %r of %s" % (value, ref))
            wanted.append((key, raw))
        x = x.base
    want = {}
    for key, raw in wanted:
        if want.get(key, raw) != raw:
            raise GenError("two criteria on %s disagree" % key)
        want[key] = raw
    lay = Layout(k, want, keyname)
    try:
        lay.entries(entries_of(c), 0, k.lines)
    except Stop as st:
        k.stop = str(st)
        k.lines.append(("stop", k.stop))
    if want:
        raise GenError("criterion on %s, which no entry before it lays out" % ", ".join(sorted(want)))
    return k


def families(db):
    """Root container -> its concrete descendants, depth first."""
    allc = {}
    for s in db.every():
        for name, el in s.containers.items():
            if tag(el) == "SequenceContainer":
                allc[(s.path, name)] = Container(s, el)
    for c in allc.values():
        if c.base_ref:
            bs, bel, _ = lookup(c.system, c.base_ref, "container")
            c.base = allc[(bs.path, bel.get("name"))]
            c.base.children.append(c)
    roots = [c for c in allc.values() if c.base is None and c.children]
    out = []
    for r in roots:
        todo, concrete = [r], []
        while todo:
            x = todo.pop(0)
            if not x.abstract and x.base is not None:
                concrete.append(x)
            todo += x.children
        out.append((r, concrete))
    return out


