NS = "{http://www.omg.org/space/xtce}"
PROV = "tools/gen/sources/xtce-PROVENANCE.md"
GENERATED = "# Generated by tools/gen/xtce2pack.py from {db}; do not edit by hand."


class GenError(Exception):
    pass


class Stop(Exception):
    """An entry or type this phase does not state: the kind's mapping ends here."""


def tag(el):
    return el.tag[len(NS):] if el.tag.startswith(NS) else el.tag


def snake(text):
    s = re.sub(r"[^0-9A-Za-z]+", "_", text).strip("_")
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower()
    return re.sub(r"_+", "_", s) or "x"


def sha256(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


# --------------------------------------------------------------- database ---

class System:
    """One SpaceSystem: its types, parameters and containers by name."""

    def __init__(self, el, parent):
        self.el, self.parent = el, parent
        self.name = el.get("name")
        self.path = (parent.path if parent else "") + "/" + self.name
        self.children = {}
        self.types, self.params, self.containers = {}, {}, {}
        tm = el.find(NS + "TelemetryMetaData")
        if tm is not None:
            for section, store in (("ParameterTypeSet", self.types), ("ParameterSet", self.params),
                                   ("ContainerSet", self.containers)):
                s = tm.find(NS + section)
                for item in (s if s is not None else []):
                    if item.get("name"):
                        store[item.get("name")] = item
        for sub in el.findall(NS + "SpaceSystem"):
            self.children[sub.get("name")] = System(sub, self)

    def root(self):
        return self.parent.root() if self.parent else self

    def every(self):
        yield self
        for c in self.children.values():
            yield from c.every()


def lookup(system, ref, kind):
    """(system, element, member path) for a reference to a parameter, type or
    container, by the path rules of XTCE: `/a/b/x` from the root, `../x` and
    `./x` relative, and a bare relative name looked up in the system and then in
    each enclosing one. For a parameter, steps after it name aggregate members."""
    store = {"param": "params", "type": "types", "container": "containers"}[kind]
    steps = ref.split("/")
    starts = [system.root()] if ref.startswith("/") else []
    if not starts:
        s = system
        while s is not None:
            starts.append(s)
            s = s.parent
    for start in starts:
        found = _walk(start, [x for x in steps if x != ""] if ref.startswith("/") else steps, store, kind,
                      absolute=ref.startswith("/"))
        if found:
            return found
        if ref.startswith(("./", "../")):
            break
    raise GenError("%s %s: no such %s from %s" % (kind, ref, kind, system.path))


def _walk(start, steps, store, kind, absolute):
    s = start
    if absolute:
        if not steps or steps[0] != s.name:
            return None
        steps = steps[1:]
    for i, step in enumerate(steps):
        if step == ".":
            continue
        if step == "..":
            if s.parent is None:
                return None
            s = s.parent
            continue
        last = i == len(steps) - 1
        table = getattr(s, store)
        if step in table and (last or kind == "param"):
            return s, table[step], [x for x in steps[i + 1:] if x not in (".",)]
        if step in s.children:
            s = s.children[step]
            continue
        return None
    return None


# ------------------------------------------------------------------ types ---

class Leaf:
    """One field of the wire: its key, its bits, its transform and key type."""

    def __init__(self, key, bits, transform, ktype, enum=None, desc=""):
        self.key, self.bits, self.transform, self.ktype = key, bits, transform, ktype
        self.enum, self.desc = enum or {}, desc

    def fixed(self):
        return self.bits is not None


def integer_encoding(enc):
    if enc is None:
        return 8, False
    if enc.get("byteOrder", "mostSignificantByteFirst") != "mostSignificantByteFirst":
        raise Stop("byte order %s" % enc.get("byteOrder"))
    coding = enc.get("encoding", "unsigned")
    if coding not in ("unsigned", "twosComplement"):
        raise Stop("integer encoding %s" % coding)
    return int(enc.get("sizeInBits", "8")), coding == "twosComplement"


def polynomial(enc):
    """(c0, c1) texts of a polynomial calibrator of degree 0 or 1, or None."""
    cal = enc.find(NS + "DefaultCalibrator") if enc is not None else None
    if cal is None:
        return None
    if cal.find(NS + "PolynomialCalibrator") is None:
        raise Stop("calibrator %s" % tag(list(cal)[0]) if len(cal) else "empty calibrator")
    terms = {int(t.get("exponent")): t.get("coefficient") for t in cal.find(NS + "PolynomialCalibrator")}
    if any(e > 1 for e in terms) or not terms:
        raise Stop("polynomial calibrator of degree above 1")
    return terms.get(0, "0"), terms.get(1, "0")


def number_text(t):
    """A coefficient as gtcheck's number text: decimal, no exponent."""
    if not re.fullmatch(r"-?\d+(\.\d+)?", t):
        raise Stop("calibrator coefficient %s" % t)
    return t


def factor_text(t):
    """A scale factor: an exact ratio is written as the fraction (`0.1` as
    `1/10`), as ruling 1 of engine-spec 0.5 asks, because the division gives the
    nearest double to the exact value and the product does not."""
    from fractions import Fraction
    f = Fraction(number_text(t))
    return str(f.numerator) if f.denominator == 1 else "%d/%d" % (f.numerator, f.denominator)


def leaves_of(system, ptype, key, desc):
    """The fields a parameter of `ptype` takes on the wire."""
    kind = tag(ptype)
    if kind == "AggregateParameterType":
        out = []
        for m in ptype.find(NS + "MemberList"):
            ms, mt, _ = lookup(system, m.get("typeRef"), "type")
            out += leaves_of(ms, mt, key + "_" + snake(m.get("name")), m.get("shortDescription") or desc)
        return out
    if kind in ("IntegerParameterType", "EnumeratedParameterType", "BooleanParameterType"):
        enc = ptype.find(NS + "IntegerDataEncoding")
        if enc is None and ptype.find(NS + "BinaryDataEncoding") is not None:
            raise Stop("binary encoding of %s" % kind)
        bits, signed = integer_encoding(enc)
        enum = {}
        if kind == "EnumeratedParameterType":
            for e in ptype.iter(NS + "Enumeration"):
                enum[e.get("label")] = int(e.get("value"))
        if kind == "BooleanParameterType":
            enum = {ptype.get("zeroStringValue", "False"): 0, ptype.get("oneStringValue", "True"): 1}
        cal = polynomial(enc)
        if cal and kind == "IntegerParameterType":
            c0, c1 = number_text(cal[0]), factor_text(cal[1])
            if (c0, c1) not in (("0", "1"), ("0.0", "1")):
                return [Leaf(key, bits, "%s:%s:%s" % ("sscale" if signed else "uscale", c1, c0), "float", desc=desc)]
        if cal and kind != "IntegerParameterType":
            raise Stop("calibrator on %s" % kind)
        return [Leaf(key, bits, "twos" if signed else "uint", "int", enum, desc)]
    if kind == "FloatParameterType":
        fenc = ptype.find(NS + "FloatDataEncoding")
        if fenc is not None:
            if fenc.get("encoding", "IEEE754_1985") != "IEEE754_1985":
                raise Stop("float encoding %s" % fenc.get("encoding"))
            if fenc.get("byteOrder", "mostSignificantByteFirst") != "mostSignificantByteFirst":
                raise Stop("byte order %s" % fenc.get("byteOrder"))
            size = int(fenc.get("sizeInBits", "32"))
            if size not in (32, 64) or fenc.find(NS + "DefaultCalibrator") is not None:
                raise Stop("float of %d bits or calibrated" % size)
            return [Leaf(key, size, "f%d" % size, "float", desc=desc)]
        enc = ptype.find(NS + "IntegerDataEncoding")
        bits, signed = integer_encoding(enc)
        cal = polynomial(enc) or ("0", "1")
        c0, c1 = number_text(cal[0]), factor_text(cal[1])
        return [Leaf(key, bits, "%s:%s:%s" % ("sscale" if signed else "uscale", c1, c0), "float", desc=desc)]
    if kind == "StringParameterType":
        senc = ptype.find(NS + "StringDataEncoding")
        size = senc.find(NS + "SizeInBits") if senc is not None else None
        fixed = size.find(NS + "Fixed") if size is not None else None
        value = fixed.find(NS + "FixedValue") if fixed is not None else None
        if value is None:
            raise Stop("a string whose size is not fixed")
        bits = int(value.text)
        if bits % 8 or not 8 <= bits <= 2040:
            raise Stop("a string of %d bits" % bits)
        return [Leaf(key, bits, "utf8", "string", desc=desc)]
    raise Stop(kind)


# ------------------------------------------------------------- containers ---

class Container:
    def __init__(self, system, el):
        self.system, self.el = system, el
        self.name = el.get("name")
        self.abstract = el.get("abstract") == "true"
        base = el.find(NS + "BaseContainer")
        self.base_ref = base.get("containerRef") if base is not None else None
        self.criteria_el = base.find(NS + "RestrictionCriteria") if base is not None else None
        self.base = None
        self.children = []


def comparisons(c):
    """The (system, parameter reference, value) comparisons of a container's
    own criteria; GenError when they cannot be stated by this phase."""
    rc = c.criteria_el
    if rc is None:
        return []
    out = []
    for item in rc:
        t = tag(item)
        if t == "Comparison":
            cmps = [item]
        elif t == "ComparisonList":
            cmps = list(item.iter(NS + "Comparison"))
        else:
            raise GenError("criteria %s" % t)
        for cmp in cmps:
            if cmp.get("comparisonOperator", "==") != "==":
                raise GenError("comparison %s" % cmp.get("comparisonOperator"))
            if cmp.get("instance", "0") != "0":
                raise GenError("comparison of instance %s" % cmp.get("instance"))
            out.append((c.system, cmp.get("parameterRef"), cmp.get("value"), cmp.get("useCalibratedValue", "true")))
    return out


class Kind:
    def __init__(self, name):
        self.name = name
        self.lines = []          # ("field", Leaf) | ("pad", bits) | ("stop", why)
        self.whens = []          # (bits, value, offset, key)
        self.leaves = []         # the Leafs of the field lines, in order
        self.stop = None


def entries_of(c):
    chain = []
    x = c
    while x is not None:
        chain.append(x)
        x = x.base
    out = []
    for x in reversed(chain):
        el = x.el.find(NS + "EntryList")
        out += [(x.system, e) for e in (el if el is not None else [])]
    return out


def build_kind(c, keyname):
    """The kind of a concrete container, or GenError when its criteria cannot be stated."""
    k = Kind(snake(c.name))
    # every comparison along the chain: (leaf key, raw value)
    wanted = []
    x = c
    while x is not None:
        for system, ref, value, calibrated in comparisons(x):
            psys, pel, members = lookup(system, ref, "param")
            tsys, tel, _ = lookup(psys, pel.get("parameterTypeRef"), "type")
            try:
                leaves = leaves_of(tsys, tel, keyname(psys, pel), "")
            except Stop as e:
                raise GenError("criterion on %s: %s" % (ref, e))
            key = keyname(psys, pel) + "".join("_" + snake(m) for m in members)
            leaf = next((lf for lf in leaves if lf.key == key), None)
            if leaf is None or leaf.ktype != "int":
                raise GenError("criterion on %s, which is not an integer, boolean or enumerated field" % ref)
            if leaf.enum and value in leaf.enum:
                raw = leaf.enum[value]
            elif re.fullmatch(r"\d+", value or ""):
                raw = int(value)
            else:
                raise GenError("criterion value %r of %s" % (value, ref))
            wanted.append((key, raw))
        x = x.base
    want = {}
    for key, raw in wanted:
        if want.get(key, raw) != raw:
            raise GenError("two criteria on %s disagree" % key)
        want[key] = raw
    offset = 0
    for system, e in entries_of(c):
        if k.stop:
            break
        try:
            t = tag(e)
            if t != "ParameterRefEntry":
                raise Stop(t)
            if e.find(NS + "IncludeCondition") is not None:
                raise Stop("an entry with an include condition")
            loc = e.find(NS + "LocationInContainerInBits")
            if loc is not None:
                fv = loc.find(NS + "FixedValue")
                if loc.get("referenceLocation", "previousEntry") != "previousEntry" or fv is None or fv.text.strip() != "0":
                    raise Stop("an entry at a stated location")
            psys, pel, members = lookup(system, e.get("parameterRef"), "param")
            if members:
                raise Stop("an entry of an aggregate's member")
            tsys, tel, _ = lookup(psys, pel.get("parameterTypeRef"), "type")
            for leaf in leaves_of(tsys, tel, keyname(psys, pel), pel.get("shortDescription") or ""):
                if leaf.key in want:
                    k.whens.append((leaf.bits, want.pop(leaf.key), offset, leaf.key))
                    k.lines.append(("pad", leaf.bits))
                else:
                    k.lines.append(("field", leaf))
                    k.leaves.append(leaf)
                offset += leaf.bits
        except Stop as s:
            k.stop = str(s)
            k.lines.append(("stop", k.stop))
    if want:
        raise GenError("criterion on %s, which no entry before it lays out" % ", ".join(sorted(want)))
    return k


def families(db):
    """Root container -> its concrete descendants, depth first."""
    allc = {}
    for s in db.every():
        for name, el in s.containers.items():
            if tag(el) == "SequenceContainer":
                allc[(s.path, name)] = Container(s, el)
    for c in allc.values():
        if c.base_ref:
            bs, bel, _ = lookup(c.system, c.base_ref, "container")
            c.base = allc[(bs.path, bel.get("name"))]
            c.base.children.append(c)
    roots = [c for c in allc.values() if c.base is None and c.children]
    out = []
    for r in roots:
        todo, concrete = [r], []
        while todo:
            x = todo.pop(0)
            if not x.abstract and x.base is not None:
                concrete.append(x)
            todo += x.children
        out.append((r, concrete))
    return out


# ----------------------------------------------------------------- output ---

def bit_writer(lines, values):
    """The message of a kind: each field's value, each pad's bits from `values`."""
    bits = []
    for item in lines:
        if item[0] == "stop":
            break
        if item[0] == "pad":
            n, v = item[1], values[("pad", len(bits))]
        else:
            leaf = item[1]
            n, v = leaf.bits, values[leaf.key]
        bits += [(v >> (n - 1 - i)) & 1 for i in range(n)]
    bits += [0] * (-len(bits) % 8)
    return bytes(int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8))


def sample(leaf, i):
    """A raw value for a vector: within the field and different per field."""
    if leaf.enum:
        vals = sorted(leaf.enum.values())
        return vals[i % len(vals)]
    if leaf.transform in ("f32", "f64"):
        return None
    if leaf.ktype == "string":
        return None
    top = (1 << (leaf.bits - (1 if leaf.transform.startswith(("twos", "sscale")) else 0))) - 1
    return (i * 37 + 5) % (top + 1) if top else 0


def vector(fmt, module, k, db_label):
    """A round trip of the kind, written by the bit writer: integers and
    enumerations get sample values; floats and texts are written as zero bits,
    an empty text and 0.0."""
    values, model, written = {}, {"@kind": k.name}, []
    offset = 0
    whens = {off: (n, v, key) for n, v, off, key in k.whens}
    for i, item in enumerate(k.lines):
        if item[0] == "stop":
            break
        if item[0] == "pad":
            n, v, key = whens[offset]
            values[("pad", offset)] = v
            model[module + "." + key] = str(v)
            offset += n
            continue
        leaf = item[1]
        raw = sample(leaf, i)
        values[leaf.key] = raw or 0
        if raw is not None and leaf.ktype == "int":
            # a two's complement value with its top bit set reads negative
            v = raw - (1 << leaf.bits) if leaf.transform == "twos" and raw >> (leaf.bits - 1) else raw
            model[module + "." + leaf.key] = str(v)
        offset += leaf.bits
    msg = bit_writer(k.lines, values).hex()
    return {"name": "rt-" + k.name, "from": fmt, "to": fmt, "input": msg, "expect": msg, "model": model,
            "source": "written by tools/gen/xtce2pack.py from the container's entries in %s" % db_label,
            "reference": "CCSDS 660.0-B-2: a sequence container's entries in order, most significant bit first"}


def pack_text(fmt, module, db_label, sources, kinds):
    L = [GENERATED.format(db=db_label),
         "# One kind per concrete container; each comparison of its restriction criteria",
         "# is a `when ... at ... as` on the bits it compares (engine-spec 0.30, 0.33).",
         "format     %s" % fmt, "version    0.1.0", "distribution public"]
    L += ['source     "%s"' % s for s in sources]
    L += ["uses       %s" % module, "wire       bits", "layout     sequential", "bit_order  msb"]
    for k in kinds:
        L += ["", "kind  %s" % k.name]
        for n, v, off, key in k.whens:
            L.append("when  %d  %d  at %d  as %s.%s" % (n, v, off, module, key))
        for item in k.lines:
            if item[0] == "pad":
                L.append("pad   %d" % item[1])
            elif item[0] == "stop":
                L.append("# not mapped from here on: %s" % item[1])
            else:
                leaf = item[1]
                L.append("field  %s.%s  %d  %s" % (module, leaf.key, leaf.bits, leaf.transform))
    return "\n".join(L) + "\n"


def module_text(module, db_label, sources, leaves):
    L = ["# The %s module: the parameters of the XTCE database %s, as its containers" % (module, db_label),
         "# lay them out. Written by tools/gen/xtce2pack.py; do not edit by hand.",
         "module        %s" % module, "version       0.1.0", "distribution  public"]
    L += ['source        "%s"' % s for s in sources[:1]]
    width = max(len(k) for k in leaves)
    for key in sorted(leaves):
        leaf = leaves[key]
        desc = (leaf.desc or key.replace("_", " ")).replace('"', "'")
        L.append('key   %-*s  %-6s -  "%s"' % (width, key, leaf.ktype, desc))
    return "\n".join(L) + "\n"


def pack_md(fmt, db_label, family, kinds, left_out):
    L = ["# %s" % fmt, "",
         "The containers of the XTCE database %s that extend `%s`, as one" % (db_label, family),
         "`layout sequential` `bits` pack written by `tools/gen/xtce2pack.py`. Each concrete",
         "container is a message kind. Its restriction criteria, and those of its bases,",
         "are `when ... at <offset> as <key>` lines on the bits they compare, so the kind is",
         "selected by them on decode and chosen by those keys on encode; the compared",
         "bits are a `pad` in the kind, since the `as` key holds them.", "",
         "| Kind | Fields | Selected by | Not mapped from |", "|---|---:|---|---|"]
    for k in kinds:
        sel = ", ".join("`%s` = %d" % (key, v) for _, v, _, key in k.whens) or "none"
        L.append("| `%s` | %d | %s | %s |" % (k.name, len(k.leaves), sel, k.stop or ""))
    if left_out:
        L += ["", "Containers left out, with the reason:", ""]
        L += ["- `%s`: %s" % (n, why) for n, why in left_out]
    L += ["", "Floats and texts are written as zero bits in the round-trip vectors, which",
          "check the bytes and the integer, boolean and enumerated keys.", "",
          "Do not edit `pack.def`, `PROVENANCE.md`, the module or the `rt-*` vectors by hand:",
          "change the generator or its inputs and run it again. The `derived-*` vectors",
          "were derived by hand from the database and the specification, with no engine",
          "and not by the generator, which keeps them."]
    return "\n".join(L) + "\n"


def provenance_md(fmt, db, table):
    return "\n".join([
        "# PROVENANCE: %s" % fmt, "",
        "| Item | Value |", "|---|---|",
        "| Source | XTCE database `%s`, from %s |" % (db["file"], table["repository"]),
        "| Commit | `%s` |" % table["commit"],
        "| SHA-256 | `%s` |" % db["sha256"],
        "| Licence | %s, stated in the file's own header and in the repository's LICENSE |" % db["licence"],
        "| Standard | XTCE, CCSDS 660.0-B-2 (OMG XTCE 1.2). Its notice grants a licence to write software based on the standard; no part of it is copied here |",
        "| Distribution | public |", "",
        "The pack was written by `tools/gen/xtce2pack.py` from this file alone.", ""])


def read_provenance(text):
    """The repository, commit and the files of tools/gen/sources/xtce-PROVENANCE.md."""
    table = {"files": []}
    for line in text.splitlines():
        m = re.match(r"\| (repository|commit) \| `?([^`|]+?)`? \|$", line)
        if m:
            table[m.group(1)] = m.group(2)
        m = re.match(r"\| `([^`]+\.xml)` \| `([0-9a-f]{64})` \| ([^|]+) \| ([a-z0-9-]+) \|$", line)
        if m:
            table["files"].append({"file": m.group(1), "sha256": m.group(2), "licence": m.group(3).strip(),
                                   "name": m.group(4)})
    if not table["files"] or "commit" not in table or "repository" not in table:
        raise GenError("%s names no repository, commit or file" % PROV)
    return table


def run(src, out, provenance=None):
    here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    table = read_provenance(open(provenance or os.path.join(here, PROV), encoding="utf-8").read())
    core = open(os.path.join(here, "model", "core.def"), encoding="utf-8").read()
    report = []
    for db in table["files"]:
        path = os.path.join(src, db["file"])
        if sha256(path) != db["sha256"]:
            raise GenError("%s does not match the SHA-256 in %s" % (db["file"], PROV))
        root = System(ET.parse(path).getroot(), None)
        module = "xtce" + re.sub(r"[^a-z0-9]", "", db["name"])
        label = "%s (%s @%s)" % (db["file"], table["repository"], table["commit"][:9])
        sources = ["XTCE database %s, %s at commit %s (sha256 %s); %s" % (
            db["file"], table["repository"], table["commit"], db["sha256"], db["licence"]),
            "XTCE, CCSDS 660.0-B-2 (OMG XTCE 1.2): the meaning of the database's containers and encodings"]

        def keyname(psys, pel):
            rel = psys.path[len(root.path):].strip("/")
            return snake((rel + "/" if rel else "") + pel.get("name"))

        leaves, packs = {}, []
        for fam, concrete in families(root):
            kinds, left_out = [], []
            for c in concrete:
                try:
                    k = build_kind(c, keyname)
                except (GenError, Stop) as e:
                    left_out.append((c.name, str(e)))
                    continue
                if not k.whens:
                    left_out.append((c.name, "no criterion selects it"))
                    continue
                kinds.append(k)
            if not kinds:
                report.append("%s: family %s: no kind (%d left out)" % (db["file"], fam.name, len(left_out)))
                continue
            # more criteria first, so a container is tried before the bases it narrows
            kinds.sort(key=lambda k: -len(k.whens))
            names = [k.name for k in kinds]
            if len(set(names)) != len(names):
                raise GenError("two containers of family %s have one name" % fam.name)
            for k in kinds:
                for lf in k.leaves:
                    leaves[lf.key] = lf
                for _, _, _, key in k.whens:
                    leaves.setdefault(key, Leaf(key, 0, "uint", "int", desc="the bits that select a container"))
            packs.append((fam, kinds, left_out))
        out.write("model/%s.def" % module, module_text(module, label, sources, leaves))
        for fam, kinds, left_out in packs:
            fmt = "xtce-%s-%s" % (db["name"], snake(fam.name).replace("_", "-"))
            pdir = "packs/" + fmt
            text = pack_text(fmt, module, label, sources, kinds)
            out.write(pdir + "/pack.def", text)
            vecs = {"rt-%s.json" % k.name: vector(fmt, module, k, label) for k in kinds}
            # only the round trips are the generator's; vectors derived by hand
            # beside them (derived-*.json) are kept
            for old in out.listdir(pdir + "/vectors"):
                if old.startswith("rt-") and old.endswith(".json") and old not in vecs:
                    out.remove("%s/vectors/%s" % (pdir, old))
            for n, v in vecs.items():
                out.write("%s/vectors/%s" % (pdir, n), json.dumps(v, indent=2) + "\n")
            model = gtcheck.Model()
            model.add(core, "model/core.def")
            model.add(out.read("model/%s.def" % module), "model/%s.def" % module)
            gtcheck.load_pack(out.read(pdir + "/pack.def"), model, pdir + "/pack.def")
            out.write(pdir + "/pack.md", pack_md(fmt, label, fam.name, kinds, left_out))
            out.write(pdir + "/PROVENANCE.md", provenance_md(fmt, db, table))
            report.append("%s: %d kinds, %d left out" % (fmt, len(kinds), len(left_out)))
    return report


def main(argv=None):
    here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap = argparse.ArgumentParser(prog="xtce2pack", description=__doc__.split("\n\n")[0])
    genio.add_arguments(ap, default_out=here)
    ap.add_argument("--src", required=True, help="the directory that holds the database files")
    ap.add_argument("--provenance", help="the table of databases (default %s)" % PROV)
    args = ap.parse_args(argv)
    out = genio.Output(args.out, check=args.check)
    try:
        lines = run(args.src, out, args.provenance)
    except (GenError, gtcheck.CheckError) as e:
        print("xtce2pack: %s" % e, file=sys.stderr)
        return 1
    print("\n".join(lines))
    return out.report("xtce2pack.py")


if __name__ == "__main__":
    sys.exit(main())
