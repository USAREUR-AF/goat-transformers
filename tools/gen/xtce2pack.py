#!/usr/bin/env python3
"""Generate goat-transformers packs from XTCE mission databases.

XTCE (XML Telemetric and Command Exchange, CCSDS 660.0-B-2 / OMG XTCE 1.2)
describes a mission's telemetry: parameter types and their encodings,
parameters, and sequence containers whose entries lay the parameters out in a
packet. A container may extend a base container and restrict it by the values
of parameters the base holds (for example a CCSDS Space Packet header's
APID). This generator was written from the text of CCSDS 660.0-B-2 in our own
words; no part of the standard or of its schema is copied into the tree.

Reads   <src>/<file>.xml for every file named in tools/gen/sources/xtce-PROVENANCE.md
        (the SHA-256 of each file is checked; a file that differs is refused)
Writes  <out>/model/xtce<name>.def                one module per database
        <out>/packs/xtce-<name>-<family>/pack.def one pack per family of containers
        <out>/packs/xtce-<name>-<family>/pack.md
        <out>/packs/xtce-<name>-<family>/PROVENANCE.md
        <out>/packs/xtce-<name>-<family>/vectors/rt-<kind>.json

A family is a root container (one with no base) and the containers that extend
it. Each concrete container of a family is a message kind of a
`layout sequential` `bits` pack; there are no common lines, so every kind holds
its whole entry list, the inherited entries first. Each comparison of the
container's restriction criteria (and its bases') becomes `when <len> <value>
at <bit offset> as <key>` (engine-spec 0.30, 0.33), and the bits of that
parameter a `pad`, so the comparison both selects the kind on decode and
chooses it on encode.

Mapped: integer, float, boolean, enumerated and fixed-size string parameter
types; aggregate parameters, member by member; integer encodings unsigned and
two's complement, most significant byte first; IEEE 754 floats of 32 and 64
bits; a polynomial calibrator of degree 0 or 1 as a scale (an exact factor as
the fraction, engine-spec 0.5 ruling 1); a comparison or a list of comparisons
(all must hold) with `==` on an uncalibrated integer, boolean or enumerated
parameter; an included container (its entries in place, its locations from
where it is included); a stated location ahead of the cursor (a `pad`); a repeat
of a fixed count (unrolled, the keys numbered `_1`, `_2`, ...); a repeat counted
by an earlier unsigned, uncalibrated parameter (that parameter's line becomes a
`count`, the repeat a `group ... count @`, engine-spec 0.21), also when the count
is stated on the bits of an earlier field of its size, which is then read again
as the count. Anything else ends the kind's mapping at that entry with a
`# not mapped from here on:` comment, and a container whose criteria cannot be
stated is left out; pack.md lists both. The most common stops name what the pack
language lacks: an entry included on the value of an earlier field
(IncludeCondition) and a count computed from a field by a formula.

Every vector is a round trip whose message is written by the bit writer in this
file from the container's entries; the generator then loads each pack with
gtcheck. Python 3 standard library only. Exit status 0 when every check passed,
1 for a refused input or a failed check, 2 for a usage error.
"""
