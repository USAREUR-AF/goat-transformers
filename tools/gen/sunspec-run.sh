#!/bin/bash
# Regenerate the SunSpec packs: one `bits` pack per SunSpec Modbus information
# model (github.com/sunspec/models, json/model_<id>.json), one module per model
# (model/sunspec<id>.def).
#
# Usage: tools/gen/sunspec-run.sh <checkout> <sources> [--fetch] [--check]
#
# <checkout> is a goat-transformers checkout; it is written: model/sunspec*.def
# and packs/sunspec-*/ (pack.def, pack.md, PROVENANCE.md, vectors/). The
# generator checks the SHA-256 of every input against
# tools/gen/sources/sunspec-PROVENANCE.md and stops when one differs. With
# --check it writes nothing and reports any file that differs from what it
# would write.
#
# <sources> is a directory for the two trees, not kept in the repository. With
# --fetch the script downloads
#   https://codeload.github.com/sunspec/models/tar.gz/a0b3e732ca9c163889a9c33f41c9315668a2488c
#   sha256 ef31dbc1c580d1832c7d1f3369dcde9c3d3e9f2b99e67c5f2b5c6e7613666442
#   (tag v2026-04-20: the model definitions)
#   https://codeload.github.com/sunspec/pysunspec2/tar.gz/bbe9e044c2ae06af54b49e5ef042493eddb7e2b8
#   sha256 59b497d6aa38645a59e28fcd5b690061d229428a32bfe9b55c450811274ec714
#   (tag v1.3.7: sunspec2/mb.py states the not-implemented value of each point
#   type; read as a Python syntax tree, not run)
# and unpacks them to <sources>/models-<commit>/ and <sources>/pysunspec2-<commit>/.
# Licenses: Apache License 2.0, both (LICENSE at the root of each commit; the
# text is quoted in tools/gen/sources/sunspec-PROVENANCE.md).
set -euo pipefail
ROOT="$(cd "$1" && pwd)"
mkdir -p "$2"
SRC="$(cd "$2" && pwd)"
GEN="$(cd "$(dirname "$0")" && pwd)"
MODELS=a0b3e732ca9c163889a9c33f41c9315668a2488c
MODELS_SHA=ef31dbc1c580d1832c7d1f3369dcde9c3d3e9f2b99e67c5f2b5c6e7613666442
PSS=bbe9e044c2ae06af54b49e5ef042493eddb7e2b8
PSS_SHA=59b497d6aa38645a59e28fcd5b690061d229428a32bfe9b55c450811274ec714
shift 2
if [ "${1:-}" = "--fetch" ]; then
  shift
  curl -sS -f -L -o "$SRC/models-$MODELS.tar.gz" "https://codeload.github.com/sunspec/models/tar.gz/$MODELS"
  echo "$MODELS_SHA  $SRC/models-$MODELS.tar.gz" | sha256sum -c -
  tar -xzf "$SRC/models-$MODELS.tar.gz" -C "$SRC"
  curl -sS -f -L -o "$SRC/pysunspec2-$PSS.tar.gz" "https://codeload.github.com/sunspec/pysunspec2/tar.gz/$PSS"
  echo "$PSS_SHA  $SRC/pysunspec2-$PSS.tar.gz" | sha256sum -c -
  tar -xzf "$SRC/pysunspec2-$PSS.tar.gz" -C "$SRC"
fi
if [ "${1:-}" != "--check" ]; then
  # remove what an earlier run wrote (files whose header names this generator)
  for f in "$ROOT"/model/sunspec*.def "$ROOT"/packs/sunspec-*/pack.def; do
    [ -e "$f" ] || continue
    if head -3 "$f" | grep -q "Generated by tools/gen/sunspec2pack.py"; then
      case "$f" in
        */pack.def) rm -rf "$(dirname "$f")" ;;
        *) rm -f "$f" ;;
      esac
    fi
  done
fi
python3 -I "$GEN/sunspec2pack.py" --models "$SRC/models-$MODELS" --pysunspec2 "$SRC/pysunspec2-$PSS" \
  --out "$ROOT" --core-def "$ROOT/model/core.def" "$@"
