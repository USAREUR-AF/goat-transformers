#!/usr/bin/env python3
"""Write two small sets of vectors:

  - `conformance-lineorder-*`: one key on two lines of a `geojson` pack. Decode
    takes the earliest line that succeeds (0.6, One key at several locators),
    whatever the order of the members in the document; encode writes both.
  - load vectors from 6548: a line valid only in a sequential pack, in a pack
    that is not sequential, followed by a line `bogus`. The refusal is in none
    of the steps 1 to 10 of 0.11 5b, so it is checked after the file and
    `bogus` is the error.

Every expected value is worked out by hand from the text and written literally.
A second computation, `recompute`, applies the rules to the document; the load
vectors are checked against tools/gen/gtcheck.py without their `bogus` line.
Nothing here imports or calls an engine.

Inputs: none. With --check nothing is written and the exit status is 1 when a
committed file differs from what this script writes.

Usage: python3 -I tools/gen/conformance-lineorder-vectors.py [--out DIR] [--check]
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402
import gtcheck  # noqa: E402

P = "conformance-lineorder-"
GENERATED = "# Generated by tools/gen/conformance-lineorder-vectors.py. Do not edit by hand.\n"
SOURCE = '"goat-transformers spec/engine-spec.md (synthetic probe format, no external standard)"'
LOAD_DIR = "packs/conformance/load-vectors"
OWN_LOAD = re.compile(r"\A65[4-9]\d-lineorder-.*\.json\Z")
SLOTS = {"geometry.lon": 0, "geometry.lat": 1}


def recompute(fields, inp):
    """(entity, output) for (key, locator) lines that read JSON numbers."""
    doc, ent = json.loads(inp), {}
    coords = (doc.get("geometry") or {}).get("coordinates")
    for key, loc in fields:
        if loc in SLOTS:
            v = coords[SLOTS[loc]] if coords else None
        else:
            v = doc["properties"].get(loc.split(".")[1])
        if isinstance(v, int):
            ent.setdefault(key, v)
    at = {loc: ent[key] for key, loc in fields if key in ent}
    point = [at.get(s) for s in SLOTS]
    geometry = None if None in point else {"type": "Point", "coordinates": point}
    props = {loc.split(".")[1]: at[loc] for _, loc in fields if loc in at and loc not in SLOTS}
    return ent, json.dumps({"type": "Feature", "geometry": geometry, "properties": props}, separators=(",", ":"))


def build(sink):
    written = {}

    def put(rel, text):
        sink.write(rel, text)
        written[rel.split("/")[1]] = written.get(rel.split("/")[1], 0) + 1

    def pack(short, about, fields, rows):
        name = P + short
        for old in sink.listdir("packs/%s/vectors" % name):
            sink.remove("packs/%s/vectors/%s" % (name, old))
        put("packs/%s/pack.def" % name, GENERATED + "# Conformance probe pack: %s (0.6, One key at\n# several locators). Public. No kinds.\n" % about
            + "format  %s\nversion 0.64.0\ndistribution public\nsource  %s\nuses    probe\nwire    geojson\n" % (name, SOURCE)
            + "".join("field   %s  %s  %s\n" % (k, l, "int" if k.startswith("probe.") else "float") for k, l in fields))
        for i, (vname, inp, out, model, ref) in enumerate(rows, 1):
            ent, got = recompute(fields, inp)
            assert got == out and {k: str(v) for k, v in ent.items()} == model, (name, vname, got, ent)
            put("packs/%s/vectors/%02d-%s.json" % (name, i, vname), json.dumps(
                {"name": vname, "from": name, "to": name, "input": inp, "expect": out, "model": model,
                 "source": "constructed", "reference": "spec 0.6, One key at several locators: " + ref}, indent=2) + "\n")

    def null(props):
        return '{"type":"Feature","geometry":null,"properties":%s}' % props

    def point(lon, lat, props):
        return '{"type":"Feature","geometry":{"type":"Point","coordinates":[%d,%d]},"properties":%s}' % (lon, lat, props)

    def props_first(lon, lat, props):
        return '{"type":"Feature","properties":%s,"geometry":{"type":"Point","coordinates":[%d,%d]}}' % (props, lon, lat)

    E = "the earliest line whose locator is present and whose transform succeeds, "
    pack("geojson", "one key on two properties", [("probe.x", "properties.a"), ("probe.x", "properties.b")], [
        ("members-in-the-other-order", null('{"b":4,"a":3}'), null('{"a":3,"b":3}'), {"probe.x": "3"},
         E + "not the earliest member; encode writes both"),
        ("members-in-line-order", null('{"a":3,"b":4}'), null('{"a":3,"b":3}'), {"probe.x": "3"}, E + "encode writes both"),
        ("earliest-line-absent", null('{"b":4}'), null('{"a":4,"b":4}'), {"probe.x": "4"}, E + "the second"),
        ("earliest-line-fails", null('{"b":4,"a":"q"}'), null('{"a":4,"b":4}'), {"probe.x": "4"},
         E + "the second; the failed line is forgiven (0.6 ruling 5)")])
    # coordinates are [lon, lat]
    pack("geojson-property-first", "one key on a property and, later, in the geometry",
         [("lon", "geometry.lon"), ("lat", "properties.la"), ("lat", "geometry.lat")], [
             ("geometry-member-first", point(2, 3, '{"la":5}'), point(2, 5, '{"la":5}'), {"lon": "2", "lat": "5"},
              E + "the property; encode writes both"),
             ("property-absent", point(2, 3, "{}"), point(2, 3, '{"la":3}'), {"lon": "2", "lat": "3"}, E + "the geometry slot"),
             ("geometry-null", null('{"la":5}'), null('{"la":5}'), {"lat": "5"},
              E + "the property; lon is absent, so geometry is null (0.1.1 ruling 5)")])
    pack("geojson-geometry-first", "one key in the geometry and, later, on a property",
         [("lon", "geometry.lon"), ("lat", "geometry.lat"), ("lat", "properties.la")], [
             ("properties-member-first", props_first(2, 3, '{"la":5}'), point(2, 3, '{"la":3}'), {"lon": "2", "lat": "3"},
              E + "the geometry slot, though `properties` stands first; encode writes both"),
             ("geometry-null", null('{"la":5}'), null('{"la":5}'), {"lat": "5"}, E + "the property")])

    for old in sink.listdir(LOAD_DIR):
        if OWN_LOAD.match(old):
            sink.remove(LOAD_DIR + "/" + old)
    core = 'module core\nversion 0.1.0\ndistribution public\nsource "probe"\nkey uid string -\nkey time_ms int ms\n'
    probe = 'module probe\nversion 0.1.0\ndistribution public\nsource "probe"\nkey x int -\nkey y int -\n'
    head = 'format probe\nversion 0.64.0\ndistribution public\nsource "probe"\nuses probe\n'
    fixed = head + "wire bits\nword_bytes 1\nfield probe.x 0:0:8 uint\n"
    js = head + "wire json\nfield probe.x x int\n"
    number = 6548
    for what, lines, wires in (
            ("also", "also probe.y\n", ("fixed",)), ("pad", "pad 8\n", ("fixed", "json")),
            ("opt", "opt\nend\n", ("fixed", "json")), ("fx", "fx\n", ("fixed", "json")),
            ("switch", "switch probe.x\n  case 1\n  else\nend\n", ("fixed", "json"))):
        for wire in wires:
            text = (fixed if wire == "fixed" else js) + lines
            got = None
            try:
                m = gtcheck.Model()
                for mod in (core, probe):
                    m.add(mod)
                gtcheck.load_pack(text, m)
            except gtcheck.CheckError as e:
                got = e.kind
            assert got == "bad-directive", (what, wire, got)
            name = "%d-lineorder-%s-on-%s-is-checked-after-the-file" % (
                number, what, "a-fixed-layout" if wire == "fixed" else "json")
            put("%s/%s.json" % (LOAD_DIR, name), json.dumps(
                {"name": name, "models": [core, probe], "pack": text + "bogus\n", "expect_error": "unknown-directive"}, indent=2) + "\n")
            number += 1
    return written


def main(argv=None):
    return genio.vector_main("conformance-lineorder-vectors.py", __doc__, build, argv)


if __name__ == "__main__":
    sys.exit(main())
