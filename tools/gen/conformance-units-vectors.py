# second computation, part 2: the sequential codec (decode and encode)
# ------------------------------------------------------------------------------
def vbits(v, n):
    return [(v >> (n - 1 - k)) & 1 for k in range(n)]


def to_bits(hx):
    return [b for i in range(0, len(hx), 2) for b in vbits(int(hx[i:i + 2], 16), 8)]


def to_hex(bits):
    bits = bits + [0] * (-len(bits) % 8)
    return "".join("%02x" % int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8))


def bytes_reversed(bits):
    """Between reading order under msb and under lsb: the bits of each byte reversed (0.2)."""
    return [b for i in range(0, len(bits), 8) for b in bits[i:i + 8][::-1]]


INNER = {}          # the parsed packs by format name, for `inner` (0.34)


class Dec:
    def __init__(self, bits, max_items, lsb=False):
        self.lsb = lsb
        self.bits, self.cur, self.stop = bits, 0, len(bits)
        self.ext = []                        # (end, counted in bytes) of each `length` block around the cursor
        self.failed, self.items, self.max, self.whole, self.slots = [], 0, max_items, None, []

    def at_end(self):
        return bool(self.ext) and self.cur >= self.ext[-1][0]

    def take(self, n):
        # 0.8: each block around the line is read within its own extent
        if any(self.cur + n > end for end, _ in self.ext) or self.cur + n > self.stop:
            raise Fail(MW, "needs bits past the extent or the input")
        v = 0
        got = self.bits[self.cur:self.cur + n]
        for b in got[::-1] if self.lsb else got:     # lsb: low bit first
            v = v * 2 + b
        self.cur += n
        return v

    def miss(self, lines, counts):
        """Ruling 9: these lines are in a part or block that is not read."""
        counts = dict(counts)
        for x in lines:
            if x.d == "count":
                counts.pop(x.a[0], None)             # it hides an outer name, and states nothing
            elif x.d == "length" and x.a[0].startswith("@") and x.a[0][1:] in counts:
                counts[x.a[0][1:]][1] = "missed"
            if x.d != "group":
                self.miss(x.body, counts)
                for _, body in x.arms:               # a switch: any of its cases
                    self.miss(body, counts)

    def scope_read(self, mark):
        """Ruling 9: the scope that holds the count lines has been read."""
        if any(value and state == "missed" for value, state in self.slots[mark:]):
            raise Fail(MW, "ruling 9: units stated and no block read")
        del self.slots[mark:]

    def block(self, lines, end, in_bytes, ent, counts, pres):
        self.ext.append((end, in_bytes))
        self.lines(lines, ent, counts, pres)
        self.ext.pop()
        self.cur = end

    def lines(self, lines, ent, counts, pres):
        for x in lines:
            d, a = x.d, x.a
            if d == "count":
                counts[a[0]] = [None, ""]             # a count line not read states nothing
                if not self.at_end():
                    plus = int(a[3]) if len(a) > 2 else 0
                    v = self.take(int(a[1]))
                    if v < plus:
                        raise Fail(MW, "below the plus")
                    counts[a[0]][0] = v - plus
                    self.slots.append(counts[a[0]])
            elif d == "field":
                if self.at_end():
                    continue
                v = self.take(int(a[1]))
                if a[2] == "chars:ascii8":
                    if 32 <= v <= 126:
                        ent[a[0]] = chr(v)
                    else:
                        self.failed.append(a[0])
                else:
                    ent[a[0]] = v
            elif d == "pad":
                if not self.at_end():
                    self.take(int(a[0]))
            elif d == "align":                       # ruling 18: never past the input or the extent
                end = min([self.stop] + [e for e, _ in self.ext])
                self.cur = max(self.cur, min(self.cur + -self.cur % int(a[0]), end))
            elif d == "presence":
                v = 0 if self.at_end() else self.take(int(a[1]))
                pres[a[0]] = vbits(v, int(a[1]))
            elif d == "if":
                name, i = a[0].split(".")
                if pres[name][int(i) - 1]:
                    self.lines(x.body, ent, dict(counts), dict(pres))
                else:
                    self.miss(x.body, counts)
            elif d == "opt":
                if not self.at_end() and self.take(1):
                    self.lines(x.body, ent, dict(counts), dict(pres))
                else:
                    self.miss(x.body, counts)
            elif d == "chain":
                inner = dict(counts)
                for k, y in enumerate(x.body):
                    if y.d == "fx":
                        if self.at_end() or not self.take(1):
                            self.miss(x.body[k + 1:], inner)
                            break
                    else:
                        self.lines([y], ent, inner, pres)
            elif d == "switch":
                v = ent.get(a[0])
                for values, body in x.arms:
                    if values is None or (v is not None and str(v) in values):
                        self.lines(body, ent, dict(counts), dict(pres))
                        break
                else:
                    raise Fail(NK)
            elif d == "length" and a[0].startswith("@"):
                if self.at_end():
                    self.miss([x], counts)           # ruling 9
                    continue                         # ruling 4: first, whatever the count states
                end = self.cur + counts[a[0][1:]][0] * int(a[2])      # exact (ruling 3)
                if self.ext and end > self.ext[-1][0]:
                    raise Fail(MW, "beyond the enclosing extent")
                if end > self.stop:
                    raise Fail(MW, "ruling 5: beyond the input or the whole")
                counts[a[0][1:]][1] = "read"
                self.block(x.body, end, int(a[2]) % 8 == 0, ent, dict(counts), dict(pres))
            elif d == "length" and "whole" in a:
                n = self.take(int(a[0])) * 8          # ruling 16: ends the input, not the block
                if not self.cur <= n <= self.stop:
                    raise Fail(MW, "whole length")
                self.stop = self.whole = n
            elif d == "length":
                assert a[1:] in ([], ["bits"])
                if self.at_end():
                    self.miss(x.body, counts)
                else:
                    n = self.take(int(a[0]))
                    end = self.cur + n * (1 if a[1:] else 8)
                    # ruling 17: a plain `length` past the input is malformed-wire by itself
                    # (conformance-seq-length 06, conformance-long-mlsb-length 03)
                    if end > self.stop or any(end > e for e, _ in self.ext):
                        raise Fail(MW, "a plain length past the input or an extent around it")
                    self.block(x.body, end, not a[1:], ent, dict(counts), dict(pres))
            elif d == "group":
                self.group(x, ent, counts)
            elif d == "inner":
                self.inner(a, ent)
            else:
                raise AssertionError(d)

    def inner(self, a, ent):
        """0.34 Decode, steps 1 to 4; reached also at the end of its extent."""
        if self.cur % 8:
            raise Fail(MW, "step 1: the cursor is not on a whole byte")
        end, in_bytes = self.ext[-1] if self.ext else (self.stop, True)
        if self.ext and (end > self.stop or end % 8):
            raise Fail(MW, "step 2: the extent ends beyond the input or inside a byte")
        data = self.bits[self.cur:end] if self.cur < end else []
        inner = Dec(data, self.max - self.items)
        got = inner.message(INNER[a[0]])
        stop = len(data) if inner.whole is None else inner.whole
        if inner.whole is None:
            stop = inner.cur + -inner.cur % 8
        if stop < len(data) and "partial" not in a:
            raise Fail(MW, "step 3: bytes after the inner message's end")
        kind = got.pop("@kind", None)
        if kind is not None:
            ent["@inner_kind"] = kind
        for k, v in got.items():
            ent.setdefault(k, v)
        self.failed += inner.failed
        self.cur = max(self.cur, end)

    def message(self, pack):
        """The common lines, then the selected kind's."""
        ent, counts, pres = {}, {}, {}
        self.lines(pack["common"], ent, counts, pres)
        start = self.cur
        for name, lines in pack["kinds"]:
            self.cur = start
            whens = [x for x in lines if x.d == "when"]
            # ruling 21 of 0.5 and 6 of 0.34: a `when` past the input does not hold
            if all(self.cur + int(x.a[0]) <= self.stop and self.take(int(x.a[0])) == int(x.a[1]) for x in whens):
                ent["@kind"] = name
                self.lines(lines[len(whens):], ent, counts, pres)
                break
        else:
            if pack["kinds"]:
                raise Fail(NK)
        self.scope_read(0)
        return ent

    def group(self, x, ent, counts):
        mode, items = x.a[1], []

        def item():
            self.items += 1
            if self.items > self.max:
                raise Fail(MW, "max_items")
            it, at, mark = {}, self.cur, len(self.slots)
            counts, pres = {}, {}
            self.lines(x.body, it, counts, pres)
            for name, lines in x.kinds:
                whens = [y for y in lines if y.d == "when"]
                start, limit = self.cur, min([self.stop] + [e for e, _ in self.ext[-1:]])
                # 0.33 ruling 6: a `when` past the input or the extent does not hold
                if all(self.cur + int(y.a[0]) <= limit and self.take(int(y.a[0])) == int(y.a[1]) for y in whens):
                    it["@kind"] = name
                    self.lines(lines[len(whens):], it, counts, pres)
                    break
                self.cur = start
            else:
                if x.kinds:
                    raise Fail(NK)
            self.scope_read(mark)
            items.append(it)
            return self.cur > at

        if mode == "rest":
            end, in_bytes = self.ext[-1] if self.ext else (self.stop, True)
            while end - self.cur >= (8 if in_bytes else 1):
                if not item():
                    raise Fail(MW, "an item that reads no bits")
        elif self.at_end():
            return
        elif mode == "while":
            while not self.at_end() and self.take(1):
                item()
        else:
            n = counts[x.a[2][1:]][0] if x.a[2].startswith("@") else self.take(int(x.a[2]))
            # the bits left are none, not fewer, when the cursor is past the end
            if n > max(0, (self.ext[-1][0] if self.ext else self.stop) - self.cur):
                raise Fail(MW, "a count larger than the bits left")
            for _ in range(n):
                item()
        ent[x.a[0]] = items


def seq_decode(pack, hx, max_items=100000):
    bits = bytes_reversed(to_bits(hx)) if pack["lsb"] else to_bits(hx)
    dec = Dec(bits, max_items, pack["lsb"])
    ent = dec.message(pack)
    if dec.failed:
        raise Fail(TD, ",".join(dec.failed))
    return ent


def content(lines, ent):
    return any((x.d in ("field", "group") and ent.get(x.a[0]) not in (None, []))
               or (x.d in ("if", "opt", "length", "chain") and content(x.body, ent))
               or (x.d == "switch" and any(values is None or str(ent.get(x.a[0], 0)) in values and content(body, ent)
                                           for values, body in x.arms)) for x in lines)


class Enc:
    def __init__(self, lsb):
        self.fills, self.lsb = [], lsb

    def value(self, v, n):
        return vbits(v, n)[::-1] if self.lsb else vbits(v, n)

    def lines(self, lines, ent, out, counts, pres, scope):
        for i, x in enumerate(lines):
            d, a = x.d, x.a
            if d == "count":
                slot = {"len": int(a[1]), "v": int(a[3]) if len(a) > 2 else 0, "buf": out, "at": len(out)}
                out += [0] * slot["len"]
                counts[a[0]] = slot
                self.fills.append(slot)
            elif d == "when":
                out += self.value(int(a[1]), int(a[0]))
            elif d == "field":
                n, v = int(a[1]), ent.get(a[0], 0)
                v = ord(v) if isinstance(v, str) else v
                if not 0 <= v < 1 << n:
                    raise Fail(TE, a[0])
                out += self.value(v, n)
            elif d == "pad":
                out += [0] * int(a[0])
            elif d == "align":                       # from the message start
                out += [0] * (-(self.base + len(out)) % int(a[0]))
            elif d == "presence":
                pres[a[0]] = [int(any(y.d == "if" and y.a[0] == "%s.%d" % (a[0], k + 1) and content(y.body, ent)
                                      for y in scope)) for k in range(int(a[1]))]
                out += pres[a[0]]
            elif d == "if":
                name, k = a[0].split(".")
                if pres[name][int(k) - 1]:
                    self.lines(x.body, ent, out, dict(counts), pres, x.body)
            elif d == "opt":
                out.append(int(content(x.body, ent)))
                if out[-1]:
                    self.lines(x.body, ent, out, dict(counts), pres, x.body)
            elif d == "chain":
                inner = dict(counts)
                for k, y in enumerate(x.body):
                    if y.d == "fx":
                        out.append(int(content(x.body[k + 1:], ent)))
                        if not out[-1]:
                            break
                    else:
                        self.lines([y], ent, out, inner, pres, x.body)
            elif d == "switch":
                v = str(ent.get(a[0], 0))            # the key's line wrote zero bits when the key is absent
                for values, body in x.arms:
                    if values is None or v in values:
                        self.lines(body, ent, out, dict(counts), pres, body)
                        break
                else:
                    raise Fail(NK)
            elif d == "length" and "whole" in a:
                self.whole = (out, len(out), int(a[0]))
                out += [0] * int(a[0])
            elif d == "length":
                ref = a[0].startswith("@")
                unit = int(a[2]) if ref else 1 if a[1:] == ["bits"] else 8
                base, self.base = self.base, self.base + len(out) + (0 if ref else int(a[0]))
                block = self.sub(x.body, ent, counts, pres, unit % 8 == 0)
                self.base = base
                if ref:
                    if len(block) % unit:
                        raise Fail(TE, "not whole units")
                    counts[a[0][1:]]["v"] += len(block) // unit
                else:
                    n = len(block) // unit
                    if n >= 1 << int(a[0]):
                        raise Fail(TE, "length")
                    out += self.value(n, int(a[0]))
                for slot in self.fills:
                    if slot["buf"] is block:
                        slot["buf"], slot["at"] = out, slot["at"] + len(out)
                if self.whole and self.whole[0] is block:
                    self.whole = (out, self.whole[1] + len(out), self.whole[2])
                out += block
            elif d == "group":
                items = ent.get(a[0])
                if a[1] == "count" and a[2].startswith("@"):
                    counts[a[2][1:]]["v"] += len(items or [])
                elif a[1] == "count":
                    out += self.value(len(items or []), int(a[2]))
                for it in items or []:
                    if a[1] == "rest":
                        self.starts.append(len(out))
                    if a[1] == "while":
                        out.append(1)
                    own, bits = {}, {}
                    self.lines(x.body, it, out, own, bits, x.body)
                    for name, lines in x.kinds:
                        if name == it["@kind"]:
                            self.lines(lines, it, out, own, bits, lines)
                if a[1] == "while":
                    out.append(0)
            elif d == "inner":                       # 0.34 Encode
                if (self.base + len(out)) % 8:
                    raise Fail(TE, "the cursor is not on a whole byte")
                part = {k: v for k, v in ent.items() if k not in ("@kind", "@inner_kind")}
                if "@inner_kind" in ent:
                    part["@kind"] = ent["@inner_kind"]
                out += to_bits(seq_encode(INNER[a[0]], part))
            else:
                raise AssertionError(d)

    def sub(self, body, ent, counts, pres, in_bytes):
        outer, self.starts, block = getattr(self, "starts", []), [], []
        self.lines(body, ent, block, dict(counts), pres, body)
        if in_bytes:
            block += [0] * (-len(block) % 8)
            if any(len(block) - s < 8 for s in self.starts):
                raise Fail(TE, "0.21 ruling 4")
        self.starts = outer
        return block


def seq_encode(pack, ent):
    enc = Enc(pack["lsb"])
    enc.starts, enc.whole, enc.base, out, counts, pres = [], None, 0, [], {}, {}
    lines = list(pack["common"])
    if pack["kinds"]:
        name = ent.get("@kind", pack["kinds"][0][0])
        lines += next(b for n, b in pack["kinds"] if n == name)
    enc.lines(lines, ent, out, counts, pres, lines)
    for s in enc.fills:                              # 0.21 ruling 30: when the message is finished
        if not 0 <= s["v"] < 1 << s["len"]:
            raise Fail(TE, "count out of range")
        s["buf"][s["at"]:s["at"] + s["len"]] = enc.value(s["v"], s["len"])
    if enc.whole:
        buf, at, n = enc.whole
        buf[at:at + n] = enc.value((len(out) + 7) // 8, n)
    out += [0] * (-len(out) % 8)
    return to_hex(bytes_reversed(out) if pack["lsb"] else out)


def json_decode(pack, text):
    obj, ent = json.loads(text), {}
    for x in pack["common"]:
        if x.a[1] in obj:
            v = obj[x.a[1]]
            ent[x.a[0]] = v if x.d == "field" else [{x.body[0].a[0]: i} for i in v]
    return ent


def json_encode(pack, ent):
    out = {}
    for x in pack["common"]:
        if x.a[0] in ent:
            v = ent[x.a[0]]
            out[x.a[1]] = v if x.d == "field" else [it[x.body[0].a[0]] for it in v]
    return json.dumps(out, separators=(",", ":"))


def model_of(ent, prefix=""):
    out = {}
    for k, v in ent.items():
        if isinstance(v, list):
            out[prefix + k + ".#"] = str(len(v))
            for i, it in enumerate(v):
                out.update(model_of(it, "%s%s[%d]." % (prefix, k, i)))
        else:
            out[prefix + k] = str(v)
    return out


# ------------------------------------------------------------------------------
# second computation, part 3: a load checker for the lines the load vectors use
# ------------------------------------------------------------------------------
KNOWN = HEADER + ("root", "field", "count", "presence", "pad", "if", "opt", "length", "group", "end", "kind", "when",
                  "switch", "case", "else", "chain", "fx", "const", "align")
AFTER_WIRE = ("field", "when", "const", "group", "end", "layout", "pad", "align", "presence", "if", "opt",
              "chain", "fx", "length")
AFTER_LAYOUT = tuple(d for d in AFTER_WIRE if d != "layout")


def check_load(text):
    """None when the pack loads, else the error kind (0.11 ruling 5b order)."""
    rows = rows_of(text)
    seen = set()
    wire = None
    for t in rows:                                    # the line checks, in file order
        if t[0] not in KNOWN:
            return "unknown-directive"
        if t[0] in AFTER_WIRE and "wire" not in seen:
            return "missing-wire"
        if t == ["layout", "sequential"] and seen & set(AFTER_LAYOUT):
            return "bad-directive"
        if t[0] == "wire":
            wire = t[1]
        seen.add(t[0])
    try:                                              # after the file
        _after(rows, wire == "bits" and ["layout", "sequential"] in rows)
    except Fail as e:
        return e.kind
    return None


def _after(rows, sequential):
    def need(ok, why):
        if not ok:
            raise Fail("bad-directive", why)
    for t in rows:
        a = t[1:]
        if t[0] == "length":
            if a and a[0].startswith("@"):
                need(sequential, "length @ on another wire or layout")
                need(len(a) == 3 and len(a[0]) > 1 and a[1] == "units" and re.match(r"[0-9]+\Z", a[2])
                     and 1 <= int(a[2]) <= 65535, "the form")
            else:
                need("units" not in a, "units without @")
    parsed = tree([t for t in rows if t[0] not in HEADER])
    need(parsed, "blocks")
    if not sequential:
        return
    common, kinds = parsed
    for choice in kinds or [[None, []]]:
        _names(common + choice[1], {}, need)
        _paths(common + choice[1], need)
        _rest(common + choice[1], [], need)


def _names(lines, visible, need):
    """References are visible counts of the same group body."""
    visible, declared = dict(visible), set()
    for x in lines:
        if x.d in ("count", "presence"):
            need(x.a[0] not in declared, "declared twice")
            declared.add(x.a[0])
            visible[x.a[0]] = x.d
        refs = x.a[:1] if x.d == "length" else x.a[2:] if x.d == "group" else []
        for r in refs:
            if r.startswith("@"):
                need(visible.get(r[1:]) == "count", "not a visible count")
        _names(x.body, {} if x.d == "group" else visible, need)
        for _, body in x.arms:
            _names(body, visible, need)


def _refs(lines, name):
    """The set of numbers of references to `name` over the reading paths."""
    got = {0}
    for x in lines:
        if x.d in ("count", "presence") and x.a[0] == name:
            break
        add = {0}
        if x.d == "group":
            add = {int("@" + name in x.a[2:])}
        elif x.d == "switch":
            add = set().union(*(_refs(body, name) for _, body in x.arms))
        elif x.body or x.d == "length":
            own = int(x.d == "length" and x.a[0] == "@" + name)
            add = {own + n for n in _refs(x.body, name)}
        got = {a + b for a, b in itertools.product(got, add)}
    return got


def _paths(lines, need):
    for i, x in enumerate(lines):
        if x.d == "count":
            need(_refs(lines[i + 1:], x.a[0]) == {1}, "not one reference in each path")
        _paths(x.body, need)
        for _, body in x.arms:
            _paths(body, need)


def _wire(x):
    """0.21 rulings 26 and 32."""
    if x.d in ("if", "chain"):
        return any(_wire(y) for y in x.body)
    if x.d == "switch":
        return any(_wire(y) for _, body in x.arms for y in body)
    return True


def _rest(lines, after, need):
    """0.21 ruling 11: a `rest` group is the last wire line of its extent."""
    for i, x in enumerate(lines):
        rest = lines[i + 1:] + after
        if x.d == "group":
            if x.a[1] == "rest":
                need(not any(_wire(y) for y in rest), "a wire line after rest")
            _rest(x.body, [], need)
        elif x.d == "length":
            _rest(x.body, [], need)
        else:
            _rest(x.body, rest, need)
            for _, body in x.arms:
                _rest(body, rest, need)


