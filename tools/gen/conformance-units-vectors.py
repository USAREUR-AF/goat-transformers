class Fail(Exception):
    """A conversion that fails with an error kind of the spec."""

    def __init__(self, kind, why=""):
        super().__init__(kind, why)
        self.kind, self.why = kind, why


# ------------------------------------------------------------------------------
# second computation, part 1: a parser of the pack lines these packs use
# ------------------------------------------------------------------------------
class L:
    """One line of a pack, with its body for a block; a `switch` has arms."""

    def __init__(self, d, a):
        self.d, self.a, self.body, self.arms, self.kinds = d, a, [], [], []


def tree(rows):
    """(common, [[kind name, lines]]) of token rows; None when blocks do not
    balance."""
    common, kinds, stack = [], [], []
    for t in rows:
        d, a = t[0], t[1:]
        if d == "end":
            if not stack:
                return None
            stack.pop()
        elif d == "kind":
            (stack[-1].kinds if stack else kinds).append([a[0], []])
        elif d in ("case", "else"):
            stack[-1].arms.append((a[0].split(",") if a else None, []))
        else:
            x = L(d, a)
            if not stack:
                (kinds[-1][1] if kinds else common).append(x)
            elif stack[-1].d == "switch":
                stack[-1].arms[-1][1].append(x)
            else:
                (stack[-1].kinds[-1][1] if stack[-1].kinds else stack[-1].body).append(x)
            if d in BLOCKS and not (d == "length" and "whole" in a):
                stack.append(x)
    return None if stack else (common, kinds)


HEADER = ("format", "version", "distribution", "source", "uses", "wire", "layout", "bit_order", "word_bytes", "armor",
          "tag", "key")


def rows_of(text):
    return [t for t in (raw.split("#")[0].split() for raw in text.splitlines()) if t]


def parse_pack(text):
    rows = rows_of(text)
    common, kinds = tree([t for t in rows if t[0] not in HEADER])
    # the default of 0.5 is lsb, so every sequential pack states its order
    assert ["wire", "json"] in rows or ["bit_order", "msb"] in rows or ["bit_order", "lsb"] in rows
    return {"lsb": ["bit_order", "lsb"] in rows, "wire": next(t[1] for t in rows if t[0] == "wire"), "common": common, "kinds": kinds}


