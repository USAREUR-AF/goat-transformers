def build(sink):
    written, parsed, counts = {}, {}, {}

    def put(rel, text):
        sink.write(rel, text)
        owner = rel.split("/")[1]
        written[owner] = written.get(owner, 0) + 1

    def write_json(rel, d):
        put(rel, json.dumps(d, indent=2, ensure_ascii=False) + "\n")

    def clear(rel_dir, keep=lambda name: False):
        for old in sink.listdir(rel_dir):
            if old.endswith(".json") and not keep(old):
                sink.remove(rel_dir + "/" + old)

    def pack(short, comment, body, wire="wire       bits\nlayout     sequential\nbit_order  msb\n"):
        name = "conformance-units-" + short
        clear("packs/%s/vectors" % name)
        text = GENERATED + "".join("# %s\n" % line.strip() for line in comment.strip().split("\n"))
        text += "format     %s\nversion    0.83.0\ndistribution public\n%s\nuses       probe\n" % (name, SOURCE)
        text += wire + body.strip("\n") + "\n"
        put("packs/%s/pack.def" % name, text)
        parsed[short] = INNER[name] = parse_pack(text)

    def decode(short, inp, max_items=100000):
        p = parsed[short]
        return json_decode(p, inp) if p["wire"] == "json" else seq_decode(p, inp, max_items)

    def vec(frm, to, name, inp, expect=None, error=None, model=None, max_items=None, ref=""):
        """One vector: the hand value, checked by the second computation."""
        assert (expect is None) != (error is None), name
        try:
            ent = decode(frm, inp, 100000 if max_items is None else max_items)
            got = json_encode(parsed[to], ent) if parsed[to]["wire"] == "json" else seq_encode(parsed[to], ent)
            kind = None
        except Fail as e:
            got, kind = None, e.kind
        assert (got, kind) == (expect, error), (frm, name, "hand:", expect, error, "computed:", got, kind)
        if model is not None:
            ent = decode(frm, inp)
            have = model_of(ent)
            for k, v in model.items():
                if k == "@absent":
                    assert not any(key in ent for key in v), (name, v)
                else:
                    assert have.get(k) == v, (name, k, v, have.get(k))
        counts[frm] = num = counts.get(frm, 0) + 1
        d = {"name": name, "from": "conformance-units-" + frm, "to": "conformance-units-" + to, "input": inp}
        d.update({"expect": expect} if error is None else {"expect_error": error})
        if model is not None:
            d["model"] = model
        if max_items is not None:
            d["max_items"] = max_items
        d["source"] = "constructed"
        d["reference"] = "spec 0.83; " + ref
        write_json("packs/conformance-units-%s/vectors/%02d-%s.json" % (frm, num, name), d)

