#!/usr/bin/env python3
"""Write the vectors of spec 0.83, a length given by an earlier count
(`length @<name> units <u>`): the packs `conformance-units-*` and the load
vectors from 8300.

Every expected value here is worked out by hand from the spec text (Version
0.83 and its rulings 1 to 18, and the sections they refer to: 0.8 `length`,
presence, `opt`, chains and rulings 7, 21, 22 and 34; 0.20 rulings 12 and 14
and its Encode; 0.21 counts, `rest` and rulings 2, 3, 4, 6, 9, 12, 15, 22, 30,
31, 34; 0.11 rulings 5b and 7). The hand working is the comment above each
vector, bytes written as hex, and the value is written out literally.

It is checked against a second computation: the small codec below parses the
pack.def text this script writes with its own parser and applies the rules to
the input; the small load checker below applies the 0.83 load rules and the
0.11 order of checks to each load vector. Both cover only the lines these
packs and load vectors use. Nothing here imports or calls an engine.

Readings of the text these vectors rest on (reported with them):
  - ruling 6 with "Encode writes every line" (0.8 ruling 7): a block of 0
    units that holds a field is written back with the field's zero bits.

The packs `conformance-units-inner-*` (an `inner` line of 0.34 in, and after, a
block of 0.83) and the inner packs they name, `conformance-units-in-*`, rest on
0.34 Decode steps 1 to 4, its Encode and its rulings 2, 3, 6 and 13, with
rulings 5 to 8, 10 and 16 of 0.83.

Inputs: none; every value is stated in this file. Writes, under --out, the
files named above. The same run always gives the same bytes. With --check
nothing is written and the exit status is 1 when a committed file differs from
what this script writes.

Usage: python3 -I tools/gen/conformance-units-vectors.py [--out DIR] [--check]
"""
