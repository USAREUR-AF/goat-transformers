#!/usr/bin/env python3
"""Cut the Suricata EVE JSON schema (etc/schema.json, one object for every
event type) into one schema per event type, for jsonschema2pack.

Each schema keeps the top-level scalar members every event carries (timestamp,
flow_id, the address tuple, event_type and the others) and the member object of
its own event type (for alert also flow, which alert records carry), with the
schema's $defs. Members of other event types are left out: they are residue on
the json wire (scalars) or not carried (arrays).

Python 3 standard library only. Usage:
  python3 -I tools/gen/suricata-eve-schemas.py <suricata>/etc/schema.json <out-dir>
  python3 -I tools/gen/suricata-eve-schemas.py --provenance <checkout> [--check]
"""
import json
import os
import sys

EVENTS = {"alert": ["alert", "flow"], "flow": ["flow"], "dns": ["dns"], "http": ["http"], "tls": ["tls"],
          "fileinfo": ["fileinfo"], "anomaly": ["anomaly"], "stats": ["stats"]}


PROVENANCE = """# Provenance: suricata-eve pack

SPDX licence: Apache-2.0

Generated by `tools/gen/suricata-eve-run.sh` (`tools/gen/suricata-eve-schemas.py`, then
`tools/gen/jsonschema2pack.py`). No source file is copied into this repository. The pack
restates the layout of Suricata's EVE JSON schema: member names, nesting and types. Suricata
is GPL-2.0; no code is copied, so under the repository's licensing model the restatement is
Apache-2.0. Read on 2026-11-20.

| | |
|---|---|
| Source | OISF Suricata, https://github.com/OISF/suricata, tag `suricata-8.0.8`, commit `89d2ac5e371873c32c8acbd7a02170a99c39bb0c` |
| `etc/schema.json` | `960fa690efcbeeca50bc0f3122b449d01c62c2107f8021067b142968e04d7c2d` |
| `doc/userguide/output/eve/eve-json-format.rst` | `6e036c94b6acbb133ba3e5255104df8fbdc403f1f0807f0e777cae8c444921a0` (the form of `timestamp`) |
| `COPYING` | `8177f97513213526df2cf6184d8ff986c675afb514d4e68a404010521b880643`: the GNU General Public License, version 2 |

The vectors are written by jsonschema2pack from values it chooses; no EVE record of Suricata
is used.
"""


def provenance(gt, check):
    path = os.path.join(gt, "packs", "suricata-eve", "PROVENANCE.md")
    if check:
        cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if cur != PROVENANCE:
            print("differs: packs/suricata-eve/PROVENANCE.md")
            sys.exit(1)
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(PROVENANCE)


def main():
    if sys.argv[1] == "--provenance":
        provenance(sys.argv[2], "--check" in sys.argv[3:])
        return
    src, out = sys.argv[1], sys.argv[2]
    s = json.load(open(src, encoding="utf-8"))
    props = s["properties"]
    common = {k: v for k, v in props.items() if v.get("type") not in ("object", "array")}
    defs_key = "$defs" if "$defs" in s else "definitions"
    os.makedirs(out, exist_ok=True)
    for ev, members in EVENTS.items():
        p = dict(common)
        for m in members:
            p[m] = props[m]
        doc = {"$schema": s.get("$schema", "http://json-schema.org/draft-07/schema#"), "type": "object",
               "properties": p, defs_key: s.get(defs_key, {})}
        with open(os.path.join(out, ev + ".json"), "w", encoding="utf-8") as f:
            json.dump(doc, f, indent=1, sort_keys=False)
            f.write("\n")


if __name__ == "__main__":
    main()
