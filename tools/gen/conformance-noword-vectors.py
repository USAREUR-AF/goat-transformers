#!/usr/bin/env python3
"""Write the vectors of spec 0.52 ruling 19, a fixed layout with no counted bit
has zero words: the packs `conformance-noword-*` and the load vector 5303.

Every expected value is worked out by hand from the spec text (ruling 19 of
0.52 and ruling 18 for a group; the length sentence of 0.5; `optional` and
ruling 14 of 0.6; 0.7 groups; the decode and encode of 0.17). The working is
each vector's `reference`; the value is written out literally. A second
computation, the small codec below, parses the pack texts with its own parser;
it covers only the lines these packs use (one gate at most). Each pack is loaded
with tools/gen/gtcheck.py. Nothing here imports or calls an engine.

An empty message is the empty string, in `input` and in `expect`: hex text of
no digits (spec/vector-format.md; `conformance-malformed-bits` 05 has that form).

Inputs: model/core.def and model/probe.def. With --check nothing is written and
the exit status is 1 when a committed file differs from what this writes.

Usage: python3 -I tools/gen/conformance-noword-vectors.py [--out DIR] [--check]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402
import gtcheck  # noqa: E402

PREFIX = "conformance-noword-"
PACKS = {}
HEAD = "# Generated by tools/gen/conformance-noword-vectors.py. Do not edit by hand.\n"


def define(name, comment, body, word=1):
    text = HEAD + "# Conformance probe pack for a fixed layout with no counted bit (spec 0.52\n# ruling 19). Public.\n"
    for line in comment.split("\n"):
        text += "# " + line + "\n"
    text += "format     %s%s\nversion    0.52.0\ndistribution public\n" % (PREFIX, name)
    text += 'source  "goat-transformers spec/engine-spec.md (synthetic probe format, no external standard)"\nuses       probe\n'
    text += "wire       bits\nword_bytes %d\n" % word if word else "wire       json\n"
    PACKS[name] = text + body.lstrip("\n")


define("gate", "Byte 0 is the gate; byte 1 is y when it is 1.", """
if      0:0:8  1
  field   probe.y  1:0:8  uint
end
""")
define("gate-words", "Words of 4 bytes. Byte 0 is the gate; byte 1 is y when it is 1.", """
if      0:0:8  1
  field   probe.y  0:8:8  uint
end
""", 4)
define("gate-zero", "Byte 0 is the gate; byte 1 is y when it is 0, the value bits nothing wrote have.", """
if      0:0:8  0
  field   probe.y  1:0:8  uint
end
""")
define("gate-optional", "Byte 0 is the gate; byte 1 is y, optional, when it is 1.", """
if      0:0:8  1
  field   probe.y  1:0:8  uint  optional
end
""")
define("none", "No line but the header.", "")
define("none-words", "Words of 4 bytes. No line but the header.", "", 4)
define("group", "A group of `count 0` that starts at bit 0.", """
group   probe.items  0:0  item 8  count 0
  field   probe.qty  0:0:8  uint
end
""")
define("optional", "Byte 0 is y, optional.", """
field   probe.y  0:0:8  uint  optional
""")
define("optional-words", "Words of 4 bytes. Byte 0 is y, optional.", """
field   probe.y  0:0:8  uint  optional
""", 4)
define("json", "The `json` mirror of the other packs.", """
field   probe.y  y  int
group   probe.items  items
  field   probe.qty  qty  int
end
""", 0)


# ------------------------------------------------------------------------------
# the second computation
# ------------------------------------------------------------------------------
class Fail(Exception):
    pass


def parse(text):
    p = {"wb": 0, "gate": None, "fields": [], "group": False}
    for raw in text.splitlines():
        t = raw.split("#")[0].split()
        if t[:1] == ["word_bytes"]:
            p["wb"] = int(t[1])

    def span(loc):
        w, pos, n = (int(x) for x in loc.split(":"))
        return (w * p["wb"] * 8 + pos, n)
    inside = None
    for raw in text.splitlines() if p["wb"] else ():
        t = raw.split("#")[0].split()
        if not t:
            continue
        if t[0] == "if":
            p["gate"], inside = (span(t[1]), int(t[2])), "if"
        elif t[0] == "group":
            p["group"], inside = True, "group"
        elif t[0] == "end":
            inside = None
        elif t[0] == "field" and inside != "group":
            p["fields"].append((t[1], span(t[2]), "optional" in t, inside == "if"))
    return p


def read(data, at, n):
    """The bytes these packs address are whole: at and n are multiples of 8."""
    if at + n > len(data) * 8:
        return None
    return int.from_bytes(data[at // 8:(at + n) // 8], "little")


def words(p, bits):
    return -(-bits // (p["wb"] * 8)) * p["wb"]


def decode(p, text):
    if not p["wb"]:
        src = json.loads(text)
        ent = {"probe.y": src["y"]} if "y" in src else {}
        if "items" in src:
            ent["probe.items"] = src["items"]
        return ent
    data, ent, need = bytes.fromhex(text), {}, 0
    held = p["gate"] is not None and read(data, *p["gate"][0]) == p["gate"][1]
    for key, (at, n), optional, gated in p["fields"]:
        if gated and not held:
            continue
        v = read(data, at, n)
        if not optional:
            need = max(need, at + n)
        if v is not None:
            ent[key] = v
    if words(p, need) > len(data):
        raise Fail("malformed-wire")
    if p["group"]:
        ent["probe.items"] = []
    return ent


def encode(p, ent):
    if not p["wb"]:
        out = {"y": ent["probe.y"]} if "probe.y" in ent else {}
        if "probe.items" in ent:
            out["items"] = ent["probe.items"]
        return json.dumps(out, separators=(",", ":"))
    if p["group"] and ent.get("probe.items") != []:
        raise Fail("transform-encode")
    out, end = {}, 0
    held = False
    if p["gate"]:
        opened = any(gated and key in ent for key, _, _, gated in p["fields"])
        held = opened or p["gate"][1] == 0      # step 4: bits nothing wrote read as 0
        if held:
            (at, n), v = p["gate"]
            out[at // 8], end = v, max(end, at + n)
    for key, (at, n), _, gated in p["fields"]:
        if held or not gated:
            out[at // 8], end = ent.get(key, 0), max(end, at + n)
    return bytes(out.get(i, 0) for i in range(words(p, end))).hex()


# ------------------------------------------------------------------------------
# the vectors
# ------------------------------------------------------------------------------
def build(sink):
    written, counters = {}, {}
    here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    model = gtcheck.Model()
    for name in ("core", "probe"):
        with open(os.path.join(here, "model", name + ".def"), encoding="utf-8") as fh:
            model.add(fh.read(), name)
    for name, text in PACKS.items():
        gtcheck.load_pack(text, model, name)
        sink.write("packs/%s%s/pack.def" % (PREFIX, name), text)
        written[PREFIX + name] = 1

    def vec(frm, to, name, inp, expect=None, error=None, model=None, ref=""):
        ent, got, failed = {}, None, None
        try:
            ent = decode(parse(PACKS[frm]), inp)
            got = encode(parse(PACKS[to]), ent)
        except Fail as e:
            failed = str(e)
        assert (got, failed) == (expect, error), (frm, to, name, expect, error, got, failed)
        for k, v in (model or {}).items():
            if k == "@absent":
                assert not set(v) & set(ent), (name, v)
            elif k.endswith(".#"):
                assert str(len(ent[k[:-2]])) == v, (name, k)
            else:
                assert str(ent[k]) == v, (name, k)
        d = {"name": name, "from": PREFIX + frm, "to": PREFIX + to, "input": inp}
        d.update({"expect_error": error} if error else {"expect": expect})
        if model:
            d["model"] = model
        d["source"] = "constructed"
        d["reference"] = ref
        counters[frm] = counters.get(frm, 0) + 1
        sink.write("packs/%s%s/vectors/%02d-%s.json" % (PREFIX, frm, counters[frm], name),
                   json.dumps(d, indent=2, ensure_ascii=False) + "\n")
        written[PREFIX + frm] += 1

    def rt(p, name, inp, expect=None, **kw):
        vec(p, p, name, inp, expect, **kw)

    def enc(p, name, inp, expect=None, **kw):
        vec("json", p, p + "-" + name, inp, expect, **kw)
    R = "spec 0.52 ruling 19: "
    MW, TE = "malformed-wire", "transform-encode"
    GONE = {"@absent": ["probe.y"]}
    Y7 = {"probe.y": "7"}
    U = R + "the one line is in a block that does not hold: zero words; "

    rt("gate", "empty-input", "", "", model=GONE, ref=U + "a gate beyond the input does not hold (0.17 Decode); encode writes none")
    rt("gate", "gate-bits-zero", "00", "", model=GONE, ref=U + "the gate reads 0, not 1; encode: the block is not open and the gate reads 0 (0.17 steps 1 and 4)")
    rt("gate", "longer-input-gate-bits-zero", "0007ff", "", model=GONE, ref=U + "the extra bytes are ignored (0.5)")
    rt("gate", "gate-bits-of-another-value", "0207", "", model=GONE, ref=U + "the gate reads 2")
    rt("gate", "gate-held", "0107", "0107", model=Y7, ref="spec 0.17: the gate holds, y = 7; encode: open, gate value 1")
    rt("gate", "gate-held-input-short", "01", error=MW, ref="spec 0.17 Decode: a field of a held block beyond the input")
    vec("gate", "json", "empty-input-to-json", "", "{}", ref=U + "no key")
    enc("gate", "without-the-key", "{}", "", ref=U + "encode writes none")
    enc("gate", "with-the-key", '{"y":7}', "0107", ref="spec 0.17 Encode steps 1, 3 and 5: open, gate value 1")

    rt("gate-words", "empty-input", "", "", model=GONE, ref=U + "there is no smallest length of one word")
    rt("gate-words", "less-than-a-word-gate-bits-zero", "00", "", model=GONE, ref=U + "decode needs no byte")
    rt("gate-words", "one-word-gate-bits-zero", "00070000", "", model=GONE, ref=U + "the word is ignored; encode writes none")
    rt("gate-words", "gate-held", "01070000", "01070000", model=Y7, ref="spec 0.17 and 0.5: one whole word")
    rt("gate-words", "gate-held-less-than-a-word", "0107", error=MW, ref="spec 0.5: the held y requires a whole word")
    enc("gate-words", "without-the-key", "{}", "", ref=U + "encode writes none, not one word")
    enc("gate-words", "with-the-key", '{"y":7}', "01070000", ref="spec 0.17 Encode: one whole word")

    Z = "spec 0.17 Encode step 4: bits nothing wrote read as 0, so the gate 0 holds although the block is not open; "
    rt("gate-zero", "empty-input", "", "0000", model=GONE, ref=R + "decode needs no byte: a gate beyond the input does not hold. " + Z + "gate and y are written")
    rt("gate-zero", "gate-not-held", "01", "0000", model=GONE, ref=R + "decode: the gate reads 1. " + Z + "gate and y are written")
    enc("gate-zero", "without-the-key", "{}", "0000", ref=Z + "the block's line counts for this entity, so the length is not zero words")

    rt("gate-optional", "empty-input", "", "", model=GONE, ref=U + "encode writes none")
    rt("gate-optional", "gate-held-field-beyond-the-input", "01", "", model=GONE,
       ref="spec 0.17 Decode: the gate holds and the optional y is absent. Encode: the block is not open and the gate reads 0: " + U + "none")
    rt("gate-optional", "gate-held", "0107", "0107", model=Y7, ref="spec 0.17: open, gate value 1")

    N = R + "no line with a bit: zero words; "
    for p in ("none", "none-words"):
        rt(p, "empty-input", "", "", model=GONE, ref=N + "decode needs no byte, encode writes none")
        rt(p, "longer-input", "aabb", "", ref=N + "the extra bytes are ignored (0.5)")
        enc(p, "from-json", '{"y":7}', "", ref=N + "encode writes none")

    G = "spec 0.52 rulings 18 and 19: a group that starts at bit 0 with no items reaches bit 0: zero words; "
    rt("group", "empty-input", "", "", model={"probe.items.#": "0"}, ref=G + "the list is present and empty (0.7)")
    rt("group", "longer-input", "aa", "", model={"probe.items.#": "0"}, ref=G + "the extra byte is ignored")
    enc("group", "empty-list", '{"items":[]}', "", ref=G + "encode writes none")
    enc("group", "absent-list", "{}", error=TE, ref="spec 0.7 ruling 5, kept by 0.52 ruling 18")

    O = "spec 0.6: `optional`: a field beyond the input is absent, encode is unchanged; ruling 14: decode requires words up to the furthest bit that is not optional, here none; "
    rt("optional", "empty-input", "", "00", model=GONE, ref=O + "encode counts the line: one byte")
    rt("optional", "key-present", "07", "07", model=Y7, ref=O + "y = 7")
    enc("optional", "without-the-key", "{}", "00", ref=O + "the line counts on encode, so the length is not zero words")
    rt("optional-words", "empty-input", "", "00000000", model=GONE, ref=O + "encode: one whole word")
    rt("optional-words", "less-than-a-word", "07", "07000000", model=Y7, ref=O + "y is inside the input; encode: one whole word")
    enc("optional-words", "without-the-key", "{}", "00000000", ref=O + "encode: one whole word")

    core = 'module core\nversion 0.1.0\ndistribution public\nsource "probe"\nkey uid string -\n'
    text = 'format probe\nversion 0.52.0\ndistribution public\nsource "probe"\nwire bits\nword_bytes 4\n'
    m = gtcheck.Model()
    m.add(core)
    gtcheck.load_pack(text, m)
    full = "5303-noword-fixed-layout-with-no-line-loads"
    sink.write("packs/conformance/load-vectors/%s.json" % full,
               json.dumps({"name": full, "models": [core], "pack": text}, indent=2) + "\n")
    written["load"] = 1
    return written


def main(argv=None):
    return genio.vector_main("conformance-noword-vectors.py", __doc__, build, argv)


if __name__ == "__main__":
    sys.exit(main())
