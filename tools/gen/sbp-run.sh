#!/bin/bash
# Regenerate the SBP packs: one pack per message package of the Swift Navigation
# Binary Protocol (github.com/swift-nav/libsbp, spec/yaml/swiftnav/sbp/*.yaml),
# one kind per message, one module per package (model/sbp<package>.def) and the
# frame-header module model/sbp.def.
#
# Usage: tools/gen/sbp-run.sh <checkout> <sources> [--fetch] [--check]
#
# <checkout> is a goat-transformers checkout; it is written: model/sbp*.def,
# packs/sbp-*/ (pack.def, pack.md, PROVENANCE.md, vectors/). The generator
# checks the SHA-256 of every input against tools/gen/sources/sbp-PROVENANCE.md
# and stops when one differs. With --check it writes nothing and reports any
# file that differs from what it would write.
#
# <sources> is a directory for the libsbp tree. It is not kept in the
# repository. With --fetch the script downloads tag v6.5.2,
#   https://codeload.github.com/swift-nav/libsbp/tar.gz/925825dea5174f069b5d6e23548f213e09f0235c
#   sha256 4054fd714b6ad412be5cdca38a781789a5aa39acafe4e3f5381c98ec24533142
# and unpacks it to <sources>/libsbp-<commit>/. License: MIT, Copyright (c)
# 2015-2021 Swift Navigation (LICENSE at the root of the commit, verbatim in
# tools/gen/sources/sbp-PROVENANCE.md).
set -euo pipefail
ROOT="$(cd "$1" && pwd)"
mkdir -p "$2"
SRC="$(cd "$2" && pwd)"
GEN="$(cd "$(dirname "$0")" && pwd)"
COMMIT=925825dea5174f069b5d6e23548f213e09f0235c
TAR_SHA=4054fd714b6ad412be5cdca38a781789a5aa39acafe4e3f5381c98ec24533142
shift 2
if [ "${1:-}" = "--fetch" ]; then
  shift
  curl -sS -f -L -o "$SRC/libsbp-$COMMIT.tar.gz" "https://codeload.github.com/swift-nav/libsbp/tar.gz/$COMMIT"
  echo "$TAR_SHA  $SRC/libsbp-$COMMIT.tar.gz" | sha256sum -c -
  tar -xzf "$SRC/libsbp-$COMMIT.tar.gz" -C "$SRC"
fi
if [ "${1:-}" != "--check" ]; then
  # remove what an earlier run wrote (files whose header names this generator)
  for f in "$ROOT"/model/sbp*.def "$ROOT"/packs/sbp-*/pack.def; do
    [ -e "$f" ] || continue
    if head -3 "$f" | grep -q "Generated by tools/gen/sbp2pack.py"; then
      case "$f" in
        */pack.def) rm -rf "$(dirname "$f")" ;;
        *) rm -f "$f" ;;
      esac
    fi
  done
fi
python3 -I "$GEN/sbp2pack.py" --src "$SRC/libsbp-$COMMIT" --out "$ROOT" --core-def "$ROOT/model/core.def" \
  --track-def "$ROOT/model/track.def" "$@"
