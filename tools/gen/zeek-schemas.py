#!/usr/bin/env python3
"""Write one JSON Schema per Zeek log from tools/gen/zeek-logs.tsv.txt (this
repository's restatement of the logged fields), for jsonschema2pack; and write
each pack's PROVENANCE.md.

Python 3 standard library only. Usage:
  python3 -I tools/gen/zeek-schemas.py schemas <zeek-logs.tsv.txt> <out-dir>
  python3 -I tools/gen/zeek-schemas.py provenance <checkout> <commit> [--check]
"""
import collections
import json
import os
import sys

LOGS = ["conn", "dns", "http", "ssl", "files", "notice", "weird", "x509", "dhcp"]
SCRIPTS = {"conn": "scripts/base/protocols/conn/main.zeek", "dns": "scripts/base/protocols/dns/main.zeek",
           "http": "scripts/base/protocols/http/main.zeek", "ssl": "scripts/base/protocols/ssl/main.zeek",
           "files": "scripts/base/frameworks/files/main.zeek", "notice": "scripts/base/frameworks/notice/main.zeek",
           "weird": "scripts/base/frameworks/notice/weird.zeek", "x509": "scripts/base/files/x509/main.zeek",
           "dhcp": "scripts/base/protocols/dhcp/main.zeek"}


def pack(log):
    return "zeek-%s-scope-underscore" % log


def schemas(tsv, out):
    logs = collections.OrderedDict()
    for line in open(tsv, encoding="utf-8"):
        if line.startswith("#") or line.startswith("log\t") or not line.strip():
            continue
        log, member, typ = line.rstrip("\n").split("\t")
        logs.setdefault(log, []).append((member, typ))
    os.makedirs(out, exist_ok=True)
    for log, fields in logs.items():
        props = collections.OrderedDict()
        for member, typ in fields:
            if typ.startswith("array:"):
                props[member] = {"type": "array", "items": {"type": typ[6:]}}
            else:
                props[member] = {"type": typ}
        with open(os.path.join(out, log + ".json"), "w", encoding="utf-8") as f:
            json.dump({"$schema": "http://json-schema.org/draft-07/schema#", "title": "Zeek %s log record" % log,
                       "type": "object", "properties": props}, f, indent=1)
            f.write("\n")


PROV = """# Provenance: {pack} pack

SPDX licence: Apache-2.0

Generated by `tools/gen/zeek-run.sh` (`tools/gen/zeek-schemas.py`, then
`tools/gen/jsonschema2pack.py`) from `tools/gen/zeek-logs.tsv.txt`, this repository's
restatement of the logged fields (names and types) of the `{log}` log. No source file is
copied into this repository. Zeek is BSD-3-Clause; no code is copied. Read on 2026-11-20.

| | |
|---|---|
| Source | Zeek, https://github.com/zeek/zeek, tag `v8.0.11`, commit `{commit}` |
| Script | `{script}` (the `&log` fields of its `Info` record){extra} |
| Licence | `COPYING`: BSD 3-Clause, "Copyright (c) 1995-now, The Regents of the University of California through the Lawrence Berkeley National Laboratory and the International Computer Science Institute. All rights reserved." |

The member names are those Zeek writes with `Log::default_scope_sep` set to `"_"`; see
pack.md. The vectors are written by jsonschema2pack from values it chooses; no Zeek log is
used.
"""


def provenance(gt, commit, check):
    bad = 0
    for log in LOGS:
        extra = ""
        if log in ("conn", "dns", "http", "ssl", "files", "notice", "weird"):
            extra = "; `scripts/base/init-bare.zeek` for the logged fields of `conn_id`"
        if log == "x509":
            extra = "; `scripts/base/init-bare.zeek` for `X509::Certificate`, `X509::SubjectAlternativeName` and `X509::BasicConstraints`"
        text = PROV.format(pack=pack(log), log=log, commit=commit, script=SCRIPTS[log], extra=extra)
        path = os.path.join(gt, "packs", pack(log), "PROVENANCE.md")
        if check:
            cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if cur != text:
                print("differs: packs/%s/PROVENANCE.md" % pack(log))
                bad += 1
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    if check and bad:
        sys.exit(1)


if __name__ == "__main__":
    if sys.argv[1] == "schemas":
        schemas(sys.argv[2], sys.argv[3])
    else:
        provenance(sys.argv[2], sys.argv[3], "--check" in sys.argv[4:])
