#!/usr/bin/env python3
"""Write the vectors of spec 0.64, one text token split into coded fields: the
packs `conformance-part-*` and the load vectors from 6400.

Every expected value is worked out by hand from the spec text (Version 0.64 and
its rulings, and what it refers to: 0.5 kinds, 0.6 tables, defaults and several
lines for one key, 0.7 groups, 0.10 the `text` wire, 0.11 the order of load
checks, 0.18 separators) and written literally. The cases named E1 to E11 are a
user's public synthetic cases, with the parts numbered from 0: part 0 is the
constant `k`, part 1 a letter of table `t2` (p 0, u 1, f 3, n 4, s 5, h 6),
part 2 a letter of table `t3` (A 1, S 2); other letters occur and are not in
the tables.

A second computation checks each value: the small codec below reads the pack
text this script writes with its own parser and applies the rules. Load vectors
are checked against tools/gen/gtcheck.py. Nothing here imports or calls an
engine.

Inputs: none. Writes, under --out, the files named above. The same run always
gives the same bytes. With --check nothing is written and the exit status is 1
when a committed file differs from what this script writes.

Usage: python3 -I tools/gen/conformance-part-vectors.py [--out DIR] [--check]
"""
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402
import gtcheck  # noqa: E402

P = "conformance-part-"
SOURCE = '"goat-transformers spec/engine-spec.md (synthetic probe format, no external standard)"'
GENERATED = "# Generated by tools/gen/conformance-part-vectors.py. Do not edit by hand.\n"
LOAD_DIR = "packs/conformance/load-vectors"
OWN_LOAD = re.compile(r"\A6[45]\d\d-part-.*\.json\Z")
SEPS = {"space": " ", "comma": ",", "colon": ":"}
INTS = {"probe.x", "probe.y", "probe.z", "time_ms"}
FLOATS = {"probe.ratio"}


class Fail(Exception):
    def __init__(self, kind, why=""):
        super().__init__(kind, why)
        self.kind = kind


# -- the second computation: a parser of the lines these packs use -------------
class Line:
    def __init__(self, d, a):
        self.d, self.a, self.body = d, a, []
        self.part = self.via = self.text = None
        self.opts = []
        if d in ("field", "const", "when", "group"):
            self.loc = a[1] if d in ("field", "group") else a[0]
        if d == "field":
            self.key, tr, rest = a[0], a[2], a[3:]
            self.tr = tr
            if "via" in rest:
                self.via = rest[rest.index("via") + 1]
            self.opts = rest
        elif d == "const":
            tr = a[1] if len(a) == 3 else ""
            self.text = a[-1][1:] if a[-1].startswith("=") else a[-1]
        else:
            tr = ""
        if tr.startswith("part:"):
            _, sep, n = tr.split(":")
            self.part = (SEPS.get(sep, sep), int(n))


def words(raw):
    return [m.group(1) if m.group(1) is not None else m.group(2)
            for m in re.finditer(r'"([^"]*)"|(\S+)', raw.split(" # ")[0])]


def parse(text):
    p = {"wire": None, "tables": {}, "typemap": [], "common": [], "kinds": [], "delim": ","}
    stack = []
    for raw in text.splitlines():
        if raw.startswith("#") or not raw.strip():
            continue
        t = words(raw)
        d, a = t[0], t[1:]
        if d == "wire":
            p["wire"] = a[0]
        elif d == "delimiter":
            p["delim"] = None if a[0] == "none" else a[0]
        elif d == "map":
            p["tables"].setdefault(a[0], []).append((a[1], a[2]))
        elif d == "typemap":
            p["typemap"].append((a[0], a[1]))
        elif d == "kind":
            p["kinds"].append((a[0], [], []))
        elif d == "requires":
            p["kinds"][-1][1].extend(a)
        elif d == "end":
            stack.pop()
        elif d in ("field", "const", "when", "default", "group"):
            x = Line(d, a)
            (stack[-1].body if stack else p["kinds"][-1][2] if p["kinds"] else p["common"]).append(x)
            if d == "group":
                stack.append(x)
    return p


# -- values --------------------------------------------------------------------
def typed(key, text, kind):
    try:
        return int(text) if key in INTS else float(text) if key in FLOATS else text
    except ValueError:
        raise Fail(kind, "%s as %s" % (text, key))


def canon(v):
    return ("%d" % v if v == int(v) else repr(v)) if isinstance(v, float) else str(v)


ABSENT = object()


def part_value(p, x, token):
    """What a part field reads from a token: a value, or ABSENT (`unlisted`)."""
    pieces = token.split(x.part[0])
    if x.part[1] >= len(pieces):
        raise Fail("transform-decode", "missing part")      # forgivable (ruling 5)
    v = pieces[x.part[1]]
    if x.via is not None:
        hit = [m for n, m in p["tables"][x.via] if n == v]
        if not hit:
            if "unlisted" in x.opts:
                return ABSENT
            e = Fail("transform-decode", "no table entry")
            e.hard = True
            raise e
        v = hit[0]
    if x.key == "type":
        v = next((c for n, c in p["typemap"] if n == v), v)
    return typed(x.key, v, "transform-decode")


def part_text(p, x, value):
    v = canon(value)
    if x.key == "type":
        v = next((n for n, c in p["typemap"] if c == v), v)
    if x.via is not None:
        hit = [n for n, m in p["tables"][x.via] if canon(typed(x.key, m, "x")) == v]
        if not hit:
            raise Fail("transform-encode", "no entry")
        v = hit[0]
    if x.part[0] in v:
        raise Fail("transform-encode", "separator")
    return v


# -- decode of one scope: `get(locator)` gives ("text", s), ("bad",) or None ----
def decode_scope(p, lines, get, items):
    ent, soft, partlocs = {}, {}, {x.loc for x in lines if x.part}
    for x in lines:
        if x.d == "group":
            got = items(x)
            if got is not None:
                ent[x.a[0]] = [decode_scope(p, x.body, g, it) for g, it in got]
        if x.d not in ("field", "const") or (x.d == "const" and not x.part):
            continue
        got = get(x.loc)
        if got is None:
            continue
        try:
            if x.d == "const":
                pieces = got[1].split(x.part[0]) if got[0] == "text" else []
                if x.part[1] >= len(pieces) or pieces[x.part[1]] != x.text:
                    raise HardFail()
                continue
            if x.part:
                if got[0] != "text":
                    raise Fail("transform-decode")
                v = part_value(p, x, got[1])
                if v is ABSENT:
                    continue
            elif x.tr == "string":
                if got[0] != "text":
                    raise Fail("transform-decode")
                v = got[1]
                if x.key == "type":
                    v = next((c for n, c in p["typemap"] if n == v), v)
            else:
                v = typed(x.key, str(got[1]), "transform-decode")
        except HardFail:
            raise Fail("transform-decode", "const")
        except Fail as e:
            if getattr(e, "hard", False):
                raise
            soft[x.key] = e
            continue
        ent.setdefault(x.key, v)
    for k, e in soft.items():
        if k not in ent:
            raise e
    return ent


class HardFail(Exception):
    pass


# -- encode of one scope: [(locator, text or number, sub-items)] in position order
def check_whole(p, lines, group, token, ent):
    for x in group:
        if not x.part:
            continue
        pieces = token.split(x.part[0])
        if x.d == "const":
            if x.part[1] >= len(pieces) or pieces[x.part[1]] != x.text:
                raise Fail("transform-encode", "const")
            continue
        if any(o is not x and o.d == "field" and o.key == x.key for o in lines):     # rulings 18, 25, 28
            continue
        try:
            v = part_value(p, x, token)
        except Fail:
            raise Fail("transform-encode")
        if x.key in ent and (v is ABSENT or ent[x.key] != v):
            raise Fail("transform-encode", "disagrees")


def token_of(p, lines, loc, ent, defaults):
    group = [x for x in lines if getattr(x, "loc", None) == loc]
    whole = next((x for x in group if x.d == "field" and not x.part), None)
    fields = [x for x in group if x.d == "field" and x.part]

    def whole_text(v):
        if whole.key == "type":
            v = next((n for n, c in p["typemap"] if c == v), v)
        check_whole(p, lines, group, v, ent)
        return v

    if whole is not None and whole.key in ent:
        return whole_text(ent[whole.key])
    has = lambda x: x.key in ent or x.key in defaults       # noqa: E731
    if any(x.key in ent for x in fields) or all(has(x) for x in fields):
        out = {}
        for x in group:
            if x.part and x.d == "const":
                out[x.part[1]] = x.text
            elif x.part:
                if not has(x):
                    raise Fail("transform-encode", "no value for %s" % x.key)
                out[x.part[1]] = part_text(p, x, ent.get(x.key, defaults.get(x.key)))
        return fields[0].part[0].join(out[i] for i in range(max(out) + 1))
    if whole is not None and whole.key in defaults:
        return whole_text(defaults[whole.key])
    return None


def encode_scope(p, lines, ent):
    defaults = {x.a[0]: typed(x.a[0], x.a[1], "x") for x in lines if x.d == "default"}
    out, seen, partlocs = [], set(), {x.loc for x in lines if x.d in ("field", "const") and x.part}
    for x in lines:
        if x.d == "default" or x.loc in seen:
            continue
        if x.loc in partlocs:
            seen.add(x.loc)
            v = token_of(p, lines, x.loc, ent, defaults)
            out.append((x.loc, v, None))
        elif x.d == "group":
            if x.a[0] in ent:
                out.append((x.loc, None, [(encode_scope(p, x.body, it), x) for it in ent[x.a[0]]]))
        elif x.d == "field":
            v = ent.get(x.key, defaults.get(x.key))
            if "with" in x.opts and x.opts[x.opts.index("with") + 1] not in ent:
                v = None
            if v is not None and x.key == "type":
                v = next((n for n, c in p["typemap"] if c == v), v)
            out.append((x.loc, v, None))
        else:
            out.append((x.loc, x.text, None))
    return out


# -- the wires -------------------------------------------------------------------
def jtext(v):
    if isinstance(v, float):
        return canon(v)
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


def jget(obj):
    def get(loc):
        v = obj
        for step in ([] if loc == "." else loc.split(".")):
            v = v.get(step) if isinstance(v, dict) else None
        if v is None:
            return None
        return ("text", v) if isinstance(v, str) else ("bad", v)
    return get


def jitems(obj):
    def items(x):
        v = obj
        for step in x.loc.split("."):
            v = v.get(step) if isinstance(v, dict) else None
        return None if v is None else [(jget(e), jitems(e)) for e in v]
    return items


def jwrite(rows):
    parts, nested = [], {}
    for loc, v, sub in rows:
        if sub is not None:
            vals = []
            for r, x in sub:
                vals.append(("null" if r[0][1] is None else jtext(r[0][1])) if r and r[0][0] == "." else jwrite(r))
            val = "[" + ",".join(vals) + "]"
        elif v is None:
            continue
        else:
            val = jtext(v)
        parts.append((loc, val))
    return "{" + ",".join(jtext(k) + ":" + v for k, v in parts) + "}"


def xml_get(el):
    def get(loc):
        path, _, last = loc.rpartition("/")
        e = el.find(path) if path else el
        if e is None:
            return None
        v = e.get(last[1:]) if last.startswith("@") else e.text or None
        return None if v is None else ("text", v)
    return get


def xml_items(el):
    return lambda x: [(xml_get(e), xml_items(e)) for e in el.findall(x.loc)] or None


def xesc(s, attr):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return s.replace('"', "&quot;") if attr else s


def xml_write(tag, rows, residue=()):
    attrs, kids = "", ""
    for loc, v, sub in rows:
        if sub is not None:
            kids += "".join(xml_write(x.loc, r) for r, x in sub)
        elif v is not None and loc.startswith("@"):
            attrs += ' %s="%s"' % (loc[1:], xesc(v if isinstance(v, str) else str(v), True))
        elif v is not None and loc == "#text":
            kids += xesc(v, False)
        elif v is not None:
            path = loc.split("/")[0]
            assert loc == path + "/#text"
            kids += "<%s>%s</%s>" % (path, xesc(v, False), path) if v else "<%s/>" % path
    for k, v in residue:
        attrs += ' %s="%s"' % (k, xesc(v, True))
    return "<%s%s>%s</%s>" % (tag, attrs, kids, tag) if kids else "<%s%s/>" % (tag, attrs)


def scope_of(p, ent=None, kind=None, probe=None):
    """(kind name or None, lines): by `when` on decode, by `requires` on encode."""
    if not p["kinds"]:
        return None, p["common"]
    for name, req, lines in p["kinds"]:
        if probe is not None:
            ok = all(probe(x.loc) == ("text", x.a[1]) for x in lines if x.d == "when")
        elif kind is not None:
            ok = name == kind
        else:
            ok = all((k.split("=")[0] in ent and canon(ent[k.split("=")[0]]) == k.split("=")[1]) if "=" in k
                     else k in ent for k in req)
        if ok:
            return name, p["common"] + [Whened(x) if x.d == "when" else x for x in lines]
    raise Fail("no-kind")


def Whened(x):
    y = Line("const", [x.a[0], x.a[1]])
    return y


def decode(p, inp):
    if p["wire"] == "xml":
        el = ET.fromstring(inp)
        get, items = xml_get(el), xml_items(el)
    elif p["wire"] == "text":
        f = inp.split(p["delim"]) if p["delim"] else [inp]
        get = text_get(f)

        def items(x):
            i, n = int(x.a[1]), int(x.a[3])
            rows = [f[j:j + n] for j in range(i, len(f), n)]
            return [(text_get(r), None) for r in rows] or None
    else:
        obj = json.loads(inp)
        get, items = jget(obj), jitems(obj)
    kind, lines = scope_of(p, probe=get)
    ent = decode_scope(p, lines, get, items)
    if kind:
        ent["@kind"] = kind
    if p["wire"] == "xml":
        mapped = {x.loc[1:] for x in lines if getattr(x, "loc", "").startswith("@")}
        ent["@residue"] = [(k, v) for k, v in el.attrib.items() if k not in mapped]
    return ent


def text_get(f):
    return lambda loc: ("text", f[int(loc)]) if int(loc) < len(f) and f[int(loc)] else None


def encode(p, ent, same):
    kind, lines = scope_of(p, ent, ent.get("@kind") if same else None)
    rows = encode_scope(p, lines, {k: v for k, v in ent.items() if k[0] != "@"})
    if p["wire"] == "xml":
        return xml_write("e", rows, ent.get("@residue", ()) if same else ())
    if p["wire"] == "geojson":
        props = [(loc[len("properties."):], v, s) for loc, v, s in rows]
        return '{"type":"Feature","geometry":null,"properties":%s}' % jwrite(props)
    if p["wire"] == "json":
        return jwrite(rows)
    f, grp = {}, None
    for loc, v, sub in rows:
        if sub is None:
            f[int(loc)] = "" if v is None else str(v)
        else:
            x = sub[0][1]
            for n, (r, _) in enumerate(sub):
                for l, v2, _s in r:
                    f[int(x.a[1]) + n * int(x.a[3]) + int(l)] = v2 or ""
    out = [f.get(i, "") for i in range(max(f) + 1)]
    for v in f.values():
        if (p["delim"] and p["delim"] in v) or any(not " " <= c <= "~" for c in v):
            raise Fail("transform-encode")
    while len(out) > 0 and out[-1] == "":
        at = [x for x in lines if getattr(x, "loc", None) == str(len(out) - 1)]
        if not at or not all(x.d == "field" and "optional" in x.opts for x in at):
            break
        out.pop()
    return p["delim"].join(out)


