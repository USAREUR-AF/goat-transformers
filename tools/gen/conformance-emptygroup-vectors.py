# the vectors
# ------------------------------------------------------------------------------
def build(sink):
    written, counters = {}, {}
    here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    model = gtcheck.Model()
    for name in ("core", "probe"):
        with open(os.path.join(here, "model", name + ".def"), encoding="utf-8") as fh:
            model.add(fh.read(), name)
    for name, text in PACKS.items():
        gtcheck.load_pack(text, model, name)
        sink.write("packs/%s%s/pack.def" % (PREFIX, name), text)
        written[PREFIX + name] = 1

    def vec(frm, to, name, inp, expect=None, error=None, model=None, ref=""):
        ent, got, failed = None, None, None
        try:
            ent = decode(parse(PACKS[frm]), inp)
            got = encode(parse(PACKS[to]), ent, frm == to)
        except Fail as e:
            failed = str(e)
        assert (got, failed) == (expect, error), (frm, to, name, expect, error, got, failed)
        have = model_of(ent or {})
        for k, v in (model or {}).items():
            if k == "@absent":
                assert not set(v) & set(have), (name, v)
                continue
            assert have.get(k) == v, (name, k, v, have.get(k))
        d = {"name": name, "from": PREFIX + frm, "to": PREFIX + to, "input": inp}
        d.update({"expect_error": error} if error else {"expect": expect})
        if model:
            d["model"] = model
        d["source"] = "constructed"
        d["reference"] = ref
        counters[frm] = counters.get(frm, 0) + 1
        sink.write("packs/%s%s/vectors/%02d-%s.json" % (PREFIX, frm, counters[frm], name),
                   json.dumps(d, indent=2, ensure_ascii=False) + "\n")
        written[PREFIX + frm] += 1

    def rt(p, name, inp, expect=None, **kw):
        vec(p, p, name, inp, expect, **kw)

    def enc(p, name, inp, expect=None, **kw):
        vec("json", p, p + "-" + name, inp, expect, **kw)
    R = "spec 0.52 ruling 18: "
    MW, TE = "malformed-wire", "transform-encode"
    NO = {"probe.items.#": "0"}

    rt("base", "input-ends-before-the-start", "0500", error=MW, ref=R + "the empty group starts at byte 4; 2 bytes are there")
    rt("base", "input-one-byte-short-of-the-start", "050000", error=MW, ref=R + "3 bytes of 4")
    rt("base", "empty-list-at-the-start", "05000000", "05000000", model=dict(NO, **{"probe.n": "5"}),
       ref=R + "4 bytes reach the start; the list is present with no items (0.7 Decode)")
    rt("base", "input-longer-than-the-start", "05000000aabb", "05000000", model=NO,
       ref="spec 0.5: extra bytes are ignored; " + R + "encode writes up to the start")
    rt("base", "bytes-no-line-writes-are-zero", "05001122", "05000000", model=NO,
       ref=R + "zero bits where no line writes; a bits pack has no residue (0.2)")
    rt("base", "one-item", "05010000aa", "05010000aa", model={"probe.items.#": "1", "probe.items[0].probe.qty": "170"},
       ref="spec 0.7: the item at byte 4")
    rt("base", "one-item-missing", "05010000", error=MW, ref="spec 0.7: the message is extended by the item; byte 4 is missing")
    vec("base", "json", "to-json-empty-list", "05000000", '{"n":5,"items":[]}', ref="spec 0.7: present and empty")
    enc("base", "empty-list", '{"n":5,"items":[]}', "05000000", ref=R + "encode writes up to the start")
    enc("base", "absent-list", '{"n":5}', "05000000", ref=R + "an absent list writes a count of 0 (ruling 14 of 0.7) and reaches the start")
    enc("base", "one-item", '{"n":5,"items":[{"qty":170}]}', "05010000aa", ref="spec 0.7 Encode: the item at byte 4")

    rt("near", "start-where-the-other-lines-end", "0500", "0500", model=NO, ref=R + "the start is byte 2, where the count ends: nothing changes")
    enc("near", "absent-list", '{"n":5}', "0500", ref=R + "nothing changes")

    rt("zero", "count-0-input-ends-before-the-start", "05", error=MW, ref=R + "`count 0` at byte 3")
    rt("zero", "count-0-input-one-byte-short", "0500", error=MW, ref=R + "2 bytes of 3")
    rt("zero", "count-0-empty-list", "050000", "050000", model=dict(NO, **{"probe.n": "5"}), ref=R + "`count 0`: 3 bytes reach the start")
    enc("zero", "count-0-empty-list", '{"n":5,"items":[]}', "050000", ref=R + "`count 0` with no items, up to the start")
    enc("zero", "count-0-absent-list", '{"n":5}', error=TE, ref="spec 0.7 ruling 5: an absent list under a fixed count")
    enc("zero", "count-0-one-item", '{"n":5,"items":[{"qty":1}]}', error=TE, ref="spec 0.7 Encode: a fixed count with a different number of items")
    rt("zero-inside", "count-0-start-before-another-line", "05000007", "05000007", model=dict(NO, **{"probe.x": "7"}),
       ref=R + "the start, byte 1, lies before x: nothing changes")
    rt("zero-inside", "count-0-input-ends-before-the-other-line", "050000", error=MW, ref="spec 0.5: x at byte 3 is missing")
    enc("zero-inside", "count-0-empty-list", '{"n":5,"x":7,"items":[]}', "05000007", ref=R + "nothing changes")

    rt("kinds", "selected-kind-input-ends-before-the-start", "010007", error=MW, ref=R + "kind a is selected; its group starts at byte 5")
    rt("kinds", "selected-kind-empty-list", "0100070000", "0100070000", model=dict(NO, **{"@kind": "a", "probe.x": "7"}),
       ref=R + "in the selected kind")
    rt("kinds", "group-of-a-kind-not-selected", "0205", "0205", model={"@kind": "b", "probe.n": "5"},
       ref=R + "kind b is selected; kind a's group does not count")
    enc("kinds", "selected-kind-absent-list", '{"x":7}', "0100070000", ref=R + "kind a requires x; up to byte 5")
    enc("kinds", "group-of-a-kind-not-selected", '{"n":5,"items":[]}', "0205", ref=R + "kind a requires x; kind b has no group")
    rt("common", "common-group-input-ends-before-the-start", "0100", error=MW, ref=R + "in the common lines: byte 4")
    rt("common", "common-group-empty-list", "01000000", "01000000", model=dict(NO, **{"@kind": "a"}), ref=R + "in the common lines")
    rt("common", "common-group-with-a-kind-line-before-it", "02000500", "02000500", model=dict(NO, **{"@kind": "b", "probe.n": "5"}),
       ref=R + "kind b's n at byte 2 ends before the start, byte 4")
    rt("common", "common-group-input-ends-after-the-kind-line", "020005", error=MW, ref=R + "3 bytes of 4")
    enc("common", "common-group-absent-list", '{"n":5}', "02000500", ref=R + "kind b; up to byte 4")

    rt("bit", "start-inside-a-byte-input-ends-before-it", "05000000", error=MW, ref=R + "the start is bit 36: 5 bytes (0.5 whole words)")
    rt("bit", "start-inside-a-byte-empty-list", "0500000000", "0500000000", model=NO, ref=R + "36 bits, 5 bytes of whole words")
    rt("bit", "start-inside-a-byte-one-item", "050100000ab0", "050100000ab0", model={"probe.items[0].probe.qty": "171"},
       ref="spec 0.7: the item is bits 36 to 43")
    enc("bit", "start-inside-a-byte-absent-list", '{"n":5}', "0500000000", ref=R + "36 bits, 5 bytes")

    rt("words", "input-ends-before-the-word", "05000000", error=MW, ref=R + "the start is bit 40, in word 1: 2 words of 4 bytes")
    rt("words", "input-reaches-the-start-and-not-the-word", "0500000000", error=MW, ref=R + "with whole words (0.5): 5 bytes of 8")
    rt("words", "empty-list", "0500000000000000", "0500000000000000", model=NO, ref=R + "2 whole words")
    rt("words", "one-item", "0501000000aa0000", "0501000000aa0000", model={"probe.items[0].probe.qty": "170"}, ref="spec 0.7: the item is byte 5")
    enc("words", "absent-list", '{"n":5}', "0500000000000000", ref=R + "2 whole words")
    rt("words-edge", "input-one-word-short", "05000000", error=MW, ref=R + "the start is bit 64, the end of word 1")
    rt("words-edge", "empty-list-reaches-two-words", "0500000000000000", "0500000000000000", model=NO,
       ref=R + "up to the start, bit 64, and no word of the items")
    enc("words-edge", "empty-list", '{"n":5,"items":[]}', "0500000000000000", ref=R + "up to the start: 2 words, not 3")

