#!/usr/bin/env python3
"""Write the vectors of spec 0.52 ruling 18, an empty counted group on a fixed
layout reaches its start: the packs `conformance-emptygroup-*`.

Every expected value is worked out by hand from the spec text (ruling 18 of
0.52; 0.5 for whole words and positions past a word; 0.7 groups and its rulings
4, 5, 14 and 17; 0.14 and its rulings 7 and 10 for armor). The working is each
vector's `reference`; the value is written out literally. A second computation,
the small codec below, parses the pack texts with its own parser and applies
the rules to the input; it covers only the lines these packs use. Each pack is
loaded with tools/gen/gtcheck.py. Nothing here imports or calls an engine.

It also writes the load vectors 5295 to 5298.

Inputs: model/core.def and model/probe.def. With --check nothing is written and
the exit status is 1 when a committed file differs from what this writes.

Usage: python3 -I tools/gen/conformance-emptygroup-vectors.py [--out DIR] [--check]
"""
