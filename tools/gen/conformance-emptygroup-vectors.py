def define(name, comment, body, head="wire       bits\nword_bytes 1\n"):
    text = "# Generated by tools/gen/conformance-emptygroup-vectors.py. Do not edit by hand.\n"
    for line in comment.strip("\n").split("\n"):
        text += ("# " + line).rstrip() + "\n"
    text += "format     %s%s\nversion    0.52.0\ndistribution public\n" % (PREFIX, name)
    text += 'source  "goat-transformers spec/engine-spec.md (synthetic probe format, no external standard)"\n'
    PACKS[name] = text + "uses       probe\n" + head + body.lstrip("\n")


