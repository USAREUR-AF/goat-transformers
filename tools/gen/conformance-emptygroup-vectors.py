# ------------------------------------------------------------------------------
# the second computation
# ------------------------------------------------------------------------------
class Fail(Exception):
    pass


def parse(text):
    pack = {"wire": "bits", "wb": 1, "msb": False, "armor": False, "lines": [], "kinds": []}
    stack = []

    def bit(loc):
        p = [int(x) for x in loc.split(":")]
        return (p[0] * pack["wb"] * 8 + p[1],) + tuple(p[2:])
    for raw in text.splitlines():
        t = raw.split("#")[0].split()
        if not t:
            continue
        d, a = t[0], t[1:]
        if d == "wire":
            pack["wire"] = a[0]
        elif d == "word_bytes":
            pack["wb"] = int(a[0])
        elif d == "bit_order":
            pack["msb"] = a[0] == "msb"
        elif d == "armor":
            pack["armor"] = True
        elif d == "kind":
            pack["kinds"].append({"name": a[0], "requires": [], "lines": []})
        elif d == "requires":
            pack["kinds"][-1]["requires"] += a
        elif d == "end":
            stack.pop()
        elif d == "if":
            pack["gate"] = (bit(a[0]), int(a[1]))
            stack.append(dict(pack["lines"][-1], lines=pack["lines"], gated=True))
        elif d in ("field", "when", "group"):
            js = pack["wire"] == "json"
            node = {"d": d, "key": a[0], "loc": a[1]}
            if d == "when":
                node.update(loc=bit(a[0]), value=int(a[1]))
            elif not js:
                node["loc"] = bit(a[1])
            if d == "group":
                node["lines"] = []
                if not js:
                    node.update(item=int(a[3]), count=bit(a[5]) if ":" in a[5] else int(a[5]))
            node["gated"] = bool(stack and stack[-1].get("gated"))
            node["optional"] = "optional" in a
            (stack[-1] if stack else pack["kinds"][-1] if pack["kinds"] else pack)["lines"].append(node)
            if d == "group":
                stack.append(node)
    return pack


def get(pack, bits, pos, n):
    part = bits[pos:pos + n]
    if len(part) < n:
        raise Fail("malformed-wire")
    return int("".join(part if pack["msb"] else part[::-1]), 2)


def to_bits(pack, text):
    if pack["armor"]:
        return list("".join(format(ord(c) - (48 if ord(c) < 96 else 56), "06b") for c in text))
    return [b for byte in bytes.fromhex(text)
            for b in (format(byte, "08b") if pack["msb"] else format(byte, "08b")[::-1])]


def decode(pack, text):
    if pack["wire"] == "json":
        def walk(lines, src):
            out = {}
            for n in lines:
                if n["loc"] in src:
                    v = src[n["loc"]]
                    out[n["key"]] = [walk(n["lines"], i) for i in v] if n["d"] == "group" else v
            return out
        return walk(pack["lines"], json.loads(text))
    bits, ent, lines = to_bits(pack, text), {}, list(pack["lines"])
    for k in pack["kinds"]:
        if all(len(bits) >= sum(w["loc"]) and get(pack, bits, *w["loc"]) == w["value"]
               for w in k["lines"] if w["d"] == "when"):
            ent["@kind"] = k["name"]
            lines += k["lines"]
            break
    else:
        if pack["kinds"]:
            raise Fail("no-kind")
    end = dec_scope(pack, bits, 0, lines, ent)
    if not pack["armor"]:
        end = -(-end // (pack["wb"] * 8)) * pack["wb"] * 8
    if end > len(bits):
        raise Fail("malformed-wire")
    return ent


def dec_scope(pack, bits, base, lines, ent):
    """Reads one scope at `base`; the furthest bit it reaches, exclusive."""
    end = base
    for n in lines:
        if n["d"] != "group":
            if n["optional"] and base + sum(n["loc"]) > len(bits):
                continue
            if n["gated"] and get(pack, bits, *pack["gate"][0]) != pack["gate"][1]:
                continue
            end = max(end, base + sum(n["loc"]))
            if n["d"] == "field":
                ent[n["key"]] = get(pack, bits, base + n["loc"][0], n["loc"][1])
            continue
        count = n["count"]
        if not isinstance(count, int):
            end = max(end, base + sum(count))
            count = get(pack, bits, base + count[0], count[1])
        pos, items = base + n["loc"][0], []
        for _ in range(count):
            item = {}
            reach = dec_scope(pack, bits, pos, n["lines"], item)
            pos = max(pos + n["item"], reach)
            items.append(item)
        end = max(end, pos)         # ruling 18: the start, when there are no items
        ent[n["key"]] = items
    return end


def encode(pack, ent, same):
    if pack["wire"] == "json":
        def walk(lines, src):
            return {n["loc"]: [walk(n["lines"], i) for i in src[n["key"]]] if n["d"] == "group" else src[n["key"]]
                    for n in lines if n["key"] in src}
        return json.dumps(walk(pack["lines"], ent), separators=(",", ":"))
    lines = list(pack["lines"])
    if pack["kinds"]:
        k = next((k for k in pack["kinds"] if (k["name"] == ent.get("@kind") if same
                                               else all(r in ent for r in k["requires"]))), None)
        if k is None:
            raise Fail("no-kind")
        lines += k["lines"]
    cells = {}

    def put(pos, n, v):
        if v >> n:
            raise Fail("transform-encode")
        s = format(v, "0%db" % n)
        for i, b in enumerate(s if pack["msb"] else s[::-1]):
            cells[pos + i] = b

    def scope(base, lines, ent):
        end = base
        for n in lines:
            if n["d"] == "field":
                if n["gated"] and ent.get("probe.n") != pack["gate"][1]:    # the gate bits are n's
                    assert n["key"] not in ent
                    continue
                put(base + n["loc"][0], n["loc"][1], ent.get(n["key"], 0))
                end = max(end, base + sum(n["loc"]))
        for n in lines:
            if n["d"] == "when":
                put(base + n["loc"][0], n["loc"][1], n["value"])
                end = max(end, base + sum(n["loc"]))
            if n["d"] == "group":
                items = ent.get(n["key"])
                if isinstance(n["count"], int):
                    if items is None or len(items) != n["count"]:
                        raise Fail("transform-encode")
                else:
                    put(base + n["count"][0], n["count"][1], len(items or []))
                    end = max(end, base + sum(n["count"]))
                pos = base + n["loc"][0]
                for item in items or []:
                    pos = max(pos + n["item"], scope(pos, n["lines"], item))
                end = max(end, pos)
        return end
    end = scope(0, lines, ent)
    unit = 6 if pack["armor"] else pack["wb"] * 8
    end = -(-end // unit) * unit
    bits = "".join(cells.get(i, "0") for i in range(end))
    if pack["armor"]:
        vals = [int(bits[i:i + 6], 2) for i in range(0, end, 6)]
        return "".join(chr(v + (48 if v < 40 else 56)) for v in vals)
    chunks = [bits[i:i + 8] for i in range(0, end, 8)]
    return "".join("%02x" % int(c if pack["msb"] else c[::-1], 2) for c in chunks)


def model_of(ent, prefix=""):
    have = {}
    for k, v in ent.items():
        if isinstance(v, list):
            have[prefix + k + ".#"] = str(len(v))
            for i, item in enumerate(v):
                have.update(model_of(item, "%s%s[%d]." % (prefix, k, i)))
        else:
            have[prefix + k] = str(v)
    return have


