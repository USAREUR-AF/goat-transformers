#!/bin/bash
# Regenerate the DroneCAN (UAVCAN v0) packs: one pack per data type of
# github.com/dronecan/DSDL that has a default data type ID, and one module per
# namespace (model/dc<namespace>.def).
#
# Usage: tools/gen/dsdl2pack-run.sh <checkout> <sources> [--fetch]
#
# <checkout> is a goat-transformers checkout; it is written: model/dc*.def,
# packs/dronecan-*/ (pack.def, pack.md, PROVENANCE.md, vectors/). The generator
# checks the SHA-256 of every input against tools/gen/sources/dronecan-PROVENANCE.md
# and stops when one differs.
#
# <sources> is a directory for the DSDL tree. It is not kept in the
# repository. With --fetch the script downloads
#   https://codeload.github.com/dronecan/DSDL/tar.gz/b4653c7abc3c47cb31b16efa24ea755232774756
#   sha256 1dab631fa41f1e7f7adce1f7edbf31bf11c4346886aeebaf9b89d0528e43cb00
# and unpacks it to <sources>/DSDL-<commit>/. License: MIT (LICENSE at the root
# of the commit, verbatim in tools/gen/sources/dronecan-PROVENANCE.md).
#
# Namespaces: uavcan (the standard types), dronecan, ardupilot, com, cuav,
# mppt. `tests/` holds test inputs of the upstream tools and is not read.
set -euo pipefail
ROOT="$(cd "$1" && pwd)"
SRC="$(cd "$2" && pwd)"
GEN="$(cd "$(dirname "$0")" && pwd)"
COMMIT=b4653c7abc3c47cb31b16efa24ea755232774756
TAR_SHA=1dab631fa41f1e7f7adce1f7edbf31bf11c4346886aeebaf9b89d0528e43cb00
if [ "${3:-}" = "--fetch" ]; then
  curl -sS -f -L -o "$SRC/dsdl-$COMMIT.tar.gz" "https://codeload.github.com/dronecan/DSDL/tar.gz/$COMMIT"
  echo "$TAR_SHA  $SRC/dsdl-$COMMIT.tar.gz" | sha256sum -c -
  tar -xzf "$SRC/dsdl-$COMMIT.tar.gz" -C "$SRC"
fi
# remove what an earlier run wrote (files whose header names this generator)
for f in "$ROOT"/model/dc*.def "$ROOT"/packs/dronecan-*/pack.def; do
  [ -e "$f" ] || continue
  if head -3 "$f" | grep -q "Generated by tools/gen/dsdl2pack.py"; then
    case "$f" in
      */pack.def) rm -rf "$(dirname "$f")" ;;
      *) rm -f "$f" ;;
    esac
  fi
done
python3 -I "$GEN/dsdl2pack.py" --dsdl "$SRC/DSDL-$COMMIT" --root "$ROOT" \
  --core-def "$ROOT/model/core.def"
