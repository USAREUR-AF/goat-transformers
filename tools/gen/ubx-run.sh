#!/bin/bash
# Regenerate the UBX packs: one pack per u-blox UBX message class, one kind per
# message definition of fixed length, from the definitions of pyubx2
# (github.com/semuconsulting/pyubx2, src/pyubx2/ubxtypes_*.py and ubxvariants.py),
# one module per class (model/ubx<class>.def).
#
# Usage: tools/gen/ubx-run.sh <checkout> <sources> [--fetch] [--check]
#
# <checkout> is a goat-transformers checkout; it is written: model/ubx*.def,
# packs/ubx-*/ (pack.def, pack.md, PROVENANCE.md, vectors/). The generator reads
# the definition files as Python syntax trees and never runs them; it checks the
# SHA-256 of every input against tools/gen/sources/ubx-PROVENANCE.md and stops
# when one differs. With --check it writes nothing and reports any file that
# differs from what it would write.
#
# <sources> is a directory for the pyubx2 tree. It is not kept in the
# repository. With --fetch the script downloads tag v1.4.1,
#   https://codeload.github.com/semuconsulting/pyubx2/tar.gz/e5335f7285b24808fb62ccaf6666a6b954f27118
#   sha256 b76d96bc2d1440b9d6b38fe5f73da88728fe225bd2abfd39b842e103bba2dcfa
# and unpacks it to <sources>/pyubx2-<commit>/. License: BSD 3-Clause,
# Copyright (c) 2020 semuadmin (Steve Smith) (LICENSE at the root of the commit,
# verbatim in tools/gen/sources/ubx-PROVENANCE.md).
#
# The units of the bound velocity, speed and heading fields come from the
# ublox_msgs .msg files of https://github.com/KumarRobotics/ublox at commit
# 3a3e1c253722b68e350a60aee6ef399d8c2304cb (BSD, as ublox_msgs/package.xml and
# ublox_msgs/src/ublox_msgs.cpp state it; the commit tools/gen/ros2-run.sh uses).
# With --fetch the script downloads the five files the generator reads to
# <sources>/ublox-<commit>/; their SHA-256 are in the provenance file.
set -euo pipefail
ROOT="$(cd "$1" && pwd)"
mkdir -p "$2"
SRC="$(cd "$2" && pwd)"
GEN="$(cd "$(dirname "$0")" && pwd)"
COMMIT=e5335f7285b24808fb62ccaf6666a6b954f27118
TAR_SHA=b76d96bc2d1440b9d6b38fe5f73da88728fe225bd2abfd39b842e103bba2dcfa
UBLOX=3a3e1c253722b68e350a60aee6ef399d8c2304cb
UBLOX_FILES="ublox_msgs/msg/NavPVT.msg ublox_msgs/msg/NavVELNED.msg ublox_msgs/msg/HnrPVT.msg ublox_msgs/package.xml ublox_msgs/src/ublox_msgs.cpp"
shift 2
if [ "${1:-}" = "--fetch" ]; then
  shift
  curl -sS -f -L -o "$SRC/pyubx2-$COMMIT.tar.gz" "https://codeload.github.com/semuconsulting/pyubx2/tar.gz/$COMMIT"
  echo "$TAR_SHA  $SRC/pyubx2-$COMMIT.tar.gz" | sha256sum -c -
  tar -xzf "$SRC/pyubx2-$COMMIT.tar.gz" -C "$SRC"
  for f in $UBLOX_FILES; do
    mkdir -p "$SRC/ublox-$UBLOX/$(dirname "$f")"
    curl -sS -f -L -o "$SRC/ublox-$UBLOX/$f" "https://raw.githubusercontent.com/KumarRobotics/ublox/$UBLOX/$f"
  done
fi
if [ "${1:-}" != "--check" ]; then
  # remove what an earlier run wrote (files whose header names this generator)
  for f in "$ROOT"/model/ubx*.def "$ROOT"/packs/ubx-*/pack.def; do
    [ -e "$f" ] || continue
    if head -3 "$f" | grep -q "Generated by tools/gen/ubx2pack.py"; then
      case "$f" in
        */pack.def) rm -rf "$(dirname "$f")" ;;
        *) rm -f "$f" ;;
      esac
    fi
  done
fi
python3 -I "$GEN/ubx2pack.py" --src "$SRC/pyubx2-$COMMIT" --ublox-msgs "$SRC/ublox-$UBLOX" --out "$ROOT" \
  --core-def "$ROOT/model/core.def" --track-def "$ROOT/model/track.def" "$@"
