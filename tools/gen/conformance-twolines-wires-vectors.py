#!/usr/bin/env python3
"""Write the vectors of 0.64 rulings 26 and 27 beyond `json` and `xml`: one key on
two lines, one of them with a value table of another type, on `bits` (both
layouts), `text`, `protobuf`, `tlv` and `cbor`, with what does not change or
what wins over the failure (a path that does not parse, an absent line, a
sentinel, a block not held, a failed transform, a list over the limit). The
packs are `conformance-twolines-w-*`.

Every expected value is worked out by hand from the text and written literally;
the working is the comment above it. A second computation, `recompute` below,
reads each message by its own small readers and applies the rules. Nothing here
imports or calls an engine.

Inputs: none. Writes, under --out, the packs named above. With --check nothing
is written and the exit status is 1 when a committed file differs from what
this script writes.

Usage: python3 -I tools/gen/conformance-twolines-wires-vectors.py [--out DIR] [--check]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genio  # noqa: E402

P = "conformance-twolines-w-"
GENERATED = "# Generated by tools/gen/conformance-twolines-wires-vectors.py. Do not edit by hand.\n"
SOURCE = '"goat-transformers spec/engine-spec.md (synthetic probe format, no external standard)"'
TABLE = {"h": 6, "f": 3}
DEC, MAL = "transform-decode", "malformed-wire"


class Malformed(Exception):
    pass


# Each reader gives [plain, tabled]: an int, a text, None (absent) or BAD (the
# transform fails); each writer takes the int and the text to write.
BAD = object()


def pb_fields(data):
    def varint(i):
        v = shift = 0
        while True:
            if i >= len(data):
                raise Malformed()
            v |= (data[i] & 127) << shift
            shift, i = shift + 7, i + 1
            if not data[i - 1] & 128:
                return v, i
    out, i = {}, 0
    while i < len(data):
        tag, i = varint(i)
        if tag & 7 == 0:
            v, i = varint(i)
        elif tag & 7 == 2:
            n, i = varint(i)
            if i + n > len(data):
                raise Malformed()
            v, i = data[i:i + n], i + n
        else:
            raise Malformed()
        out[tag >> 3] = (tag & 7, v)
    return out


def pb(plain, path):
    def read(hx):
        top = pb_fields(bytes.fromhex(hx))
        x = top.get(plain)
        sub, steps = top, path
        while len(steps) > 1 and sub is not None:
            got = sub.get(steps[0])
            if got is not None and got[0] != 2:
                raise Malformed()
            sub, steps = (None if got is None else pb_fields(got[1])), steps[1:]
        y = None if sub is None else sub.get(steps[0])
        return [None if x is None else x[1] if x[0] == 0 else BAD,
                None if y is None else y[1].decode() if y[0] == 2 else BAD]

    def write(n, s):
        y = bytes([path[-1] << 3 | 2, len(s)]) + s.encode()
        for step in path[:-1][::-1]:
            y = bytes([step << 3 | 2, len(y)]) + y
        return b"".join(b for _, b in sorted([(plain, bytes([plain << 3, n])), (path[0], y)])).hex()
    return read, write


def tlv(plain, tabled):
    def read(hx):
        b, i, got = bytes.fromhex(hx), 0, {}
        while i < len(b):
            got.setdefault(b[i], b[i + 2:i + 2 + b[i + 1]])
            i += 2 + b[i + 1]
        x, y = got.get(plain), got.get(tabled)
        return [int.from_bytes(x, "big") if x else None, None if y is None else y.decode()]
    items = lambda n, s: {plain: bytes([plain, 1, n]), tabled: bytes([tabled, len(s)]) + s.encode()}    # noqa: E731
    return read, lambda n, s: b"".join(v for _, v in sorted(items(n, s).items())).hex()


def cbor(plain, tabled):
    def read(hx):
        b, i, got = bytes.fromhex(hx), 1, {}
        for _ in range(b[0] & 31):
            key, head = b[i], b[i + 1]
            size = head & 31 if head >> 5 == 3 else 0
            got[key] = (head >> 5, head & 31 if head >> 5 == 0 else b[i + 2:i + 2 + size])
            i += 2 + size
        assert i == len(b)
        x, y = got.get(plain), got.get(tabled)
        return [None if x is None else x[1] if x[0] == 0 else BAD,
                None if y is None else y[1].decode() if y[0] == 3 else BAD]
    items = lambda n, s: {plain: bytes([plain, n]), tabled: bytes([tabled, 0x60 + len(s)]) + s.encode()}    # noqa: E731
    return read, lambda n, s: "a2" + b"".join(v for _, v in sorted(items(n, s).items())).hex()


def two_bytes(first):
    """One byte each: the plain one at `first`, the tabled one at the other."""
    def read(hx):
        b = bytes.fromhex(hx)
        return [b[first], chr(b[1 - first])]
    return read, lambda n, s: bytes([n, ord(s)] if first == 0 else [ord(s), n]).hex()


def opt_block():
    def read(hx):
        b = bytes.fromhex(hx)
        return [b[0], chr(b[2]) if b[1] & 128 else None]
    return read, lambda n, s: bytes([n, 0x80, ord(s)]).hex()


def record(first):
    def read(text):
        f = text.split(",")
        x, y = (f + [""])[first], (f + [""])[1 - first]
        return [None if not x else int(x) if x.isdigit() else BAD, y or None]
    return read, lambda n, s: ",".join([str(n), s] if first == 0 else [s, str(n)])


def members(sentinel=None, lists=False):
    def read(text):
        o = json.loads(text)
        y = o.get("b")
        return [o.get("a"), None if y in (None, sentinel) else y if isinstance(y, str) else BAD]

    def write(n, s, inp):
        o = {"a": n, "b": s}
        if lists and "nums" in json.loads(inp):
            o["nums"] = json.loads(inp)["nums"]
        return json.dumps(o, separators=(",", ":"))
    write.with_input = True
    return read, write


def recompute(codec, later, inp, limit):
    """The output and the key's value, or (error kind, None)."""
    read, write = codec
    try:
        plain, tabled = read(inp)
    except Malformed:
        return MAL, None
    if limit is not None and len(json.loads(inp).get("nums", ())) > limit:
        return MAL, None                                # 7f of 0.11
    if isinstance(tabled, str) and tabled not in TABLE:
        return DEC, None                                # ruling 26
    vals = [plain, TABLE[tabled] if isinstance(tabled, str) else tabled]
    good = [v for v in (vals if later else vals[::-1]) if v is not None and v is not BAD]
    if not good:
        assert BAD in vals
        return DEC, None
    native = next(k for k, v in TABLE.items() if v == good[0])
    out = write(good[0], native, inp) if hasattr(write, "with_input") else write(good[0], native)
    return out, good[0]


def build(sink):
    written = {}

    def put(rel, text):
        sink.write(rel, text)
        written[rel.split("/")[1]] = written.get(rel.split("/")[1], 0) + 1

    def pack(short, about, body, codec, later, rows):
        name = P + short
        for old in sink.listdir("packs/%s/vectors" % name):
            sink.remove("packs/%s/vectors/%s" % (name, old))
        put("packs/%s/pack.def" % name, GENERATED + "# Conformance probe pack: one key on two lines, one with a value table of\n"
            "# another type (0.64 rulings 26 and 27). Public. No kinds.\n# %s\n" % about
            + "format  %s\nversion 0.64.0\ndistribution public\nsource  %s\nuses    probe\n" % (name, SOURCE)
            + body.strip("\n") + "\nmap     t h 6\nmap     t f 3\n")
        for i, row in enumerate(rows, 1):
            vname, inp, want, value, ref = row[:5]
            limit = row[5] if len(row) > 5 else None
            got = recompute(codec, later, inp, limit)
            assert got == (want, value), (name, vname, "hand", want, value, "computed", got)
            d = {"name": vname, "from": name, "to": name, "input": inp}
            if value is None:
                d["expect_error"] = want
            else:
                d["expect"] = want
                d["model"] = {"probe.x": str(value)}
            if limit is not None:
                d["max_items"] = limit
            d["source"], d["reference"] = "constructed", "spec 0.64 " + ref
            put("packs/%s/vectors/%02d-%s.json" % (name, i, vname), json.dumps(d, indent=2) + "\n")

    R26 = "ruling 26: no entry and another type fails the decode, "
    KEEP = "ruling 26: the earliest line's value is kept; encode writes both lines (0.6)"
    LATER = [("no-entry-in-the-later-line", R26 + "after a line that succeeds"), ("entry-in-the-later-line", KEEP)]
    EARLY = [("no-entry-in-the-earlier-line", R26 + "before a line that succeeds"), ("entry-in-the-earlier-line", KEEP)]

    def way(names, miss, hit, out, value):
        return [(names[0][0], miss, DEC, None, names[0][1]), (names[1][0], hit, out, value, names[1][1])]

    F, V = "field   probe.x  ", "  via t\n"
    # 3 then "z" (7a) or "h" (68); kept 3 is written `f` (66). Reversed: 6 is kept, written `h` and 6.
    fixed = "wire    bits\nword_bytes 1\nbit_order msb\n"
    pack("bits-later", "A fixed layout: the table on the later line.", fixed + F + "0:0:8  uint\n" + F + "1:0:8  ascii" + V,
         two_bytes(0), True, way(LATER, "037a", "0368", "0366", 3))
    pack("bits-earlier", "A fixed layout: the table on the earlier line.", fixed + F + "0:0:8  ascii" + V + F + "1:0:8  uint\n",
         two_bytes(1), False, way(EARLY, "7a03", "6803", "6806", 6))
    seq = "wire    bits\nlayout  sequential\nbit_order msb\n"
    pack("seq-later", "A sequential layout: the table on the later line.", seq + F + "8  uint\n" + F + "8  ascii" + V,
         two_bytes(0), True, way(LATER, "037a", "0368", "0366", 3))
    pack("seq-earlier", "A sequential layout: the table on the earlier line.", seq + F + "8  ascii" + V + F + "8  uint\n",
         two_bytes(1), False, way(EARLY, "7a03", "6803", "6806", 6))
    # opt bit 0: the block is not held. The key is content for the opt bit on encode: 80, then `f`.
    pack("seq-opt", "The later line in an `opt` block.", seq + F + "8  uint\nopt\n  pad 7\n  " + F + "8  ascii" + V + "end\n",
         opt_block(), True, [
             ("later-line-in-a-block-not-held", "0300", "038066", 3, "ruling 27: a line in a block not held changes nothing"),
             ("no-entry-in-a-block-held", "03807a", DEC, None, R26 + "in a block that is read")])
    pack("text-later", "The `text` wire: the table on the later line.", "wire    text\n" + F + "0  int\n" + F + "1  string" + V,
         record(0), True, way(LATER, "3,zz", "3,h", "3,f", 3) + [
             ("later-line-absent", "3,", "3,f", 3, "ruling 27: an absent line changes nothing")])
    pack("text-earlier", "The `text` wire: the table on the earlier line.", "wire    text\n" + F + "0  string" + V + F + "1  int\n",
         record(1), False, way(EARLY, "zz,3", "h,3", "h,6", 6) + [
             ("later-transform-fails", "h,q", "h,6", 6, "ruling 27: a line whose transform fails changes nothing")])
    # 08 03: field 1 varint 3. 12 01 xx: field 2, one byte of text.
    pack("pb-later", "The `protobuf` wire: the table on the later line.", "wire    protobuf\n" + F + "1  pvarint\n" + F + "2  pstring" + V,
         pb(1, (2,)), True, way(LATER, "080312027a7a", "0803120168", "0803120166", 3) + [
             ("later-transform-fails", "08031005", "0803120166", 3,
              "ruling 27: another wire type is a failed transform (0.9 ruling 15), which changes nothing")])
    pack("pb-earlier", "The `protobuf` wire: the table on the earlier line.", "wire    protobuf\n" + F + "1  pstring" + V + F + "2  pvarint\n",
         pb(2, (1,)), False, way(EARLY, "0a017a1003", "0a01681003", "0a01681006", 6))
    # The later line at 2.1. 12 03 0a 01 xx: field 2 holds field 1, one byte of text.
    pack("pb-path", "The later line inside a submessage.", "wire    protobuf\n" + F + "1  pvarint\n" + F + "2.1  pstring" + V,
         pb(1, (2, 1)), True, [
             ("no-entry-in-a-submessage", "080312030a017a", DEC, None, R26 + "inside a submessage"),
             ("submessage-that-does-not-parse", "08031201ff", MAL, None,
              "ruling 27 and 9c of 0.11: ff is a cut varint, whatever the earlier line gave"),
             ("prefix-not-length-delimited", "08031005", MAL, None, "ruling 27 and 9c of 0.11"),
             ("submessage-absent", "0803", "080312030a0166", 3, "ruling 27: an absent line changes nothing"),
             ("empty-submessage", "08031200", "080312030a0166", 3, "ruling 27: an absent line changes nothing"),
             ("later-transform-fails", "080312020805", "080312030a0166", 3,
              "ruling 27: another wire type is a failed transform (0.9 ruling 15), which changes nothing")])
    # tag 1 length 1 value 3; tag 2 length 1 text.
    pack("tlv-later", "The `tlv` wire: the table on the later line.", "wire    tlv\n" + F + "1:1  uint\n" + F + "2  utf8" + V,
         tlv(1, 2), True, way(LATER, "01010302017a", "010103020168", "010103020166", 3) + [
             ("later-line-absent", "010103", "010103020166", 3, "ruling 27: an absent line changes nothing")])
    pack("tlv-earlier", "The `tlv` wire: the table on the earlier line.", "wire    tlv\n" + F + "1  utf8" + V + F + "2:1  uint\n",
         tlv(2, 1), False, way(EARLY, "01017a020103", "010168020103", "010168020106", 6))
    # a2: a map of two members; 01 03: key 1, integer 3; 02 61 xx: key 2, one byte of text.
    pack("cbor-later", "The `cbor` wire: the table on the later line.", "wire    cbor\n" + F + "1  uint\n" + F + "2  text" + V,
         cbor(1, 2), True, way(LATER, "a2010302617a", "a20103026168", "a20103026166", 3) + [
             ("later-line-absent", "a10103", "a20103026166", 3, "ruling 27: an absent line changes nothing"),
             ("later-transform-fails", "a201030205", "a20103026166", 3, "ruling 27: a line whose transform fails changes nothing")])
    pack("cbor-earlier", "The `cbor` wire: the table on the earlier line.", "wire    cbor\n" + F + "1  text" + V + F + "2  uint\n",
         cbor(2, 1), False, way(EARLY, "a201617a0203", "a20161680203", "a20161680206", 6))
    js = "wire    json\n" + F + "a  int\n" + F + "b  string" + V
    pack("json-sentinel", "The later line has a sentinel.", js.rstrip("\n") + " absent NA\n", members("NA"), True, [
        ("later-line-a-sentinel", '{"a":3,"b":"NA"}', '{"a":3,"b":"f"}', 3, "ruling 27: a sentinel changes nothing"),
        ("no-entry-that-is-not-the-sentinel", '{"a":3,"b":"NB"}', DEC, None, R26 + "after a line that succeeds")])
    pack("json-limit", "A list beside the two lines.", js + "group   probe.nums  nums\n  field   probe.val  .  int\nend\n",
         members(lists=True), True, [
             ("over-the-limit-wins", '{"a":3,"b":"zz","nums":[1,2]}', MAL, None, "ruling 27 and 7f of 0.11: over the limit wins", 1),
             ("at-the-limit", '{"a":3,"b":"zz","nums":[1]}', DEC, None, R26 + "with the list at the limit", 1),
             ("at-the-limit-with-an-entry", '{"a":3,"b":"h","nums":[1]}', '{"a":3,"b":"f","nums":[1]}', 3, KEEP, 1)])
    # A switch on the key of two lines. Decode of 06 68 09: the first line gives 6, `h` gives 6; case 6: z = 9.
    # An absent key writes zero bits at both lines: 00 00. The second is an `ascii` field of NUL, the empty
    # text (0.5 ruling 3), which has no entry and is of another type: the line fails (ruling 26), so the
    # bits do not read back and no case is one decode would select (0.20 rulings 31 and 33).
    switch = ("switch  probe.x\n  case 0\n    field  probe.y  8  uint\n  case 6\n    field  probe.z  8  uint\nend\n")
    mir, sw = P + "mirror", P + "seq-switch"
    for name in (mir, sw):
        for old in sink.listdir("packs/%s/vectors" % name):
            sink.remove("packs/%s/vectors/%s" % (name, old))
    top = "format  %s\nversion 0.64.0\ndistribution public\nsource  %s\nuses    probe\n"
    put("packs/%s/pack.def" % mir, GENERATED + "# A flat json mirror that hands an entity to conformance-twolines-w-seq-switch.\n" + top % (mir, SOURCE)
        + "wire    json\nfield   probe.x  x  int\nfield   probe.y  y  int\nfield   probe.z  z  int\n")
    put("packs/%s/pack.def" % sw, GENERATED + "# Conformance probe pack: a switch on a key of two lines, the later with a value\n"
        "# table of another type (0.64 ruling 26; 0.20 rulings 31 and 33). Public. No kinds.\n" + top % (sw, SOURCE)
        + seq + F + "8  uint\n" + F + "8  ascii" + V + switch + "map     t h 6\nmap     t f 3\n")

    def switched(x, y, z):
        """Second computation: write both lines, read the bits back as decode would, then the case."""
        native = [k for k, v in TABLE.items() if v == x]
        if x is not None and not native:
            return "transform-encode"
        bits = bytes([x or 0, ord(native[0]) if native else 0])
        text = bytes([bits[1]]).decode().rstrip("\0")
        if text not in TABLE:
            return "transform-encode"
        case = {0: y, 6: z}
        return "no-kind" if bits[0] not in case else (bits + bytes([case[bits[0]] or 0])).hex()

    R = "0.20 rulings 31 and 33 with 0.64 ruling 26: "
    rows = [(sw, "case-of-the-key", "066809", "066809", {"probe.x": "6", "probe.z": "9"}, None,
             "0.20 and 0.64 ruling 26: the second line has an entry, the first gives the key"),
            (sw, "no-entry-before-the-switch", "000009", DEC, None, None,
             "ruling 26: the NUL text is the empty text (0.5 ruling 3), which has no entry"),
            (mir, "held-key-selects-its-case", '{"x":6,"z":9}', "066809", None, (6, None, 9), R + "both lines read back"),
            (mir, "absent-key-does-not-read-back", '{"y":9}', "transform-encode", None, (None, 9, None),
             R + "the zero bits of the second line have no entry, so the output would not decode")]
    num = {}
    for frm, vname, inp, want, model, args, ref in rows:
        error = want in (DEC, "transform-encode")
        assert args is None or switched(*args) == want, (vname, switched(*args))
        if args is None:
            b = bytes.fromhex(inp)
            ok = bytes([b[1]]).decode().rstrip("\0") in TABLE
            assert ok is not error and (error or switched(b[0], None, b[2]) == want), vname
        num[frm] = num.get(frm, 0) + 1
        d = {"name": vname, "from": frm, "to": sw, "input": inp, "expect_error" if error else "expect": want}
        if model:
            d["model"] = model
        d["source"], d["reference"] = "constructed", "spec " + ref
        put("packs/%s/vectors/%02d-%s.json" % (frm, num[frm], vname), json.dumps(d, indent=2) + "\n")
    return written


def main(argv=None):
    return genio.vector_main("conformance-twolines-wires-vectors.py", __doc__, build, argv)


if __name__ == "__main__":
    sys.exit(main())
