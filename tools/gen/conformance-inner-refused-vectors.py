class Fail(Exception):
    def __init__(self, kind):
        super().__init__(kind)
        self.kind = kind


def parse(text):
    """{"json", "common", "kinds", "tables", "typemap"}; a node is a dict with `d`, `a`, `body`."""
    pack = {"json": False, "body": [], "kinds": [], "tables": {}, "typemap": []}
    stack = [pack]
    for raw in text.splitlines():
        t = [w.strip('"') for w in raw.split("#")[0].split()]
        if not t or t[0] in ("format", "version", "distribution", "source", "uses", "layout", "bit_order"):
            continue
        d, a, top = t[0], t[1:], stack[-1]
        if d == "wire":
            pack["json"] = a[0] == "json"
        elif d == "map":
            pack["tables"].setdefault(a[0], []).append((a[1], a[2]))
        elif d == "typemap":
            pack["typemap"].append((a[0], a[1]))
        elif d == "end":
            stack.pop()
            if stack[-1].get("d") == "switch" and top.get("d") == "case":
                stack.pop()
        elif d == "kind":
            (top if top.get("d") == "group" else pack)["kinds"].append({"name": a[0], "requires": [], "body": []})
        elif d == "requires":
            pack["kinds"][-1]["requires"] += a
        else:
            node = {"d": d, "a": a, "body": [], "kinds": []}
            if d in ("case", "else"):
                if top["d"] == "case":
                    stack.pop()
                node.update(d="case", values=a[0].split(",") if a else None)
                stack[-1]["body"].append(node)
                stack.append(node)
                continue
            if top["kinds"]:
                top["kinds"][-1]["body"].append(node)
            else:
                top["body"].append(node)
            if d in ("group", "if", "opt", "chain", "length", "switch") and a[1:] != ["whole"]:
                stack.append(node)
    return pack


PARSED = {}


def pack_of(name):
    if name not in PARSED:
        PARSED[name] = parse(PACKS[name])
    return PARSED[name]


def as_key(node):
    return node["a"][node["a"].index("as") + 1] if node["d"] == "when" and "as" in node["a"] else None


def entries(lines, pre=""):
    out = set()
    for n in lines:
        if n["d"] in ("field", "also"):
            out.add(pre + n["a"][0])
        elif as_key(n):
            out.add(pre + as_key(n))
        elif n["d"] == "group":
            here = pre + n["a"][0] + "[]"
            out |= {here} | entries(n["body"], here + ".")
        else:
            out |= entries(n["body"], pre)
    return out


def has(lines, node):
    return any(n is node or has(n["body"], node) for n in lines)


def check(pack, kind, node):
    """Check 1 of 0.34, and ruling 20: the fifth check."""
    if node["a"][0] not in PACKS:
        raise Fail("unknown-format")
    if has(pack["body"], node):
        reach = entries(pack["body"]) | entries([n for k in pack["kinds"] for n in k["body"]])
    else:
        reach = entries(pack["body"]) | entries(kind["body"])
    inner = pack_of(node["a"][0])
    if reach & (entries(inner["body"]) | entries([n for k in inner["kinds"] for n in k["body"]])):
        raise Fail("bad-directive")


def ranges(node):
    return [(int(v.split("..")[0]), int(v.split("..")[-1])) for v in node["a"][1].split(",")]


def matches(v, node):
    return any(lo <= v <= hi for lo, hi in ranges(node))


class Decoder:
    def __init__(self, name, data, limit, used=0):
        self.pack, self.bits = pack_of(name), "".join(format(b, "08b") for b in data)
        self.pos, self.end = 0, len(self.bits)
        self.limit, self.ent, self.bad = limit, {}, False
        self.outside, self.kind, self.inner_kind = used, None, None
        self.names, self.failed = {}, set()

    def take(self, n):
        if self.pos + n > self.end:
            raise Fail("malformed-wire")
        self.pos += n
        return int(self.bits[self.pos - n:self.pos], 2)

    def items(self, ent):
        return sum(1 + self.items(i) for v in ent.values() if isinstance(v, list) for i in v)

    def allow(self, extra, replaced):
        if self.outside + self.items(self.ent) - replaced + extra > self.limit:
            raise Fail("malformed-wire")

    def value(self, node, raw):
        tr, key = node["a"][2], node["a"][0]
        if tr == "sscale:1/2":
            return (raw - 256 if raw > 127 else raw) / 2
        v = raw if tr == "uint" else ("" if raw == 0 else chr(raw) if 0x20 <= raw <= 0x7e else None)
        if "via" in node["a"]:
            v = dict((int(x), y) for x, y in self.pack["tables"][node["a"][-1]]).get(v)
        if v is not None and key == "type":
            v = dict(self.pack["typemap"]).get(v, v)
        return v

    def lines(self, lines, ent, extent=False):
        for n in lines:
            d, a = n["d"], n["a"]
            if extent and self.pos >= self.end and d in ("field", "length", "pad"):
                continue            # ruling 7 and 21 of 0.8
            if d == "field":
                v = self.value(n, self.take(int(a[1])))
                if v is None:
                    self.bad = True
                    self.failed.add(a[0])
                else:
                    ent.setdefault(a[0], v)
                    self.last = v
            elif d == "also":
                ent.setdefault(a[0], self.last)
            elif d == "when":
                v = self.take(int(a[0]))
                if not matches(v, n):
                    raise Fail("no-kind")
                if as_key(n):
                    ent[as_key(n)] = v
            elif d == "pad":
                self.take(int(a[0]))
            elif d == "align":
                self.pos = -(-self.pos // int(a[0])) * int(a[0])
            elif d == "presence":
                self.names[a[0]] = self.take(int(a[1]))
            elif d == "if":
                name, i = a[0].split(".")
                if self.names[name] >> (8 - int(i)) & 1:
                    self.lines(n["body"], ent, extent)
            elif d == "opt":
                if self.take(1):
                    self.lines(n["body"], ent, extent)
            elif d == "chain":
                for m in n["body"]:
                    if m["d"] == "fx":
                        if not self.take(1):
                            break
                    else:
                        self.lines([m], ent, extent)
            elif d == "count":
                self.names[a[0]] = self.take(int(a[1]))
            elif d == "length" and a[1:] == ["whole"]:
                self.end = 8 * self.take(int(a[0]))
                if self.end > len(self.bits):
                    raise Fail("malformed-wire")
            elif d == "length":
                size, outer = self.take(int(a[0])), self.end
                self.end = self.pos + 8 * size
                if self.end > outer:            # 20b: at the `length` line, whatever the block holds
                    raise Fail("malformed-wire")
                self.lines(n["body"], ent, True)
                self.pos, self.end = self.end, outer
            elif d == "group":
                held = ent.get(a[0], [])
                replaced = len(held) + sum(self.items(i) for i in held)
                got = []
                if a[1] == "count":
                    count = self.names[a[2][1:]] if a[2][0] == "@" else self.take(int(a[2]))
                    self.allow(count, replaced)
                    for _ in range(count):
                        got.append(self.item(n))
                else:
                    while self.end - self.pos >= 8:
                        self.allow(len(got) + 1, replaced)
                        got.append(self.item(n))
                ent[a[0]] = got
                self.allow(0, 0)
            elif d == "switch":
                if a[0] not in ent and a[0] in self.failed:
                    raise Fail("transform-decode")      # ruling 35 of 0.20
                case = next((c for c in n["body"] if c["values"] is None or str(ent.get(a[0])) in c["values"]), None)
                if case is None:
                    raise Fail("no-kind")
                self.lines(case["body"], ent, extent)
            elif d == "inner":
                self.inner(n)
            else:
                assert d in ("default",), d

    def item(self, n):
        item = {}
        self.lines(n["body"], item)
        for k in n["kinds"]:            # item kinds of one `when` and no other line
            (w,) = k["body"]
            if matches(self.take(int(w["a"][0])), w):
                return item
            self.pos -= int(w["a"][0])
        if n["kinds"]:
            raise Fail("no-kind")
        return item

    def inner(self, n):
        check(self.pack, self.kind, n)
        if self.pos % 8:
            raise Fail("malformed-wire")
        data = bytes(int(self.bits[i:i + 8], 2) for i in range(self.pos, self.end, 8))
        sub = Decoder(n["a"][0], data, self.limit, self.outside + self.items(self.ent))
        sub.run()
        if -(-sub.pos // 8) * 8 < len(sub.bits) and n["a"][1:] != ["partial"]:
            raise Fail("malformed-wire")
        assert not set(sub.ent) & set(self.ent)
        self.ent.update(sub.ent)
        self.bad |= sub.bad
        if sub.kind:
            self.inner_kind = (n["a"][0], sub.kind["name"])
        self.pos = self.end

    def run(self):
        self.lines(self.pack["body"], self.ent)
        start = self.pos
        for k in self.pack["kinds"]:
            whens = [n for n in k["body"] if n["d"] == "when"]
            pos, got = start, {}
            for w in whens:
                at = start + int(w["a"][w["a"].index("at") + 1]) if "at" in w["a"] else pos
                if at + int(w["a"][0]) > self.end or not matches(int(self.bits[at:at + int(w["a"][0])], 2), w):
                    break
                if as_key(w):
                    got[as_key(w)] = int(self.bits[at:at + int(w["a"][0])], 2)
                if "at" not in w["a"]:
                    pos += int(w["a"][0])
            else:
                self.kind, self.pos = k, pos
                self.ent.update(got)
                self.lines([n for n in k["body"] if n["d"] != "when"], self.ent)
                break
        else:
            if self.pack["kinds"]:
                raise Fail("no-kind")


def decode(name, text, limit):
    pack = pack_of(name)
    if pack["json"]:
        obj = json.loads(text)
        return {n["a"][0]: obj[n["a"][1]] for n in pack["body"] if n["a"][1] in obj}, None, None
    d = Decoder(name, bytes.fromhex(text), limit)
    d.run()
    if d.bad:
        raise Fail("transform-decode")
    return d.ent, d.kind and d.kind["name"], d.inner_kind


def content(lines, ent):
    return any(n["d"] in ("field", "also") and n["a"][0] in ent or n["d"] == "group" and ent.get(n["a"][0])
               or content(n["body"], ent) for n in lines if n["d"] != "group" or n["a"][0] in ent)


class Encoder:
    def __init__(self, name, ent, kind, inner_kind):
        self.name, self.pack, self.ent, self.inner_kind = name, pack_of(name), ent, inner_kind
        self.out = ""
        self.kind = None
        if self.pack["kinds"]:
            self.kind = next((k for k in self.pack["kinds"] if (k["name"] == kind if kind else self.qualifies(k))), None)
            if self.kind is None:
                raise Fail("no-kind")
        self.defaults = {n["a"][0]: int(n["a"][1]) for n in self.pack["body"] if n["d"] == "default"}

    def qualifies(self, k):
        for n in k["body"]:
            key = as_key(n)
            if key and not (matches(self.ent[key], n) if key in self.ent else n["a"][-1] == "optional"):
                return False
        return all(r in self.ent for r in k["requires"])

    def put(self, v, n):
        if v >> n:
            raise Fail("transform-encode")
        self.out += format(v, "0%db" % n)

    def raw(self, node, v):
        if node["a"][0] == "type" and v is not None:
            v = {m: t for t, m in self.pack["typemap"]}.get(v, v)
        if v is None:
            return 0
        if "via" in node["a"]:
            back = {y: int(x) for x, y in self.pack["tables"][node["a"][-1]]}
            if v not in back:
                raise Fail("transform-encode")
            return back[v]
        if node["a"][2] == "sscale:1/2":
            assert (v * 2).is_integer() and -64 <= v < 64
            return int(v * 2) & 255
        if node["a"][2] == "ascii":
            if len(v) > 1:
                raise Fail("transform-encode")
            return ord(v) if v else 0
        return v

    def lines(self, lines, ent, after=None):
        for i, n in enumerate(lines):
            d, a = n["d"], n["a"]
            if d == "field":
                also = [m["a"][0] for m in lines[i + 1:i + 2] if m["d"] == "also"]
                key = next((k for k in [a[0]] + also if k in ent), None)
                v = ent[key] if key else self.defaults.get(a[0])
                self.put(self.raw(n, v), int(a[1]))
            elif d == "when":
                v, key = ranges(n)[0][0], as_key(n)
                if "at" in a:
                    continue
                if key in ent:
                    v = ent[key]
                    if not matches(v, n):
                        raise Fail("transform-encode")
                self.put(v, int(a[0]))
            elif d == "pad":
                self.put(0, int(a[0]))
            elif d == "align":
                self.out += "0" * (-len(self.out) % int(a[0]))
            elif d == "presence":
                bits, lev = 0, self.pack["body"]
                for m in lev:
                    if m["d"] == "if" and m["a"][0].split(".")[0] == a[0] and content(m["body"], ent):
                        bits |= 1 << (8 - int(m["a"][0].split(".")[1]))
                self.put(bits, 8)
            elif d == "if":
                if content(n["body"], ent):
                    self.lines(n["body"], ent)
            elif d == "opt":
                self.put(int(content(n["body"], ent)), 1)
                if content(n["body"], ent):
                    self.lines(n["body"], ent)
            elif d == "chain":
                at = next(j for j, m in enumerate(n["body"]) if m["d"] == "fx")
                self.lines(n["body"][:at], ent)
                more = content(n["body"][at + 1:], ent)
                self.put(int(more), 1)
                if more:
                    self.lines(n["body"][at + 1:], ent)
            elif d == "count":
                group = next(m for m in lines if m["d"] == "group" and m["a"][2] == "@" + a[0])
                self.put(len(ent.get(group["a"][0], [])), int(a[1]))
            elif d == "length":
                head = self.out
                self.out = ""
                self.lines(n["body"], ent, after=len(head) + int(a[0]))
                block = self.out
                self.out = head
                self.put(len(block) // 8, int(a[0]))
                self.out += block
            elif d == "group":
                items = ent.get(a[0], [])
                if a[1] == "count" and a[2][0] != "@":
                    self.put(len(items), int(a[2]))
                for item in items:
                    self.lines(n["body"], item)
            elif d == "switch":
                v = ent.get(a[0], 0 if a[0] != "probe.label" else "")
                case = next((c for c in n["body"] if c["values"] is None or str(v) in c["values"]), None)
                if case is None:
                    raise Fail("no-kind")
                self.lines(case["body"], ent)
            elif d == "inner":
                check(self.pack, self.kind, n)
                if (len(self.out) + (after or 0)) % 8:
                    raise Fail("transform-encode")
                kind = self.inner_kind[1] if self.inner_kind and self.inner_kind[0] == a[0] else None
                self.out += Encoder(a[0], self.ent, kind, None).run()

    def run(self):
        self.lines(self.pack["body"], self.ent)
        if self.kind:
            self.lines(self.kind["body"], self.ent)
        return self.out + "0" * (-len(self.out) % 8)


def encode(name, ent, kind, inner_kind):
    if pack_of(name)["json"]:
        return json.dumps({n["a"][1]: ent[n["a"][0]] for n in pack_of(name)["body"] if n["a"][0] in ent}, separators=(",", ":"))
    bits = Encoder(name, ent, kind, inner_kind).run()
    return "".join("%02x" % int(bits[i:i + 8], 2) for i in range(0, len(bits), 8))


def inner_formats(name):
    def walk(lines):
        for n in lines:
            if n["d"] == "inner":
                yield n["a"][0]
            yield from walk(n["body"])
    p = pack_of(name)
    return set(walk(p["body"])) | {g for k in p["kinds"] for g in walk(k["body"])}


def convert(frm, to, text, context, limit):
    ent, kind, inner = decode(frm, text, limit)
    full = dict(ent)
    for k, v in (context or {}).items():
        full.setdefault(k, int(v))
    if "probe.n" in full and frm != to:
        full.setdefault("probe.n_copy", full["probe.n"])
    if frm == to:
        return ent, kind, inner, lambda: encode(to, full, kind, inner)
    keep = inner if inner and inner[0] in inner_formats(to) | {to} else None
    if kind and frm in inner_formats(to):
        keep = keep or (frm, kind)
    return ent, kind, inner, lambda: encode(to, full, keep[1] if keep and keep[0] == to else None, keep)


def model_of(ent, prefix=""):
    have = {}
    for k, v in ent.items():
        if isinstance(v, list):
            have[prefix + k + ".#"] = str(len(v))
            for i, item in enumerate(v):
                have.update(model_of(item, "%s%s[%d]." % (prefix, k, i)))
        else:
            have[prefix + k] = str(v)
    return have


