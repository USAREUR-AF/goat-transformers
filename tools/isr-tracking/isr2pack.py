#!/usr/bin/env python3
"""isr2pack.py: write the isr-tracking pack (xml wire) and its model module from
the AEDP-12 data model in tools/isr-tracking/model.tsv.txt and kinds.tsv.txt.

The documents give the UML model and two rules for its XML form: every attribute
of a class is an element, except an attribute named `type`, which is an XML
attribute; the root element is NITSRoot. The XML schema itself is not held. This
pack therefore assumes, unchecked against the schema:
  - no namespace; element names are the attribute names of the model
  - element order is the model's attribute order
  - a UUID is the text of its element, and its optional guide prefix is the
    XML attribute `gidp`
  - an element of the abstract class Shape names its concrete class in
    `xsi:type`, and holds the elements of Shape and of that class (Polygon or
    Ellipsoid)
  - values written as space-separated lists (positions, matrices, arrays)
    are one text each

How the model becomes lines (a scope is a kind or a group item):
  - a primitive or enumeration attribute: `field <key> <path>/#text`
  - a list of primitives: a group of the elements, the item value `#text`
  - a single class: its attributes under `<path>/`
  - a list of a class: a group, the item holding that class's attributes
Keys are `isrtrack.<owner>_<path>`, where the owner is the class of the kind's
root or of the group item, in lower case, and the path is the element names
below it. A list is named the same way.

Usage: python3 -I tools/isr-tracking/isr2pack.py   (from the repository root)
"""
import collections
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
MOD = "isrtrack"
SRC = ("NATO AEDP-12 Edition B Version 2 (STANAG 4676), NATO Intelligence, Surveillance and Reconnaissance "
       "Tracking Standard, March 2022; NSG Standards Registry, nsgreg.nga.mil")
SRC_T = "data model restated in tools/isr-tracking/model.tsv.txt and kinds.tsv.txt of this repository"
HEAD = "# Generated by tools/isr-tracking/isr2pack.py from tools/isr-tracking/*.tsv.txt. Do not edit by hand."
INTS = {"UInt", "UnsignedInt", "long", "int", "unsignedByte", "unsignedShort", "byte"}
FLOATS = {"double", "float"}
SHAPES = ["Polygon", "Ellipsoid"]      # the concrete classes of the abstract Shape



# --check: compare with the files in the tree instead of writing them; exit 1 when one differs.
import io as _io
CHECK_MODE = "--check" in sys.argv[1:]
DIFFERS = []


class _Cmp(_io.StringIO):
    def __init__(self, path):
        super().__init__()
        self.path = path

    def close(self):
        if not self.closed:
            try:
                cur = open(self.path, encoding="utf-8").read()
            except OSError:
                cur = None
            if cur != self.getvalue():
                DIFFERS.append(os.path.relpath(self.path, REPO))
        super().close()


def out_open(path):
    return _Cmp(path) if CHECK_MODE else open(path, "w", encoding="utf-8")


def check_exit(name):
    if CHECK_MODE:
        for d in DIFFERS:
            print("differs: " + d)
        print("%s: %s" % (name, "ok" if not DIFFERS else "%d differ" % len(DIFFERS)))
        sys.exit(1 if DIFFERS else 0)

def rows(name):
    with open(os.path.join(HERE, name), newline="", encoding="utf-8") as f:
        return list(csv.DictReader([l for l in f if not l.startswith("#")], delimiter="\t"))


def main():
    model = collections.OrderedDict()
    for r in rows("model.tsv.txt"):
        model.setdefault(r["class"], []).append(r)
    kinds = rows("kinds.tsv.txt")
    keys = collections.OrderedDict()
    lists = collections.OrderedDict()
    stats = collections.Counter()
    seen_classes = set()

    def key(name, ty, meaning):
        old = keys.get(name)
        if old and old[0] != ty:
            raise SystemExit("key %s with two types" % name)
        keys.setdefault(name, (ty, meaning))
        return MOD + "." + name

    def prim(t):
        if t in INTS:
            return "int", "int"
        if t in FLOATS:
            return "float", "float"
        return "string", "string"

    def loc(path, leaf):
        return ("%s/%s" % (path, leaf)) if path else leaf

    def quote(l):
        return '"%s"' % l if l.startswith("#") else l

    def emit(cls, owner, path, ind, out, depth, binds):
        if depth > 12:
            raise SystemExit("model nesting too deep at %s" % path)
        seen_classes.add(cls)
        attrs = list(model.get(cls, []))
        if cls == "Shape":
            out.append("%sfield  %s  %s  string" % (ind, key(owner + "_" + kpath(path, "xsitype"), "string",
                                                             "concrete class of the shape (xsi:type)"), loc(path, "@xsi:type")))
            for c in SHAPES:
                attrs += model[c]
                seen_classes.add(c)
        for a in attrs:
            el, t, mult = a["element"], a["type"], a["mult"].strip("[]")
            many = mult.endswith("*")
            p = loc(path, el)
            kp = kpath(path, el)
            if el == "type" and t not in model:
                out.append("%sfield  %s  %s  string" % (ind, key(owner + "_" + kp, "string", "%s of %s (XML attribute)" % (el, cls)),
                                                        loc(path, "@type")))
                stats["fields"] += 1
                continue
            if t == "UUID":
                seen_classes.add("UUID")
                if many:
                    ln = owner + "_" + kp
                    lists[ln] = "%s of %s, one item per element" % (el, cls)
                    out.append("%sgroup  %s.%s  %s" % (ind, MOD, ln, p))
                    out.append('%s  field  %s  "#text"  string' % (ind, key(ln + "_value", "string", "a UUID of " + ln)))
                    out.append("%s  field  %s  @gidp  int" % (ind, key(ln + "_gidp", "int", "guide prefix of that UUID")))
                    out.append("%send" % ind)
                    stats["lists"] += 1
                else:
                    bound = binds.get(p)
                    k = bound or key(owner + "_" + kp, "string", "%s of %s (UUID)" % (el, cls))
                    out.append("%sfield  %s  %s  string" % (ind, k, quote(loc(p, "#text"))))
                    out.append("%sfield  %s  %s  int" % (ind, key(owner + "_" + kp + "_gidp", "int", "guide prefix of " + el),
                                                         loc(p, "@gidp")))
                    stats["bound"] += bool(bound)
                stats["fields"] += 1
                continue
            if t in model or t == "Shape":
                if not model.get(t) and t != "Shape":
                    stats["empty"] += 1
                    continue
                if many:
                    ln = owner + "_" + kp
                    lists[ln] = "%s of %s, one item per element" % (el, cls)
                    out.append("%sgroup  %s.%s  %s" % (ind, MOD, ln, p))
                    emit(t, t.lower(), "", ind + "  ", out, depth + 1, {})
                    out.append("%send" % ind)
                    stats["lists"] += 1
                else:
                    emit(t, owner, p, ind, out, depth + 1, binds)
                continue
            ty, tr = prim(t)
            if many:
                ln = owner + "_" + kp
                lists[ln] = "%s of %s (%s), one item per element" % (el, cls, t)
                out.append("%sgroup  %s.%s  %s" % (ind, MOD, ln, p))
                out.append('%s  field  %s  "#text"  %s' % (ind, key(ln + "_value", ty, "a value of " + ln), tr))
                out.append("%send" % ind)
                stats["lists"] += 1
            else:
                bound = binds.get(p)
                if bound:
                    out.append("%sfield  %s  %s  %s" % (ind, bound[0], quote(loc(p, "#text")), bound[1]))
                    stats["bound"] += 1
                else:
                    out.append("%sfield  %s  %s  %s" % (ind, key(owner + "_" + kp, ty, "%s of %s (%s)" % (el, cls, t)),
                                                        quote(loc(p, "#text")), tr))
            stats["fields"] += 1

    out = [HEAD,
           "# AEDP-12 (STANAG 4676) track products in XML, from the data model. The XML schema is not held:",
           "# no namespace, element order as the model's attribute order (unchecked; see pack.md).",
           "format        isr-tracking", "version       0.1.0", "distribution  public",
           'source        "%s"' % SRC, 'source        "%s"' % SRC_T, "uses          %s" % MOD, "wire          xml"]
    per_kind = []
    for k in kinds:
        before = sum(stats.values())
        out += ["kind  %s" % k["kind"], "root  %s" % k["root"], "requires  %s" % k["requires"]]
        binds = {}
        for b in filter(None, k["binds"].split(";")):
            el, kk, tr = b.split()
            binds[el] = (kk, tr) if tr != "-" else kk
        body = []
        emit(k["class"], k["class"].lower(), "", "", body, 0, binds)
        out += body
        per_kind.append((k, sum(1 for l in body if l.strip().startswith("field")),
                         sum(1 for l in body if l.strip().startswith("group"))))
    mod = [HEAD, "# Raw values of the AEDP-12 data model (STANAG 4676) as the isr-tracking pack reads them.",
           "module        %s" % MOD, "version       0.1.0", "distribution  public",
           'source        "%s"' % SRC, 'source        "%s"' % SRC_T]
    for n, (ty, meaning) in keys.items():
        mod.append('key  %s  %s  -  "%s"' % (n, ty, meaning))
    for n, meaning in lists.items():
        mod.append('list  %s  "%s"' % (n, meaning))
    os.makedirs(os.path.join(REPO, "packs", "isr-tracking"), exist_ok=True)
    with out_open(os.path.join(REPO, "packs", "isr-tracking", "pack.def")) as f:
        f.write("\n".join(out) + "\n")
    with out_open(os.path.join(REPO, "model", MOD + ".def")) as f:
        f.write("\n".join(mod) + "\n")
    classes = set(model) | {"ESMSensor", "ESMInformation", "ESM"}
    write_md(per_kind, len(keys), len(lists), classes, seen_classes, model)
    print("isr-tracking: %d kinds, %d keys, %d lists, %d classes reached" % (len(kinds), len(keys), len(lists),
                                                                             len(seen_classes)), file=sys.stderr)


def kpath(path, leaf):
    return "_".join([p.lower() for p in path.split("/") if p] + [leaf.lower()])


def write_md(per_kind, nkeys, nlists, classes, seen, model):
    unreached = sorted(classes - seen)
    t = [HEAD.replace("# ", "<!-- ", 1) + " -->", "", "# isr-tracking", "",
         "STANAG 4676 ISR track products (AEDP-12 Edition B Version 2) on the `xml` wire.",
         "`distribution public`.", "",
         "Layouts from NATO standardization documents published on the NSG Standards Registry; NATO is",
         "acknowledged as their source. They are restated in this project's own words; see PROVENANCE.md.", "",
         "## What the pack rests on", "",
         "AEDP-12 defines a data model in UML and two encodings of it, plain XML and EXI, both by an XML",
         "schema that the standard refers to and does not print (Annex B says it is distributed on an",
         "access-controlled NATO site). The schema is not held. The documents state: the root element is",
         "`NITSRoot`; every attribute of a class is an element, except attributes named `type`, which are",
         "XML attributes; an element of an abstract class names its concrete class in `xsi:type`. Beyond",
         "that, this pack assumes, and has not checked against the schema:", "",
         "- no namespace: element names are the model's attribute names, unqualified;",
         "- element order is the order of the attributes in the model's tables;",
         "- a UUID is the text of its element; its guide prefix (`gidp`) is an XML attribute;",
         "- a Shape element holds the elements of Shape and of its concrete class (Polygon or Ellipsoid);",
         "- the contents of a covariance matrix other than its type are not stated by the model.", "",
         "A document from a producer that follows the schema decodes where these assumptions hold. Where",
         "they do not (a namespace on every element, another order), decode still fills the keys whose",
         "elements are found, because the xml wire matches elements by name; encode writes this pack's",
         "order and no namespace.", "",
         "## Kinds", "",
         "A conformant document has the root `NITSRoot` (kind `nits`). The other kinds read one object of",
         "the model on its own, rooted at the element name its parent gives it (`<track>`, `<tp>`, ...): a",
         "fragment that a system exchanging single objects can use. Such a fragment is not a conformant",
         "AEDP-12 document.", "",
         "| kind | root element | class | `field` lines | groups | shared keys |", "|---|---|---|---|---|---|"]
    for k, nf, ng in per_kind:
        b = ", ".join("`%s`" % x.split()[1] for x in k["binds"].split(";") if x) or "-"
        t.append("| `%s` | `%s` | %s | %d | %d | %s |" % (k["kind"], k["root"], k["class"], nf, ng, b))
    t += ["", "%d keys and %d lists in `model/isrtrack.def`. Numbers of the model's integer types read as" % (nkeys, nlists),
          "`int`, its `double` and `float` as `float` (written back in the shortest form, so `60.0` becomes",
          "`60`); everything else (text, enumerations, booleans, dates, space-separated arrays) is text.", "",
          "## Shared keys", "",
          "| key | kind | element | evidence |", "|---|---|---|---|",
          "| `time_ms` | `nits` | `msgCreatedTime` | the date and time the object was written, reported in UTC (ISO 8601) |",
          "| `time_ms` | `message` | `baseTime` | the reference time of the message's relative times, a UTC date and time |",
          "| `uid` | every kind but `nits` and `message` | the root object's `uid` | the UUID of that object |", "",
          "No position binds. The model gives a position as one element holding a space-separated list",
          "(`pos`, `points`, `vertices`, `center`) in the coordinate system the sibling `cs` names; a",
          "latitude, longitude or height is never an element of its own. Those lists are raw text keys.", "",
          "## The track module (`model/track.def`)", "",
          "A track of this model maps onto the track module only through its identity. The other keys a",
          "track carries are not elements of their own here, and each needs a construct the pack language",
          "does not have:", "",
          "| track key | element of the model | why it is not bound |", "|---|---|---|",
          "| `uid` | `TrackData/uid` (kind `track`), `TrackPoint/uid` (kind `tp`) | bound: the UUID of the object |",
          "| `track.scoped_id`, `track.source_id` | `TrackData/uid`; `trackSource/sensorUID`, `trackerUID` | `scoped_id` would read the same element as `uid`: an xml field line reads one key, and a derive line may target only core or its own module (`isrtrack`), not `track`. The sources are lists (`0..*`), so a scalar key cannot take one of them |",
          "| `lat`, `lon`, `hae` | `TrackPoint/dynamics/pos` with `cs` | one text holding the numbers of a vector, for example `<cs>...</cs><pos>48.5 11.25 512.0</pos>`, whose order and frame the sibling `cs` names: needs a transform that reads the n-th number of a text, and a choice by the value of `cs` (a kind or gate on an element of each list item) |",
          "| `track.vel_east_ms`, `track.vel_north_ms`, `track.vel_up_ms` | `TrackPoint/dynamics/vel` | as `pos`: one text of three numbers in the frame `cs` names |",
          "| `time_ms` of a track point | `TrackPoint/relTime` | `baseTime + relTime x relTimeIncrement`: two keys of the message (another kind) and a product of keys, which no derive function computes |",
          "| `track.confidence` | `TrackPoint/confidence/value` | an unsigned byte whose meaning the sibling `type` (a certainty statistic) chooses; not one scale |",
          "| `track.class` | `TrackedObject/objectClass` | an APP-6 table and entity codes; the mapping onto the track vocabulary is not stated by the model |",
          "| `track.confirmed`, `track.coasting`, `track.final_update` | `TrackSegment/status` | an enumeration (`TrackStatus`) whose values the model's tables in this repository do not list |", "",
          "## Not mapped", "",
          "| What | Count | Why (construct the pack language lacks) |", "|---|---|---|",
          "| classes with no attributes (ESMSensor, ESMInformation, ESM) | 3 classes | placeholders of the model: an empty element, nothing to map |",
          "| positions, velocities, accelerations, arrays | every `DoubleArray`, `IntegerArray` and `unsignedByteArray` element | a list of numbers in one text, read by meaning of a sibling (`cs`): kept as one text key; a value list inside one text is not a construct of the xml wire |",
          "| times of track points, detections, events | every `relTime` | a count of increments after the message's `baseTime` (`relTime x relTimeIncrement + baseTime`): a product and a sum of keys; kept raw |",
          "| covariance matrix values | every `cov` and `ellipsoidParameters` | the model states the matrix type only |",
          "| xsi:type of other abstract uses | - | Shape is the only abstract class the model names |",
          "| dates with more than three fraction digits, or no `Z` | `msgCreatedTime`, `baseTime` | `iso8601_ms` reads milliseconds; such a date fails `transform-decode` |",
          "| extensions (open content, `xsi:type` of an extended class) | - | content of an extension is not in the model |",
          "| EXI | the binary encoding | no wire for it |", ""]
    if unreached:
        t += ["Classes of the model not reached from any kind: %s." % ", ".join(unreached), ""]
    else:
        t += ["Every class with attributes is reached from the `nits` kind.", ""]
    t += ["## Message convention", "",
          "One XML document, canonical form of the xml wire (no declaration, no whitespace between",
          "elements). Vectors are synthetic, written by `tools/isr-tracking/vectors.py` from its own",
          "reading of `model.tsv.txt`.", ""]
    with out_open(os.path.join(REPO, "packs", "isr-tracking", "pack.md")) as f:
        f.write("\n".join(t))


if __name__ == "__main__":
    main()
    check_exit("isr2pack")
